/** 맞은 자리 앞뒤를 잘라 온다 — 어디가 맞았는지 보여 줘야 고를 수 있다 */
function 조각내기(본문, 낮춘본문, 찾을말, 길이 = 84) {
  const 자리 = 낮춘본문.indexOf(찾을말);
  if (자리 < 0) return 본문.slice(0, 길이) + (본문.length > 길이 ? "…" : "");
  const 앞 = Math.max(0, 자리 - Math.floor(길이 / 3));
  const 뒤 = Math.min(본문.length, 앞 + 길이);
  return (앞 > 0 ? "…" : "") + 본문.slice(앞, 뒤).trim() + (뒤 < 본문.length ? "…" : "");
}

/** 찾기. 점수 높은 순으로 돌려준다. */
export function 찾기(말, 최대 = 20) {
  const 찾을말 = String(말 || "").trim().toLowerCase();
  if (찾을말.length < 1) return [];

  const 결과 = [];
  for (const ㅋ of 색인()) {
    const 제목맞음 = ㅋ.낮춘제목.includes(찾을말);
    const 본문맞음 = ㅋ.낮춘본문.includes(찾을말);
    if (!제목맞음 && !본문맞음) continue;

    /* 제목에서 맞으면 위로 — 그 화면 자체를 찾는 경우가 많다.
       본문에서 여러 번 나오면 그만큼 관련이 깊다고 본다(다섯 번까지만 센다). */
    const 횟수 = 본문맞음 ? Math.min(5, ㅋ.낮춘본문.split(찾을말).length - 1) : 0;
    const 점수 = (제목맞음 ? 100 : 0) + 횟수 * 6;

    결과.push({
      제목: ㅋ.제목,
      어디: ㅋ.어디,
      길: ㅋ.길,
      조각: 조각내기(ㅋ.본문, ㅋ.낮춘본문, 찾을말),
      점수,
    });
  }

  결과.sort((ㄱ, ㄴ) => ㄴ.점수 - ㄱ.점수);
  return 결과.slice(0, 최대);
}
