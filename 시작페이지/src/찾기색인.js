/* ═══════════════════════════════════════════════════════
   찾기 색인 — 이 사이트에 적힌 글을 한곳에 모은다

   [왜 손으로 적지 않나]
   화면에 보이는 글은 이미 데이터 파일(데이터/*.js)에 있다. 검색용으로
   따로 베껴 적으면, 본문을 고칠 때마다 두 곳을 고쳐야 하고 언젠가 어긋난다.
   그래서 **같은 파일을 그대로 읽어** 색인을 만든다. 본문이 바뀌면 검색
   결과도 저절로 따라온다.

   [어떻게 찾나]
   서버가 없으니 전부 브라우저 안에서 한다. 글이 많지 않아(수천 줄) 단순히
   훑어도 사람이 못 느낄 만큼 빠르다.
   · 대소문자와 앞뒤 공백을 무시한다.
   · 제목에서 맞으면 본문에서 맞은 것보다 위로 올린다 — 제목이 맞았다는 건
     그 화면 자체를 찾는다는 뜻일 때가 많다.
   · 맞은 자리 앞뒤를 잘라 보여 준다. 어디가 맞았는지 봐야 고를 수 있다.
   ═══════════════════════════════════════════════════════ */

/* 글 묶음을 한 줄짜리 문자열로 눌러 편다 */
function 펴기(무엇) {
  if (무엇 == null) return "";
  if (typeof 무엇 === "string") return 무엇;
  if (typeof 무엇 === "number") return String(무엇);
  if (Array.isArray(무엇)) return 무엇.map(펴기).join(" ");
  if (typeof 무엇 === "object") return Object.values(무엇).map(펴기).join(" ");
  return "";
}

/* 한 칸 = 검색 결과 하나. 제목·본문·갈 곳을 갖는다. */
function 칸(제목, 어디, 길, 본문) {
  return { 제목, 어디, 길, 본문: 펴기(본문).replace(/\s+/g, " ").trim() };
}

