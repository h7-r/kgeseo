import { useNavigate } from "react-router-dom";
import { 눌러이동 } from "../이동표.js";
import 무대 from "../무대.jsx";
import 영상히어로 from "../구간/영상히어로.jsx";
import 몰입경험 from "../구간/몰입경험.jsx";
import 캐릭터소개 from "../구간/캐릭터소개.jsx";
import 게임영상 from "../구간/게임영상.jsx";
import 하위푸터 from "../구간/하위푸터.jsx";

/* ═══════════════════════════════════════════════════════
   게임영상 및 캐릭터 페이지

   자리는 피그마 좌표 그대로다 — 메인 프레임 안에 숨겨진 채로
   히어로 y=129 · 몰입경험 y=1113 · 캐릭터 y=2203 · 영상 y=2938
   · 큰 카드 y=3740 · 쪽번호 y=4513 에 놓여 있다.
   ═══════════════════════════════════════════════════════ */
const 푸터위 = 4513 + 72 + 80;

export default function 영상캐릭터() {
  const 가기 = useNavigate();
  const 누름 = 눌러이동(가기);
  return (
    <무대 높이={푸터위 + 186}>
      <영상히어로 위={129} 누름={누름} />
      <몰입경험 위={1113} />
      <캐릭터소개 위={2203} />
      <게임영상 위={2938} 큰카드위={3740} 쪽번호위={4513} />
      <하위푸터 />
    </무대>
  );
}
