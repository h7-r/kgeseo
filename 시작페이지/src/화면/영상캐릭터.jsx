import { useNavigate } from "react-router-dom";
import { 눌러이동 } from "../이동표.js";
import 무대 from "../무대.jsx";
import 영상히어로 from "../구간/영상히어로.jsx";
import 몰입경험 from "../구간/몰입경험.jsx";
import 캐릭터소개 from "../구간/캐릭터소개.jsx";
import 게임영상 from "../구간/게임영상.jsx";
import 하위푸터 from "../구간/하위푸터.jsx";

/* ═══════════════════════════════════════════════════════
   게임영상 및 캐릭터 페이지

   자리는 피그마 좌표에서 시작했다(히어로 129 · 몰입경험 1113 · 캐릭터 2203 · 영상 2938 · 큰 카드 3740).
   [고친 것 — 구간 사이 틈을 고르게]
   피그마 그대로면 네모 칸들 사이 틈이 144 · 115 · 285 로 제각각이었다
   (특히 게임 영상 칸과 큰 카드 사이가 휑했다). 전부 칸틈(144)으로 맞춘다.
   → 위 칸의 **바닥 + 칸틈** 으로 다음 칸 자리를 계산한다. 칸 높이가 바뀌어도 틈은 그대로 유지된다.
   (히어로 ↔ 밝은 바탕은 화면 끝까지 닿는 면끼리 맞붙는 자리라 그대로 둔다)
   ═══════════════════════════════════════════════════════ */
const 칸틈 = 144;
const 캐릭터위 = 2203; //         밝은 바탕 바닥(2059) + 144
const 캐릭터높이 = 620;
const 영상위 = 캐릭터위 + 캐릭터높이 + 칸틈; //   2967
const 영상높이 = 517;
const 큰카드위 = 영상위 + 영상높이 + 칸틈; //     3628
const 큰카드높이 = 715;
const 쪽번호위 = 큰카드위 + 큰카드높이 + 58; //    4401 — 카드 바로 아래 붙는 쪽번호(카드의 일부)
const 푸터위 = 쪽번호위 + 72 + 80;

export default function 영상캐릭터() {
  const 가기 = useNavigate();
  const 누름 = 눌러이동(가기);
  return (
    <무대 높이={푸터위 + 186}>
      <영상히어로 위={129} 누름={누름} />
      <몰입경험 위={1113} />
      <캐릭터소개 위={캐릭터위} />
      <게임영상 위={영상위} 큰카드위={큰카드위} 쪽번호위={쪽번호위} />
      <하위푸터 />
    </무대>
  );
}
