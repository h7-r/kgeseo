import { useState } from "react";
import { useNavigate } from "react-router-dom";
import 인증폼 from "../구간/인증폼.jsx";
import 가입히어로 from "../구간/가입히어로.jsx";
import 약관구간 from "../구간/약관.jsx";
import 하위푸터 from "../구간/하위푸터.jsx";
import { 약관높이 } from "../데이터/약관탭.js";
import 무대 from "../무대.jsx";

/* ═══════════════════════════════════════════════════════
   인증 화면 — 왼쪽에 카드(98:1172 자리), 오른쪽에 소개 글(90:1053)

   자리는 피그마 좌표 그대로다: 카드 (178, 393) · 소개 글 (1160, 482).

   [소개 글을 네 화면 모두에 두는 이유]
   피그마에서 이 글의 이름은 signup-hero-content 라 회원가입 전용처럼 보인다.
   하지만 카드는 왼쪽 593px 만 쓰기 때문에, 빼면 오른쪽 절반이 텅 빈다.
   프로토타입 연결을 못 읽어서 확인이 안 된 부분이라 **가정**으로 적어 둔다.
   회원가입에만 둬야 한다면 아래 조건 한 줄만 바꾸면 된다.
   ═══════════════════════════════════════════════════════ */

/* 어느 글자를 누르면 어디로 가는가 — 프로토타입 흐름표.
   카드 하단 링크는 피그마 원본에 적힌 그대로고, 단추는 이름에서 이어지는
   자연스러운 다음 단계다(프로토타입 연결을 MCP 로 못 읽어 추정한 부분). */
const 흐름 = {
  // 하단 링크 (원본에 글자로 적혀 있음)
  로그인: "/로그인",
  회원가입: "/회원가입",
  "비밀번호 찾기": "/비밀번호-찾기",
  // 오른쪽 소개 글의 단추
  "게임 소개": "/게임소개",
  "지역 탐험하기": "/",
};

/* 약관 탭은 인증 카드 **아래에** 붙는다 (피그마 94:1137, x=178 y=1410 w=1563) */
const 약관위 = 1410;
const 약관왼쪽 = 178;
const 약관폭 = 1563;
/* 푸터는 가장 긴 약관 탭에 맞춰 못 박는다 — 탭을 눌러도 안 움직인다 */
const 가장긴약관 = Math.max(...Object.values(약관높이));

export default function 인증({ 모드 }) {
  const 가기 = useNavigate();
  const [약관탭, set약관탭] = useState("이용약관");
  const 이동 = (글) => {
    const 길 = 흐름[글];
    if (길) 가기(길);
  };

  const 푸터위 = 약관위 + 가장긴약관 + 80;

  return (
    <무대 높이={푸터위 + 186}>
      <div style={{ position: "absolute", left: "178px", top: "393px" }}>
        <인증폼 모드={모드} 이동={이동} 가기={가기} />
      </div>
      <div style={{ position: "absolute", left: "1160px", top: "482px", width: "560px" }}>
        <가입히어로 누름={이동} />
      </div>
      {/* 원본에서 인증 폼 아래에 붙어 있는 약관 탭 (94:1137) */}
      <약관구간 탭={약관탭} 위={약관위} 왼쪽={약관왼쪽} 폭={약관폭} 탭누르기={set약관탭} />
      {/* 가장 긴 약관 탭만큼 자리를 잡아 둔다 — 푸터가 탭마다 안 움직이게 */}
      <div style={{ position: "absolute", left: 0, top: `${약관위}px`, width: "1px", height: `${가장긴약관 + 80}px`, pointerEvents: "none" }} />
      <하위푸터 />
    </무대>
  );
}
