import { useState } from "react";
import 무대 from "../무대.jsx";
import 게임소개구간 from "../구간/게임소개.jsx";
import 하위푸터 from "../구간/하위푸터.jsx";

/* 게임 소개 페이지 — nav(149) + 틈(56) + 소개 구간(630) + 푸터(186) */
const 내비높이 = 149;
const 구간높이 = 650; // 탭 다섯 개 모두 650 — 가장 긴 것에 맞춰 못 박는다
/* 흰 면이 헤더에 바로 붙으면 머리띠가 흰 면의 일부처럼 보여 답답하다.
   어두운 바탕이 넉넉히 보이도록 띄운다. 뒤에 깔린 입체 공간도 이 틈으로 비친다. */
const 머리틈 = 104;

export default function 게임소개() {
  const [탭, set탭] = useState("게임 소개");

  return (
    <무대 높이={내비높이 + 머리틈 + 구간높이 + 186}>
      <게임소개구간 탭={탭} 위={내비높이 + 머리틈} 탭누르기={set탭} />
      <하위푸터 />
    </무대>
  );
}
