/* ═══════════════════════════════════════════════════════
   게임 시작 — 「모험 시작하기」가 가는 곳

   게임 본편은 이 시작페이지와 **따로 도는 앱**이다(개발 중엔 5173 포트).
   그래서 주소를 코드에 박지 않고 .env 의 VITE_GAME_URL 로 받는다.
     예) VITE_GAME_URL=http://localhost:5173
   개발 서버에서는 시작페이지/.env.development 가 5173 을 적어 둔다.
   아직 안 적었으면 게임 소개 화면으로 보낸다(막다른 길 대신 뭘 하는 게임인지라도 보이게).
   ★ 환경변수 이름은 **영문만** 쓴다. 전엔 VITE_게임주소 였는데, Vite 가 .env 를 읽는 규칙(dotenv)은
     이름에 영문·숫자·_ 만 알아봐서 한글 이름 줄은 **통째로 무시**했다 → 주소가 늘 비어
     「모험 시작하기」가 게임 대신 게임 소개로 갔다(직접 확인: loadEnv 결과가 {}). */
/* 개발 서버(import.meta.env.DEV)에서는 .env 에 안 적어도 본편 개발 서버(5173)로 간다 — 두 서버를 같이 켜면 바로 이어진다.
   배포본은 반드시 VITE_GAME_URL 을 적어야 한다(없으면 게임 소개로). */
export const 게임주소 = import.meta.env.VITE_GAME_URL || (import.meta.env.DEV ? "http://localhost:5173" : "");
/* 게임에 들어가면 **캐릭터 생성부터** 한다 → 완료하면 게임이 튜토리얼(/)로 넘긴다.
   (본편 src/main.jsx 의 /캐릭터생성 · src/캐릭터생성연결.jsx) */
export const 게임첫화면 = "/캐릭터생성";
export function 게임시작(가기) {
  if (게임주소) window.location.assign(게임주소.replace(/\/$/, "") + 게임첫화면); // 다른 앱이라 페이지째 옮겨 간다
  else 가기("/게임소개");
}

/* ═══════════════════════════════════════════════════════
   게임을 시작하는 단추 글자 — 누르면 **게임(캐릭터 생성)** 으로 간다

   사이트 곳곳에 이름만 다른 「게임 시작」 단추가 있다(히어로 플레이하기 · 앙암바위 미션 시작하기 ·
   마무리 지금 시작하기 · 환영판/마이페이지 모험 시작하기). 전엔 이 중 일부만 게임으로 가고
   나머지는 회원가입으로 가서, 같은 뜻의 단추가 서로 다른 곳으로 갔다.
   → 여기 모아 둔 글자는 **전부 같은 길**을 탄다:
      로그인했으면 → 바로 게임(게임주소/캐릭터생성)
      안 했으면   → 로그인 화면 → 로그인하면 자동으로 게임(/게임시작 이 이어 준다, 앱.jsx)
   새 단추를 만들 때 글자만 여기 넣으면 된다.
   ═══════════════════════════════════════════════════════ */
export const 게임시작단어 = new Set([
  "모험 시작하기",
  "게임 시작하기",
  "게임 시작",
  "게임하기",
  "플레이하기",
  "플레이",
  "지금 플레이",
  "지금 시작하기",
  "미션 시작하기",
  "탈출 시작하기",
]);
/* 사이트 안의 「게임으로 이어 주는」 자리 — 로그인 뒤 돌아올 곳(?다음=)으로도 쓴다 */
export const 게임시작길 = "/게임시작";

/** 단추 글자를 받아 알맞은 곳으로 보내는 함수를 만든다.
 *  표에 없는 글자는 아무 일도 안 한다(아직 갈 곳이 정해지지 않은 단추).
 *  게임시작단어 는 누르는 **그 순간**의 로그인 여부로 가른다(지금로그인) — 그래서 이 함수를 부르는
 *  쪽이 로그인 상태를 넘기지 않아도(푸터·영상캐릭터 등) 똑같이 동작한다. */
export function 눌러이동(가기) {
  return (글) => {
    if (게임시작단어.has(글)) {
      if (지금로그인()) return 게임시작(가기);
      return 가기(`/로그인?다음=${encodeURIComponent(게임시작길)}`);
    }
    const 길 = 단추이동[글];
    if (길) 가기(길);
  };
}

