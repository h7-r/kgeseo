import { createElement, lazy, useState } from "react";

/* ═══════════════════════════════════════════════════════
   화면 코드 목록 — 화면마다 떼어 낸(lazy) 코드와 「미리 받기」

   [왜 앱.jsx 에서 따로 뺐나]
   머리띠(내비층.jsx)도 이 목록을 써야 한다 — 메뉴에 마우스를 올리면 그 화면
   코드를 미리 받아 두려고. 앱.jsx 는 내비층을 불러오는 쪽이라, 거꾸로 내비층이
   앱.jsx 를 부르면 서로 물고 도는 import 가 된다. 그래서 둘 다 여기서 가져간다.

   [미리된화면 — React.lazy 를 한 겹 감싼 이유]
   React.lazy 는 코드를 **이미 받아 둔 뒤에도** 처음 그릴 때 한 번은 꼭 멈춘다
   (import() 가 늘 「나중에」 답하는 약속이라서). 그 한 번 때문에
   쪽을 옮길 때 빈 칸(Suspense fallback)을 한 번 그리고, 다음 틱에 다시 그린다 —
   전환이 한 박자 늦어진다.
   그래서 받아 둔 모듈을 여기 기억해 두고, 이미 있으면 lazy 를 거치지 않고
   **바로** 그린다. 아직 없을 때만 원래대로 lazy(= Suspense 기다림)로 간다.
   ═══════════════════════════════════════════════════════ */
function 미리된화면(가져오기) {
  let 모듈 = null;
  let 약속 = null;
  const 받기 = () => {
    if (!약속) {
      약속 = 가져오기().then((m) => { 모듈 = m; return m; });
      /* 받다 실패하면(잠깐 끊긴 망 등) 다음에 다시 시도할 수 있게 비워 둔다 */
      약속.catch(() => { 약속 = null; });
    }
    return 약속;
  };
  const 느린판 = lazy(받기);
  function 화면(props) {
    /* ★ 처음 그릴 때 한 번만 고른다. 그리는 도중에 모듈이 도착해 종류가 바뀌면
       리액트가 화면을 통째로 새로 만들어(입력하던 값 등이 날아간다) 버리기 때문이다. */
    const [고른것] = useState(() => (모듈 ? 모듈.default : 느린판));
    return createElement(고른것, props);
  }
  화면.미리받기 = 받기;
  return 화면;
}

export const 인증 = 미리된화면(() => import("./화면/인증.jsx"));
export const 게임소개 = 미리된화면(() => import("./화면/게임소개.jsx"));
export const 약관화면 = 미리된화면(() => import("./화면/약관.jsx"));
export const 고객센터화면 = 미리된화면(() => import("./화면/고객센터.jsx"));
export const 요금제화면 = 미리된화면(() => import("./화면/요금제.jsx"));
export const 마이페이지화면 = 미리된화면(() => import("./화면/마이페이지.jsx"));
export const 영상캐릭터 = 미리된화면(() => import("./화면/영상캐릭터.jsx"));
export const 찾기화면 = 미리된화면(() => import("./화면/찾기.jsx"));

/* 주소 → 그 화면 코드. 머리띠가 마우스를 올린 메뉴의 코드를 미리 받을 때 쓴다. */
const 주소표 = {
  "/게임소개": 게임소개,
  "/약관": 약관화면,
  "/고객센터": 고객센터화면,
  "/요금제": 요금제화면,
  "/마이페이지": 마이페이지화면,
  "/영상캐릭터": 영상캐릭터,
  "/찾기": 찾기화면,
  "/로그인": 인증,
  "/회원가입": 인증,
};

/** 이 주소의 화면 코드를 미리 받는다(이미 받았으면 아무 일도 없다). 메인("/")은 처음부터 들어 있다. */
export function 주소미리받기(주소) {
  const 길 = String(주소 || "").split("?")[0];
  const 화면 = 주소표[길] || (길.startsWith("/비밀번호") ? 인증 : null);
  return 화면 ? 화면.미리받기().catch(() => {}) : Promise.resolve();
}

/** 전부 미리 받기 — 첫 화면이 다 뜬 뒤 한가할 때 한 번 */
export function 모두미리받기() {
  for (const 화면 of [인증, 게임소개, 약관화면, 고객센터화면, 요금제화면, 마이페이지화면, 영상캐릭터, 찾기화면]) {
    화면.미리받기().catch(() => {});
  }
}
