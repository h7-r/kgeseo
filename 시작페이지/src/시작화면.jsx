import { useNavigate } from "react-router-dom";
import { 눌러이동 } from "./이동표.js";
import 무대, { use화면배율 } from "./무대.jsx";
import 히어로핀, { 히어로끝 } from "./구간/히어로핀.jsx";
import 소개 from "./구간/소개.jsx";
import 영상 from "./구간/영상.jsx";
import 가입폼 from "./구간/가입폼.jsx";
import 세로선 from "./세로선.jsx";
import { 소개글끝, 가입폼왼쪽, 소개폼중심, 앙암잠금, 영상잠금, 구간밀기 } from "./공통.js";
import 배경장식, { 가운데빛, 큰빛 } from "./구간/배경장식.jsx";
import 지역선택 from "./구간/지역선택.jsx";
import 지역카드 from "./구간/지역카드.jsx";
import 앙암바위 from "./구간/앙암바위.jsx";
import 마무리 from "./구간/마무리.jsx";
import 마키 from "./구간/마키.jsx";
import 푸터 from "./구간/푸터.jsx";

/* 메인 랜딩 — 피그마 3:3 「메인 (Main)」 (1920 × 9020) */
export default function 시작화면() {
  const 가기 = useNavigate();
  /* 「플레이하기」 등 게임 시작 단추 — 로그인했으면 게임, 아니면 로그인 뒤 게임(이동표.js 눌러이동) */
  const 누름 = 눌러이동(가기);
  const 배율 = use화면배율();

  return (
    <>
    {/* 힉스필드식 히어로 핀 — 화면에 붙은 채 스크롤한 만큼 영상이 흐르고,
        끝까지 내려야 풀린다(구간/히어로핀.jsx). 무대 밖이라 sticky 가 제대로 잡힌다. */}
    <히어로핀 누름={누름} />
    {/* 무대를 히어로 높이만큼 끌어올려, 핀이 풀리는 순간 소개가 바로 이어지게 한다 */}
    <div style={{ marginTop: `-${Math.round(히어로끝 * 배율)}px` }}>
    <무대 높이={9297} 바닥틈={0}>
      {/* ── 칠하는 순서 = 피그마 레이어 순서 ──────────────────
           위에서 아래로 갈수록 화면 **앞쪽**에 온다.
           특히 큰빛과 가입폼은 반드시 맨 뒤여야 한다 —
           앞으로 옮기면 렌즈가 빛 위로 떠올라 검은 덩어리가 된다. */}
      <배경장식 />
      {/* 히어로는 무대 앞의 히어로핀으로 옮겼다 (그 자리는 비워 둔다) */}
      <소개 누름={누름} />
      {/* ── 밀림 상자 ── 구간을 통째로 아래로 내리는 높이 0 짜리 상자(아래 밀림 함수).
          내리는 이유는 두 가지다.
            ① 멈춤(핀) 자리 — 사건 파일·앙암바위가 가운데 멈춰 있는 동안 스크롤할 거리(영상잠금·앙암잠금)
            ② 고른 틈 — 구간 사이 빈 곳을 모두 구간틈(320)으로 맞추는 고침값(공통.js 구간밀기)
          구간 안 좌표는 피그마 그대로 두고 상자 top 만 바꾼다 → 피그마와 대조하기 쉽다.
          칠하는 순서(아래로 갈수록 앞)는 전과 같다. */}
      <밀림 y={구간밀기.영상}><영상 /></밀림>
      <밀림 y={영상잠금 + 구간밀기.지역카드}><지역카드 /></밀림>
      <밀림 y={영상잠금 + 구간밀기.지역선택}><지역선택 누름={누름} /></밀림>
      <밀림 y={영상잠금 + 구간밀기.앙암}><앙암바위 누름={누름} /></밀림>
      <밀림 y={영상잠금 + 구간밀기.지역선택}><가운데빛 /></밀림>
      <밀림 y={영상잠금 + 앙암잠금 + 구간밀기.마무리}><마무리 누름={누름} /></밀림>
      <밀림 y={영상잠금 + 앙암잠금 + 구간밀기.마키}><마키 누름={누름} /></밀림>
      <푸터 />
      <큰빛 />
      {/* ═══ 왼쪽 소개 글과 오른쪽 가입폼을 가르는 호 ═══
          가로: **상자 폭**이 아니라 **눈에 보이는 글 끝**을 기준으로 잡는다.
                소개 덩이의 상자는 970 까지지만 글은 883 에서 끝나고, 폼은 1145 에서
                시작한다. 상자 기준(1057)으로 놓으면 눈에는 오른쪽으로 치우쳐 보인다.
          세로: 두 덩이가 같은 중심선(소개폼중심)을 쓰니 호도 그 중심에 맞춘다. */}
      <세로선 가운데={(소개글끝 + 가입폼왼쪽) / 2} 위={소개폼중심 - 420} 높이={840} />
      <가입폼 누름={누름} />
    </무대>
    </div>
    </>
  );
}

/* 밀림 상자 — 안의 구간을 y(무대 px)만큼 통째로 내린다.
   · position:absolute + top → 안의 absolute 구간들이 이 상자를 기준으로 놓여 같이 내려간다.
   · 높이 0 이라 스스로는 자리를 안 차지한다 → 무대.jsx 가 data-밀림 을 보고 속까지 들여다봐 높이를 잰다. */
function 밀림({ y, children }) {
  return (
    <div data-밀림="1" style={{ position: "absolute", left: 0, top: `${y}px`, width: "100%", height: 0 }}>
      {children}
    </div>
  );
}
