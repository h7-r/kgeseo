/* ═══════════════════════════════════════════════════════
   입력 검사 규칙 (유효성 검사)

   [이 파일이 하는 일]
   「이 값이 규칙에 맞나?」만 판단한다. 맞으면 빈 문자열(""), 틀리면 보여 줄 말.
   화면(빨간 밑줄·✓ 표시)은 폼검사.js 의 use폼 이 이 결과를 보고 그린다.
   → 규칙과 화면을 나눠 두면, 규칙을 바꿀 때 화면 코드를 안 건드려도 된다.

   [언제 검사하나 — 폼검사.js 에서 정한다]
   · 칸을 **처음 치는 동안**엔 혼내지 않는다(아직 다 안 적었는데 빨간 글씨는 억울하다).
   · 칸을 **떠나는 순간**(blur) 검사해서 틀리면 빨간 밑줄 + 이유를 띄운다.
   · 한 번 검사된 칸은 그다음부터 **칠 때마다** 다시 본다 → 고치는 즉시 빨강이 풀리고 ✓.
   · 제출 단추를 누르면 모든 칸을 한꺼번에 검사한다.
   · 예외: 영문 칸의 한글, Caps Lock 은 치는 즉시 알려 준다(다 치고 나서 알면 늦다).

   ★ 프론트 검사는 **편의**다. 개발자 도구로 얼마든지 우회할 수 있어서,
     서버가 붙으면 서버도 같은 규칙으로 반드시 다시 검사해야 한다.
   ═══════════════════════════════════════════════════════ */

/* ── 입력 정리 ─────────────────────────────────────────
   검사하기 **전에** 값을 한 번 다듬는다. 눈에 안 보이는 글자가 섞이면
   「같아 보이는데 다른 값」이 생겨 중복 검사·로그인이 어긋난다.
   · NFC 정규화 — 맥에서 복사한 한글은 자모가 풀린(NFD) 채로 올 때가 있다.
     「가」 한 글자가 「ㄱ+ㅏ」 두 글자로 저장되면 같은 닉네임이 둘 생긴다.
   · 폭 없는 글자(​‌‍﻿)·제어 문자 제거 — 복사·붙여넣기로 몰래 들어온다. */
const 안보이는글자 = /[\u0000-\u001f\u007f​-‍⁠﻿]/g;
export function 다듬기(v) {
  return String(v ?? "").normalize("NFC").replace(안보이는글자, "");
}

/* 칸마다 받을 수 있는 최대 길이 — input 의 maxLength 로도 쓰고 검사에도 쓴다.
   아주 긴 값을 넣어 화면·저장소를 괴롭히는 것을 막는다.
   숫자는 ERD(app_user)와 맞췄다: email varchar(255), nickname varchar(12). */
export const 최대길이 = { 이메일: 254, 비밀번호: 64, 새비밀번호: 64, 비밀번호확인: 64, 닉네임: 12, 지역: 10, 인증코드: 6 };

/* ── 이메일 ─────────────────────────────────────────────
   예전 규칙(/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/)은 「a@b.cc」 모양만 봤다.
   그래서 「..a@b.com」, 「a@-b.com」, 「a@b..com」 같은 것도 통과했다.
   · 앞(아이디): 영문·숫자·._%+- 만, 1~64자, 점으로 시작·끝나거나 점이 연속되면 안 됨
   · 뒤(도메인): 점으로 나뉜 칸마다 영문·숫자·하이픈(앞뒤 하이픈 X), 마지막은 영문 2자 이상 */
const 이메일꼴 = /^(?!\.)(?!.*\.\.)[A-Za-z0-9._%+-]{1,64}(?<!\.)@(?:[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,}$/;

/** 한글이 섞였나 — 이메일·비밀번호처럼 영문만 받는 칸에 쓴다 */
export const 한글있나 = (v) => /[ㄱ-ㅎㅏ-ㅣ가-힣]/.test(v || "");

/** 영문 전용 칸에 한글을 치면 바로 알려 준다 (칸 오른쪽 안내) */
export const 영문만안내 = "영문으로 입력해주세요";

/** 영문만 받는 칸 목록 */
export const 영문칸 = new Set(["이메일", "비밀번호", "비밀번호확인", "새비밀번호"]);

/* 틀린 **까닭**을 짚어 준다 — 「형식이 아닙니다」만 보면 어디를 고칠지 모른다 */
function 이메일규칙(원래) {
  const v = 다듬기(원래).trim();
  if (!v) return "이메일을 입력해주세요.";
  if (한글있나(v)) return "이메일에는 한글을 쓸 수 없습니다.";
  if (/\s/.test(v)) return "이메일 형식이 아닙니다. 띄어쓰기를 빼주세요.";
  const 골뱅이 = (v.match(/@/g) || []).length;
  if (골뱅이 === 0) return "이메일 형식이 아닙니다. @ 가 빠졌어요. (예: explorer@escape.kr)";
  if (골뱅이 > 1) return "이메일 형식이 아닙니다. @ 는 하나만 쓸 수 있어요.";
  if (v.length > 최대길이.이메일) return "이메일이 너무 깁니다.";
  const [앞, 뒤] = v.split("@");
  if (!앞) return "이메일 형식이 아닙니다. @ 앞에 아이디가 없어요.";
  if (!뒤 || !뒤.includes(".")) return "이메일 형식이 아닙니다. @ 뒤 주소를 확인해주세요. (예: naver.com)";
  if (!이메일꼴.test(v)) return "이메일 형식이 아닙니다. (예: explorer@escape.kr)";
  return "";
}

/* ── 이메일 오타 감지 ── 막지는 않고 「혹시 이건가요?」만 띄운다 (틀린 게 아닐 수도 있어서) */
const 자주쓰는메일 = ["naver.com", "gmail.com", "daum.net", "hanmail.net", "kakao.com", "nate.com", "icloud.com", "outlook.com", "hotmail.com"];
/* 두 글자가 얼마나 다른가(편집 거리) — 한 글자 틀림·빠짐·바뀜을 1 로 센다 */
function 거리(ㄱ, ㄴ) {
  const 표 = Array.from({ length: ㄱ.length + 1 }, (_, i) => [i]);
  for (let j = 1; j <= ㄴ.length; j += 1) 표[0][j] = j;
  for (let i = 1; i <= ㄱ.length; i += 1) {
    for (let j = 1; j <= ㄴ.length; j += 1) {
      표[i][j] = Math.min(표[i - 1][j] + 1, 표[i][j - 1] + 1, 표[i - 1][j - 1] + (ㄱ[i - 1] === ㄴ[j - 1] ? 0 : 1));
    }
  }
  return 표[ㄱ.length][ㄴ.length];
}
/** 「gmial.com」 → 「혹시 gmail.com 인가요?」. 없으면 "" */
export function 메일오타(원래) {
  const v = 다듬기(원래).trim().toLowerCase();
  const 뒤 = v.split("@")[1];
  if (!뒤 || 자주쓰는메일.includes(뒤)) return "";
  const 가까운 = 자주쓰는메일.find((d) => 거리(뒤, d) <= 2);
  return 가까운 ? `혹시 ${v.split("@")[0]}@${가까운} 인가요?` : "";
}

/* ── 닉네임 ─────────────────────────────────────────────
   ERD: nickname varchar(12) unique, 「2~12자. 금칙어 검사 통과분만」(USR-006)
   · 한글·영문·숫자·밑줄(_)만 — 특수문자·이모지는 다른 화면에서 깨지거나 사칭에 쓰인다
   · 운영자 사칭이 되는 이름, 테스트 계정 이름(TEST)은 못 쓴다
   · 욕설 금칙어는 목록이 길어 서버(/nickname/check)가 맡는다 — 여기선 예시만 막는다
   · 문구는 짧게 — 닉네임 칸이 반쪽 폭이라 라벨 옆에 16자 안팎만 들어간다 */
const 예약닉네임 = ["관리자", "운영자", "운영팀", "admin", "administrator", "root", "system", "test", "테스트", "왜곡", "gm"];
const 금칙어 = ["시발", "씨발", "병신", "fuck", "shit"]; // 예시. 실제 목록은 서버에 둔다
function 닉네임규칙(원래) {
  const v = 다듬기(원래).trim();
  if (!v) return "닉네임을 입력해주세요.";
  if (v.length < 2) return "2자 이상 입력해주세요.";
  if (v.length > 최대길이.닉네임) return "12자까지 쓸 수 있습니다.";
  if (/\s/.test(v)) return "띄어쓰기는 쓸 수 없어요.";
  if (/[ㄱ-ㅎㅏ-ㅣ]/.test(v)) return "자음·모음만 따로 쓸 수 없어요.";
  if (!/^[가-힣A-Za-z0-9_]+$/.test(v)) return "특수문자는 _ 만 쓸 수 있어요.";
  const 작게 = v.toLowerCase();
  if (예약닉네임.includes(작게)) return "사용할 수 없는 닉네임입니다.";
  if (금칙어.some((w) => 작게.includes(w))) return "쓸 수 없는 단어가 있어요.";
  return "";
}

/* ── 지역 ── 적어 넣는 대신 목록에서 고르게 한다. 목록에 없는 값은 막는다 */
export const 지역목록 = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종", "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"];

/* ── 비밀번호 ───────────────────────────────────────────
   국내 서비스에서 흔히 쓰는 기준: 8~64자 · 대문자 · 소문자 · 숫자 · 한글/공백 금지 ·
   같은 글자 3번 연속 금지. 여기에 두 가지를 더했다.
   · 누구나 먼저 넣어 보는 비밀번호(목록)는 규칙을 다 맞춰도 막는다.
   · 이메일 아이디나 닉네임이 그대로 들어 있으면 막는다 — 남이 알기 쉬운 정보다. */
const 흔한비번 = ["password", "qwerty", "qwer1234", "asdf1234", "abcd1234", "iloveyou", "letmein", "welcome", "admin123", "12345678", "11111111", "1q2w3e4r", "zxcv1234", "passw0rd"];
function 비밀번호규칙(원래, 값 = {}) {
  const v = String(원래 ?? "");
  if (!v) return "비밀번호를 입력해주세요.";
  if (한글있나(v)) return "비밀번호에는 한글을 쓸 수 없습니다.";
  if (/\s/.test(v)) return "공백은 쓸 수 없습니다.";
  if (v.length < 8) return "8자 이상이어야 합니다.";
  if (v.length > 최대길이.비밀번호) return "64자까지 쓸 수 있습니다.";
  if (!/[A-Z]/.test(v)) return "영문 대문자를 한 자 이상 넣어주세요.";
  if (!/[a-z]/.test(v)) return "영문 소문자를 한 자 이상 넣어주세요.";
  if (!/\d/.test(v)) return "숫자를 한 자 이상 넣어주세요.";
  if (/(.)\1\1/.test(v)) return "같은 글자를 세 번 이상 잇달아 쓸 수 없습니다.";
  const 작게 = v.toLowerCase();
  if (흔한비번.some((p) => 작게.includes(p))) return "너무 흔한 비밀번호입니다. 다른 조합을 써주세요.";
  const 아이디 = 다듬기(값.이메일).trim().toLowerCase().split("@")[0];
  if (아이디 && 아이디.length >= 3 && 작게.includes(아이디)) return "비밀번호에 이메일 아이디를 넣을 수 없습니다.";
  const 닉 = 다듬기(값.닉네임).trim().toLowerCase();
  if (닉 && 닉.length >= 3 && 작게.includes(닉)) return "비밀번호에 닉네임을 넣을 수 없습니다.";
  return "";
}

