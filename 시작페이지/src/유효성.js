/* ═══════════════════════════════════════════════════════
   입력 검사 규칙

   피그마에는 오류 상태가 그려져 있지 않다. 그래서 **원본을 해치지 않는 선**에서
   칸 아래에 붉은 한 줄만 띄운다 — 칸 높이가 늘어나 배치가 밀리지 않도록
   절대 위치로 띄운다.

   검사 시점은 「단추를 누른 뒤부터」다. 타이핑하는 도중에 빨간 글씨가 뜨면
   아직 다 적지도 않았는데 혼나는 느낌이 든다.
   ═══════════════════════════════════════════════════════ */

const 이메일꼴 = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

/** 규칙 하나하나. 통과하면 빈 문자열, 아니면 보여 줄 말. */
export const 규칙 = {
  닉네임: (v) => (!v?.trim() ? "닉네임을 입력해주세요." : v.trim().length < 2 ? "2자 이상 입력해주세요." : ""),
  지역: (v) => (!v?.trim() ? "지역을 선택해주세요." : ""),
  이메일: (v) => (!v?.trim() ? "이메일을 입력해주세요." : !이메일꼴.test(v.trim()) ? "이메일 형식이 아닙니다." : ""),
  비밀번호: (v) => (!v ? "비밀번호를 입력해주세요." : v.length < 8 ? "8자 이상이어야 합니다." : ""),
  인증코드: (v) => (!v?.trim() ? "인증코드를 입력해주세요." : !/^\d{6}$/.test(v.trim()) ? "숫자 6자리입니다." : ""),
  제목: (v) => (!v?.trim() ? "제목을 입력해주세요." : ""),
  내용: (v) => (!v?.trim() ? "내용을 입력해주세요." : v.trim().length < 10 ? "10자 이상 적어주세요." : ""),
  문의유형: (v) => (!v ? "문의 유형을 선택해주세요." : ""),
};

/** 비밀번호 확인은 원본 값이 있어야 판단할 수 있다 */
export function 같은가(비밀번호, 확인) {
  if (!확인) return "비밀번호를 한 번 더 입력해주세요.";
  return 비밀번호 === 확인 ? "" : "비밀번호가 서로 다릅니다.";
}

/** 비밀번호 세기 0~3 — 회원가입의 막대 세 칸에 쓴다 */
export function 세기(비밀번호 = "") {
  let 점수 = 0;
  if (비밀번호.length >= 8) 점수 += 1;
  if (/[A-Za-z]/.test(비밀번호) && /\d/.test(비밀번호)) 점수 += 1;
  if (/[^A-Za-z0-9]/.test(비밀번호) || 비밀번호.length >= 12) 점수 += 1;
  return 점수;
}

/** 칸 이름 목록을 받아 한 번에 검사한다 */
export function 모두검사(칸들, 값) {
  const 결과 = {};
  for (const 이름 of 칸들) {
    if (이름 === "비밀번호확인") 결과[이름] = 같은가(값.비밀번호 ?? 값.새비밀번호, 값.비밀번호확인);
    else if (이름 === "새비밀번호") 결과[이름] = 규칙.비밀번호(값.새비밀번호);
    else 결과[이름] = 규칙[이름] ? 규칙[이름](값[이름]) : "";
  }
  return 결과;
}

/** 오류가 하나라도 있나 */
export const 통과했나 = (오류) => Object.values(오류).every((v) => !v);
