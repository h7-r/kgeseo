/** 칸 이름 목록을 받아 한 번에 검사한다.
 *  { 로그인: true } 를 주면 비밀번호는 「비었나」만 본다(위 로그인비밀번호). */
export function 모두검사(칸들, 값, { 로그인 = false } = {}) {
  const 결과 = {};
  for (const 이름 of 칸들) {
    if (이름 === "비밀번호확인") 결과[이름] = 같은가(값.비밀번호 ?? 값.새비밀번호, 값.비밀번호확인);
    else if (이름 === "새비밀번호") 결과[이름] = 규칙.비밀번호(값.새비밀번호, 값);
    else if (이름 === "비밀번호" && 로그인) 결과[이름] = 규칙.로그인비밀번호(값.비밀번호);
    else 결과[이름] = 규칙[이름] ? 규칙[이름](값[이름], 값) : "";
  }
  return 결과;
}

/** 오류가 하나라도 있나 */
export const 통과했나 = (오류) => Object.values(오류).every((v) => !v);
