/** 하위 메뉴 줄 높이(설계 px) — 머리띠(149) 바로 아래 */
export const 하위높이 = 56;

/**
 * 탭을 주소의 ?탭= 으로 들고 있는다 — 하위 메뉴가 탭을 바꿀 수 있게.
 * 페이지 안 탭 단추도 같은 함수를 쓰므로 둘이 늘 같은 탭을 가리킨다.
 * (replace 로 바꿔서 탭을 누를 때마다 뒤로가기 기록이 쌓이지 않는다)
 */
export function use질의탭(목록, 기본) {
  const [질의, set질의] = useSearchParams();
  const 값 = 질의.get("탭");
  const 탭 = 목록.includes(값) ? 값 : 기본;
  const 바꾸기 = useCallback(
    (새탭) =>
      set질의(
        (옛) => {
          const 새 = new URLSearchParams(옛);
          새.set("탭", 새탭);
          return 새;
        },
        { replace: true },
      ),
    [set질의],
  );
  return [탭, 바꾸기];
}

/**
 * 이 요소가 문서에서 **원래** 놓인 높이(px).
 * [왜 getBoundingClientRect 를 안 쓰나] 사건 파일·앙암바위는 화면에 멈춰 있는 동안
 *   transform 으로 따라 내려온다. 그러면 화면 위치가 늘 같아서 「어디서 시작하는 덩이인지」를
 *   알 수 없다. offsetTop 은 transform 을 무시하므로 **배치된 자리**를 준다.
 *   무대 안은 1920 설계 좌표라, 무대속(scale 이 걸린 칸)까지의 offsetTop 합에 배율을 곱한다.
 */
export function 문서위(el, 배율) {
  let 합 = 0;
  let 지금 = el;
  while (지금 && !지금.classList?.contains("무대속")) {
    합 += (지금.offsetTop || 0) + 고정이동(지금);
    지금 = 지금.offsetParent;
  }
  if (!지금) return el.getBoundingClientRect().top + window.scrollY; // 무대 밖
  return 지금.getBoundingClientRect().top + window.scrollY + 합 * 배율;
}

/**
 * 이 덩이가 차지하는 범위 { 위, 높이 }(px).
 * 메인의 덩이들은 「밀림 상자」(시작화면.jsx) 하나에 여러 조각(제목·그림·카드)으로 흩어져 있다.
 * 찾은 요소 하나만 재면 제목 한 줄만 잡혀 가운데가 어긋난다 — 그래서 **같은 밀림 상자의
 * 조각을 모두 합친 범위**를 쓴다. 밀림 밖(요금제·영상캐릭터의 section)은 그 요소 하나가 덩이다.
 */
function 구역(el, 배율) {
  const 밀림 = el.closest?.("[data-밀림]");
  if (!밀림) return { 위: 문서위(el, 배율), 높이: el.offsetHeight * 배율 };
  let 위 = Infinity;
  let 아래 = -Infinity;
  for (const c of 밀림.children) {
    if (!c.offsetHeight) continue;
    const t = 문서위(c, 배율);
    위 = Math.min(위, t);
    아래 = Math.max(아래, t + c.offsetHeight * 배율);
  }
  return Number.isFinite(위) ? { 위, 높이: 아래 - 위 } : { 위: 문서위(el, 배율), 높이: el.offsetHeight * 배율 };
}

/**
 * 이 덩이를 보려면 스크롤을 어디에 둬야 하나(px).
 * (2026-10-01 사용자 지시 「행간이 같게 띄워져 있으니 거기 맞춰 화면이 잡혀야 한다」)
 *   덩이 사이 틈이 모두 같으므로(공통.js 구간틈), 덩이를 **머리띠 아래 남은 화면의 한가운데**에
 *   놓으면 위아래 틈이 똑같이 보인다. 화면보다 긴 덩이는 머리띠 바로 아래에서 시작한다.
 */
export function 맞춤자리(구, 머리높이) {
  const 남은 = window.innerHeight - 머리높이;
  if (구.높이 <= 남은) return Math.max(0, 구.위 + 구.높이 / 2 - (머리높이 + 남은 / 2));
  return Math.max(0, 구.위 - 머리높이 - 16);
}

/**
 * 요소에 **늘 걸려 있는** 세로 이동(px, 설계 좌표).
 * 소개처럼 가운데 정렬을 transform(translateY(-50%))으로 하는 덩이는 offsetTop 만 보면
 * 436px 아래로 잘못 잰다(실측). 그래서 transform 의 세로 이동은 더한다.
 * ★ 단 「핀」(사건 파일 · 앙암바위 — 영상핀 · 앙암핀)은 화면에 멈춰 있는 동안 스크롤만큼
 *   따라 내려오는 이동이라 **빼야** 원래 자리가 나온다.
 */
function 고정이동(el) {
  if (/핀/.test(String(el.className ?? ""))) return 0;
  const t = getComputedStyle(el).transform;
  if (!t || t === "none") return 0;
  try {
    return new DOMMatrixReadOnly(t).m42;
  } catch {
    return 0;
  }
}

/* 잰 값을 잠깐 다시 쓴다 — 스크롤마다 덩이 전부를 다시 재면(getComputedStyle·offsetTop) 브라우저가
   매 프레임 배치를 다시 계산해서 버벅였다. 같은 페이지·배율·머리 높이면 0.4초 안에는 그대로 쓴다. */
let 캐시 = { 키: "", 때: 0, 값: [] };
export function 구간자리들캐시(길, 배율, 머리높이 = 0) {
  const 키 = `${길}|${배율}|${머리높이}`;
  const 지금 = performance.now();
  if (캐시.키 !== 키 || 지금 - 캐시.때 > 400) 캐시 = { 키, 때: 지금, 값: 구간자리들(길, 배율, 머리높이) };
  return 캐시.값;
}

/** 지금 페이지의 구간들 — [{ 이름, 위, 높이, 잠금끝, 맞춤 }](px) 위에서 아래 순 */
export function 구간자리들(길, 배율, 머리높이 = 0) {
  const 메뉴 = 하위메뉴[길];
  if (!메뉴 || 메뉴.종류 !== "구간") return [];
  const 결과 = [];
  for (const ㅎ of 메뉴.항목) {
    if (!ㅎ.찾기) {
      결과.push({ 이름: ㅎ.이름, 위: 0, 높이: 0, 잠금끝: 0, 맨위: true, 맞춤: 0 });
      continue;
    }
    const el = document.querySelector(ㅎ.찾기);
    if (!el) continue;
    const 구 = 구역(el, 배율);
    결과.push({ 이름: ㅎ.이름, ...구, 잠금끝: 구.위 + (ㅎ.잠금 ?? 0) * 배율, 맞춤: 맞춤자리(구, 머리높이) });
  }
  return 결과.sort((a, b) => a.위 - b.위);
}
