import { useCallback, useEffect, useRef, useState } from "react";
import { 모두검사, 다듬기, 최대길이 } from "./유효성.js";

/* ═══════════════════════════════════════════════════════
   use폼 — 입력칸들의 「값 · 검사 · 보여 줄 상태」를 한곳에서 다룬다

   [왜 훅으로 뺐나]
   메인 페이지 가입폼(가입폼.jsx)과 로그인·회원가입 카드(인증폼.jsx)가
   같은 규칙을 **각자** 구현하고 있었다. 한쪽만 고치면 둘이 다르게 동작한다.
   → 「언제 빨간색을 띄우나」 같은 규칙을 여기 한 벌만 두고 둘 다 쓴다.

   [칸 하나의 상태 4가지]
     기본   : 아직 안 건드림 → 아무 표시 없음
     오류   : 검사했는데 틀림 → 빨간 밑줄 + 이유 한 줄      (className "오류칸")
     확인중 : 규칙은 맞고, 저장소에 중복을 물어보는 중       (이메일·닉네임)
     맞음   : 검사했고 통과 → 초록 밑줄 + ✓                  (className "맞음칸")

   [「검사됨」 의 기준 — 만짐]
   칸을 한 번 **떠나면**(blur) 그 칸은 「만짐」이 된다. 만진 칸만 결과를 보여 준다.
   제출을 누르면 모든 칸이 만짐이 된다. → 치는 도중엔 안 혼나고, 떠나면 바로 알려 준다.

   [비동기 검사 — 중복 확인]
   이메일·닉네임 중복은 저장소(IndexedDB)에 물어봐야 알 수 있다(시간이 걸린다).
   · 규칙(형식)부터 맞아야 물어본다 — 형식이 틀린 값으로 저장소를 두드릴 필요가 없다.
   · 치는 동안은 0.4초 멈췄을 때만 묻는다(디바운스) — 한 글자마다 묻지 않는다.
   · 늦게 온 옛 답은 버린다(순번) — 「a」의 답이 「ab」의 답보다 늦게 오면 엉뚱한 결과가 뜬다.
   ═══════════════════════════════════════════════════════ */
export function use폼({ 칸들, 로그인 = false, 비동기 = {}, 처음값 = null }) {
  /* 처음값 — 처음 한 번만 채워 둘 값(예: 재설정 단계에서 이미 적은 이메일) */
  const [값, set값] = useState(() => 처음값 ?? {});
  const [만짐, set만짐] = useState({}); // { 이메일: true, ... }
  const [제출함, set제출함] = useState(false);
  const [원격, set원격] = useState({}); // 비동기 검사 결과 { 이메일: "이미 가입된 이메일입니다." }
  const [확인중, set확인중] = useState({}); // { 이메일: true } — 물어보는 중
  const 순번 = useRef({}); // 칸별 최신 요청 번호
  const 타이머 = useRef({});

  /* 동기 검사는 값이 바뀔 때마다 **계산**한다(상태로 들고 있지 않는다 — 어긋날 일이 없다) */
  const 규칙오류 = 모두검사(칸들, 값, { 로그인 });

  /* ── 비동기 검사 한 번 ── */
  const 물어보기 = useCallback(
    (이름, 지금값) => {
      const 묻기 = 비동기[이름];
      if (!묻기) return;
      clearTimeout(타이머.current[이름]);
      /* 형식부터 틀리면 묻지 않는다 — 이전 답도 지운다 */
      if (모두검사([이름], 지금값, { 로그인 })[이름]) {
        set원격((r) => ({ ...r, [이름]: "" }));
        set확인중((c) => ({ ...c, [이름]: false }));
        return;
      }
      const 번호 = (순번.current[이름] ?? 0) + 1;
      순번.current[이름] = 번호;
      set확인중((c) => ({ ...c, [이름]: true }));
      타이머.current[이름] = setTimeout(async () => {
        let 답 = "";
        try {
          답 = await 묻기(지금값[이름]);
        } catch {
          답 = ""; // 저장소가 막혀도 입력은 계속할 수 있어야 한다 — 최종 판단은 제출 때 한다
        }
        if (순번.current[이름] !== 번호) return; // 그사이 더 새 값이 들어왔다 → 이 답은 버린다
        set원격((r) => ({ ...r, [이름]: 답 }));
        set확인중((c) => ({ ...c, [이름]: false }));
      }, 400);
    },
    // 비동기 함수 묶음은 부모가 매번 새로 만들 수 있어 의존성에서 뺀다(내용은 늘 같다)
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [로그인],
  );

  useEffect(() => () => Object.values(타이머.current).forEach(clearTimeout), []);

  /* ── 칠 때 ── */
  const 적기 = (이름) => (e) => {
    /* 보이지 않는 글자를 걸러 내고, 최대 길이에서 자른다 */
    let 새것 = 다듬기(e.target.value);
    if (최대길이[이름]) 새것 = 새것.slice(0, 최대길이[이름]);
    const 새값 = { ...값, [이름]: 새것 };
    set값(새값);
    if (만짐[이름] || 제출함) 물어보기(이름, 새값); // 이미 검사된 칸이면 고치는 동안에도 다시 본다
  };

  /* ── 떠날 때 ── 이 순간부터 이 칸은 결과를 보여 준다 */
  const 떠나기 = (이름) => () => {
    if (!값[이름] && !제출함) return; // 빈 칸을 스치고 지나간 것만으로 혼내지 않는다
    set만짐((m) => ({ ...m, [이름]: true }));
    물어보기(이름, 값);
  };

  /* ── 칸 하나가 지금 보여 줄 것 ── */
  const 보임 = (이름) => Boolean(만짐[이름] || 제출함);
  const 오류 = (이름) => (보임(이름) ? 규칙오류[이름] || 원격[이름] || "" : "");
  const 맞음 = (이름) => 보임(이름) && Boolean(값[이름]) && !규칙오류[이름] && !원격[이름] && !확인중[이름];

  /** 입력 컴포넌트에 그대로 펼쳐 넣는 속성 묶음 */
  const 속성 = (이름) => ({
    이름,
    값: 값[이름] ?? "",
    바꾸기: 적기(이름),
    떠나기: 떠나기(이름),
    오류: 오류(이름),
    맞음: 맞음(이름),
    확인중: Boolean(확인중[이름]),
    최대: 최대길이[이름],
  });

  /** 제출 — 모든 칸을 검사하고 통과했으면 true. 비동기 검사도 끝까지 기다린다. */
  const 전부검사 = async () => {
    set제출함(true);
    const 동기 = 모두검사(칸들, 값, { 로그인 });
    const 결과 = { ...동기 };
    for (const 이름 of Object.keys(비동기)) {
      if (!칸들.includes(이름) || 동기[이름]) continue;
      try {
        결과[이름] = await 비동기[이름](값[이름]);
      } catch {
        결과[이름] = "";
      }
      set원격((r) => ({ ...r, [이름]: 결과[이름] }));
    }
    return Object.values(결과).every((v) => !v);
  };

  /** 비밀번호처럼 남겨 두면 안 되는 칸을 비운다 (실패·성공 뒤) */
  const 비우기 = (이름들) => set값((v) => { const 새 = { ...v }; for (const 이름 of 이름들) 새[이름] = ""; return 새; });

  /** 한 칸만 밖에서 바꾼다 — 「혹시 gmail.com 인가요?」를 눌러 고칠 때 */
  const 넣기 = (이름, 새것) => {
    const 새값 = { ...값, [이름]: 새것 };
    set값(새값);
    set만짐((m) => ({ ...m, [이름]: true }));
    물어보기(이름, 새값);
  };

  return { 값, 속성, 전부검사, 비우기, 넣기, 제출함 };
}

/* ═══════════════════════════════════════════════════════
   Caps Lock 감지 — 비밀번호 칸에서 대문자 잠금이 켜졌는지

   비밀번호는 가려져 있어서, 대문자 잠금이 켜진 채 치면 틀린 줄도 모르고
   계속 실패한다(→ 로그인 잠금까지 간다). 키를 누를 때마다 확인해서 알려 준다.
   getModifierState("CapsLock") 은 그 순간 잠금 키가 켜져 있는지를 돌려준다.
   ═══════════════════════════════════════════════════════ */
export function use대문자잠금() {
  const [켜짐, set켜짐] = useState(false);
  const 살피기 = (e) => {
    if (typeof e.getModifierState === "function") set켜짐(e.getModifierState("CapsLock"));
  };
  return { 켜짐, 살피기, 끄기: () => set켜짐(false) };
}

/** Enter 로 제출 — 한글 입력 중(조합 중)의 Enter 는 글자 확정이라 무시한다 */
export const 엔터로 = (보내기) => (e) => {
  if (e.key === "Enter" && !e.nativeEvent.isComposing) {
    e.preventDefault();
    보내기();
  }
};
