/**
 * 요금제 카드를 눌렀을 때 뜨는 「자세히 보기」 내용.
 * 카드에 적힌 줄을 풀어 쓴 것이라 숫자는 카드 · 이용약관과 같아야 한다.
 * 재시도 최대 2회 · 일할 환불 영업일 3~5일 · 청약철회 7일과 3영업일(이용약관 제8조) · 결제 기록 5년(개인정보처리방침 제3조).
 */

type Pair = readonly [label: string, value: string];

/** 모달 안의 한 덩이. 모양에 따라 그리는 법이 다르다. */
export type DetailBlock =
  | { kind: "list"; heading: string; items: readonly string[] }
  /** 순서가 있는 절차. 번호를 붙여 그린다. */
  | { kind: "steps"; heading: string; items: readonly string[] }
  /** 이름 + 한 줄 풀이(혜택 · 플랜 비교). */
  | { kind: "terms"; heading: string; items: readonly Pair[] }
  /** 이름만 늘어놓는 갈래(카드사·간편결제 등). */
  | { kind: "chips"; heading: string; groups: readonly { label: string; values: readonly string[] }[] }
  /** 계산 예시. 마지막 줄은 합계로 강조한다. */
  | { kind: "calculation"; heading: string; rows: readonly Pair[]; total: Pair; note: string };

export interface PaymentDetail {
  /** 모달 맨 위 한 줄 요약. */
  lead: string;
  blocks: readonly DetailBlock[];
}

export interface PlanDetail {
  /** 가격 옆에 붙는 청구 방식. */
  billing: string;
  blocks: readonly DetailBlock[];
}

