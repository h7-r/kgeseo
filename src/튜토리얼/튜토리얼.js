//   · 튜토리얼UI.jsx(캔버스 밖) 가 지금 단계의 안내판을 그린다.
//
// [퍼즐을 순서와 다르게 풀면]
//   단계마다 「이미 됐나」를 보고, 됐으면 **바로 다음으로 넘어간다**(한 프레임에
//   여러 칸도). 안내가 이미 끝난 일을 시키며 멈춰 있지 않게.
//
