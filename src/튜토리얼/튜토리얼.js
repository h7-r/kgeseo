//
// [구조]
//   · 이 파일 = 단계표 + 상태 + 키 기록. 렌더와 무관하다.
//   · 튜토리얼판.jsx(캔버스 안) 가 매 프레임 `튜토리얼틱()` 을 불러 조건을 보고
//     바닥 동그라미를 그린다. 소화전 자물쇠 id 처럼 Scene 만 아는 값을 넘겨준다.
//   · 튜토리얼UI.jsx(캔버스 밖) 가 지금 단계의 안내판을 그린다.
//
// [퍼즐을 순서와 다르게 풀면]
//   단계마다 「이미 됐나」를 보고, 됐으면 **바로 다음으로 넘어간다**(한 프레임에
//   여러 칸도). 안내가 이미 끝난 일을 시키며 멈춰 있지 않게.
//
// 콘솔: `__튜토리얼.값()` 지금 상태 · `__튜토리얼.건너뛰기()` 다음 단계 ·
