// ── 상태 ───────────────────────────────────────────────────────
let 값 = { 단계: 0, 방금: null, 끝냄: false, 숨김: false };
const 듣는이 = new Set();
function 세팅(부분) {
  값 = { ...값, ...부분 };
  for (const f of 듣는이) f();
}
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};
export const 튜토리얼 = { 값: () => 값, 구독 };
export const use튜토리얼 = () => useSyncExternalStore(구독, () => 값);

// 이번 단계에서 모은 기록 — 단계가 바뀌면 비운다
const 기록 = { 눌림: new Set(), 횟수: {}, 돈각: 0, 만짐: false, 이전yaw: null };
function 기록비우기() {
  기록.눌림 = new Set();
  기록.횟수 = {};
  기록.돈각 = 0;
  기록.만짐 = false;
  기록.이전yaw = null;
}

function 다음으로(n = 값.단계 + 1) {
  const 끝 = 단계들.length - 1;
  const 다음 = Math.min(n, 끝);
  기록비우기();
  세팅({ 단계: 다음, 방금: 단계들[값.단계]?.id ?? null, 끝냄: 다음 === 끝 });
}

// ── 키 기록 ────────────────────────────────────────────────────
//   게임의 키 처리(use이동 · App onKey)와 **따로** 듣는다 — 그쪽을 건드리지 않는다.
const 키이름 = {
  ShiftLeft: "Shift",
  ShiftRight: "Shift",
  Space: "Space",
  KeyC: "C",
  KeyV: "V",
  KeyE: "E",
  KeyH: "H",
};
if (typeof window !== "undefined") {
  window.addEventListener("keydown", (e) => {
    if (e.repeat) return;
    const 이름 = 키이름[e.code];
    if (!이름) return;
    기록.눌림.add(이름);
    기록.횟수[이름] = (기록.횟수[이름] ?? 0) + 1;
    // 겨냥한 게 있을 때 E = 실제로 무언가를 만졌다
    if (이름 === "E" && 겨냥.값()) 기록.만짐 = true;
  });
  window.__튜토리얼 = {
    값: () => ({ ...값, 단계id: 단계들[값.단계]?.id }),
    건너뛰기: () => 다음으로(),
    처음부터: () => {
      기록비우기();
      세팅({ 단계: 0, 방금: null, 끝냄: false, 숨김: false });
    },
  };
}

const 조작항상 =
  typeof window !== "undefined" &&
  new URLSearchParams(window.location.search).get("조작") === "항상";

/**
 * 매 프레임 부른다(튜토리얼판.jsx).
 * @param 문맥 { 눈: {x,z}, yaw: 카메라 y 회전, 소화전문id }
 */
export function 튜토리얼틱(문맥) {
  const 지금 = 단계들[값.단계];
  if (!지금 || 값.끝냄) return;

  // 둘러본 양 — yaw 변화량을 누적한다(한 바퀴 넘어갈 때 튀지 않게 감싸 준다)
  if (기록.이전yaw !== null) {
    let d = 문맥.yaw - 기록.이전yaw;
    d = Math.atan2(Math.sin(d), Math.cos(d));
    기록.돈각 += Math.abs(d);
  }
  기록.이전yaw = 문맥.yaw;

  const c = {
    ...기록,
    잠김: 조작항상 || (typeof document !== "undefined" && !!document.pointerLockElement),
    안에있나:
      !!지금.자리 &&
      Math.hypot(문맥.눈.x - 지금.자리[0], 문맥.눈.z - 지금.자리[1]) < 동그라미반지름,
    소화전문id: 문맥.소화전문id,
  };

  // 퍼즐 구간: 더 뒤 단계가 이미 끝났으면 그 다음으로 곧장 간다
  if (값.단계 >= 퍼즐부터) {
    for (let i = 단계들.length - 2; i > 값.단계; i -= 1) {
      if (단계들[i].됐나(c)) {
        다음으로(i + 1);
        return;
      }
    }
  }
  if (지금.됐나(c)) 다음으로();
}

/** 안내판을 잠깐 숨기거나 되살린다([F1]) — 화면을 가리고 싶을 때 */
export function 튜토리얼숨김토글() {
  세팅({ 숨김: !값.숨김 });
}
