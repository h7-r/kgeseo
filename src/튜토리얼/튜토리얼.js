//   「어떤 식으로 하는지는 알려 주지만 퍼즐 자체를 푸는 법은 알려 주지 않는다.」
//   그래서 퍼즐 단계 문구는 **키·손 쓰는 법**(E 로 집기, ←→ 칸 고르기 …)만 말하고
