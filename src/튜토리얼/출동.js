// 출동.js — 튜토리얼 다음: 본부실에서 **나주 출동 명령**을 받고 기차로 가는 흐름 (상태 상자)
//
// [흐름] (사용자 지시 2026-10-01)
//   복도 튜토리얼 끝 → 본부실에 들어선다 → 약 5초 뒤 상황실 긴급 호출
//   「나주 앙암바위에서 왜곡 발생 — 출동」 → 바닥에 화살표가 기차 문까지 이어진다
//   → 기차에 오르면 끝(기차 안 홀로그램에서 나주로 넘어간다).
//
// [단계]
//   대기   : 튜토리얼이 아직이거나 본부실에 안 들어왔다
//   카운트 : 본부실에 들어섰다 — 이때부터 `알림까지` 초를 센다(한 번 들어오면 계속 센다)
//   알림   : 긴급 호출 카드가 떠 있다(화살표도 이미 깔린다)
//   안내   : 카드를 닫았다 — 목표 표시 + 바닥 화살표
//   탑승   : 기차에 올랐다 — 다 끝
//
// 콘솔: `__출동.값()` · `__출동.당기기()` 기다리지 않고 바로 알림 · `__출동.처음부터()`

import { useSyncExternalStore } from "react";
import { 튜토리얼 } from "./튜토리얼.js";

export const 알림까지 = 5; // 초. 본부실에 들어선 뒤 긴급 호출까지 (2026-10-01 사용자 지시 60 → 20 → 5)

let 값 = { 단계: "대기", 들어온때: null, 남은초: null, 문거리: null };
const 듣는이 = new Set();
function 세팅(부분) {
  값 = { ...값, ...부분 };
  for (const f of 듣는이) f();
}
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};
export const 출동 = { 값: () => 값, 구독 };
export const use출동 = () => useSyncExternalStore(구독, () => 값);

/** 카드를 닫는다 — 화살표 안내만 남는다 */
export function 출동확인() {
  if (값.단계 === "알림") 세팅({ 단계: "안내" });
}

/**
 * 매 프레임(출동길.jsx) 또는 기차 안에서 부른다.
 * @param 문맥 { 본부실안: boolean, 기차안: boolean, 문거리?: number }
 */
export function 출동틱({ 본부실안, 기차안, 문거리 = null }) {
  const 단 = 값.단계;
  if (단 === "탑승") return;
  // 언제든 기차에 오르면 끝 — 호출 전에 먼저 타도 안내를 띄우지 않는다
  if (기차안) {
    if (단 !== "대기") 세팅({ 단계: "탑승" });
    return;
  }
  if (단 === "대기") {
    if (튜토리얼.값().끝냄 && 본부실안) 세팅({ 단계: "카운트", 들어온때: performance.now() });
    return;
  }
  if (단 === "카운트") {
    const 지난 = (performance.now() - 값.들어온때) / 1000;
    const 남은초 = Math.max(0, Math.ceil(알림까지 - 지난));
    if (남은초 <= 0) 세팅({ 단계: "알림", 남은초: 0 });
    else if (남은초 !== 값.남은초) 세팅({ 남은초 });
    return;
  }
  // 알림·안내 — 문까지 거리(미터)를 1m 단위로만 갱신해 리렌더를 아낀다
  if (문거리 !== null) {
    const m = Math.round(문거리 * 0.3);
    if (m !== 값.문거리) 세팅({ 문거리: m });
  }
}

if (typeof window !== "undefined") {
  window.__출동 = {
    값: () => 값,
    당기기: () => 세팅({ 단계: "알림", 남은초: 0 }),
    처음부터: () => 세팅({ 단계: "대기", 들어온때: null, 남은초: null, 문거리: null }),
  };
}
