// ═══════════════════════════════════════════════════════════════
//  안내상태.js — 튜토리얼 안내의 **상자와 판정**
// ═══════════════════════════════════════════════════════════════
// [왜 zustand 를 안 쓰나]
//   `게임상태.js` · `화면층.js` 와 같은 방식(useSyncExternalStore)으로 맞춘다.
//   의존성을 늘리지 않고, 스냅샷 규칙("같은 값이면 같은 참조")만 지키면 된다.
//
// [★ 스냅샷 규칙]
//   `현재()` 는 값이 바뀌지 않았으면 **같은 객체를 그대로** 돌려줘야 한다.
//   매번 새 객체를 만들면 useSyncExternalStore 가 "바뀌었다"로 보고 무한 렌더한다.
//   그래서 `상자` 하나를 두고, 바뀔 때만 새로 만든다.
//
// [★ 매 프레임 setState 금지]
//   판정은 `판정하기()` 가 useFrame 에서 **값만 읽는다.** 단계가 실제로 넘어갈 때만
//   상자를 갈아 끼운다. 키 안내가 뜨고 지는 것도 마찬가지 — 시각만 기록하고,
//   보임/숨김은 그 시각을 보고 CSS 가 한다.
//
// [왜 바깥에서 주입받나]
//   복도 크기(Leva 저장값)와 자물쇠 id(자리에서 계산된다)는 이 파일이 알 수 없다.
//   억지로 import 하면 순환 참조가 되거나 좌표가 두 곳에 적힌다. 그래서 붙이는
//   쪽(App.jsx)이 한 줄로 건네주고, 안 건네주면 그 판정만 쉰다(터지지 않는다).

import { useSyncExternalStore } from "react";
import { 안내단계, 안내설정 } from "./안내단계.js";
import { 든동전, 동전위치 } from "../소품/동전상태.js";
import { 든음료 } from "../소품/종이컵상태.js";
import { 다풀렸나 } from "../소품/배전반배선.js";

// ── 상자 ────────────────────────────────────────────────────
let 상자 = {
  켜짐: false,
  단계번호: 0,
  단계시작시각: 0, // performance.now() / 1000 (초)
  키보임: false,
  마지막입력시각: 0,
};
const 듣는이 = new Set();
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};
const 알리기 = () => 듣는이.forEach((f) => f());
/** ★ 바뀐 것이 없으면 상자를 갈지 않는다(같은 값 = 같은 참조) */
function 갈기(덧) {
  let 바뀜 = false;
  for (const k of Object.keys(덧)) {
    if (상자[k] !== 덧[k]) {
      바뀜 = true;
      break;
    }
  }
  if (!바뀜) return;
  상자 = { ...상자, ...덧 };
  알리기();
}

const 지금 = () => performance.now() / 1000;

// ── 바깥에서 받아 두는 것 ───────────────────────────────────
//   ① 복도 상자 { x0, x1, z0, z1, 바닥y } — 폭 비율을 세계 좌표로 풀 때 쓴다
//   ② 대상위치(id) — 겨냥 등록표에서 물건 자리를 읽는 함수
//   ③ 신호(이름) — 이 파일이 import 할 수 없는 완료 신호(자물쇠 등)
let 복도 = null;
let 대상위치제공 = null;
const 주입신호 = new Map();

export function 복도설정(상자값) {
  복도 = 상자값 ?? null;
}
export function 대상위치제공하기(fn) {
  대상위치제공 = typeof fn === "function" ? fn : null;
}
/** 자물쇠처럼 이 파일이 못 읽는 신호를 바깥이 건네준다. `신호제공({ "자물쇠.풀림": () => 풀림 })` */
export function 신호제공(표) {
  for (const k in 표) 주입신호.set(k, 표[k]);
}

// ── 완료 신호표 ─────────────────────────────────────────────
//   여기서 읽을 수 있는 것만 둔다. 없는 것은 주입신호로 받는다.
//   ※ 소화전·텔레포트는 구독할 수 있는 완료 신호가 없어서 단계에서 뺐다(안내단계.js 주석).
const 신호표 = {
  "동전.주움": () => 든동전() != null,
  // 동전은 두 개다. 캔 동전은 **음료** 자판기, 종이컵 동전은 **커피** 자판기에 들어간다
  //   (동전상태.js `맞는자판기`). 엉뚱한 데 넣으면 반환구로 도로 나온다 — 그래서
  //   "넣었나"는 든 것이 없어진 게 아니라 **소비됐나**로 본다.
  "동전.캔듦": () => 든동전() === "캔",
  "동전.캔넣음": () => 동전위치("캔") === "소비",
  "동전.종이컵듦": () => 든동전() === "종이컵",
  "동전.종이컵넣음": () => 동전위치("종이컵") === "소비",
  "음료.듦": () => 든음료() != null,
  "배전반.다풀림": () => 다풀렸나(),
};
function 신호읽기(이름) {
  const f = 신호표[이름] ?? 주입신호.get(이름);
  if (!f) return null; // 모르는 신호 — 판정을 쉰다(터지지 않는다)
  try {
    return !!f();
  } catch {
    return null;
  }
}

// ── 좌표 풀기 ───────────────────────────────────────────────
//   { 폭: 0~1, z } → 세계 [x, z] · { 대상: id } → 등록표에서 읽기
// 대상이 잠깐 사라져도 **마지막 자리를 기억한다.**
//   [왜]  동전을 집어 들면 그 겨냥 대상이 등록에서 빠진다. 그러면 "자판기에 넣어라"
//   단계에서 바닥 원이 통째로 사라져 어디로 가야 할지 알 수 없다(사용자 지적).
//   집기 전 자리가 곧 자판기 앞이므로, 그 자리를 그대로 가리키면 맞다.
const 마지막자리 = new Map();

export function 자리풀기(목표) {
  if (!목표) return null;
  if (목표.대상) {
    const p = 대상위치제공?.(목표.대상);
    if (p) {
      마지막자리.set(목표.대상, [p[0], p[2]]);
      return [p[0], p[2]];
    }
    return 마지막자리.get(목표.대상) ?? null;
  }
  if (!복도) return null;
  const { x0, x1 } = 복도;
  return [x0 + (x1 - x0) * (목표.폭 ?? 0.5), 목표.z ?? 0];
}

// ── 켜짐 판정 ───────────────────────────────────────────────
//   첫 회차(튜토리얼 미완료)에만 켠다. ?guide=1 / ?guide=0 으로 덮어쓴다.
function 쿼리값() {
  if (typeof location === "undefined") return null;
  const v = new URLSearchParams(location.search).get("guide");
  return v === "1" ? true : v === "0" ? false : null;
}
/** 붙이는 쪽이 진행 상태를 넣어 부른다. 복도에 들어오기 **전에 한 번만** 정한다. */
export function 켜기정하기(진행) {
  const 강제 = 쿼리값();
  const 켬 = 강제 ?? !진행?.튜토리얼완료;
  갈기({ 켜짐: !!켬, 단계번호: 0, 단계시작시각: 지금(), 키보임: !!켬, 마지막입력시각: 지금() });
  return !!켬;
}

// ── 단계 ────────────────────────────────────────────────────
export const 현재 = () => 상자;
export const use안내 = () => useSyncExternalStore(구독, 현재);
export const 지금단계 = () => 안내단계[상자.단계번호] ?? null;

export function 다음단계() {
  if (!상자.켜짐) return;
  const 다음 = Math.min(안내단계.length - 1, 상자.단계번호 + 1);
  if (다음 === 상자.단계번호) return;
  갈기({ 단계번호: 다음, 단계시작시각: 지금(), 키보임: (안내단계[다음]?.키?.length ?? 0) > 0 });
}

/** 마지막 단계까지 끝냈나 — 붙이는 쪽이 이걸 보고 서버에 완료를 알린다 */
export const 다끝났나 = () => 상자.단계번호 >= 안내단계.length - 1;

// ── 입력 ────────────────────────────────────────────────────
//   종류: "마우스" | "WASD" | "Space" | "C" | "E"
export function 입력기록(종류) {
  if (!상자.켜짐) return;
  const t = 지금();
  const 단계 = 지금단계();
  // 그 단계가 가르치려던 키를 실제로 썼으면 키 안내를 거둔다.
  const 가르친것 = 단계?.키?.length
    ? (종류 === "WASD" && 단계.키.includes("W")) ||
      (종류 === "Space" && 단계.키.includes("Space")) ||
      (종류 === "C" && 단계.키.includes("C")) ||
      (종류 === "E" && 단계.키.includes("E")) ||
      (종류 === "마우스" && 단계.키.includes("마우스"))
    : false;
  갈기({ 마지막입력시각: t, ...(가르친것 ? { 키보임: false } : null) });
}

/** USR-115 입력 허용 목록. 안내가 꺼져 있으면 **언제나 통과**시킨다. */
export function 허용되나(입력) {
  if (!상자.켜짐) return true;
  const 단계 = 지금단계();
  if (!단계?.허용입력) return true;
  return 단계.허용입력.includes(입력);
}

// ── 판정 (useFrame 에서 부른다. 값만 읽고, 넘어갈 때만 상자를 간다) ──
//   맥락: { 위치: [x, y, z] · 시선각: 라디안 · 앉음 · 점프: 참/거짓 }
let 시선누적 = 0;
let 지난시선각 = null;
export function 판정하기(맥락) {
  if (!상자.켜짐) return;
  const 단계 = 지금단계();
  const 완료 = 단계?.완료;
  if (!완료 || 완료.종류 === "없음") return;

  if (완료.종류 === "시점회전") {
    const a = 맥락?.시선각;
    if (typeof a !== "number") return;
    if (지난시선각 !== null) {
      // 한 바퀴를 넘어갈 때 각이 −π ↔ π 로 튄다. 짧은 쪽 차이만 센다.
      let d = a - 지난시선각;
      while (d > Math.PI) d -= Math.PI * 2;
      while (d < -Math.PI) d += Math.PI * 2;
      시선누적 += Math.abs(d);
    }
    지난시선각 = a;
    if ((시선누적 * 180) / Math.PI >= (완료.누적도 ?? 90)) {
      시선누적 = 0;
      지난시선각 = null;
      다음단계();
    }
    return;
  }

  if (완료.종류 === "구역도착") {
    const p = 맥락?.위치;
    const 목표 = 자리풀기(단계.목표);
    if (!p || !목표) return;
    const dx = p[0] - 목표[0];
    const dz = p[2] - 목표[1];
    const r = 완료.반지름 ?? 1.2;
    if (dx * dx + dz * dz <= r * r) 다음단계();
    return;
  }

  if (완료.종류 === "점프") {
    // 구역에 **도착만 해도** 넘어가던 것을 고친다 — 점프를 가르치는 단계인데
    //   걸어서 지나가면 아무것도 안 배운 채 링만 사라졌다(사용자 지적).
    if (맥락?.점프) 다음단계();
    return;
  }

  if (완료.종류 === "앉음") {
    if (맥락?.앉음) 다음단계();
    return;
  }

  if (완료.종류 === "상태값") {
    if (신호읽기(완료.신호) === true) 다음단계();
  }
}

/** 키 안내를 다시 띄울 때가 됐나 — 방치 시간을 보고 정한다(CSS 가 실제 표시를 한다) */
export function 키다시보일때인가() {
  if (!상자.켜짐 || 상자.키보임) return false;
  if (!(지금단계()?.키?.length > 0)) return false;
  return 지금() - 상자.마지막입력시각 >= 안내설정.방치재표시초;
}
export function 키다시보이기() {
  갈기({ 키보임: true, 마지막입력시각: 지금() });
}

// ── 콘솔 확인용 손잡이 (화면층.js 와 같은 방식) ──────────────
if (typeof window !== "undefined") {
  window.__안내 = {
    현재,
    단계: 지금단계,
    표: 안내단계,
    설정: 안내설정,
    다음단계,
    자리풀기,
    켜기: (v = true) => 갈기({ 켜짐: !!v, 단계번호: 0, 단계시작시각: 지금() }),
    // ★ 키 안내도 같이 되살린다. 안 그러면 개발용으로 단계를 건너뛸 때
    //   "안내가 아예 안 뜬다"로 보인다(실제로 그렇게 보였다) — 앞 단계에서 이미
    //   걷힌 `키보임` 이 그대로 남기 때문이다. `다음단계()` 는 이미 이렇게 한다.
    단계로: (n) => {
      const k = Math.max(0, Math.min(안내단계.length - 1, n));
      갈기({ 단계번호: k, 단계시작시각: 지금(), 키보임: (안내단계[k]?.키?.length ?? 0) > 0, 마지막입력시각: 지금() });
    },
  };
}
