// 게임상태.js — 세션·진행 상태를 담는 단 하나의 상자 (USR-110)
//
// [왜 리덕스 같은 걸 안 쓰나]
//   지금 필요한 값이 「어느 세션에 있나」 + 「서버가 알려준 진행 상태」 두 덩어리뿐이다.
//   리액트 내장 useSyncExternalStore 로 충분하고, 3D 씬 밖(HTML UI)에서도 같은 값을
//   봐야 하는데 부모-자식이 아니라 props 로 못 넘긴다 → 바깥에 상자를 두고 둘 다 본다.
//   (App.jsx 에서 이미 쓰던 방식과 같다)

import { useSyncExternalStore } from "react";
import { 서버 } from "../서버/api.js";
import { 세션, 케이스세션인가 } from "../세션/세션정의.js";

let 값 = {
  세션: 세션.부팅, // 지금 화면
  진행: null, // 서버가 준 진행 상태 (null = 아직 모름)
  조회실패: false, // USR-110 예외 — 실패하면 게스트 신규로 취급한다
  안내: null, // 게이트에 막혔을 때 띄울 문구 (전역-003)
};

const 듣는이 = new Set();

function 세팅(부분) {
  값 = { ...값, ...부분 };
  for (const f of 듣는이) f();
}

export const 게임상태 = {
  값: () => 값,
  구독: (f) => {
    듣는이.add(f);
    return () => 듣는이.delete(f);
  },
  세팅,
};

// ★ useSyncExternalStore 는 '같은 값이면 같은 참조'를 돌려줘야 한다.
//   매번 새 객체를 만들면 무한 렌더가 된다. 그래서 통째로 하나만 돌려준다.
export const use게임상태 = () =>
  useSyncExternalStore(게임상태.구독, 게임상태.값);

// ── 전역-002 세션 라우팅 ──────────────────────────────────────
// 진행 상태를 보고 어느 세션으로 보낼지 정한다.
//   · 아바타 없음      → S2 캐릭터 생성 (신규)
//   · 튜토리얼 미완료  → S4 로비 (케이스 잠금 상태)
//   · 완료            → S4 로비 (자유)
// 로비로 보내는 건 같지만 '잠금 상태'가 다르다. 그 판단은 아래 케이스진입가능()이 한다.
export function 목적지판정(진행) {
  if (!진행 || !진행.아바타있음) return 세션.캐릭터생성;
  return 세션.로비;
}

// ── 전역-003 튜토리얼 게이트 ─────────────────────────────────
// 케이스(S6·S7)에 들어갈 수 있는지. **반드시 서버 값(진행.튜토리얼완료) 기준.**
export function 케이스진입가능(진행) {
  return !!(진행 && 진행.튜토리얼완료);
}
export const 게이트문구 =
  "훈련실을 먼저 마쳐야 사건 현장에 들어갈 수 있습니다.";

// ── 부팅: 진행 상태를 받아 첫 세션을 정한다 ──────────────────
export async function 부팅하기() {
  try {
    const 진행 = await 서버.진행상태조회();
    세팅({ 진행, 조회실패: false, 세션: 목적지판정(진행) });
  } catch (e) {
    // USR-110 예외 처리 — 상태 조회 실패 시 '게스트 신규'로 취급한다.
    //   막아 세우면 아무것도 못 하므로, 새 사람인 셈 치고 캐릭터 생성부터 보낸다.
    console.warn("[진행 상태] 조회 실패 → 게스트 신규로 취급합니다.", e);
    세팅({
      진행: null,
      조회실패: true,
      세션: 세션.캐릭터생성,
    });
  }
}

// ── 세션 이동 ────────────────────────────────────────────────
// 화면에서 세션을 바꿀 때는 반드시 이 함수를 거친다.
//   여기 한 곳에서만 게이트를 검사하므로, 우회 경로가 생기지 않는다.
export function 세션이동(대상) {
  const { 진행 } = 값;
  if (케이스세션인가(대상) && !케이스진입가능(진행)) {
    세팅({ 안내: 게이트문구 });
    return false;
  }
  세팅({ 세션: 대상, 안내: null });
  return true;
}

export const 안내닫기 = () => 세팅({ 안내: null });

// 진행 상태를 서버에서 다시 받아온다(튜토리얼을 마쳤을 때 등).
export async function 진행다시읽기() {
  try {
    const 진행 = await 서버.진행상태조회();
    세팅({ 진행, 조회실패: false });
    return 진행;
  } catch {
    세팅({ 조회실패: true });
    return null;
  }
}
