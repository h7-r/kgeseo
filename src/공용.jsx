//   늘리거나 돌려도 선이 어긋나지 않기 때문이다.
// ═══════════════════════════════════════════════════════════════
//  그림자 맵 다시 그리기 관리
// ═══════════════════════════════════════════════════════════════
// [무엇이 문제였나]
//   three 는 기본으로 **매 프레임 그림자 맵을 통째로 다시 그린다.** 그림자를
//   만드는 빛이 하나뿐이고 그 빛은 절대 안 움직이는데도 그렇다.
//   실제로 재 보니 방 한가운데에서 한 프레임 10.43ms 중 **5.78ms(55%)** 가
//   그림자 다시 그리기였다(그림자 갱신만 꺼 보니 4.65ms).
//
// [어떻게 고치나]
//   자동 갱신을 끄고, **필요할 때만** 다시 그린다.
//     ① 뭔가 움직였다는 신호가 오면 그 뒤 잠깐 동안은 매 프레임 (문이 열리는
