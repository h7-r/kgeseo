/** [E] 로 무언가를 만졌다 — 팔을 한 번 뻗는다. */
export function 팔뻗기시작(길이 = 0.6) {
  뻗기.시작 = performance.now();
  뻗기.길이 = 길이;
}
// 콘솔·시험용 — [E] 는 마우스 잠금(locked) 안에서만 먹어서, 헤드리스로는
