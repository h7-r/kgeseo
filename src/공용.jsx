// EdgesGeometry 캐시 — 같은 지오메트리·같은 각도면 다시 만들지 않는다.
//   WeakMap이라 지오메트리가 버려지면 캐시도 같이 사라진다(메모리 누수 없음).
const 주름캐시 = new WeakMap();
function 주름지오(geo, 각도) {
  let m = 주름캐시.get(geo);
  if (!m) {
    m = new Map();
    주름캐시.set(geo, m);
  }
  if (!m.has(각도)) m.set(각도, new THREE.EdgesGeometry(geo, 각도));
  return m.get(각도);
}

// ═══════════════════════════════════════════════════════════════
//  외곽선 껍데기 — 지오·재질을 값이 같으면 돌려 쓴다
// ═══════════════════════════════════════════════════════════════
// [왜 drei <Outlines> 를 버렸나 — 실측]
//   drei 는 <Outlines> 하나마다 ① new OutlinesMaterial() ② toCreasedNormals 로
//   만든 새 지오 ③ ref 를 걸 <group> 하나 — 셋을 만든다.
//   본부실에 외곽선이 **475 개**다 → 재질 475 · 지오 475 · 그룹 475.
//   그런데 값이 다른 것은 **색·굵기 조합 20 개**뿐이었다.
//   three 는 재질 인스턴스가 바뀔 때마다 유니폼을 통째로 다시 올리고
//   (WebGLRenderer 의 `material.id !== _currentMaterialId` → `WebGLUniforms.upload`),
//   렌더 목록은 material.id 로 정렬한다(painterSortStable).
//   **같은 인스턴스를 돌려 쓰면 그 업로드가 1 회로 줄어든다.**
//   그룹 475 개도 없앤다 — 우리는 geo 를 인수로 받으니 부모를 읽을 ref 가
//   애초에 필요 없다. 프로파일의 projectObject·updateMatrixWorld·multiplyMatrices
//   (합 17%) 중 상당 몫이 **아무 픽셀도 안 만드는 래퍼 그룹**이었다.
//
// [두 번째 이유 — 조용한 버그]
//   `toCreasedNormals` 는 **인덱스가 없는 지오를 복제하지 않고 제자리에서 고친다**
//   (three-stdlib 의 `geometry.index ? geometry.toNonIndexed() : geometry` →
//    그 뒤 `setAttribute("normal", …)`).
//   이 씬에는 무인덱스 지오가 585 개 있고(돌·잔해의 flatShading 용 toNonIndexed),
//   그중 50 개가 외곽선과 지오메트리를 **공유하고 있었다.**
//     ① 부모 메시의 법선이 몰래 평균화된다 — 그 50 개가 대부분 flatShading 이라
//        (셰이더가 dFdx 로 법선을 만든다) 우연히 화면에 안 드러났을 뿐이다.
//     ② 그 외곽선이 언마운트될 때 drei 의 `mesh.geometry.dispose()` 가
//        **부모의 지오메트리를 버린다.** Leva 로 잡동사니를 재생성하면 터진다.
//   여기서는 언제나 복제부터 해서 둘을 같이 막는다.

const 껍데기캐시 = new WeakMap(); // 주름캐시와 같은 방식 — 지오가 버려지면 같이 사라진다
function 껍데기지오(geo, 각도 = Math.PI) {
  let m = 껍데기캐시.get(geo);
  if (!m) {
    m = new Map();
    껍데기캐시.set(geo, m);
  }
  if (!m.has(각도)) {
    // ★ 반드시 복제부터. 인덱스가 있으면 toNonIndexed 가 새 것을 주고,
    //   없으면 clone 해야 한다 — 안 그러면 위 ①② 가 그대로 일어난다.
    const 복 = geo.index ? geo.toNonIndexed() : geo.clone();
    m.set(각도, toCreasedNormals(복, 각도)); // 복을 제자리에서 고쳐 돌려준다
  }
  return m.get(각도);
}

// 굵기를 '픽셀'로 맞추는 데 쓰는 렌더 버퍼 크기.
//   ★ Vector2 **한 개**를 모든 껍데기 재질이 유니폼 값으로 공유한다.
//     그래서 창 크기가 바뀌면 이 하나만 고쳐 쓰면 전부 따라온다.
const 껍데기화면 = new THREE.Vector2(1, 1);

// 셰이더는 drei 의 것을 그대로 옮겼다 — **화면이 달라지면 안 되니까.**
//   원리: 면을 뒤집어(BackSide) 법선 방향으로 clip 공간에서 밀어낸다.
//   size 로 나누므로 밀어내는 양이 화면 픽셀 단위가 된다(물건을 눌러도 굵기 일정).
class 껍데기셰이더 extends THREE.ShaderMaterial {
  constructor(색, 굵기) {
    super({
      side: THREE.BackSide,
      uniforms: {
        screenspace: { value: false },
        color: { value: new THREE.Color(색) },
        opacity: { value: 1 },
        thickness: { value: 굵기 },
        size: { value: 껍데기화면 }, // ★ 공유 객체
      },
      vertexShader: /* glsl */ `
        #include <common>
        #include <morphtarget_pars_vertex>
        #include <clipping_planes_pars_vertex>
        uniform float thickness;
        uniform vec2 size;
        void main() {
          #include <begin_vertex>
          #include <morphtarget_vertex>
          #include <project_vertex>
          #include <clipping_planes_vertex>
          vec4 tNormal = vec4(normal, 0.0);
          vec4 tPosition = vec4(transformed, 1.0);
          vec4 clipPosition = projectionMatrix * modelViewMatrix * tPosition;
          vec4 clipNormal   = projectionMatrix * modelViewMatrix * tNormal;
          vec2 offset = normalize(clipNormal.xy) * thickness / size * clipPosition.w * 2.0;
          clipPosition.xy += offset;
          gl_Position = clipPosition;
        }`,
      fragmentShader: /* glsl */ `
        uniform vec3 color;
        uniform float opacity;
        #include <clipping_planes_pars_fragment>
        void main(){
          #include <clipping_planes_fragment>
          gl_FragColor = vec4(color, opacity);
          #include <tonemapping_fragment>
          #include <colorspace_fragment>
        }`,
    });
  }
}

// (색, 굵기)가 같으면 재질 한 개.
//   ★ Leva 로 값을 돌리면 **키가 바뀌어 새 재질이 생긴다** → 조절은 그대로 산다.
//     대신 슬라이더를 끌면 중간값마다 하나씩 쌓이므로 상한을 두고 오래된 것을 버린다.
const 껍데기재질캐시 = new Map();
function 껍데기재질(색, 굵기) {
  const 키 = `${색}|${굵기}`;
  let m = 껍데기재질캐시.get(키);
  if (!m) {
    if (껍데기재질캐시.size > 64) {
      const 첫 = 껍데기재질캐시.keys().next().value;
      껍데기재질캐시.get(첫).dispose();
      껍데기재질캐시.delete(첫);
    }
    m = new 껍데기셰이더(색, 굵기);
    껍데기재질캐시.set(키, m);
  }
  return m;
}

