export const 카메라주인 = { 누구: null };
/** 컷신이 카메라를 넘겨받는다. 이미 다른 주인이 있으면 빼앗지 않고 false. */
export function 카메라잡기(누구) {
  if (카메라주인.누구 && 카메라주인.누구 !== 누구) return false;
  카메라주인.누구 = 누구;
  return true;
}
/** 잡았던 쪽만 놓을 수 있다(남의 것을 실수로 놓지 않게). */
export function 카메라놓기(누구) {
  if (카메라주인.누구 === 누구) 카메라주인.누구 = null;
}
