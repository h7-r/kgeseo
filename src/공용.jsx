if (typeof window !== "undefined") window.__팔뻗기 = 팔뻗기시작;

/** 지금 얼마나 뻗었나 0~1. 빠르게 나갔다 천천히 돌아온다. */
export function 팔뻗은양() {
  if (!뻗기.시작) return 0;
  const t = (performance.now() - 뻗기.시작) / 1000;
  if (t >= 뻗기.길이) return 0;
  const 나감 = 0.16; // 이 시간 안에 끝까지 나간다
  if (t < 나감) return t / 나감;
  // 남은 시간 동안 천천히 돌아온다(끝이 부드럽게)
  const u = (t - 나감) / Math.max(0.01, 뻗기.길이 - 나감);
  return 1 - u * u;
}

