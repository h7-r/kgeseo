// 개인정보보호법상 만 14세 미만은 법정대리인의 동의가 필요하다.
//   12월 범위에는 법정대리인 동의 절차가 없으므로, 여기서는 **안내하고 멈춘다.**
//   생년은 '연도'만 받는다 — 필요한 것은 나이 구간뿐이고,
//   생년월일까지 받으면 필요 없는 개인정보를 더 모으는 셈이 된다.
export const 최소나이 = 14;

export function 만나이(생년, 오늘 = new Date()) {
  if (!생년) return null;
  return 오늘.getFullYear() - Number(생년);
}

export function 나이제한걸림(생년) {
  const 나이 = 만나이(생년);
  return 나이 !== null && 나이 < 최소나이;
}

