// 화면층.js — 화면 위에 뜨는 창을 '한 번에 하나만' 열리게 하는 관리자
//
// [왜 이걸 따로 두는가]
//   PRD 가드레일 GRD-11 · CMN-035 「한 번에 하나의 모달」이 규칙이다.
//   창마다 각자 열림 상태를 들고 있으면, 소지품을 연 채로 수첩을 열 수 있게 되고
//   그러면 사용자가 **무엇을 눌러야 닫히는지 모르게 된다.**
//   그래서 "지금 열린 창"을 딱 한 칸만 두고, 새로 열면 앞의 것이 저절로 닫히게 한다.
//
// [지금은 소지품 하나뿐인데 왜 미리 만드나]
//   앞으로 수첩(N) · 힌트(H) · 설정 · 일시정지(ESC)가 줄줄이 붙는다.
//   첫 창을 만들 때 자리를 안 잡아 두면 네 번째쯤에서 전부 다시 짜야 한다.
//   지금 넣는 비용이 제일 싸다.

import { useSyncExternalStore } from "react";

// 열릴 수 있는 창 이름. 늘어나면 여기에 적는다.
export const 층 = {
  소지품: "소지품",
  수첩: "수첩", // 아직 없음
  힌트: "힌트", // 아직 없음
  일시정지: "일시정지", // 아직 없음
};

let 열린것 = null; // null = 아무것도 안 열림
const 듣는이 = new Set();
const 알리기 = () => {
  for (const f of 듣는이) f();
};

export const 화면층 = {
  값: () => 열린것,
  구독: (f) => {
    듣는이.add(f);
    return () => 듣는이.delete(f);
  },
  // 열기 — 다른 창이 열려 있으면 그건 그냥 덮인다(따로 닫을 필요 없다)
  열기(이름) {
    if (열린것 === 이름) return;
    열린것 = 이름;
    알리기();
  },
  닫기() {
    if (열린것 === null) return;
    열린것 = null;
    알리기();
  },
  // 같은 창을 다시 부르면 닫힌다 — I 키를 두 번 누르면 닫히는 동작
  토글(이름) {
    열린것 = 열린것 === 이름 ? null : 이름;
    알리기();
  },
};

// ★ 단순값만 돌려준다. 객체를 새로 만들어 돌려주면 매번 다른 값으로 보여
//   React 가 무한 렌더에 빠진다(조사시스템.js 와 같은 이유).
export const use열린층 = () =>
  useSyncExternalStore(화면층.구독, 화면층.값);

// 아무 창이나 열려 있나 — 이동 입력을 막을지 판단할 때 쓴다
export const use창열림 = () =>
  useSyncExternalStore(화면층.구독, () => 화면층.값() !== null);

// 콘솔 확인용
if (typeof window !== "undefined") window.__화면층 = 화면층;
