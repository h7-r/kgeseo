// 소지품.js — 플레이어가 지닌 물건 (USR-052 · S7-028~034)
//
// [모양을 이렇게 잡은 이유]
//   앞으로 물건은 백엔드가 정해서 내려준다. 계약(v0.3.1)에서 획득은 전부
//   `clue_acquired` 상태 변경으로 오고, 물건 자체는 **단서(Clue)** 로 표현된다.
//   그래서 여기 한 칸의 모양을 계약의 Clue 와 맞춰 뒀다 —
//   나중에 서버 응답을 그대로 꽂기만 하면 되고 화면 코드는 안 건드린다.
//
//     { id, 이름, 분류: "열쇠" | "기록", 설명, 그림 }
//
// [지켜야 하는 규칙 — PRD 가드레일]
//   · 소모 없음(GRD-01 / S7-033)  — 써도 사라지지 않는다. 그래서 '빼기'가 없다.
//   · 슬롯 상한 없음(S7-034)      — 12월 물량이 10종이라 칸 관리가 손해다.
//   · 최초 1개를 얻으면 한 번만 자동으로 열린다(S7-030) — 존재를 알리는 장치.

import { useSyncExternalStore } from "react";
import { 화면층, 층 } from "./화면층.js";

const 목록 = new Map(); // id -> 물건
let 판 = 0; // 목록이 바뀔 때마다 올린다(바뀐 걸 React 에 알리는 값)
let 자동열림했나 = false;

const 듣는이 = new Set();
const 알리기 = () => {
  판++;
  for (const f of 듣는이) f();
};

export const 소지품 = {
  판: () => 판,
  구독: (f) => {
    듣는이.add(f);
    return () => 듣는이.delete(f);
  },
  목록: () => [...목록.values()],
  찾기: (id) => 목록.get(id) || null,
  가졌나: (id) => 목록.has(id),

  /**
   * 물건을 넣는다. 이미 있으면 아무 일도 안 한다(중복 획득 방지 · S7-021)
   * @param 조용히 첫 물건이어도 창을 열지 않는다.
   *   ★ 이게 왜 필요한가 — **새로고침 복원** 때문이다.
   *     계약(v0.3.1)에서 재접속하면 `acquired_clue_ids` 를 통째로 받아 다시 넣는데,
   *     그때 자동 열림이 걸리면 접속할 때마다 소지품 창이 튀어나온다.
   *     '처음 얻었다'와 '원래 갖고 있었다'는 다른 사건이라 구분해야 한다.
   */
  넣기(물건, { 조용히 = false } = {}) {
    if (!물건?.id || 목록.has(물건.id)) return false;
    목록.set(물건.id, { 분류: "기록", ...물건 });
    // ★ 첫 물건일 때만 소지품을 한 번 열어 준다(S7-030).
    //   설명 없이 아이콘만 띄우면 못 보고 지나가는 사람이 반드시 생긴다.
    if (!자동열림했나 && !조용히) {
      자동열림했나 = true;
      화면층.열기(층.소지품);
    }
    if (조용히) 자동열림했나 = true; // 복원분은 '이미 겪은 것'으로 친다
    알리기();
    return true;
  },

  넣기여러개(배열, 옵션) {
    for (const a of 배열) 소지품.넣기(a, 옵션);
  },

  /** 개발·테스트용 초기화. 실제 플레이에서는 부르지 않는다 */
  비우기() {
    목록.clear();
    자동열림했나 = false;
    알리기();
  },
};

// ★ 단순값(판)만 구독하고 목록은 그때 꺼내 쓴다.
//   배열을 그대로 돌려주면 매번 새 배열이라 무한 렌더가 난다.
export const use소지품 = () => {
  useSyncExternalStore(소지품.구독, 소지품.판);
  return 소지품.목록();
};

// 콘솔 확인용 — __소지품.넣기({id:"X", 이름:"쪽지"}) 로 바로 넣어 볼 수 있다
if (typeof window !== "undefined") window.__소지품 = 소지품;
