// 힌트함.js — 주워 모은 '힌트'를 보관하는 곳 ([H] 로 연다)
//
// [소지품과 왜 나눠 두나]
//   소지품(I)은 **들고 다니며 쓰는 것**이다 — 열쇠·증거물처럼 어딘가에 쓰인다.
//   힌트(H)는 **다시 읽는 것**이다. 한 번 보고 나면 손에 들 이유가 없고,
//   막혔을 때 되돌아와 들여다보는 것이 전부다.
//   둘을 한 창에 섞으면 "쓸 것"과 "읽을 것"이 구분이 안 된다 — 소지품UI 가
//   열쇠와 기록을 굳이 두 줄로 나눠 놓은 것과 같은 이유다.
//
// [보관하면 실물은 어떻게 되나]
//   힌트함에 들어가는 순간 손에서 사라진다. 적어 두었으니 종이는 필요 없다.
//   버리고 싶으면 [E] — 그건 바닥에 떨어져 다시 주울 수 있다(힌트종이.js).

import { useSyncExternalStore } from "react";

const 모은것 = []; // { id, 이름, 설명, 그림, 얻은때 }
let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

/** 이미 가진 힌트인가. */
export const 힌트있나 = (id) => 모은것.some((h) => h.id === id);
/** 지금 모은 것 — 읽기 전용으로만 쓴다. */
export const 힌트목록 = () => 모은것;
/** 몇 개 모았나 — 버튼 뱃지에 쓴다. */
export const 힌트수 = () => 모은것.length;

/**
 * 힌트를 보관한다.
 * @param 힌트 { id, 이름, 설명, 그림 } — 그림은 data URL(캔버스에서 뽑은 것)
 * @returns true 면 새로 들어갔다. 이미 있으면 false.
 */
export function 힌트넣기(힌트) {
  if (!힌트?.id || 힌트있나(힌트.id)) return false;
  모은것.push({ ...힌트, 얻은때: Date.now() });
  알리기();
  return true;
}

/**
 * 힌트함에서 뺀다([E]).
 * ★ **지우는 게 아니라 도로 내놓는 것**이다. 실물 쪽지가 바닥에 다시 떨어진다
 *   (부르는 쪽이 힌트종이.종이도로놓기 를 같이 부른다).
 *   영영 지워 버리면 잘못 누른 사람이 되돌릴 길이 없다 — 이 게임은 동전도
 *   관창도 쪽지도 전부 '버리면 바닥에 남는' 세계다(GRD-01 되돌릴 수 있음).
 * @returns 뺀 힌트. 없으면 null.
 */
export function 힌트빼기(id) {
  const i = 모은것.findIndex((h) => h.id === id);
  if (i < 0) return null;
  const [뺀것] = 모은것.splice(i, 1);
  알리기();
  return 뺀것;
}

// ── [H] 를 누른 순간 화면 왼쪽 표시가 한 번 반짝인다 ──────────
//   창이 열리는 것만으로는 "무엇이 열렸나"가 안 읽힌다. 왼쪽 표시가 같이
//   깜빡여야 **저기가 힌트함이구나** 가 눈에 박힌다.
let 반짝때 = 0;
export const 힌트반짝때 = () => 반짝때;
export function 힌트반짝() {
  반짝때 = performance.now();
  알리기();
}

/** 개발·테스트용 */
export function 힌트비우기() {
  모은것.length = 0;
  알리기();
}

// ★ 판(숫자)만 구독한다. 배열을 그대로 돌려주면 매번 새 값으로 보여
//   리액트가 무한 렌더에 빠진다(화면층.js 와 같은 이유).
export const use힌트함 = () => {
  useSyncExternalStore(구독, () => 판);
  return 모은것;
};

if (typeof window !== "undefined")
  window.__힌트함 = { 모은것, 힌트넣기, 힌트비우기 };
