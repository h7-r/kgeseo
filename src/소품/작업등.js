/** 바닥이나 분기함에서 집어 든다(E). */
export function 작업등집기() {
  if (상태.곳 === "손") return false;
  if (손이찼나()) return false;
  const 뽑는중 = 분기함칸.includes(상태.곳);
  상태.곳 = "손";
  소리재생(뽑는중 ? "박스놓기" : "박스들기", { 볼륨: 0.85 });
  알리기();
  return true;
}

/**
 * 분기함에 꽂는다(E). 들고 있지 않으면 아무 일도 없다.
 * 꽂는 순간 그 칸의 표식을 **본 것으로** 적어 둔다 — 한 번 읽었으면
 * 다시 꽂으러 오게 만들 이유가 없다(왕복은 한 번이면 충분하다).
 */
export function 작업등꽂기(칸) {
  if (상태.곳 !== "손") return false;
  if (!분기함칸.includes(칸)) return false;
  상태.곳 = 칸;
  if (!상태.본표식.includes(칸)) 상태.본표식 = [...상태.본표식, 칸];
  소리재생("박스놓기", { 볼륨: 0.95 });
  알리기();
  return true;
}

/**
 * 바닥에 내려놓는다(E) — **아무 데나** 둘 수 있다.
 * @param 자리 [x, y, z] 놓을 곳. 안 주면 있던 자리에 그대로 둔다.
 *
 * [왜 자리를 받나]
 *   처음에는 처음 굴러다니던 그 한 곳에서만 놓을 수 있었다. 그러면 램프를
 *   들고 복도 반대쪽까지 갔다가 동전을 주우려면 **55 유닛을 되돌아와야** 했다.
 *   그건 퍼즐이 아니라 벌이다. 보고 있는 바닥에 그냥 내려놓게 한다.
 */
export function 작업등놓기(자리 = null) {
  if (상태.곳 !== "손") return false;
  상태.곳 = "바닥";
  if (자리) 상태.바닥자리 = [자리[0], 자리[1], 자리[2]];
  소리재생("박스놓기", { 볼륨: 0.8 });
  알리기();
  return true;
}

