export function 선집기(이름) {
  if (!선모양[이름]) return false;
  if (상태.쥔선) return false;
  if (상태.곳 === "손" || 손이찼나()) return false; // 한 손 규칙
  for (const k of ["원", "사", "삼"])
    if (상태.꽂힌선[k] === 이름) 상태.꽂힌선 = { ...상태.꽂힌선, [k]: null };
  상태.쥔선 = 이름;
  소리재생("박스들기", { 볼륨: 0.7 });
  알리기();
  return true;
}

/** 손에 쥔 가닥을 놓는다 — 제자리(늘어진 상태)로 돌아간다 */
export function 선놓기() {
  if (!상태.쥔선) return false;
  상태.쥔선 = null;
  소리재생("박스놓기", { 볼륨: 0.6 });
  알리기();
  return true;
}

let _배선타이머 = null;

/**
 * 쥔 가닥을 꽂는 자리에 꽂는다.
 *
 * [★ 모양이 안 맞아도 **꽂히기는 한다**]
 *   막아 버리면 「왜 안 되지」가 되고 규칙도 안 배운다. 꽂히고 → **빠지직 튀고
 *   도로 빠진다.** 그러면 「끝 모양을 봐야 하는구나」가 그 자리에서 읽힌다.
 */
export function 선꽂기(자리) {
  const 이름 = 상태.쥔선;
  if (!이름) return false;
  if (!선모양[자리]) return false;
  if (상태.꽂힌선[자리]) return false;
  상태.쥔선 = null;
  상태.꽂힌선 = { ...상태.꽂힌선, [자리]: 이름 };
  알리기();
  if (이름 === 자리) {
    소리재생("버튼", { 볼륨: 0.9 });
    return true;
  }
  소리재생("잠김문", { 볼륨: 0.9 });
  if (_배선타이머) clearTimeout(_배선타이머);
  _배선타이머 = setTimeout(() => {
    _배선타이머 = null;
    if (상태.꽂힌선[자리] !== 이름) return;
    상태.꽂힌선 = { ...상태.꽂힌선, [자리]: null };
    상태.배선튄때 = performance.now() / 1000;
    소리재생("잠김문", { 볼륨: 1 });
    알리기();
  }, 600);
  return true;
}

// ── ⟦분리수거 퍼즐⟧ ─────────────────────────────────────
export const 든쓰레기 = () => 상태.든쓰레기;
export const 쓰레기곳 = (id) =>
  상태.든쓰레기 === id ? "손" : 상태.쓰레기[id] ?? "바닥";
export const 쓰레기튄때 = () => 상태.쓰레기튄때;
export const 튄통 = () => 상태.튄통;
/** 이 통에 제대로 들어간 수 */
export const 통에든수 = (통) =>
  쓰레기목록.filter((t) => 상태.쓰레기[t.id] === 통).length;
export const 분리수거끝났나 = () =>
  쓰레기목록.every((t) => 상태.쓰레기[t.id] === t.종류);

/** 바닥의 쓰레기를 줍는다 — 비상 전원이 들어온 뒤에만(어둠 속에선 안 보인다) */
export function 쓰레기줍기(id) {
  if (!상태.전원 || 분리수거끝났나()) return false;
  if (상태.쓰레기[id] !== "바닥") return false;
  if (상태.곳 === "손" || 손이찼나()) return false; // 한 손 규칙
  상태.든쓰레기 = id;
  소리재생("박스들기", { 볼륨: 0.6 });
  알리기();
  return true;
}

/** 든 쓰레기를 제자리 바닥에 도로 둔다([F]) */
export function 쓰레기놓기() {
  if (!상태.든쓰레기) return false;
  상태.든쓰레기 = null;
  소리재생("박스놓기", { 볼륨: 0.6 });
  알리기();
  return true;
}

/**
 * 통에 버린다.
 * [★ 틀려도 **들어가기는 한다**]  배선 퍼즐과 같은 원칙이다. 막아 버리면
 *   「왜 안 되지」가 되고 규칙을 안 배운다. 들어갔다가 **덜컹 튀어나와**
 *   제자리 바닥으로 돌아간다 — 「이건 여기가 아니구나」가 그 자리에서 읽힌다.
 */
export function 쓰레기버리기(통) {
  const id = 상태.든쓰레기;
  if (!id || !통이름[통]) return false;
  const 것 = 쓰레기목록.find((t) => t.id === id);
  상태.든쓰레기 = null;
  if (것.종류 !== 통) {
    상태.쓰레기튄때 = performance.now() / 1000;
    상태.튄통 = 통;
    소리재생("잠김문", { 볼륨: 0.9 });
    알리기();
    return false;
  }
  상태.쓰레기 = { ...상태.쓰레기, [id]: 통 };
  소리재생("박스놓기", { 볼륨: 0.9 });
  // 이 통 몫을 다 채웠다 — 그 통의 선으로 전류가 흐르기 시작한다
  if (통완료(통)) {
    상태.흐른때[통] = performance.now() / 1000;
    소리재생("버튼", { 볼륨: 1 });
  }
  알리기();
  return true;
}

/** 이 통의 몫을 다 채웠나 — 그 통의 전선에 전류가 흐른다 */
export const 통완료 = (통) =>
  쓰레기목록.filter((t) => t.종류 === 통).every((t) => 상태.쓰레기[t.id] === 통);
/** 전류가 흐르기 시작한 시각(초) — 앞머리가 선을 타고 가는 연출에 쓴다 */
export const 흐른때 = (통) => 상태.흐른때[통];
/** 두 통 다 흐른다 — 그림 액자에 전기가 들어왔다 */
export const 그림전원 = () => 통완료("일반") && 통완료("플라");

// ── ⟦그림 퍼즐⟧ 객차 조명 시험반 ───────────────────────────
export const 창스위치 = (i) => 상태.창스위치[i];
/** "100110" 처럼 — 켬 = 1. 그림 속 창의 불도 이 값을 그대로 따른다 */
export const 창스위치키 = () => 상태.창스위치.map((v) => (v ? "1" : "0")).join("");
/**
 * 시험반 스위치 하나를 젖힌다 — 그 창의 불이 켜지거나 꺼진다. 그림에 전기가 와야(두 통 다) 산다.
 * ★ 사람 있는 창만 켜지고 빈 창이 다 꺼지는 **그 순간** 완전 전원이 들어온다 — 따로 확인 버튼이 없다.
 *   맞으면 스위치가 잠긴다(다시 끄면 복도가 도로 꺼지는 건 벌이지 퍼즐이 아니다).
 */
export function 창스위치토글(i) {
  if (!그림전원() || 상태.완전전원) return false;
  const 새 = [...상태.창스위치];
  새[i] = !새[i];
  상태.창스위치 = 새;
  소리재생("버튼", { 볼륨: 0.55 });
  if (창스위치키() === 막차사람) {
    상태.완전전원 = true;
    소리재생("박스놓기", { 볼륨: 1 });
  }
  알리기();
  return true;
}

/** 처음부터 다시(개발용) */
export function 작업등되돌리기() {
  상태.곳 = "바닥";
  상태.본표식 = [];
  상태.전원 = false;
  상태.완전전원 = false;
  상태.바닥자리 = null;
  상태.끝문해제 = false;
  상태.쥔선 = null;
  상태.꽂힌선 = { 원: null, 사: null, 삼: null };
  상태.배선튄때 = -99;
  for (const t of 쓰레기목록) 상태.쓰레기[t.id] = "바닥";
  상태.쓰레기 = { ...상태.쓰레기 };
  상태.든쓰레기 = null;
  상태.쓰레기튄때 = -99;
  상태.튄통 = null;
  상태.창스위치 = 처음불배열();
  상태.흐른때 = { 일반: -99, 플라: -99 };
  if (_배선타이머) {
    clearTimeout(_배선타이머);
    _배선타이머 = null;
  }
  알리기();
}

