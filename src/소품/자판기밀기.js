// 자판기밀기.js — 소화전 밸브가 돌면 음료 자판기가 옆으로 밀려난다(비밀문)
//
// [무엇을 담나]
//   밀린 정도(0~1) 하나. 매 프레임 바뀌는 값이라 **리액트 state 로 두면 안 된다** —
//   복도 전체가 초당 60번 다시 그려진다. 그래서 모듈 바깥 상자에 둔다
//   (같은 이유로 비밀 통로도 App.jsx 의 `통로` 상자를 쓴다).
//
// [두 가지를 서로 다른 방법으로 먹인다]
//   ① 자판기 자체 — 매 프레임 그룹 position 을 직접 만진다(다시 그리지 않는다).
//   ② 소화전 밑 배전관 — 길이가 늘어야 하니 **지오를 다시 떠야** 한다.
//      그건 값이 싸지 않아서, 0.08 유닛 칸으로 **뚝뚝 끊어** 알린다.
//      끊긴 걸 눈으로 알아채긴 어렵다(관은 벽에 붙어 있고 끝만 움직인다).
import { useSyncExternalStore } from "react";

let 진행 = 0; // 0 = 제자리, 1 = 다 밀렸다
let 거리 = 0; // 다 밀렸을 때 z 로 얼마나 가나
let 칸값 = 0; // 관에게 알려 줄 '뚝뚝 끊은' 밀림
const 칸크기 = 0.08;

let 판 = 0;
const 듣는이 = new Set();
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};

// 0→1 을 **부드럽게** 바꿔 준다(느리게 떠나 느리게 멈춘다).
//   ★ 진행 자체를 지수 감쇠로 굴리면 끝이 한없이 늘어져 「시간」 값이
//     거짓이 된다(2.2 로 적어 두고 3.4초가 걸렸다). 진행은 **시간대로**
//     선형으로 올리고, 부드러움은 읽을 때 입힌다.
const 매끈 = (t) => t * t * (3 - 2 * t);

// ── 억지로 꾹 밀리는 느낌 ────────────────────────────────
// [왜 매끈하면 안 되나]
//   매끈하게 흐르면 **저절로 미끄러지는** 물건이 된다. 무거운 자판기를
//   억지로 밀어 옮기는 것이라, 한 번 꾹 밀고 → 멈칫 → 또 꾹 밀어야 한다.
// [어떻게]
//   구간을 여러 칸으로 자르고, 각 칸의 **앞부분에서 확 밀고 뒤는 멈춘다.**
//   먼지와 화면 떨림도 이 칸이 바뀌는 순간에 맞춰 터뜨린다(자판기연출.jsx).
// ★ 멈칫이 크면 **무게감이 아니라 '렉'으로 읽힌다.** 7번(멈춤 51%) → 5번(34%)
//   → 지금은 **세 번, 각 칸의 앞 83% 동안 미는** 정도만 남겼다.
//   거의 이어서 흐르되 세 번 '툭' 하고 힘이 실리는 느낌만 준다.
const 밀칸수 = 3; // 몇 번에 걸쳐 힘을 주나
export const 칸번호 = (t) => Math.min(밀칸수 - 1, Math.floor(t * 밀칸수));
const 억지로 = (t) => {
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  const i = 칸번호(t);
  const u = t * 밀칸수 - i; // 이 칸 안에서의 진행 0~1
  const 급 = Math.min(1, u * 1.2); // 앞 83% 동안 밀고 아주 살짝만 멈칫
  return (i + 매끈(급)) / 밀칸수;
};

/** 지금 밀린 거리(연속) — 자판기 그룹이 매 프레임 쓴다 */
export const 밀림 = () => 억지로(진행) * 거리;
/** 관이 쓰는 밀림(칸으로 끊어져 있다) */
export const 관밀림 = () => 칸값;
export const 밀림진행 = () => 진행;

/**
 * 한 프레임 굴린다.
 * @param 열림  1 = 밸브가 돌았다(밀려야 한다) · 0 = 제자리
 * @param dt    프레임 간격(초)
 * @param 시간  다 미는 데 걸리는 시간(초)
 * @param 목표  다 밀렸을 때의 z 이동량
 */
export function 밀기진행(열림, dt, 시간, 목표) {
  거리 = 목표;
  // **시간대로** 굴린다 — 「시간」 초에 정확히 끝난다(0 → 1 선형, 읽을 때 매끈).
  const 걸음 = dt / Math.max(0.1, 시간);
  진행 += (열림 ? 1 : -1) * 걸음;
  if (진행 > 1) 진행 = 1;
  if (진행 < 0) 진행 = 0;
  const 새칸 = Math.round(밀림() / 칸크기) * 칸크기;
  if (새칸 !== 칸값) {
    칸값 = 새칸;
    알리기();
  }
  return 진행;
}

// ── 연출(컷신) 중인가 ───────────────────────────────────
// [왜 store 에 두나]
//   연출 중에는 **걷기·마우스 조작을 멈춰야** 한다. 그 판단은 App 껍데기가
//   하는데(active), 연출을 돌리는 건 씬 안의 컴포넌트다. 둘 사이를 여기서 잇는다.
let 연출 = false;
export const 연출중 = () => 연출;
// ── 컷신을 **이미 봤나** ─────────────────────────────────
// [왜 모듈에 두나]
//   전에는 자판기연출.jsx 가 `옛밸브` 라는 **컴포넌트 ref** 로 "밸브가 막 돌아간
//   순간"을 잡았다. 그런데 기차에 탔다 내리면 역 씬이 통째로 다시 마운트되면서
//   그 ref 가 false 로 되돌아간다. 밸브는 모듈 값이라 여전히 열려 있으니
//   **올라가는 모서리로 착각해 컷신이 다시 돌았다** — 내리자마자 화면이 자판기로
//   끌려가고, 열리는 소리가 또 나고, 다시 문 앞으로 돌아오던 그 증상이다.
//   한 번 봤다는 사실은 씬보다 오래 살아야 하므로 여기에 둔다.
let 봤나 = false;
export const 연출봤나 = () => 봤나;
/** @param v true = 봤다(다시 안 돈다) · false = 되돌렸다(다음에 열리면 다시 돈다) */
export const 연출봤다치기 = (v = true) => {
  봤나 = !!v;
};
// ── 지금 돌려 보기 ──
//   밸브는 배전반 회로가 다 살아야 돌아간다. 연출만 손보는 동안 퍼즐을 매번
//   푸는 건 말이 안 되니, **밸브가 돌아간 척** 하는 스위치를 둔다(Leva 버튼).
let 열림흉내 = false;
export const 열림흉내내나 = () => 열림흉내;
export function 연출강제() {
  열림흉내 = true;
  알리기();
}
export function 연출시작() {
  if (연출) return false;
  연출 = true;
  알리기();
  return true;
}
export function 연출끝() {
  if (!연출) return;
  연출 = false;
  알리기();
}
/** App 껍데기가 이걸 구독해 연출 동안 조작을 멈춘다(시작·끝 두 번만 다시 그린다) */
export const use연출 = () => {
  useSyncExternalStore(구독, () => 판);
  return 연출;
};

/**
 * 진행도를 **직접** 정한다(컷신용).
 *   ★ 컷신은 dt 를 쌓아 굴리면 안 된다. 카메라가 순간이동하면 구역 최적화가
 *     방·복도를 새로 올려 프레임이 뚝 끊기고, dt 를 묶어 둔 만큼(0.05)
 *     연출이 제 시간보다 **길어진다**(2.2초로 적어 두고 3.9초가 걸렸다).
 *     그래서 컷신은 벽시계 시간으로 진행도를 재어 여기에 넣는다.
 */
export function 밀기설정(값, 목표) {
  거리 = 목표;
  진행 = 값 < 0 ? 0 : 값 > 1 ? 1 : 값;
  const 새칸 = Math.round(밀림() / 칸크기) * 칸크기;
  if (새칸 !== 칸값) {
    칸값 = 새칸;
    알리기();
  }
  return 진행;
}

/** 개발·시험용 */
export function 밀기초기화() {
  진행 = 0;
  칸값 = 0;
  봤나 = false;
  연출 = false;
  열림흉내 = false;
  알리기();
}

// 관 쪽만 구독한다 — 씬(복도 전체)은 이 값이 바뀌어도 다시 그리지 않는다.
export const use관밀림 = () => {
  useSyncExternalStore(구독, () => 판);
  return 칸값;
};

if (typeof window !== "undefined")
  window.__자판기밀기 = {
    밀림, 관밀림, 밀림진행, 밀기설정, 밀기초기화, 칸번호,
    연출중, 연출시작, 연출끝, 연출강제, 열림흉내내나,
  };
