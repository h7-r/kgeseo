// 동전상태.js — 자판기 동전(토큰)의 '지금 상태'와 규칙.
//
// [무엇을 담나]
//   각 동전의 위치와, 지금 손에 든 동전. 매 프레임 안 바뀌고 '집고/넣는
//   사건'에만 바뀌므로 가벼운 외부 store 로 둔다(자판기상태와 같은 방식).
//
//   위치: "바닥"  — 바닥에 놓여 있음(주울 수 있다)
//         "손"    — 지금 들고 있음(카메라 앞에 따라온다)
//         "소비"  — 자판기에 제대로 넣어져 사라짐
//         "반환:음료" / "반환:커피" — 잘못 넣어 그 자판기 반환구로 도로 나옴
//
// [규칙 — 핵심]
//   캔 그림 동전 = 음료 자판기에만, 종이컵 그림 동전 = 커피 자판기에만 들어간다.
//   틀리게 넣으면 그 자판기 반환구로 도로 나온다(다시 주울 수 있다).

import { useSyncExternalStore } from "react";
import { 돈넣기 } from "./자판기상태.js";
import { 소리재생 } from "../소리.js";
// 전용 동전 효과음이 아직 없어 금속성 소리(자물쇠)를 빌려 쓴다 — 나중에 교체 가능.

// 동전 종류 → 들어갈 수 있는 자판기 id
const 맞는자판기 = { 캔: "음료", 종이컵: "커피" };

const 상태 = {
  위치: { 캔: "바닥", 종이컵: "바닥" },
  든것: null, // "캔" | "종이컵" | null
  넣는중: null, // { 종류, id, 결과, 슬롯:[x,y,z], t0 } — 투입 모션 재생 중
  놓인자리: { 캔: null, 종이컵: null }, // 내려놓은 월드 좌표(null 이면 기본 자리)
  놓은때: { 캔: 0, 종이컵: 0 }, // 내려놓은 시각(ms) — 낙하·반동 연출의 시작점
};

let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

export function 든동전() {
  return 상태.든것;
}
export function 동전위치(종류) {
  return 상태.위치[종류];
}
export function 넣는중() {
  return 상태.넣는중;
}
export function 놓인위치(종류) {
  return 상태.놓인자리[종류];
}
/** 이 동전을 마지막으로 내려놓은 시각(ms). 0 이면 낙하 연출 없음(처음부터 바닥). */
export function 놓은때(종류) {
  return 상태.놓은때[종류];
}

// ── 자판기 반환구(월드 좌표) ────────────────────────────────
//   잘못 넣은 동전은 그 자판기의 '실제 반환구멍' 앞에서 나와야 한다.
//   자판기(결제부)가 자기 반환구멍의 월드 좌표를 여기 등록해 두고,
//   화면 쪽은 반환 상태일 때 이 자리에서 동전을 그린다(없으면 Leva 기본 자리).
const 반환자리 = { 음료: null, 커피: null };
export function 반환구등록(자판기id, 자리) {
  반환자리[자판기id] = 자리;
}
export function 반환구자리(자판기id) {
  return 반환자리[자판기id];
}
// 반환구 '앞쪽' 착지점 — 동전이 구멍에서 나와 자판기보다 조금 앞 바닥에 떨어진다.
const 반환앞 = { 음료: null, 커피: null };
export function 반환앞등록(자판기id, 자리) {
  반환앞[자판기id] = 자리;
}
export function 반환앞자리(자판기id) {
  return 반환앞[자판기id];
}

/** 바닥/반환구의 동전을 줍는다(E). 이미 뭔가 들고 있거나 넣는 중이면 무시. */
export function 줍기(종류) {
  if (상태.든것 || 상태.넣는중) return false; // 한 번에 하나만
  const 위 = 상태.위치[종류];
  if (위 === "손" || 위 === "소비") return false;
  상태.위치[종류] = "손";
  상태.든것 = 종류;
  소리재생("자물쇠다이얼", { 볼륨: 0.7 }); // 동전을 집어 드는 금속음
  알리기();
  return true;
}

/**
 * 든 동전을 내려놓는다(E, 투입구 아닌 곳).
 * @param 자리 [x,y,z] — 겨냥한 바닥 자리(본부실 물건처럼). 없으면 원래 자리로.
 */
export function 내려놓기(자리 = null) {
  if (!상태.든것 || 상태.넣는중) return false;
  const 종류 = 상태.든것;
  상태.위치[종류] = "바닥";
  상태.놓인자리[종류] = 자리 ? [자리[0], 자리[1], 자리[2]] : null;
  상태.놓은때[종류] = performance.now(); // 지금부터 떨어져 눕는 연출을 시작
  상태.든것 = null;
  소리재생("자물쇠다이얼", { 볼륨: 0.9 }); // 동전을 바닥에 떨구는 금속음
  알리기();
  return true;
}

/**
 * 자판기 투입구에 E. 바로 넣지 않고 '투입 모션'을 시작한다(든것→넣는중).
 * 모션이 끝나면 넣기완료()가 결과를 확정한다:
 *   맞으면 자판기 안으로 사라지고 불이 켜짐(성공), 틀리면 반환구로 나옴(반환).
 */
export function 넣기시도(자판기id, 슬롯 = null) {
  const 든 = 상태.든것;
  if (!든 || 상태.넣는중) return null;
  const 결과 = 맞는자판기[든] === 자판기id ? "성공" : "반환";
  // 슬롯 = 투입구 월드 좌표. 동전이 여기로 날아가 들어간다.
  상태.넣는중 = { 종류: 든, id: 자판기id, 결과, 슬롯, t0: 0 };
  상태.든것 = null;
  소리재생("자물쇠다이얼", { 볼륨: 0.7 }); // 투입구로 동전이 들어가는 소리
  알리기();
  return 결과;
}

/** 투입 모션이 끝나면 호출 — 결과를 확정한다. */
export function 넣기완료() {
  const n = 상태.넣는중;
  if (!n) return;
  if (n.결과 === "성공") {
    상태.위치[n.종류] = "소비"; // 자판기 안으로
    소리재생("자물쇠열림", { 볼륨: 0.9 }); // 동전이 기계 안으로 떨어져 받아들여지는 소리
    돈넣기(n.id); // 버튼 전체 점등(불 연출)
  } else {
    상태.위치[n.종류] = "반환:" + n.id; // 반환구로 도로 나옴
    상태.놓은때[n.종류] = performance.now(); // 반환구에서 떨어지며 눕는 연출
    소리재생("자물쇠다이얼", { 볼륨: 0.9 }); // 반환구로 튕겨 나오는 금속음
  }
  상태.넣는중 = null;
  알리기();
}

/** 개발·테스트용 초기화 */
export function 동전초기화() {
  상태.위치 = { 캔: "바닥", 종이컵: "바닥" };
  상태.든것 = null;
  상태.넣는중 = null;
  상태.놓인자리 = { 캔: null, 종이컵: null };
  상태.놓은때 = { 캔: 0, 종이컵: 0 };
  알리기();
}

// 값(판)만 구독하고 상태는 그때 꺼내 쓴다(배열/객체를 돌려주면 무한 렌더).
export const use동전 = () => {
  useSyncExternalStore(구독, () => 판);
  return 판;
};

if (typeof window !== "undefined")
  window.__동전 = { 상태, 줍기, 넣기시도, 동전초기화 };
