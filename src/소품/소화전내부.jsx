// 소화전내부.jsx — 문을 열면 보이는 옥내소화전함 속
//
// [무엇을 담는가] 실물 옥내소화전함 그대로다.
//   위 칸  : 경종(종) · 발신기(누름 버튼) · 위치표시등 · 스피커 구멍
//   아래 칸: 개폐 밸브(빨간 핸들) · 접어 넣은 소방호스 · 노즐(관창)
//
// [호스를 왜 따로 빼 두나]
//   나중에 반대편 고압 밸브에 이 호스를 이어 붙일 계획이다. 그때 호스만
//   꺼내 쓸 수 있어야 하므로 지오메트리를 만드는 함수를 따로 내보낸다.
//   함 안에 그리는 부분과 밖으로 끌어내는 부분이 **같은 모양**이라야
//   "그 호스가 그대로 나왔다"로 읽힌다.
//
// [축]
//   함은 z 가 가로, y 가 세로, x 가 깊이다. 앞면은 d(방향) 쪽.
//   여기 좌표는 전부 '함 한가운데'를 0 으로 잡은 로컬 좌표다.

import { useMemo, useEffect } from "react";
import * as THREE from "three";
import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { TOON_GRADIENT, 만화선, 색밝기, makeRandom } from "../공용.jsx";

const 툰 = (색, 밝 = 1) => (
  <meshToonMaterial color={색밝기(색, 밝)} gradientMap={TOON_GRADIENT} />
);

// ── 접어 넣은 소방호스 ──────────────────────────────────────
// 실물은 납작한 천 호스를 지그재그로 접어 걸어 둔다. 그래서 **아래로 늘어진
// 여러 가닥**으로 보인다. 굵은 관 하나를 그리면 호스가 아니라 배관이 된다.
//   가닥마다 길이·굵기·앞뒤 자리를 조금씩 흔들어야 '접어 넣은 천'이 된다.
export function 호스지오({
  폭 = 1.0, // 걸린 가로 폭
  높이 = 0.9, // 늘어진 길이
  깊이 = 0.16, // 앞뒤로 겹쳐 걸린 두께
  가닥 = 16,
  seed = 7,
} = {}) {
  const r = makeRandom(seed);
  const 것 = [];
  const 칸 = 폭 / Math.max(1, 가닥 - 1);
  for (let i = 0; i < 가닥; i++) {
    const u = 가닥 === 1 ? 0.5 : i / (가닥 - 1);
    const z = (u - 0.5) * 폭;
    // 가운데가 길고 양끝이 짧다 — 접어 걸면 자연히 그렇게 된다
    const 길이 = 높이 * (0.62 + 0.38 * Math.sin(u * Math.PI)) * (0.88 + r() * 0.24);
    // ★ 소방호스는 **납작한 천**이다. 넓은 면이 앞을 봐야 사진처럼 빽빽해 보인다.
    //   전에는 앞뒤로 두껍고 좌우로 얇아서, 정면에서 보면 가는 막대 여러 개였다.
    const 리본폭 = 칸 * (0.72 + r() * 0.12); // 좌우(보이는 폭)
    const 리본두께 = 0.022 + r() * 0.012; // 앞뒤
    const 앞뒤 = (r() - 0.5) * 깊이;
    // 한 가닥 = 위에서 아래로 내려오다 끝이 살짝 도로 말린다
    const 마디 = 4;
    for (let k = 0; k < 마디; k++) {
      const t0 = k / 마디;
      const t1 = (k + 1) / 마디;
      const h = 길이 * (t1 - t0);
      const g = new THREE.BoxGeometry(리본두께, h, 리본폭);
      // 아래로 갈수록 살짝 흔들린다(천이라 반듯하지 않다)
      const 흔들 = Math.sin(t0 * 3.1 + i) * 0.018;
      g.translate(앞뒤 + 흔들, -길이 * ((t0 + t1) / 2), z + 흔들 * 0.35);
      것.push(g);
    }
    // 끝단 커플링 — 사진처럼 몇 가닥 끝에 금속 고리가 보인다
    if (i % 4 === 1) {
      const c = new THREE.CylinderGeometry(리본폭 * 0.42, 리본폭 * 0.42, 0.07, 8);
      c.translate(앞뒤, -길이 - 0.03, z);
      것.push(c);
    }
    // 접힌 꼭대기 — 걸이 막대에 걸쳐 넘어간 부분.
    //   ★ 고리 면은 **막대와 직각**이라야 한다. 막대가 z 로 놓였으니 고리는 x-y 평면.
    //     (Torus 기본이 x-y 평면이라 돌리면 안 된다. z 쪽으로 눕히면 고리 폭이
    //      가닥 간격보다 넓어져 위쪽이 통째로 붙어 버린다 — 천이 아니라 판이 된다)
    const 고리 = new THREE.TorusGeometry(0.042, 리본두께 * 0.8, 4, 8, Math.PI);
    고리.translate(앞뒤, 0, z);
    것.push(고리);
  }
  const 합 = mergeGeometries(것, false);
  것.forEach((g) => g.dispose());
  return 합;
}

export function 소화전내부({
  폭 = 1.4,
  높이 = 2.25,
  깊이 = 0.38,
  d = 1, // 앞면이 향하는 x 방향(+1 / −1)
  안색 = "#2b2f36",
  금속색 = "#9aa1a8",
  호스색 = "#d9d3c2",
  빨강 = "#c0392b",
  밝기 = 1,
  선,
}) {
  const 반깊 = 깊이 / 2;
  // ★ 함체 껍데기의 앞 테두리(0.08)보다 **조금 더** 안으로 들어간다.
  //   딱 맞추면 두 면이 같은 자리라 멀리서 깜빡인다(z-fighting).
  const 안폭 = 폭 - 0.24;
  const 안높 = 높이 - 0.24;
  // 위 칸(경종·발신기) 과 아래 칸(호스)을 가르는 선반 높이
  const 칸경계 = 안높 * 0.29;

  // 안쪽 상자 — 앞이 열린 어두운 통. 이게 있어야 '속이 빈 함'으로 보인다.
  const 안 = useMemo(() => {
    const 뒤 = -d * (반깊 - 0.03);
    const 것 = [
      // 뒷판
      { 크기: [0.06, 안높, 안폭], 위치: [뒤, 0, 0] },
      // 위·아래
      { 크기: [깊이 * 0.9, 0.06, 안폭], 위치: [0, 안높 / 2, 0] },
      { 크기: [깊이 * 0.9, 0.06, 안폭], 위치: [0, -안높 / 2, 0] },
      // 좌·우
      { 크기: [깊이 * 0.9, 안높, 0.06], 위치: [0, 0, -안폭 / 2] },
      { 크기: [깊이 * 0.9, 안높, 0.06], 위치: [0, 0, 안폭 / 2] },
      // 칸막이 선반
      { 크기: [깊이 * 0.85, 0.05, 안폭], 위치: [0, 안높 / 2 - 칸경계, 0] },
    ];
    const 조각 = 것.map((b) => {
      const g = new THREE.BoxGeometry(...b.크기);
      g.translate(...b.위치);
      return g;
    });
    const 합 = mergeGeometries(조각, false);
    조각.forEach((g) => g.dispose());
    return 합;
  }, [깊이, 안폭, 안높, 반깊, d, 칸경계]);

  const 호스 = useMemo(
    () =>
      호스지오({
        // 0.72 → 0.62. 양옆에 밸브·노즐이 설 자리를 낸다.
        //   (밸브가 호스에 가리지도, 함 옆벽을 뚫지도 않으려면 이만큼이 필요하다)
        폭: 안폭 * 0.62,
        높이: (안높 - 칸경계) * 0.72,
        깊이: 깊이 * 0.4,
        가닥: 13,
      }),
    [안폭, 안높, 칸경계, 깊이],
  );

  useEffect(
    () => () => {
      안?.dispose();
      호스?.dispose();
    },
    [안, 호스],
  );

  // 위 칸 부품 자리
  const 위y = 안높 / 2 - 칸경계 / 2;
  const zf = d * (반깊 - 0.06); // 부품을 놓는 앞쪽 면
  const 걸이y = 안높 / 2 - 칸경계 - 0.12; // 호스가 걸리는 높이

  return (
    <group>
      <mesh geometry={안} receiveShadow>
        {툰(안색, 밝기)}
      </mesh>

      {/* ── 위 칸 — 경종 · 발신기 · 표시등 ───────────────────
             실물은 이 셋이 나란히 붙어 있다. 빨간 원 두 개가 소화전의 얼굴이다. */}
      {/* 경종(종) — 큰 빨간 원판 */}
      <group position={[zf, 위y, -안폭 * 0.26]} rotation={[0, 0, Math.PI / 2]}>
        <mesh castShadow>
          <cylinderGeometry args={[칸경계 * 0.3, 칸경계 * 0.3, 0.05, 16]} />
          {툰(빨강, 밝기)}
          <만화선 선={선} />
        </mesh>
        <mesh position={[0, 0.03, 0]}>
          <cylinderGeometry args={[칸경계 * 0.1, 칸경계 * 0.1, 0.03, 10]} />
          {툰("#7d2820", 밝기)}
        </mesh>
      </group>
      {/* 발신기(누름 버튼) — 가운데가 눌리는 빨간 버튼 */}
      <group position={[zf, 위y, 0]} rotation={[0, 0, Math.PI / 2]}>
        <mesh castShadow>
          <cylinderGeometry args={[칸경계 * 0.19, 칸경계 * 0.21, 0.06, 14]} />
          {툰(빨강, 밝기)}
          <만화선 선={선} />
        </mesh>
        <mesh position={[0, 0.04, 0]}>
          <cylinderGeometry args={[칸경계 * 0.12, 칸경계 * 0.12, 0.03, 12]} />
          {툰("#8e2a22", 밝기)}
        </mesh>
      </group>
      {/* 위치표시등 — 불이 꺼진 상태라도 유리알은 보인다 */}
      <mesh position={[zf, 위y + 칸경계 * 0.22, 안폭 * 0.3]}>
        <sphereGeometry args={[칸경계 * 0.12, 10, 8]} />
        <meshBasicMaterial color={색밝기("#b4524a", 밝기)} toneMapped={false} />
      </mesh>
      {/* 왼쪽 끝 작은 창 — 사진에 있는 은색 표시창. 점(스피커 구멍)은 뺐다:
             그 크기에서는 구멍이 아니라 그냥 검은 점 네 개로 보인다. */}
      <mesh position={[zf, 위y, -안폭 * 0.44]} rotation={[0, 0, Math.PI / 2]}>
        <boxGeometry args={[0.03, 칸경계 * 0.42, 칸경계 * 0.16]} />
        {툰(금속색, 밝기)}
        <만화선 선={선} />
      </mesh>

      {/* ── 아래 칸 — 밸브 · 호스 · 노즐 ────────────────────── */}
      {/* 개폐 밸브 — 호스 왼쪽, 걸이보다 위.
             [자리를 어떻게 잡았나 — 세 군데를 동시에 피해야 한다]
               · 옆벽(안폭/2 = 0.58): 바퀴 바깥이 0.093 이니 중심이 0.487 을 넘으면 뚫는다.
               · 호스(리본 바깥 0.382): 중심이 0.475 보다 안쪽이면 호스에 가린다.
                 → 둘 사이 한가운데인 안폭×0.414 에 놓는다.
               · 칸막이 선반(0.422): 바퀴 꼭대기가 그보다 낮아야 한다.
                 → 걸이보다 0.15 내려 놓으면 꼭대기가 0.365 다.
             [왜 출구가 아래인가]
               출구가 위를 보면 호스를 **아래에서 위로 밀어 끼워야** 한다.
               실물은 물이 위에서 아래로 떨어지게 출구가 아래를 본다. */}
      <group position={[d * 반깊 * 0.3, 걸이y - 0.15, -안폭 * 0.414]}>
        {/* 뒤(급수관)에서 나오는 가로 관 */}
        <mesh position={[-d * 0.11, 0, 0]} rotation={[0, 0, Math.PI / 2]} castShadow>
          <cylinderGeometry args={[0.04, 0.04, 0.22, 10]} />
          {툰(금속색, 밝기)}
          <만화선 선={선} />
        </mesh>
        {/* 몸통(엘보) */}
        <mesh castShadow>
          <cylinderGeometry args={[0.05, 0.055, 0.14, 10]} />
          {툰(금속색, 밝기)}
          <만화선 선={선} />
        </mesh>
        {/* 아래로 내려가는 출구 + 커플링 — 여기에 호스가 위에서 아래로 물린다 */}
        <mesh position={[0, -0.13, 0]} castShadow>
          <cylinderGeometry args={[0.042, 0.042, 0.14, 10]} />
          {툰(금속색, 밝기)}
          <만화선 선={선} />
        </mesh>
        <mesh position={[0, -0.21, 0]} castShadow>
          <cylinderGeometry args={[0.055, 0.055, 0.06, 10]} />
          {툰("#b9a24a", 밝기)}
          <만화선 선={선} />
        </mesh>
        {/* 핸들 — 얼굴이 앞을 보게 세운다. 작게 줄여 옆벽에 안 닿는다. */}
        <group position={[0, 0.12, 0]} rotation={[0, Math.PI / 2, 0]}>
          <mesh castShadow>
            <torusGeometry args={[0.07, 0.016, 6, 14]} />
            {툰(빨강, 밝기)}
            <만화선 선={선} />
          </mesh>
          {[0, 1, 2].map((i) => (
            <mesh key={`spoke${i}`} rotation={[0, 0, (i * Math.PI) / 3]} castShadow>
              <boxGeometry args={[0.14, 0.016, 0.015]} />
              {툰(빨강, 밝기)}
            </mesh>
          ))}
          <mesh>
            <cylinderGeometry args={[0.024, 0.024, 0.045, 8]} />
            {툰(빨강, 밝기)}
          </mesh>
        </group>
      </group>

      {/* 밸브 → 호스 이음 — 출구에서 내려와 호스 뭉치로 들어간다.
             이게 없으면 밸브와 호스가 남남으로 놓인 두 물건으로 보인다. */}
      <group position={[d * 반깊 * 0.3, 걸이y - 0.455, -안폭 * 0.414]}>
        {/* 출구에서 곧게 내려오는 토막 */}
        <mesh castShadow>
          <boxGeometry args={[0.05, 0.13, 0.075]} />
          {툰(호스색, 밝기 * 0.95)}
          <만화선 선={선} />
        </mesh>
        {/* 호스 뭉치 쪽으로 꺾여 들어가는 토막 */}
        <mesh
          position={[0, -0.1, 안폭 * 0.028]}
          rotation={[-0.6, 0, 0]}
          castShadow
        >
          <boxGeometry args={[0.05, 0.16, 0.075]} />
          {툰(호스색, 밝기 * 0.95)}
          <만화선 선={선} />
        </mesh>
      </group>

      {/* 호스 — 접어 걸어 둔 천 호스. 함 속을 채우는 주인공이다. */}
      <group position={[d * 반깊 * 0.1, 걸이y, 0]}>
        <mesh geometry={호스} castShadow receiveShadow>
          {툰(호스색, 밝기 * 0.95)}
          <만화선 선={선} />
        </mesh>
        {/* 호스를 거는 가로 막대 */}
        <mesh position={[0, 0.05, 0]} rotation={[Math.PI / 2, 0, 0]}>
          {/* 걸이 막대 — 호스 폭에만 걸친다. 길면 밸브·노즐과 부딪힌다. */}
          <cylinderGeometry args={[0.022, 0.022, 안폭 * 0.66, 8]} />
          {툰(금속색, 밝기)}
        </mesh>
      </group>

      {/* 노즐(관창) — 오른쪽 끝에 **세로로** 선다.
             앞으로 눕히면 정면에서 원 하나로 보여 무엇인지 안 읽힌다.
             물 나오는 끝이 아래를 보고, 위쪽 커플링이 호스와 이어진다. */}
      <group position={[d * 반깊 * 0.24, 걸이y - 0.35, 안폭 * 0.4]}>
        {/* 위쪽 커플링 — 호스와 물리는 자리 */}
        <mesh position={[0, 0.2, 0]} castShadow>
          <cylinderGeometry args={[0.062, 0.062, 0.08, 12]} />
          {툰("#b9a24a", 밝기)}
          <만화선 선={선} />
        </mesh>
        {/* 몸통 — 위가 굵고 아래로 갈수록 가늘어진다 */}
        <mesh castShadow>
          <cylinderGeometry args={[0.058, 0.04, 0.32, 12]} />
          {툰(금속색, 밝기)}
          <만화선 선={선} />
        </mesh>
        {/* 손잡이 테 */}
        <mesh position={[0, 0.06, 0]} castShadow>
          <cylinderGeometry args={[0.05, 0.05, 0.05, 12]} />
          {툰("#b9a24a", 밝기)}
        </mesh>
        {/* 헤더 — 물 나오는 끝. 아래를 본다. */}
        <mesh position={[0, -0.2, 0]} castShadow>
          <cylinderGeometry args={[0.034, 0.046, 0.09, 12]} />
          {툰(금속색, 밝기)}
          <만화선 선={선} />
        </mesh>
        <mesh position={[0, -0.25, 0]}>
          <cylinderGeometry args={[0.024, 0.024, 0.02, 10]} />
          {툰("#15181c", 밝기)}
        </mesh>
        {/* 호스와 이어지는 짧은 천 — 위로 올라가 뭉치에 붙는다 */}
        <mesh position={[0, 0.3, -안폭 * 0.03]} rotation={[0.35, 0, 0]} castShadow>
          <boxGeometry args={[0.05, 0.16, 0.075]} />
          {툰(호스색, 밝기 * 0.95)}
          <만화선 선={선} />
        </mesh>
      </group>
    </group>
  );
}
