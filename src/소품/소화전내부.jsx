  //     "함 속 호스가 그대로 빠져나온다"로 읽힌다.
  const 호스끝ref = useRef(null);
  useEffect(() => 함끝등록(호스끝ref.current, [d, 0, 0]), [d]);
  // 호스가 이만큼이라 이보다 멀리는 못 간다(App 의 막힘 이 이 값을 본다).
  // [곧게 잰 거리로 바꿔 놓는 이유]
  //   호스는 **바닥을 찍고** 가므로 곧게 잰 거리보다 더 많이 쓴다. 게다가
  //   함 속에서 문밖으로 돌아 나오는 몫과, 눈앞에 들고 있는 몫이 늘 먼저 빠진다.
