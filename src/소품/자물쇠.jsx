export function 열림자세(t, 몸짓 = 열림몸짓) {
  const clamp01 = (x) => Math.max(0, Math.min(1, x));
  const 구간 = ([a, b]) => clamp01((t - a) / (b - a));
  const 부드럽 = (x) => 1 - Math.pow(1 - x, 3); // ease-out
  const 방출 = 부드럽(구간(몸짓.칸.방출));
  const 기울 = 부드럽(구간(몸짓.칸.기울));
  const 밀림 = 부드럽(구간(몸짓.칸.밀림));
  const 대각 = 부드럽(구간(몸짓.칸.대각));
  const 낙하 = 구간(몸짓.칸.낙하) ** 2; // 제곱 = 가속(중력감)
  return {
    방출: 방출 * 몸짓.방출거리, // 본체가 아래로 내려가는 정도
    각: -기울 * 몸짓.눕는각, // x 축 회전(음수 = 화면 쪽으로 눕는다)
    밀림: 밀림 * 몸짓.빠지는거리, // 구멍 축(+x) 으로
    위로: 대각 * 몸짓.대각위로, // 빠져나온 뒤 비스듬히 — 위로
    앞으로: 대각 * 몸짓.대각앞으로, //                    — 화면 쪽으로
    낙하: 낙하 * 몸짓.낙하거리,
    보임: t < 0.999,
  };
}

/**
 * 쇠막대(피벗)를 제자리에 못 박은 채 몸만 돌리는 자리 계산.
 *   피벗은 로컬 (0, pv, 0) 을 지나는 x 축. 그룹 원점 = 피벗월드 − Rx(각)·피벗로컬.
 *   Rx·(0, pv, 0) = (0, pv·cos, pv·sin)
 */
export function 열림자리(자세, { 좌우, 위아래, 깊이 }) {
  const pv = -위아래; // 원점 → 걸쇠 구멍 높이(로컬 y)
  const c = Math.cos(자세.각), sn = Math.sin(자세.각);
  return [
    좌우 + 자세.밀림,
    위아래 + pv - pv * c + (자세.위로 ?? 0) - 자세.낙하,
    깊이 - pv * sn + (자세.앞으로 ?? 0),
  ];
}

function 다이얼({ 지오, 재질, x, 칸, 칸수, 빠르기 = 10 }) {
  const g = useRef(null);
  const 각 = useRef(칸각도(칸, 칸수));
  useFrame((_, dt) => {
    const o = g.current;
    if (!o) return;
    const 목표 = 칸각도(칸, 칸수);
    // 가장 가까운 쪽으로 돈다(9 → 0 에서 한 바퀴 거꾸로 돌면 안 된다)
    let 차 = 목표 - 각.current;
    const 한바퀴 = Math.PI * 2;
    차 = ((차 % 한바퀴) + 한바퀴 * 1.5) % 한바퀴 - 한바퀴 / 2;
    각.current += 차 * (1 - Math.exp(-dt * 빠르기));
    o.rotation.x = 각.current;
  });
  return (
    <group ref={g} position={[x, 0, 0]}>
      <mesh geometry={지오} material={재질} castShadow />
    </group>
  );
}

