  눕는각: Math.PI / 2, // 90° — 매달린 본체가 화면 쪽으로 반듯이 눕는다
  빠지는거리: 0.55, // 구멍 축(+x)으로 밀려 나가는 거리(로컬, 크기 배수 이전)
