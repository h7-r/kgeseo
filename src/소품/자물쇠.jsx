  //   문과 **같은 id** 로 흔들린다. 잠긴 문에 [E] 를 누르면 문도 자물쇠도
  //   같이 덜컹거려서, 안 열리는 이유가 이 자물쇠라는 게 눈으로 읽힌다.
  const 자물쇠ref = useRef(null);
