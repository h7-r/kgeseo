/** 칸 k 를 정면(+z)으로 돌리는 각도
 *  ★ 부호에 주의. rotateX(φ) 는 (y,z) 를 돌려 점을 **θ−φ** 자리로 옮긴다.
 *    그래서 θ 에 있는 칸을 정면(0)에 두려면 φ = θ 다 — 빼는 게 아니라 **더한다.**
 *    처음에 음수로 뒀다가 열 칸이 전부 반대편에 섰다(시험이 잡아냈다). */
export const 칸각도 = (k, 칸수) => ((k + 0.5) / 칸수) * Math.PI * 2;

// ── 다이얼 한 칸 ───────────────────────────────────────────
// ── [E] 로 만지는 동안 카메라를 자물쇠 앞으로 당긴다 ────────
// [왜 설 자리를 좌표로 안 적나]
//   "자물쇠 앞 여기"를 좌표로 박아 두면 Leva 로 자물쇠를 옮기거나 돌릴 때마다
//   그 자리도 같이 고쳐야 하고, 조금만 틀어져도 카메라가 벽 속에 박힌다.
//   **플레이어가 이미 서 있는 쪽에서 다가가기만** 하면 둘 다 안 생긴다 —
//   거기까지 걸어온 길이니 그 사이에는 벽이 없다.
const _눈점 = new THREE.Vector3();
const _눈방향 = new THREE.Vector3();
const _눈자리 = new THREE.Vector3();
const _눈틀 = new THREE.Matrix4();
const _눈각 = new THREE.Quaternion();
// 겨냥이 "이 자물쇠가 어디 있나" 물어올 때 돌려 쓰는 그릇
const _자물쇠점 = new THREE.Vector3();

function 시점당기기({ id, 대상ref, 거리 }) {
  const { camera } = useThree();
  // 들어오기 전에 서 있던 자리·시선. 나갈 때 여기로 되돌린다.
  const 옛 = useRef(null);
  // ★ 만지는 도중에 자물쇠가 사라지면(Leva 로 껐다든지) 아무도 조작을 끝내 주지
  //   않는다. 그러면 이동이 멈춘 채로 영영 갇힌다 — 여기서 치워 준다.
  useEffect(
    () => () => {
      if (옛.current) {
        camera.position.copy(옛.current.p);
        camera.quaternion.copy(옛.current.q);
        옛.current = null;
      }
      const 상태 = 조작상태();
      if (상태 && 상태.id === id) 조작끝();
    },
    [id, camera],
  );
  useFrame((_, dt) => {
    const 상태 = 조작상태();
    const 켬 = !!상태 && 상태.id === id && 상태.단계 === "켬";
    const o = 대상ref.current;
    if (켬 && o) {
      if (!옛.current)
        옛.current = {
          p: camera.position.clone(),
          q: camera.quaternion.clone(),
        };
      o.getWorldPosition(_눈점);
      _눈방향.copy(옛.current.p).sub(_눈점);
      _눈방향.y *= 0.3; // 위에서 내려다보지 않게 눕힌다 — 다이얼이 안 읽힌다
      if (_눈방향.lengthSq() < 1e-8) _눈방향.set(0, 0, 1);
      _눈방향.normalize();
      _눈자리.copy(_눈점).addScaledVector(_눈방향, 거리);
      const k = 1 - Math.exp(-dt * 7);
      camera.position.lerp(_눈자리, k);
      _눈틀.lookAt(camera.position, _눈점, camera.up);
      _눈각.setFromRotationMatrix(_눈틀);
      camera.quaternion.slerp(_눈각, k);
      return;
    }
    if (옛.current) {
      const k = 1 - Math.exp(-dt * 9);
      camera.position.lerp(옛.current.p, k);
      camera.quaternion.slerp(옛.current.q, k);
      if (camera.position.distanceToSquared(옛.current.p) < 1e-4) {
        camera.position.copy(옛.current.p);
        camera.quaternion.copy(옛.current.q);
        옛.current = null;
        // ★ 다 돌아온 **뒤에야** 조작이 끝난다. 여기서 끝내지 않고 ESC 를 누른
        //   순간 끝내 버리면, 돌아오는 동안 이동이 되살아나 화면이 두 힘에
        //   끌려 덜덜 떤다.
        if (상태 && 상태.id === id) 조작끝();
      }
      return;
    }
    // 들어가 보지도 않았는데 "나감" 으로 남아 있으면 그대로 끝낸다(안 그러면 갇힌다)
    if (상태 && 상태.id === id && 상태.단계 === "나감") 조작끝();
  });
  return null;
}

// ── 열림 연출 자세 계산 (순수 함수) ──────────────────────────
// [왜 떼어 놨나]
//   useFrame 안에 두면 **눈으로만** 확인할 수밖에 없다. 그런데 화면으로는
//   한 프레임이 길어질 때 연출이 통째로 뛰어 버려서 중간 자세를 볼 수가 없다
//   (실제로 헤드리스에서 0.2초 만에 끝까지 가 버렸다).
//   순수 계산으로 떼어 두면 시험이 t 를 0부터 1까지 돌려 보며
//   "쇠막대가 구멍에 박힌 채 있나" 같은 걸 **수로** 확인할 수 있다.
