//   ② 걸쇠 구멍을 꿴 **쇠막대를 축으로** 앞으로 눕는다 — 꿰인 채로 돌기 때문에
//      구멍 밖으로 나가는 부분이 없다. 매달려 있던 본체(번호 다이얼)가
//      화면 쪽으로 누워서 걸쇠판을 안 때리고 지나간다.
//   ③ 다 누운 **뒤에야** 구멍 축(옆 = +x)으로 밀려 나간다.
//   ④ 빠진 뒤 떨어진다.
//
// [축이 왜 x 인가]
//   전에는 z 축으로 돌렸다(= 옆으로 넘어짐). 그러면 도는 동안 자물쇠가 구멍 선을
//   벗어나 **이미 빠져나간 부분**이 생기고, 본체가 걸쇠 쪽으로 휘둘려 부딪힌다.
//   쇠막대(= 구멍 축)를 그대로 회전축으로 삼아야 벗어나는 데가 없다.
