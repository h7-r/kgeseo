// ── 몸통 — 좌우 **두 덩이**. 가운데는 뚫려 있다 ─────────────
//   ★ 통으로 막으면 다이얼이 안 보인다. 몸통 앞면이 다이얼을 가려서,
//     앞으로 삐져나온 얇은 조각만 보인다 — 검은 막대에 네모 몇 개가 된다
//     (화면에서 정확히 그렇게 보였다).
//     실물도 가운데가 뚫려 있고 그 자리를 다이얼이 통째로 채운다.
//   ★ 상자+원기둥을 이어 붙이지 않고 윤곽을 뽑는다. 붙이면 원기둥 마구리가
//     속에 남아 주름선이 앞면에 커다란 타원을 그린다.
// 덩이 하나의 가로. ★ 몸통지오와 표식 자리가 **같은 값**을 봐야 한다 —
//   한쪽만 고치면 표식이 덩이 밖으로 나가거나 다이얼을 덮는다.
export const 덩이폭구하기 = ({ 폭, 높이, 다이얼폭 }) =>
  Math.max(높이 * 0.55, (폭 - 다이얼폭) / 2);
// 모서리를 깎은 양 = **앞면 평평한 부분이 윤곽에서 들어간 거리.**
//   앞면에 뭘 새길 때는 이만큼 안으로 들어와야 한다. 베벨 위에 얹으면
//   그 자리는 면이 뒤로 물러나 있어서 새긴 게 공중에 떠 보인다.
export const 깎구하기 = ({ 높이, 깊이, 덩이폭 }) =>
  Math.max(
    0.0005,
    Math.min(높이 * 0.09, 깊이 * 0.18, (덩이폭 - 높이 * 0.2) / 2.2),
  );

function 덩이지오({ 덩이폭, 높이, 깊이, 쪽, 옆둥글기 = 1 }) {
  // ★ 모서리를 조금 깎는다. 안 깎으면 앞뒤 면이 칼같이 잘려, 주름선이 몸통
  //   한가운데를 가로지르는 딱딱한 금으로 보인다(마감이 싸 보인다).
  //   ★ 베벨은 윤곽을 **바깥으로 부풀린다.** 그래서 깎을 만큼 미리 안으로
  //     줄여 놓아야 최종 크기가 맞는다. 안 그러면 가로·세로가 깎×2 만큼 커지고,
  //     좌우 덩이가 가운데(다이얼 자리)로 삐져나와 다이얼을 가린다.
  const 깎 = 깎구하기({ 높이, 깊이, 덩이폭 });
  const r = Math.max(0.0005, 높이 / 2 - 깎);
  const 안쪽 = 깎; // 가운데 쪽 평평한 변
  const 바깥 = 덩이폭 - 깎;
  // ★ 바깥 끝을 얼마나 둥글릴지. 1 이면 반원(맹꽁이 자물쇠 원형),
  //   0 이면 각진 네모다. 그 사이는 **모서리만 둥근 네모** — 반원과 네모를
  //   한 식으로 이어 놓아서, 값을 얼마로 주든 윤곽이 끊기지 않는다.
  //   (둥 = r 을 넣으면 위아래 곧은 변이 0 이 되어 예전 반원과 정확히 같아진다)
  const 둥 = Math.min(
    r * Math.max(0, Math.min(1, 옆둥글기)),
    Math.max(0, (바깥 - 안쪽) * 0.98),
  );
  const 중심 = Math.max(안쪽 + 0.0002, 바깥 - 둥); // 둥근 모서리의 중심 x
  const s = new THREE.Shape();
  s.moveTo(안쪽, -r);
  s.lineTo(중심, -r);
  if (둥 > 0.0002) {
    s.absarc(중심, -r + 둥, 둥, -Math.PI / 2, 0, false); // 아래 바깥 모서리
    s.lineTo(바깥, r - 둥); // 바깥 곧은 변
    s.absarc(중심, r - 둥, 둥, 0, Math.PI / 2, false); // 위 바깥 모서리
  } else {
    s.lineTo(바깥, -r);
    s.lineTo(바깥, r);
  }
  s.lineTo(안쪽, r);
  const g = new THREE.ExtrudeGeometry(s, {
    depth: Math.max(0.001, 깊이 - 깎 * 2),
    bevelEnabled: true,
    bevelThickness: 깎,
    bevelSize: 깎,
    bevelSegments: 2,
    curveSegments: 16,
  });
  g.translate(0, 0, -깊이 / 2 + 깎);
  // 왼쪽 덩이는 돌려서 만든다(거울로 뒤집으면 면이 뒤집혀 안쪽이 보인다)
  if (쪽 < 0) g.rotateY(Math.PI);
  return g;
}

function 몸통지오({ 폭, 높이, 깊이, 다이얼폭, 옆둥글기 }) {
  const 덩이폭 = 덩이폭구하기({ 폭, 높이, 다이얼폭 });
  const 조각 = [-1, 1].map((쪽) => {
    const g = 덩이지오({ 덩이폭, 높이, 깊이, 쪽, 옆둥글기 });
    g.translate((쪽 * 다이얼폭) / 2, 0, 0);
    return g;
  });
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

// ── 읽는 줄 표식 — 본체 왼쪽 덩이에 새긴 "→" ────────────────
// [왜 있나]
//   다이얼은 세 줄이 함께 보인다(위·정면·아래). 그런데 맞춰야 하는 건
//   **정면 한 줄**이다. 표식이 없으면 위 줄에 정답을 세워 놓고
//   왜 안 열리나 하게 된다. 실물 문자 자물쇠도 이 자리에 금이 새겨져 있다.
// [왼쪽에만 두는 이유]
//   양쪽에 두면 다이얼을 가운데 끼운 과녁처럼 보여서, "여기서 읽어라" 가
//   아니라 그냥 무늬가 된다. 한쪽만 있어야 가리키는 게 읽힌다.
// [앞면에 납작하게]
//   튀어나온 화살표를 붙이면 다이얼을 돌릴 때 손가락 자리를 먹고,
//   누울 때 걸쇠에도 닿는다. 앞면에 칠한 것처럼 평평한 조각으로 둔다.
function 표식지오({ 길이, 머리길이, 머리반, 꼬리반 }) {
  const s = new THREE.Shape();
  s.moveTo(0, 0); // 화살 끝 — 다이얼(오른쪽)을 가리킨다
  s.lineTo(-머리길이, 머리반);
  s.lineTo(-머리길이, 꼬리반);
  s.lineTo(-길이, 꼬리반);
  s.lineTo(-길이, -꼬리반);
  s.lineTo(-머리길이, -꼬리반);
  s.lineTo(-머리길이, -머리반);
  s.closePath();
  return new THREE.ShapeGeometry(s, 1);
}

// ── 고리 — 반원 + 두 다리 ─────────────────────────────────
function 고리지오({ 반지름, 굵기, 다리, 긴다리비 = 1, 짧은다리비 = 1 }) {
  // 토러스 0~π 는 (R,0,0) 에서 (0,R,0) 을 지나 (−R,0,0) 까지 — 위쪽 반원이다.
  const 조각 = [new THREE.TorusGeometry(반지름, 굵기, 10, 26, Math.PI)];
  for (const s of [-1, 1]) {
    // ★ 오른쪽(+) 다리를 길게 = 실물 자물쇠의 '긴(고정) 다리'.
    //   왼쪽(−)은 짧은 다리 — 비번 풀면 이쪽이 먼저 몸통에서 빠진다.
    //   위쪽 끝은 굵기 절반만큼 반원 속에 물린다(이음매 감추기).
    const L = s > 0 ? 다리 * 긴다리비 : 다리 * 짧은다리비; // 오른쪽 길게 / 왼쪽 짧게
    const c = new THREE.CylinderGeometry(굵기, 굵기, L, 12, 1);
    c.translate(s * 반지름, 굵기 / 2 - L / 2, 0);
    조각.push(c);
  }
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

// ── 걸쇠 판 한 장 ─────────────────────────────────────────
//   실물은 고리가 아니라 **구멍 뚫린 철판**이다. 두 장을 마주 물려 놓고
//   그 구멍으로 자물쇠 쇠막대가 지나간다.
//     ㄱ자 — 한쪽 날개를 문 앞면에 대고, 꺾여 나온 쪽에 큰 구멍(문쪽)
//     평판 — 날개 없이 곧은 판. 옆으로 세워 테두리에 댄다(테두리쪽)
//
//   [축] 판은 y-z 평면에 서고, **구멍 축이 x** 다. 자물쇠 쇠막대가 꼭대기에서
//     좌우(x)로 지나므로 그래야 꿰진다. 원점은 **큰 구멍 한가운데**다 —
//     거기를 쇠막대 길 위에 얹으면 끝이라 자리 잡기가 쉽다.
// 나사가 박히는 자리. ★ 판을 뚫는 식과 **같은 계산**을 쓴다 —
//   따로 적으면 판을 고칠 때 나사만 엉뚱한 데 남는다.
function 나사자리({ 판반폭, 길이, 두께, 날개, 나사수, 나사반, 나사날개 }) {
  const n = Math.max(0, Math.round(나사수));
  const 날 = 날개 > 두께;
  const 날개에 = 나사날개 ?? 날;
  const 목 = [];
  if (n === 0) return 목;
  if (날개에 && 날) {
    const x0 = -두께 / 2, x1 = 날개 - 두께 / 2;
    for (let i = 0; i < n; i++) {
      const x = x0 + (x1 - x0) * ((i + 1) / (n + 1));
      if (x - 나사반 < x0 + 두께 || x + 나사반 > x1 - 두께 * 0.5) continue;
      // 날개는 x-y 평면, 두께가 z → 나사 축도 z
      목.push({ 자리: [x, 0, -길이 + 두께 / 2], 축: "z" });
    }
  } else if (!날개에) {
    const X = 길이 - Math.max(나사반 * 1.8, 판반폭 * 0.7);
    for (let i = 0; i < n; i++) {
      const Y = n === 1 ? 0 : (i / (n - 1) - 0.5) * (판반폭 * 1.1);
      if (X - 나사반 < 판반폭 || X + 나사반 > 길이 - 두께 * 0.5) continue;
      // 판은 돌려 세워서 모양 X → −z, 두께 → x → 나사 축은 x
      목.push({ 자리: [0, Y, -X], 축: "x" });
    }
  }
  return 목;
}

// 나사 머리 — 구멍만 뚫려 있으면 '나사가 빠진 자리'로 보인다. 앞뒤로 하나씩 문다.
function 나사지오(목, 나사반, 두께) {
  if (!목.length) return null;
  const 조각 = [];
  for (const { 자리, 축 } of 목) {
    for (const s of [-1, 1]) {
      const g = new THREE.CylinderGeometry(나사반 * 1.55, 나사반 * 1.15, 나사반 * 0.9, 12, 1);
      if (축 === "x") g.rotateZ(Math.PI / 2);
      else g.rotateX(Math.PI / 2);
      const d = 두께 / 2 + 나사반 * 0.45;
      g.translate(
        자리[0] + (축 === "x" ? s * d : 0),
        자리[1],
        자리[2] + (축 === "z" ? s * d : 0),
      );
      조각.push(g);
    }
  }
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

function 걸쇠판지오({ 구멍반, 판반폭, 길이, 두께, 날개, 나사수, 나사반, 나사날개 }) {
  const n = Math.max(0, Math.round(나사수));
  const 날 = 날개 > 두께;
  // ★ 나사는 **판을 대는 면**에 박힌다.
  //   ㄱ자면 꺾인 날개에, 평판이면 구멍 없는 네모 끝에. 가운데에 뚫으면
  //   실물과 달라 보이고, 무엇보다 거기는 아무 데도 안 닿는 허공이다.
  const 날개에 = 나사날개 ?? 날;

  const 몸 = new THREE.Shape();
  몸.absarc(0, 0, 판반폭, Math.PI / 2, Math.PI * 1.5, false); // 구멍 쪽 둥근 끝
  몸.lineTo(길이, -판반폭);
  몸.lineTo(길이, 판반폭);
  몸.closePath();
  // 큰 구멍 — 쇠막대가 지나는 자리
  const 큰 = new THREE.Path();
  큰.absarc(0, 0, 구멍반, 0, Math.PI * 2, true);
  몸.holes.push(큰);
  if (!날개에 && n > 0) {
    // 평판 — 구멍 없는 네모 끝에 나란히 박는다
    const x = 길이 - Math.max(나사반 * 1.8, 판반폭 * 0.7);
    for (let i = 0; i < n; i++) {
      const y = n === 1 ? 0 : (i / (n - 1) - 0.5) * (판반폭 * 1.1);
      if (x - 나사반 < 판반폭 || x + 나사반 > 길이 - 두께 * 0.5) continue;
      const p = new THREE.Path();
      p.absarc(x, y, 나사반, 0, Math.PI * 2, true);
      몸.holes.push(p);
    }
  }
  const g = new THREE.ExtrudeGeometry(몸, {
    depth: 두께,
    bevelEnabled: false,
    curveSegments: 16,
  });
  g.translate(0, 0, -두께 / 2);
  g.rotateY(Math.PI / 2); // 모양 X → −z, 뽑은 두께 → x (구멍 축이 x 가 된다)
  const 조각 = [g];

  if (날) {
    // ㄱ자로 꺾인 날개 — 판 끝에서 옆(x)으로 나간다. 여기가 문에 닿는 면이다.
    //   이 모양은 이미 x-y 평면이고 두께가 z 라, 돌릴 필요가 없다.
    const w = new THREE.Shape();
    const x0 = -두께 / 2, x1 = 날개 - 두께 / 2;
    w.moveTo(x0, -판반폭);
    w.lineTo(x1, -판반폭);
    w.lineTo(x1, 판반폭);
    w.lineTo(x0, 판반폭);
    w.closePath();
    if (날개에 && n > 0) {
      for (let i = 0; i < n; i++) {
        const x = x0 + (x1 - x0) * ((i + 1) / (n + 1));
        if (x - 나사반 < x0 + 두께 || x + 나사반 > x1 - 두께 * 0.5) continue;
        const p = new THREE.Path();
        p.absarc(x, 0, 나사반, 0, Math.PI * 2, true);
        w.holes.push(p);
      }
    }
    const wg = new THREE.ExtrudeGeometry(w, {
      depth: 두께,
      bevelEnabled: false,
      curveSegments: 12,
    });
    wg.translate(0, 0, -길이);
    조각.push(wg);
  }
  if (조각.length === 1) return 조각[0];
  const 합 = mergeGeometries(조각, false);
  조각.forEach((x) => x.dispose());
  return 합;
}

// ── 다이얼 글자 띠 ─────────────────────────────────────────
// [왜 원기둥에 텍스처를 안 씌우고 직접 만드나]
//   원기둥의 uv 는 **축을 따라 v, 둘레를 따라 u** 로 간다. 그런데 다이얼을
//   정면에서 보면 둘레 방향이 **위아래**, 축 방향이 **좌우**다. 그대로 씌우면
//   글자가 90° 누워 버린다. 칸마다 uv 를 직접 물려 세워 놓는다.
//
//   [자리] 점(θ, x) = (x, R sinθ, R cosθ) — θ=0 이 정면(+z)이다.
function 띠지오({ 칸수, 반지름, 폭 }) {
  const p = [];
  const n = [];
  const uv = [];
  const 쪼갬 = 3; // 칸 하나를 몇 조각으로 — 많을수록 둥글다
  for (let k = 0; k < 칸수; k++) {
    for (let s = 0; s < 쪼갬; s++) {
      const t0 = (k + s / 쪼갬) / 칸수;
      const t1 = (k + (s + 1) / 쪼갬) / 칸수;
      const a0 = t0 * Math.PI * 2;
      const a1 = t1 * Math.PI * 2;
      const 점 = (a, x) => [x, 반지름 * Math.sin(a), 반지름 * Math.cos(a)];
      const 법 = (a) => [0, Math.sin(a), Math.cos(a)];
      const A = 점(a0, -폭 / 2), B = 점(a1, -폭 / 2);
      const C = 점(a1, 폭 / 2), D = 점(a0, 폭 / 2);
      // uv — u 는 좌우(축), v 는 위아래(둘레). 그래야 글자가 선다.
      const uA = [0, t0], uB = [0, t1], uC = [1, t1], uD = [1, t0];
      // ★ 감는 순서(A→C→B)에 주의. A→B→C 로 감으면 면이 **안쪽**을 봐서
      //   바깥에서 보면 통째로 잘려 나간다 — 글자가 하나도 안 보이고
      //   속심(검은 원통)만 남는다. 화면에서 정확히 그랬다.
      for (const [v, t, q] of [[A, 법(a0), uA], [C, 법(a1), uC], [B, 법(a1), uB],
                               [A, 법(a0), uA], [D, 법(a0), uD], [C, 법(a1), uC]]) {
        p.push(...v); n.push(...t); uv.push(...q);
      }
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute("position", new THREE.Float32BufferAttribute(p, 3));
  g.setAttribute("normal", new THREE.Float32BufferAttribute(n, 3));
  g.setAttribute("uv", new THREE.Float32BufferAttribute(uv, 2));
  return g;
}

// ── 줄마다 다른 글자 세트 ──────────────────────────────────
// [왜 줄마다 다르게 하나]
//   한 세트를 다섯 줄이 같이 쓰면 다섯 줄에 **똑같은 글자가 나란히** 늘어선다.
//   그러면 "어느 줄에든 같은 글자가 있다"가 한눈에 보여서 찍기가 쉬워지고,
//   무엇보다 실물 문자 자물쇠와 다르다 — 실물은 줄마다 새겨진 글자가 다르다.
// [규칙]
//   ① 그 줄의 **정답 글자는 반드시** 들어간다. 안 넣으면 그 줄은 절대 못 맞춘다.
//   ② 나머지는 뽑을글자(알파벳)에서 **겹치지 않게** 뽑는다 — 줄마다 다른 씨로.
//   ③ 정답 글자가 늘 같은 자리에 오면 그것만 보고 풀 수 있으니, 끼울 자리도 씨로 정한다.
//   ④ 씨가 같으면 항상 같은 결과다(다시 켰을 때 글자가 바뀌면 퍼즐이 아니다).
function 줄글자만들기({ 정답, 칸수, 칸글자수, 뽑을글자, 씨 }) {
  const 풀 = [
    ...new Set(
      String(뽑을글자 ?? "")
        .toUpperCase()
        .split("")
        .filter((c) => c.trim()),
    ),
  ];
  const 답 = String(정답 ?? "").toUpperCase();
  return Array.from({ length: Math.max(1, 칸수) }, (_, i) => {
    const rnd = makeRandom(씨 * 1013 + i * 7919 + 17);
    const 내답 = 답[i] || null;
    const 남은 = 풀.filter((c) => c !== 내답);
    // 피셔-예이츠 섞기 — 앞에서부터 뽑으면 겹치지 않는다
    for (let k = 남은.length - 1; k > 0; k--) {
      const j = Math.floor(rnd() * (k + 1));
      [남은[k], 남은[j]] = [남은[j], 남은[k]];
    }
    const 뽑기 = 남은.slice(0, Math.max(1, 칸글자수 - (내답 ? 1 : 0)));
    if (내답) 뽑기.splice(Math.floor(rnd() * (뽑기.length + 1)), 0, 내답);
    return 뽑기.join("");
  });
}

