// 힌트종이.js — 밸브 힌트 쪽지가 '지금 어디 있나'
//
// [곳]
//   "자판기" — 캔을 뽑으면 같이 나와 배출구에 놓여 있다(자판기상태.힌트종이)
//   "손"     — 집어 들었다(종이컵상태 의 듦/종류="종이" 와 짝을 이룬다)
//   "바닥"   — [E] 로 버렸다. **사라지지 않는다** — 다시 주울 수 있다.
//   "보관"   — [H] 로 힌트함에 적어 넣었다. 실물은 더 이상 없다.
//
// [왜 바닥 상태를 따로 두나]
//   버리면 그냥 사라지던 시절엔, 잘못 눌러 버린 사람에게 되돌릴 길이 없었다.
//   동전·관창이 전부 '내려놓으면 그 자리에 남는다'로 되어 있는데 이것만 증발하면
//   같은 세계의 물건으로 안 읽힌다(GRD-01 되돌릴 수 있음).

import { useSyncExternalStore } from "react";

/** 이 쪽지가 힌트함에 들어갈 때 쓰는 내용. UI 가 그대로 읽는다. */
export const 밸브힌트 = {
  id: "밸브힌트",
  이름: "밸브 쪽지",
  설명:
    "자판기 배출구에서 캔과 함께 나온 쪽지. 핸들휠 그림 아래 다섯 칸이 비어 있다.",
};

const 상태 = {
  곳: "자판기",
  놓인자리: null, // [x, y, z] — "바닥" 일 때만 쓴다
  놓은때: 0, // 떨어지는 연출의 시작 시각(ms)
};

let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

// ── 플레이어 발 앞 ─────────────────────────────────────────
// [왜 필요한가]
//   쪽지를 버리면 **본 데가 아니라 서 있는 자리**에 떨어뜨린다.
//   겨냥 자리(놓을자리찾기)를 쓰려다 한 번 크게 틀렸다 — 그 함수는 좌표를
//   본부실 바닥 경계 안으로 당긴다(배치.js 의 조이기). 복도는 그 경계 밖이라
//   복도에서 버리면 쪽지가 **벽 속(x −19.8)으로 끌려가** 안 보였다.
//   발 앞은 어디서 버리든 눈앞이라, 떨어진 게 바로 보이고 바로 주울 수 있다.
let 발앞 = null;
export const 발앞적기 = (p) => {
  발앞 = p;
};
export const 발앞자리 = () => 발앞;

export const 종이곳 = () => 상태.곳;
export const 종이놓인자리 = () => 상태.놓인자리;
export const 종이놓은때 = () => 상태.놓은때;

/** 자판기·바닥에서 집어 든다. */
export function 종이집음() {
  if (상태.곳 === "손" || 상태.곳 === "보관") return false;
  상태.곳 = "손";
  알리기();
  return true;
}

/**
 * [E] — 손에서 놓는다. 겨냥한 바닥 자리가 있으면 거기, 없으면 발 앞.
 * @param 자리 [x, y, z]
 */
export function 종이버리기(자리) {
  // ★ '곳' 이 뭐든 바닥으로 보낸다.
  //   전에는 곳 === "손" 일 때만 놓아 줬는데, 그러면 집을 때 종이집음() 이
  //   한 번이라도 빠지면(핫리로드로 이 모듈만 새로 뜬 경우 등) 버리기가 조용히
  //   실패하고 **손만 비워져 쪽지가 통째로 증발했다.**
  //   손에 들었는지는 종이컵상태가 알고 있고, 부르는 쪽이 이미 확인한 뒤다.
  상태.곳 = "바닥";
  상태.놓인자리 = 자리 ? [자리[0], 자리[1], 자리[2]] : null;
  상태.놓은때 = performance.now();
  알리기();
  return true;
}

/** [H] — 힌트함에 적어 넣는다. 실물은 사라진다. */
export function 종이보관() {
  if (상태.곳 !== "손") return false;
  상태.곳 = "보관";
  상태.놓인자리 = null;
  알리기();
  return true;
}

/**
 * 힌트함에서 뺐다 — 실물 쪽지를 도로 바닥에 내놓는다.
 * 자리를 안 주면 마지막으로 놓였던 자리, 그것도 없으면 기본 자리(App)가 쓰인다.
 */
export function 종이도로놓기(자리) {
  if (상태.곳 !== "보관") return false;
  상태.곳 = "바닥";
  if (자리) 상태.놓인자리 = [자리[0], 자리[1], 자리[2]];
  상태.놓은때 = performance.now();
  알리기();
  return true;
}

/** 개발·테스트용 */
export function 종이초기화() {
  상태.곳 = "자판기";
  상태.놓인자리 = null;
  상태.놓은때 = 0;
  알리기();
}

export const use힌트종이 = () => {
  useSyncExternalStore(구독, () => 판);
  return 판;
};

if (typeof window !== "undefined")
  window.__힌트종이 = { 상태, 종이버리기, 종이보관, 종이초기화 };
