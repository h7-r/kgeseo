// 배전반배선.js — 배전반 속 퍼즐 3색 선의 '지금 상태'와 규칙.
//
// [무엇을 담나]
//   접속함에서 늘어진 위 선 셋(암)과, 차단기에서 나온 아래 선 셋(수).
//   아래 것을 잡아 위에 꽂는다. 색이 맞아야 회로가 산다.
//
//   색 번호는 위·아래가 같다 —  0 = 빨강 · 1 = 파랑 · 2 = 노랑.
//   그래서 "위 t 에 아래 c 가 꽂혔는데 t === c" 면 그 한 줄이 맞은 것이다.
//
// [규칙]
//   ① 아래 선에 [E] — **잡는다.** 들고 다니는 게 아니라 손에 쥔 채 서 있는 것이다.
//      (한 번 더 [E] 를 누르면 놓는다. 한 번에 한 가닥만 쥔다)
//   ② 위 선에 [E] — 쥐고 있으면 거기 꽂는다. **색이 틀려도 꽂힌다.**
//      틀린 자리를 알아채고 도로 뽑는 것까지가 이 퍼즐이다.
//      (동전을 엉뚱한 자판기에 넣으면 반환구로 나오는 것과 같은 결이다)
//   ③ 꽂힌 위 선에 [E] — 뽑는다. 뽑으면 그 가닥을 **다시 쥔 상태**가 된다.
//      바로 옆에 꽂아 볼 수 있어야 손이 안 끊긴다.
//   ④ 셋 다 제 색에 꽂히면 풀린다 → 접속함 덮개에 불이 들어온다.
//
// [왜 리액트 state 가 아닌가]
//   자판기·동전과 같은 이유다. 매 프레임 바뀌는 값이 아니라 '집고 꽂는 사건'에만
//   바뀌므로, 가벼운 외부 store 로 두고 바뀔 때만 씬을 다시 그린다.

import { useSyncExternalStore } from "react";
import { 열렸나 } from "./여닫이.js";
import { 관창곳 } from "./관창.js";
import { 소리재생 } from "../소리.js";

export const 색수 = 3;
export const 색이름 = ["빨강", "파랑", "노랑"];

const 상태 = {
  쥔것: null, // null | 0|1|2 — 지금 쥐고 있는 아래 선의 색 번호
  꽂힘: [null, null, null], // 꽂힘[t] = 위 선 t 에 꽂힌 아래 선의 색 번호
  푼때: 0, // 셋 다 제 색에 꽂힌 시각(ms). 0 이면 아직 안 풀림 —
  //          접속함 불빛이 이 시각을 기준으로 켜진다.
};

let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

/** 지금 쥐고 있는 아래 선의 색 번호. 없으면 null. */
export const 쥔선 = () => 상태.쥔것;
/** 위 선 t 에 꽂힌 아래 선의 색 번호. 안 꽂혔으면 null. */
export const 꽂힌선 = (t) => 상태.꽂힘[t] ?? null;
/** 아래 선 c 가 어디에 꽂혀 있나. 안 꽂혔으면 −1. */
export const 꽂힌자리 = (c) => 상태.꽂힘.indexOf(c);
/** 아래 선 c 가 지금 '자유단'인가 — 쥐지도 꽂지도 않은 원래 자리. */
export const 놀고있나 = (c) => 상태.쥔것 !== c && 꽂힌자리(c) < 0;
/** 셋 다 제 색에 꽂혔나. */
export const 다풀렸나 = () => 상태.꽂힘.every((c, t) => c === t);
/** 푼 시각(ms). 0 이면 아직. */
export const 푼때 = () => 상태.푼때;

// 풀렸는지 다시 재고, 막 풀린 순간이면 시각을 찍는다.
//   ★ 뽑아서 풀림이 깨지면 시각도 0 으로 되돌린다 — 그래야 다시 풀 때
//     불빛이 처음부터 다시 켜진다(켜진 채로 남아 있으면 푼 티가 안 난다).
function 풀림다시재기() {
  const 풀림 = 다풀렸나();
  if (풀림 && !상태.푼때) 상태.푼때 = performance.now();
  else if (!풀림 && 상태.푼때) 상태.푼때 = 0;
}

/** 아래 선을 쥔다 / 쥐고 있던 그 선이면 놓는다. */
export function 쥐기(c) {
  if (상태.쥔것 === c) {
    상태.쥔것 = null; // 같은 선을 또 누르면 놓는다
    소리재생("버튼", { 볼륨: 0.9 }); // 선을 놓는 딸깍
    알리기();
    return true;
  }
  if (상태.쥔것 !== null) return false; // 한 번에 한 가닥만
  if (꽂힌자리(c) >= 0) return false; // 이미 어딘가 꽂혀 있다
  상태.쥔것 = c;
  소리재생("버튼", { 볼륨: 0.9 }); // 선을 쥐는 딸깍
  알리기();
  return true;
}

/** 쥔 손을 그냥 놓는다. */
export function 놓기() {
  if (상태.쥔것 === null) return false;
  상태.쥔것 = null;
  알리기();
  return true;
}

/**
 * 쥐고 있는 선을 위 선 t 에 꽂는다.
 * ★ 색이 틀려도 들어간다. 맞는지는 ④(다풀렸나)가 판단한다.
 */
export function 꽂기(t) {
  if (상태.쥔것 === null) return false;
  if (상태.꽂힘[t] !== null) return false; // 그 자리는 이미 찼다
  상태.꽂힘[t] = 상태.쥔것;
  상태.쥔것 = null;
  소리재생("버튼", { 볼륨: 0.9 }); // 선을 꽂는 딸깍
  풀림다시재기();
  알리기();
  return true;
}

/**
 * 위 선 t 에 꽂힌 것을 뽑는다. 뽑은 가닥은 **그대로 쥔 상태**가 된다.
 * 다른 걸 쥐고 있으면 못 뽑는다(양손이 아니다).
 */
export function 뽑기(t) {
  const c = 상태.꽂힘[t];
  if (c === null) return false;
  if (상태.쥔것 !== null) return false;
  상태.꽂힘[t] = null;
  상태.쥔것 = c;
  소리재생("버튼", { 볼륨: 0.9 }); // 선을 뽑는 딸깍
  풀림다시재기();
  알리기();
  return true;
}

// ── 차단기까지 본 '회로가 살았나' ─────────────────────────────
// [왜 여기에 두나]
//   선이 이어졌는지는 이 파일이 알고, 차단기가 올라갔는지는 여닫이.js 가 안다.
//   그런데 **어느 차단기가 어느 색인지**는 배전반내부.jsx 만 안다(줄·열 배치).
//   그래서 배전반이 한 번 열릴 때 그 짝을 여기 적어 두고, 그 뒤로는 누구나
//   물어볼 수 있게 한다 — 소화전 밸브가 이걸 알아야 돌아갈지 말지를 정한다.
//   ★ 함을 닫아도 남아 있어야 한다. 배전반 컴포넌트는 문을 닫으면 사라지는데,
//     그때 이 값까지 없어지면 복도 반대편에서 밸브가 다시 잠긴다.
let 스위치짝 = [null, null, null]; // 색 → 차단기 id

/** 배전반이 제 차단기 id 셋을 알려 준다(색 순서: 빨강·파랑·노랑). */
export function 스위치짝등록(ids) {
  스위치짝 = ids;
}

/** 색 c 의 회로가 살았나 — 선이 제 짝에 꽂히고 그 차단기가 올라갔나. */
export function 회로산나(c) {
  if (상태.꽂힘[c] !== c) return false;
  const id = 스위치짝[c];
  return !!id && 열렸나(id);
}

/** 셋 다 살았나. */
export const 회로다살았나 = () => 회로산나(0) && 회로산나(1) && 회로산나(2);

// ── 소화전 개폐 밸브 ────────────────────────────────────────
//   [언제 돌아가나] 배전반 회로가 다 살고 **관창까지 꽂혀야** 한다.
//   물을 보낼 길이 다 이어진 뒤에야 밸브를 여는 것이 순서다.
let 밸브 = 0; // 0 = 잠김, 1 = 열림
export const 밸브열림 = () => 밸브;
export const 밸브돌릴수있나 = () =>
  !밸브 && 회로다살았나() && 관창곳() === "꽂힘";
export function 밸브돌리기() {
  if (!밸브돌릴수있나()) return false;
  밸브 = 1;
  소리재생("자물쇠열림", { 볼륨: 0.9 }); // 밸브가 열리는 묵직한 소리
  알리기();
  return true;
}

/** 개발·테스트용 초기화 */
export function 배선초기화() {
  상태.쥔것 = null;
  상태.꽂힘 = [null, null, null];
  상태.푼때 = 0;
  밸브 = 0;
  알리기();
}

// 값(판)만 구독하고 상태는 그때 꺼내 쓴다(배열/객체를 돌려주면 무한 렌더).
export const use배전반배선 = () => {
  useSyncExternalStore(구독, () => 판);
  return 판;
};

if (typeof window !== "undefined")
  window.__배전반배선 = { 상태, 쥐기, 꽂기, 뽑기, 밸브돌리기, 배선초기화 };
