// ── 전선 한 가닥 ────────────────────────────────────────────
// 점 몇 개만 찍으면 나머지는 곡선이 알아서 메운다.
//   장력 0.3 — 0.5(기본)면 꺾이는 데서 밖으로 부풀어 전선이 '튕겨 나간' 것처럼 보인다.
function 전선지오(점들, 굵기, 마디 = 24, 각 = 7) {
  const c = new THREE.CatmullRomCurve3(
    점들.map((p) => new THREE.Vector3(p[0], p[1], p[2])),
    false,
    "catmullrom",
    0.3,
  );
  return new THREE.TubeGeometry(c, 마디, 굵기, 각, false);
}

// ── 벗겨 놓은 구리 끝 ──────────────────────────────────────
//   선이 끝나는 **방향 그대로** 원뿔대를 세운다. 아래로 늘어진 줄은 아래로,
//   옆에서 위로 꺾여 올라온 줄은 위로 — 방향이 안 맞으면 끝이 꺾여 붙어
//   '잘린 자리'가 아니라 '부러진 자리'로 보인다.
//   ★ 위아래가 **암수**다. 늘어진 쪽(위)은 굵은 통, 스위치 쪽(아래)은 가는 핀.
//     이러면 아래 것을 끌어 올려 위 통에 **꽂는** 그림이 된다. 둘이 같은 굵기면
//     끝끼리 맞대는 모양이라 이어졌는지 안 이어졌는지 눈으로 구분이 안 된다.
const _위 = new THREE.Vector3(0, 1, 0);
function 구리끝지오(가닥들, 뿌리, 끝굵기, 길이) {
  if (!가닥들.length) return null;
  const 조각 = 가닥들.map((점들) => {
    const 끝 = new THREE.Vector3(...점들[점들.length - 1]);
    const 앞 = new THREE.Vector3(...점들[점들.length - 2]);
    const 방향 = 끝.clone().sub(앞).normalize();
    const g = new THREE.CylinderGeometry(끝굵기, 뿌리, 길이, 8, 1);
    g.applyQuaternion(new THREE.Quaternion().setFromUnitVectors(_위, 방향));
    const c = 끝.clone().addScaledVector(방향, 길이 * 0.4);
    g.translate(c.x, c.y, c.z);
    return g;
  });
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

// 여러 가닥을 한 메시로. 색이 같은 것끼리만 부른다.
function 전선묶음(가닥들, 굵기, 마디 = 24) {
  if (!가닥들.length) return null;
  const 조각 = 가닥들.map((점들) => 전선지오(점들, 굵기, 마디));
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

// ── 「전기위험」 딱지 — 주차단기에 붙은 작은 노란 표 ──────────
// ★ 본편 표지판(배전반라벨텍스처)과 **같은 순서**로 맞췄다.
//   Noto Sans KR 을 앞에 두면 그 웹폰트가 안 실린 화면에서 엉뚱한 글꼴로
//   떨어져 글자 폭이 어긋난다. 기기에 실제로 있는 것부터 부른다.
const 딱지폰트 = `"Apple SD Gothic Neo","Malgun Gothic","Noto Sans KR",sans-serif`;
const _딱지캐시 = new Map();
function 위험딱지텍스처(바탕 = "#e8c53a", 글자 = "#c0281f") {
  const 키 = 바탕 + "|" + 글자;
  if (_딱지캐시.has(키)) return _딱지캐시.get(키);
  // ★ 넓고 낮은 띠다.
  //   전에는 256×96 에 위아래로 빗금 띠를 둘러 글자 자리가 62px 밖에 안 남았다.
  //   화면에서 이 딱지는 8cm 남짓이라, 그 안에 네 글자를 욱여넣으면 뭉개진다.
  //   실물 「전기위험」 표찰도 가로로 길다 — 빗금을 좌우 끝으로 보내고
  //   세로를 통째로 글자에 준다.
  const W = 384,
    H = 88;
  const c = document.createElement("canvas");
  c.width = W;
  c.height = H;
  const g = c.getContext("2d", { willReadFrequently: true });
  const 띠 = 46; // 좌우 빗금 폭
  g.fillStyle = "#1b1b1c";
  g.fillRect(0, 0, W, H);
  g.fillStyle = 바탕;
  g.fillRect(4, 4, W - 8, H - 8);
  // 좌우 끝 빗금 — 실물 경고 표찰의 그 줄무늬
  g.save();
  g.beginPath();
  g.rect(4, 4, 띠, H - 8);
  g.rect(W - 4 - 띠, 4, 띠, H - 8);
  g.clip();
  g.fillStyle = "#1b1b1c";
  for (let i = -H; i < W; i += 22) {
    g.beginPath();
    g.moveTo(i, 4);
    g.lineTo(i + 11, 4);
    g.lineTo(i + 11 + H, H - 4);
    g.lineTo(i + H, H - 4);
    g.closePath();
    g.fill();
  }
  g.restore();
  // 글자 — 세로를 다 쓴다. 가운데 정렬이라 좌우 빗금과 안 겹친다.
  g.fillStyle = 글자;
  g.textAlign = "center";
  g.textBaseline = "middle";
  g.font = `800 56px ${딱지폰트}`;
  g.fillText("전기위험", W / 2, H / 2 + 3);
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  // 비스듬히 볼 때 밉맵이 글자를 뭉개는 걸 막는다(문을 열면 늘 비스듬히 본다)
  t.anisotropy = 16;
  _딱지캐시.set(키, t);
  return t;
}
// ── 스위치 한 개 — [E] 로 좌우로 민다 ───────────────────────
//   [왜 하나씩 따로 그리나] 여섯 개를 한 덩어리로 합치면 하나만 움직일 수가 없다.
//     메시가 여섯 개 늘지만 손잡이는 작아서 값이 싸다.
//   [왜 자리를 state 로 안 두나] 미는 동안 매 프레임 바뀐다. state 면 그때마다
//     함 전체가 다시 그려진다. 켜짐/꺼짐만 여닫이 저장소가 들고, 자리는
//     여기서 useFrame 이 스스로 좁혀 간다(함 문과 같은 방식이다).
const _손점 = new THREE.Vector3();
function 스위치손잡이({ id, 지오, 자리, 꺼짐z, 켜짐z, 색, 밝기, 선, 만질수있나 }) {
  const g = useRef(null);
  const 값 = useRef(0); // 0 = 꺼짐, 1 = 켜짐
  useFrame((_, dt) => {
    const o = g.current;
    if (!o) return;
    const 목표 = 열렸나(id) ? 1 : 0;
    값.current += (목표 - 값.current) * (1 - Math.exp(-dt * 14));
    o.position.z = 꺼짐z + (켜짐z - 꺼짐z) * 값.current;
  });
  return (
    <>
      <mesh ref={g} geometry={지오} position={[자리[0], 자리[1], 꺼짐z]} castShadow>
        {툰(색, 밝기)}
        <만화선 geo={지오} 선={선} />
      </mesh>
      <상호대상
        id={id}
        반경={0.26}
        거리={4}
        /* ★ 끔 은 **함수**다(상호작용.js 규약). 값으로 넘기면 겨냥 루프가
           t.끔() 에서 예외를 던지고, 그 루프가 죽으면 문·물건·호버까지
           전부 멈춘다. 실제로 그렇게 통째로 먹통이 됐다. */
        끔={() => !만질수있나}
        라벨=""
        위치={() => {
          const o = g.current;
          if (!o) return null;
          o.getWorldPosition(_손점);
          return [_손점.x, _손점.y, _손점.z];
        }}
        실행={() => 여닫기(id)}
      />
    </>
  );
}

