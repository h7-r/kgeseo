  const 접지아래 = 분기위 + Math.min(0.1, 위줄높 * 0.2);

  // 세로 부스바 3줄 — 두 차단기 줄 **사이 틈**에 딱 들어가야 한다.
  //   틈의 반폭 = 열z − 차단기폭/2. 바 두께까지 재서 그 안에 넣는다.
  const 틈반폭 = 안폭 * 0.2 - 차단기폭 / 2;
  const 부스두께 = Math.min(0.034, 틈반폭 * 0.6);
  const 부스간 = Math.max(0, 틈반폭 - 부스두께 / 2 - 0.004) * 0.78;
