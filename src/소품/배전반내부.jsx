//
// [무엇을 담는가] 실물 저압 분전반 그대로다(참고 사진 기준).
//   위 줄  : 주차단기(MCCB) · 계기용 변류기(CT) 함 · 접지 동판
//   가운데 : 세로 부스바(동판) 3줄 + 줄마다 좌우로 뻗는 동판 접속편 + 노란 회로 표찰
//   좌우   : 분기차단기 두 줄 · 배선 덕트(빗살) · 덕트로 빨려 들어가는 전선들
//
// [전선을 왜 튜브로 뽑나]
//   상자를 꺾어 이으면 마디마다 턱이 져서 '토막을 붙인 것'으로 보인다.
//   실물 전선은 꺾이는 데가 전부 둥글다. 그래서 가운데 선을 CatmullRom 으로
//   부드럽게 뽑고 그 위를 관으로 훑는다. 소화전 호스를 띠로 훑은 것과 같은 이유다.
//
// [축]
//   함은 z 가 가로, y 가 세로, x 가 깊이다. 앞면은 d(방향) 쪽.
//   깊이는 X(t) 로만 쓴다 — t 는 **뒤판을 0, 함 앞면을 깊이**로 잰 값이라
//   방향(d)이 뒤집혀도 코드를 그대로 둘 수 있다.

