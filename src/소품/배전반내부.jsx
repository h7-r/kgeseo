// ── 전선 한 가닥 ────────────────────────────────────────────
// 점 몇 개만 찍으면 나머지는 곡선이 알아서 메운다.
//   장력 0.3 — 0.5(기본)면 꺾이는 데서 밖으로 부풀어 전선이 '튕겨 나간' 것처럼 보인다.
function 전선지오(점들, 굵기, 마디 = 24, 각 = 7) {
  const c = new THREE.CatmullRomCurve3(
    점들.map((p) => new THREE.Vector3(p[0], p[1], p[2])),
    false,
    "catmullrom",
    0.3,
  );
  return new THREE.TubeGeometry(c, 마디, 굵기, 각, false);
}

// 여러 가닥을 한 메시로. 색이 같은 것끼리만 부른다.
function 전선묶음(가닥들, 굵기, 마디 = 24) {
  if (!가닥들.length) return null;
  const 조각 = 가닥들.map((점들) => 전선지오(점들, 굵기, 마디));
  const 합 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합;
}

