//   부드럽게 뽑고 그 위를 관으로 훑는다. 소화전 호스를 띠로 훑은 것과 같은 이유다.
//
// [축]
//   함은 z 가 가로, y 가 세로, x 가 깊이다. 앞면은 d(방향) 쪽.
//   깊이는 X(t) 로만 쓴다 — t 는 **뒤판을 0, 함 앞면을 깊이**로 잰 값이라
