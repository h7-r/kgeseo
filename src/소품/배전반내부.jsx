  const 몸통 = useMemo(() => {
    const 것 = [
      { 크기: [주깊 * 깊배, 주높, 주폭], 위치: [깊(주깊 / 2), 주y, 주z] },
      { 크기: [0.12 * 깊배, 변높, 변폭], 위치: [깊(0.06), 주y, 변z] },
    ];
    줄y.forEach((y) => {
      for (const z of 열z)
        것.push({
          크기: [차단기깊 * 깊배, 차단기높, 차단기폭],
          위치: [깊(차단기깊 / 2), y, z],
        });
    });
    return 상자합치기(것);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [치수키, 줄y]);

