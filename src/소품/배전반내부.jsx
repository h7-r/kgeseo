// ── ① 붙는 동안 — 형광등이 켜지듯 **어두운 철판과 흰빛을 오간다** ──
//   경계 시각(초). 짝수 칸이 켜짐, 홀수 칸이 꺼짐이다.
//   불규칙해야 '붙는 중'으로 읽힌다 — 일정하면 그냥 깜빡이는 표시등이다.
const 점화표 = [0.05, 0.11, 0.15, 0.27, 0.32, 0.40, 0.58, 0.66];
const 점화끝 = 점화표[점화표.length - 1];
function 점화켜짐(t) {
  for (let i = 0; i < 점화표.length; i++) if (t < 점화표[i]) return i % 2 === 0;
  return true;
}
// ── ② 붙고 나서 — 텀을 두고 반짝인다 ──
//   쉬지 않고 깜빡이면 '고장 난 형광등'이다. 두 번 치고 한동안 숨 쉬는 편이
//   **신호**로 읽힌다. 값이 1 을 넘는 만큼 Bloom 이 물어 번진다.
function 불세기(t) {
  if (t < 점화끝) return 점화켜짐(t) ? 3.4 : 0.04; // 붙는 중 — 확 밝았다 확 꺼진다
  const u = (t - 점화끝) % 2.7;
  if (u < 0.1) return 3.1;
  if (u < 0.24) return 0.8; // 텀 ①
  if (u < 0.36) return 3.1;
  return 1.7 + 0.22 * Math.sin(u * 2.4); // 긴 텀 — 은은하게 숨 쉰다
}
// 지금 얼마나 '흰가'. 0 = 원래 어두운 철판, 1 = 흰빛.
function 불흰정도(t) {
  if (t < 점화끝) return 점화켜짐(t) ? 1 : 0; // 오간다 — 섞지 않는다
  return 1;
}
