// 종이컵상태.js — 손에 든 '음료(커피 컵 / 음료 캔)'의 상태와 규칙.
//
// [무엇을 담나]
//   커피 자판기의 종이컵, 음료 자판기의 캔을 집으면 여기로 온다. 컵·캔을 한
//   저장소에서 함께 다룬다(둘 다 '들고 → (캔이면 따고) → 마시고 → 버린다').
//   매 프레임 안 바뀌고 '집기/따기/마시기/버리기' 사건에만 바뀌므로 가벼운
//   외부 store 로 둔다(동전상태·자판기상태와 같은 방식).
//
// [E 한 번의 흐름]
//   컵: 마시기(양이 준다) → … → 다 비면 버리기.
//   캔: 따기(뚜껑 오픈) → 마시기(양이 준다) → … → 다 비면 버리기.

import { useSyncExternalStore } from "react";
import { 소리재생 } from "../소리.js";

const 한모금 = 0.34; // 한 번 마실 때 줄어드는 양(0~1) → 약 3모금이면 빈다

const 상태 = {
  듦: false, // 무언가 들고 있나
  종류: null, // "컵" | "캔"
  색: null, // 용기 색(컵 종이색 / 캔 라벨색)
  음료색: null, // 안의 음료 색
  남은: 1, // 남은 양 0~1 (마실수록 준다)
  딴: false, // 캔을 땄나(컵은 항상 true)
  마신때: 0, // 마시기/따기 모션 시작 시각(ms)
  동작: null, // "따기" | "마시기"
};

let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

/** 지금 든 음료 정보. 안 들고 있으면 null. */
export function 든음료() {
  return 상태.듦
    ? {
        종류: 상태.종류,
        색: 상태.색,
        음료색: 상태.음료색,
        남은: 상태.남은,
        딴: 상태.딴,
      }
    : null;
}
/** 지금 재생 중인 동작과 시작 시각(모션 그리기용). */
export function 음료동작() {
  return { 동작: 상태.동작, 마신때: 상태.마신때 };
}

/** 커피 종이컵을 집는다(E). 컵은 뚜껑이 없으니 처음부터 '딴' 상태다. */
export function 컵집기(색, 음료색) {
  if (상태.듦) return false;
  상태.듦 = true;
  상태.종류 = "컵";
  상태.색 = 색;
  상태.음료색 = 음료색;
  상태.남은 = 1;
  상태.딴 = true;
  상태.동작 = null;
  상태.마신때 = 0;
  알리기();
  return true;
}

/** 음료 캔을 집는다(E). 캔은 아직 안 딴 상태 — 처음 E 는 '따기'다. */
export function 캔집기(색, 음료색) {
  if (상태.듦) return false;
  상태.듦 = true;
  상태.종류 = "캔";
  상태.색 = 색;
  상태.음료색 = 음료색;
  상태.남은 = 1;
  상태.딴 = false;
  상태.동작 = null;
  상태.마신때 = 0;
  알리기();
  return true;
}

/** 밸브 힌트 종이를 집는다(E). 마실 것이 아니라 '보는' 물건이다(종류="종이"). */
export function 종이집기() {
  if (상태.듦) return false;
  상태.듦 = true;
  상태.종류 = "종이";
  상태.색 = "#f3efe2";
  상태.음료색 = null;
  상태.남은 = 1;
  상태.딴 = false; // 종이에선 '펼쳐 봤나'로 쓴다
  상태.동작 = null;
  상태.마신때 = 0;
  알리기();
  return true;
}

/**
 * 든 음료에 E 를 한 번 누른 결과를 처리한다.
 *   ① 종이면 → 펼쳐 보기(가까이) → 한 번 더 E 면 버리기
 *   ② 캔인데 아직 안 땄으면 → 따기(모션만, 양은 그대로)
 *   ③ 남은 양이 있으면 → 마시기(양이 한 모금 준다)
 *   ④ 다 비었으면 → 버리기(손에서 사라진다)
 */
export function 음료E() {
  if (!상태.듦) return null;
  if (상태.종류 === "종이") {
    if (!상태.딴) {
      상태.딴 = true; // 펼쳐 봤다
      상태.동작 = "보기";
      상태.마신때 = performance.now();
      알리기();
      return "보기";
    }
    버리기();
    return "버림";
  }
  if (상태.종류 === "캔" && !상태.딴) {
    상태.딴 = true;
    상태.동작 = "따기";
    상태.마신때 = performance.now();
    알리기();
    return "따기";
  }
  if (상태.남은 > 0.001) {
    상태.남은 = Math.max(0, 상태.남은 - 한모금);
    상태.동작 = "마시기";
    상태.마신때 = performance.now();
    // 캔은 '내부 배출' 짧은 소리를 마실 때마다(사용자 지시). 컵은 조용히.
    if (상태.종류 === "캔" || 상태.종류 === "컵") 소리재생("캔마시기", { 볼륨: 0.9 }); // 캔·커피 둘 다 마시는 소리
    알리기();
    return "마시기";
  }
  // 다 비어 버릴 때: 캔은 같은 짧은 소리, 컵은 '내려두는' 소리.
  const 끝종류 = 상태.종류;
  버리기();
  if (끝종류 === "캔") 소리재생("캔마시기", { 볼륨: 0.9 });
  else if (끝종류 === "컵") 소리재생("컵버리기", { 볼륨: 0.9 });
  return "버림";
}

/** 버린다 — 손에서 사라진다. */
export function 버리기() {
  if (!상태.듦) return false;
  상태.듦 = false;
  상태.종류 = null;
  상태.색 = null;
  상태.음료색 = null;
  상태.남은 = 1;
  상태.딴 = false;
  상태.동작 = null;
  상태.마신때 = 0;
  알리기();
  return true;
}

/** 개발·테스트용 초기화 */
export function 음료초기화() {
  버리기();
}

// 값(판)만 구독하고 상태는 그때 꺼내 쓴다(객체를 돌려주면 무한 렌더).
export const use음료 = () => {
  useSyncExternalStore(구독, () => 판);
  return 판;
};

if (typeof window !== "undefined")
  window.__음료 = { 상태, 컵집기, 캔집기, 음료E, 버리기, 음료초기화 };
