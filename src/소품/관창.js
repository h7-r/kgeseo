// 관창.js — 소화전 관창(호스 노즐)이 지금 어디 있나
//
// [무엇을 담나]
//   관창 하나의 '곳'. 매 프레임 바뀌는 값이 아니라 **집고 꽂는 사건**에만
//   바뀌므로, 리액트 밖 store 로 둔다(동전상태.js 와 같은 방식).
//   이렇게 두면 관창을 집었다고 해서 복도 전체가 다시 그려지지 않는다.
//
//   곳: "함"   — 소화전함 안 제자리. 문이 열려 있으면 [E] 로 집는다.
//       "손"   — 지금 들고 있다. 카메라 앞에 따라온다(손에든것).
//       "꽂힘" — 배전반 관창 구멍에 꽂혀 있다. [E] 로 다시 뽑을 수 있다.
//
// [한 손 규칙]
//   ★ 동전이나 머그컵을 들고 있으면 관창을 못 집는다. 두 개를 동시에 들면
//     둘 다 카메라 앞 같은 자리에 겹쳐서 그려진다(실제로 그렇게 겹쳤다).
//   ★ 반대 방향(동전·물건 쪽에서 관창을 보는 것)은 여기서 하지 않는다.
//     동전상태.js 가 이 파일을 부르면 **순환 import** 가 된다 —
//     그쪽은 App 의 「끔」에서 관창곳() 을 보고 막는다.
import { useSyncExternalStore } from "react";
import { 든동전 } from "./동전상태.js";
import { 로비상태 } from "../로비/상호작용.js";
import { 소리재생 } from "../소리.js";

const 상태 = { 곳: "함" };

let 판 = 0;
const 듣는이 = new Set();
const 알리기 = () => {
  판 += 1;
  for (const f of 듣는이) f();
};
const 구독 = (f) => {
  듣는이.add(f);
  return () => 듣는이.delete(f);
};

/** "함" | "손" | "꽂힘" */
export const 관창곳 = () => 상태.곳;
export const 관창들었나 = () => 상태.곳 === "손";

/** 이미 뭔가 들고(끌고) 있나 — 관창을 집을 수 있는지의 판단 기준 */
export function 손이바쁘다() {
  if (든동전()) return true;
  const 로 = 로비상태.값();
  return !!로.든것 || !!로.끄는의자;
}

/** 함 속이나 꽂힌 자리에서 집어 든다(E). 이미 들고 있으면 아무 일 없음. */
export function 관창집기() {
  if (상태.곳 === "손") return false;
  if (손이바쁘다()) return false;
  상태.곳 = "손";
  소리재생("박스들기", { 볼륨: 0.9 }); // 관창(금속 노즐)을 집어 든다
  알리기();
  return true;
}

/** 배전반 구멍에 꽂는다(E). 들고 있지 않으면 아무 일 없음. */
export function 관창꽂기() {
  if (상태.곳 !== "손") return false;
  상태.곳 = "꽂힘";
  소리재생("박스놓기", { 볼륨: 0.9 }); // 배전반 구멍에 관창을 꽂는다
  알리기();
  return true;
}

// ── 호스가 매달릴 두 끝 ─────────────────────────────────
// [왜 store 가 이걸 들고 있나]
//   관창을 들고 나가면 **호스도 따라 나와야** 연결된 것으로 보인다.
//   그 호스를 그리려면 두 자리가 필요하다 —
//     ① 함 쪽 호스 끝(고정) ② 지금 관창의 커플링(함 속·손·배전반 중 어디든).
//   둘은 서로 다른 컴포넌트가 그리므로, 여기서 **만나게** 해 준다.
//   (좌표가 아니라 Object3D 를 받는다. 자리는 매 프레임 바뀌고,
//    부모가 움직이면 좌표는 곧 낡은 값이 된다.)
// ★ 마지막 월드 좌표를 따로 챙겨 둔다.
//   구역 최적화가 복도를 끄면 함 쪽 그룹이 사라진다. 그때 좌표까지 없어지면
//   들고 있던 호스가 통째로 끊겨 보인다 — 마지막 자리를 그대로 쓴다.
const 자리 = {
  // ★ **고정 기준점** — 관창이 함에 걸려 있던 자리(움직이지 않는다).
  //   얼마나 끌려 나왔나 · 어디까지 갈 수 있나를 **이 점**으로 잰다.
  //   다발 끝(함끝)으로 재면 안 된다: 다발이 줄면 그 점이 움직이고, 그러면
  //   길이가 달라져 가닥 수가 또 바뀌고, 그래서 **호스가 매 프레임 출렁인다**
  //   (실제로 그랬다 — 위아래로 계속 떨렸다).
  기준값: null,
  함끝: null,
  관창끝: null,
  함끝값: null,
  앞: [1, 0, 0],
  // 호스 길이 — 소화전함이 재서 넣어 준다. 이만큼만 끌고 갈 수 있다.
  총길이: 0,
  최대거리: 0,
  나온길이: 0, // 지금 그려진 줄의 길이(눈으로 보는 값 — 판단에는 안 쓴다)
  관창거리: 0, // 기준점에서 관창까지 — 다발을 얼마나 풀지 이걸로 정한다
  지금거리: 0, // 기준점에서 눈까지 — '멀어지는 걸음'만 막으려고 본다
};

/** 함 쪽 호스 끝을 알려 준다. 돌려받은 함수를 부르면 등록이 풀린다. */
export function 함끝등록(o, 앞 = [1, 0, 0]) {
  자리.함끝 = o;
  자리.앞 = 앞;
  return () => {
    if (자리.함끝 === o) 자리.함끝 = null;
  };
}
/** 움직이지 않는 기준점(관창 제자리)을 알려 준다 — 길이·한계 계산의 근거. */
export function 기준등록(x, y, z) {
  자리.기준값 = [x, y, z];
}
/** 지금 화면에 있는 관창의 커플링(호스가 물리는 자리)을 알려 준다. */
export function 관창끝등록(o) {
  자리.관창끝 = o;
  return () => {
    if (자리.관창끝 === o) 자리.관창끝 = null;
  };
}
export const 호스자리 = 자리;

// ── 호스가 다 풀리면 더 못 간다 ─────────────────────────
// [왜 필요한가]
//   관창을 들고 있으면 **호스를 들고 있는 것**이다. 호스는 늘어나지 않으니,
//   다 풀린 뒤에도 걸어가면 줄이 고무줄처럼 늘어나 버린다.
// [왜 '멀어지는 걸음'만 막나]
//   이미 한계 밖에 서 있을 수도 있다(설정을 줄였거나, 호스 길이가 다시 계산됐거나).
//   그때 바깥을 통째로 막으면 **그 자리에 갇힌다.** 가까워지는 쪽은 늘 허락한다.
export function 호스줄당김(x, z) {
  if (상태.곳 !== "손") return false;
  const a = 자리.기준값 ?? 자리.함끝값;
  if (!a || !(자리.최대거리 > 0)) return false;
  const d = Math.hypot(x - a[0], z - a[2]);
  if (d <= 자리.최대거리) return false;
  return d >= (자리.지금거리 || d) - 1e-6;
}

/** 개발·시험용 — 소화전함 제자리로 되돌린다 */
export function 관창되돌리기() {
  상태.곳 = "함";
  알리기();
}

// 값(판)만 구독하고 곳은 그때 꺼내 쓴다(객체를 돌려주면 무한 렌더).
export const use관창 = () => {
  useSyncExternalStore(구독, () => 판);
  return 상태.곳;
};

if (typeof window !== "undefined")
  window.__관창 = {
    상태, 관창곳, 관창집기, 관창꽂기, 관창되돌리기, 손이바쁘다,
    호스자리: 자리, 호스줄당김,
  };
