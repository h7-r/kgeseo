// api.js — 서버와 이야기하는 창구 (USR-110 · 전역-002 · 전역-003)
//
// ═══════════════════════════════════════════════════════════════
//  ★ 백엔드 담당자에게
// ═══════════════════════════════════════════════════════════════
// 이 파일은 **인터페이스만 확정해 둔 자리**다.
// 지금은 안쪽이 localStorage 로 흉내만 내고 있고, 실제 서버가 준비되면
// `모의서버` 를 `fetch` 구현으로 바꾸기만 하면 된다. **화면 코드는 하나도 안 건드린다.**
//
// 지켜야 할 원칙(가드레일 GRD-13):
//   잠금·해금 판단은 **반드시 서버 값**이다. 클라이언트 플래그로 판단하면
//   새로고침 한 번으로 우회된다. 그래서 화면은 절대 자기 상태로 게이트를 열지 않고,
//   언제나 여기서 받은 값만 본다.
//
// 필요한 엔드포인트(제안):
//   GET  /me/progress        → 진행상태조회()
//   POST /me/avatar          → 아바타저장()
//   GET  /me/name-check      → 조사관명검사()
//   POST /me/tutorial/done   → 튜토리얼완료()
//   POST /me/consent         → 동의저장()   ★ 갱신이 아니라 append (S1-006)
//   GET  /me/consent         → 동의이력조회()
//   POST /play/checkpoint    → 체크포인트저장()
//   GET  /play/checkpoint    → 체크포인트조회()
//
// 모든 함수는 Promise 를 돌려주고, 실패하면 예외를 던진다.
// 화면 쪽은 실패를 '게스트 신규'로 해석한다(USR-110 예외 처리).

const 저장키 = "왜곡.진행.v1";
const 지연 = (ms) => new Promise((r) => setTimeout(r, ms));

// 개발 중 예외 처리를 실제로 확인하려고 둔 스위치.
//   콘솔에서 `왜곡_서버실패(true)` 를 치면 그때부터 조회가 실패한다.
//   ★ 저장소에 남겨 둔다 — 새로고침해도 유지돼야 '부팅 때 실패'를 재현할 수 있다.
const 실패키 = "왜곡.서버실패";
let 강제실패 = false;
try {
  강제실패 = localStorage.getItem(실패키) === "1";
} catch {
  /* 저장소를 못 쓰는 환경이면 그냥 정상 동작 */
}
if (typeof window !== "undefined") {
  window.왜곡_서버실패 = (v = true) => {
    강제실패 = v;
    try {
      v ? localStorage.setItem(실패키, "1") : localStorage.removeItem(실패키);
    } catch {
      /* 저장 실패는 무시 — 이번 세션에서만 적용된다 */
    }
    console.log(`[모의서버] 강제실패 = ${v} (새로고침해도 유지)`);
  };
}

function 읽기() {
  try {
    return JSON.parse(localStorage.getItem(저장키) || "null");
  } catch {
    return null;
  }
}
function 쓰기(값) {
  try {
    localStorage.setItem(저장키, JSON.stringify(값));
  } catch {
    /* 저장 공간이 막혀 있으면 조용히 넘어간다 */
  }
}

// 서버가 돌려주는 진행 상태의 모양.
//   ★ 이 모양이 계약서다. 백엔드도 이대로 내려줘야 한다.
const 기본진행 = {
  게스트: true, // 계정 없이 플레이 중인가 (USR-005)
  아바타있음: false, // S2 를 마쳤는가 (USR-111)
  조사관명: null,
  튜토리얼완료: false, // S5 훈련실을 마쳤는가 (전역-003 · S5-013)
  최근플레이세션: null, // 이어하기 후보 (전역-004)
  약관동의: false, // S1-006 — 필수 항목에 모두 동의했는가
  생년: null, // 만 14세 미만 분기용. 연도만 받는다(USR-003)
  마케팅동의: false, // 선택 항목
};

// 동의 이력은 진행 상태와 따로 쌓는다.
//   ★ S1-006 「갱신하지 않고 쌓는다」 — 덮어쓰면 '언제 무엇에 동의했는지'가 사라진다.
//     약관이 개정되면 새 버전으로 한 줄이 더 쌓이고, 옛 줄은 그대로 남아야 한다.
const 동의키 = "왜곡.동의이력.v1";

const 모의서버 = {
  async 진행상태조회() {
    await 지연(120);
    if (강제실패) throw new Error("진행 상태 조회 실패(모의)");
    return { ...기본진행, ...(읽기() || {}) };
  },

  async 진행갱신(부분) {
    await 지연(80);
    const 다음 = { ...기본진행, ...(읽기() || {}), ...부분 };
    쓰기(다음);
    return 다음;
  },

  // S5-013 — 튜토리얼 완료는 서버가 기록한다. 클라이언트 플래그가 아니다.
  async 튜토리얼완료() {
    return this.진행갱신({ 튜토리얼완료: true });
  },

  // S2-009 · S2-010 — 조합 검증은 원래 서버 몫이다. 지금은 통과시킨다.
  async 아바타저장(조합, 조사관명) {
    return this.진행갱신({ 아바타있음: true, 조합, 조사관명 });
  },

  // ── USR-003 · S1-006 동의 ─────────────────────────────────
  // 레코드 하나 = 「누가 · 언제 · 어느 버전에 · 무엇에」 동의했는가.
  //   필수 항목이 하나라도 빠지면 서버가 거절한다(예외: 필수 미동의 차단).
  async 동의저장(레코드) {
    await 지연(120);
    if (강제실패) throw new Error("동의 저장 실패(모의)");
    const 필수빠짐 = (레코드.항목 || []).some((a) => a.필수 && !a.동의);
    if (필수빠짐) throw new Error("필수 항목에 동의하지 않았습니다.");

    let 이력 = [];
    try {
      이력 = JSON.parse(localStorage.getItem(동의키) || "[]");
    } catch {
      이력 = [];
    }
    이력.push(레코드); // ★ 덮어쓰지 않고 쌓는다
    try {
      localStorage.setItem(동의키, JSON.stringify(이력));
    } catch {
      /* 저장 공간이 막혀 있어도 진행은 막지 않는다 */
    }

    const 마케팅 = (레코드.항목 || []).find((a) => a.키 === "마케팅");
    return this.진행갱신({
      약관동의: true,
      생년: 레코드.생년 ?? null,
      마케팅동의: !!(마케팅 && 마케팅.동의),
    });
  },

  async 동의이력조회() {
    await 지연(60);
    try {
      return JSON.parse(localStorage.getItem(동의키) || "[]");
    } catch {
      return [];
    }
  },

  // S2-008 — 금칙어 목록은 클라이언트로 내려보내지 않는다. 판정 결과만 준다.
  async 조사관명검사(이름) {
    await 지연(100);
    const 길이 = [...(이름 || "")].length;
    if (길이 < 2 || 길이 > 12) return { 가능: false, 사유: "2~12자로 정해 주세요." };
    return { 가능: true };
  },
};

// 화면 코드는 이 이름만 쓴다. 구현이 바뀌어도 여기만 갈아끼우면 된다.
export const 서버 = 모의서버;

// 지금이 모의 서버인지 알려 준다(화면 구석 표시용).
export const 모의서버인가 = true;
