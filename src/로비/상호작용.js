// ═══════════════════════════════════════════════════════════════
//  ① 겨냥 — 자주 바뀌므로 물건 상태와 **다른 상자**에 담는다
// ═══════════════════════════════════════════════════════════════
// 겨냥은 고개를 돌릴 때마다 바뀐다. 이걸 물건 상태와 같은 상자에 넣으면
// 화면을 둘러보기만 해도 로비 전체가 다시 그려진다. 그래서 분리했다.
//   · 겨냥  → 화면 아래 안내문(HUD) 만 구독한다
//   · 상태  → 씬이 구독한다 (여닫기·들기처럼 실제로 뭔가 바뀔 때만 알린다)

const 대상 = new Map(); // id -> { 라벨, 위치(), 실행(), 반경, 거리, 끔() }

let 겨냥id = null;
const 겨냥듣는이 = new Set();
const 겨냥알리기 = () => {
  for (const f of 겨냥듣는이) f();
};

export const 겨냥 = {
  값: () => 겨냥id,
  라벨: () => (겨냥id ? 라벨읽기(대상.get(겨냥id)) : ""),
  구독: (f) => {
    겨냥듣는이.add(f);
    return () => 겨냥듣는이.delete(f);
  },
};

const 라벨읽기 = (t) =>
  !t ? "" : typeof t.라벨 === "function" ? t.라벨() : (t.라벨 ?? "");

export const use겨냥 = () => useSyncExternalStore(겨냥.구독, 겨냥.값);

// 화면 아래 안내문용. 겨냥이 바뀔 때뿐 아니라 **물건 상태가 바뀔 때도** 다시 읽어야 한다.
//   서랍을 열면 같은 물건인데 문구가 「열기」에서 「닫기」로 바뀌기 때문이다.
export const use겨냥라벨 = () => {
  useSyncExternalStore(겨냥.구독, 겨냥.값);
  useSyncExternalStore(로비상태.구독, 로비상태.값);
  return 겨냥.라벨();
};

/** 지금 겨냥 중인 것을 실행한다. 처리했으면 true (E 키가 여기서 소비된다) */
export function 실행() {
  const t = 겨냥id && 대상.get(겨냥id);
  if (!t) return false;
  t.실행();
  return true;
}

// ── 겨냥 판정 ──────────────────────────────────────────────
// [왜 광선(Raycaster)을 안 쓰는가]
//   이 씬은 드로우콜을 줄이려고 메시를 병합해 뒀고, 물건마다 외곽선 메시가 한 겹 더 있다.
//   거기에 광선을 쏘면 맞은 것에서 부모를 거슬러 올라가 주인을 찾아야 하고 비용도 크다.
//   물건이 전부 '한 점'으로 대표되는 소품이라, **시선에서 옆으로 얼마나 벗어났나**만
//   재면 충분하다. 계산이 싸고 결과가 예측 가능하다(벽 뒤가 안 잡히는 대신,
//   손 닿는 거리가 1.8m 라 벽 너머가 걸리는 경우가 사실상 없다).
const 손닿는거리 = 6; // 1 유닛 ≈ 0.30m → 6 ≈ 1.8m (조사시스템의 판정.거리와 같은 값)
const 기본반경 = 0.9; // 시선에서 옆으로 이만큼(≈27cm) 안이면 겨냥으로 친다

const _앞 = new THREE.Vector3();
const _차 = new THREE.Vector3();

/** 매 프레임(정확히는 겨냥판정 컴포넌트가 정한 주기마다) 부른다 */
// 이미 한 번 일러 준 대상은 다시 안 찍는다(매 프레임 콘솔이 넘친다)
const 터진대상 = new Set();

export function 겨냥갱신(카메라, 켬 = true) {
  if (!켬) {
    if (겨냥id !== null) {
      겨냥id = null;
      겨냥알리기();
    }
    return;
  }
  카메라.getWorldDirection(_앞);
  const c = 카메라.position;

  let 찾은id = null;
  let 최소옆거리 = Infinity;

  for (const [id, t] of 대상) {
    // ★ 여기서 예외가 나면 **겨냥 루프 전체가 죽는다.** 그러면 이 물건 하나가
    //   아니라 문·물건 집기·호버까지 한꺼번에 먹통이 된다. 실제로 겪었다
    //   (끔 을 함수가 아니라 값으로 넘긴 대상 하나 때문에 전부 멈췄다).
    //   그래서 ① 끔 은 함수든 값이든 받고 ② 한 대상이 터져도 건너뛰기만 한다.
    let p;
    try {
      const 끔 = typeof t.끔 === "function" ? t.끔() : t.끔;
      if (끔) continue;
      p = t.위치();
    } catch (e) {
      if (!터진대상.has(id)) {
        터진대상.add(id);
        console.error(`[겨냥] "${id}" 가 말썽이라 건너뜁니다.`, e);
      }
      continue;
    }
    if (!p) continue;
    _차.set(p[0] - c.x, p[1] - c.y, p[2] - c.z);

    // 시선 방향 성분(앞거리)과 그에 수직인 성분(옆거리)으로 나눈다.
    const 앞거리 = _차.dot(_앞);
    if (앞거리 <= 0) continue; // 뒤에 있는 것
    if (앞거리 > (t.거리 ?? 손닿는거리)) continue; // 너무 멂
    const 옆거리제곱 = _차.lengthSq() - 앞거리 * 앞거리;
    const 반경 = t.반경 ?? 기본반경;
    if (옆거리제곱 > 반경 * 반경) continue; // 시선에서 너무 벗어남

    // 가장 정면에 가까운 것 하나만. (거리보다 '얼마나 정조준했나'를 우선한다 —
    // 책상 위에 물건이 붙어 있어서 거리로 고르면 옆 물건이 자꾸 잡힌다)
    if (옆거리제곱 < 최소옆거리) {
      최소옆거리 = 옆거리제곱;
      찾은id = id;
    }
  }

  if (찾은id !== 겨냥id) {
    겨냥id = 찾은id;
    겨냥알리기();
  }
}

/**
 * 겨냥 대상으로 등록한다. 컴포넌트가 살아 있는 동안만 등록된다.
 * @param id    물건마다 다른 이름
 * @param 정보  { 라벨, 위치:()=>[x,y,z], 실행:()=>void, 반경?, 거리?, 끔?:()=>bool|bool }
 *
 * ★ 위치·실행은 매 렌더 새로 만들어지는 함수라 의존성에 넣으면 등록이 계속 풀린다.
 *   그래서 최신 값을 상자에 담아 두고, 등록된 쪽은 상자를 통해 읽게 한다.
 */
export function use대상(id, 정보) {
  const 상자 = useRef(정보);
  상자.current = 정보;
  useEffect(() => {
    대상.set(id, {
      get 라벨() {
        return 상자.current.라벨;
      },
      get 반경() {
        return 상자.current.반경;
      },
      get 거리() {
        return 상자.current.거리;
      },
      get 끔() {
        return 상자.current.끔;
      },
      위치: () => 상자.current.위치(),
      실행: () => 상자.current.실행(),
    });
    return () => {
      대상.delete(id);
      if (겨냥id === id) {
        겨냥id = null;
        겨냥알리기();
      }
    };
  }, [id]);
}

