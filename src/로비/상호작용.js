//   여닫기·들기·밀기 같은 물리 조작이 아예 없다.**
//   반면 로비는 계약 대상이 아닌 FE 전용 공간이다(PRD USR-101 「백엔드 발표시점과 무관」).
//   둘을 한 곳에 섞으면 나중에 서버를 붙일 때 무엇이 계약이고 무엇이 우리 연출인지
//   구분이 안 된다. 그래서 어휘가 다른 만큼 층도 나눠 둔다.
//
// [지켜야 하는 가드레일]
//   GRD-01 되돌릴 수 있음 — 물건은 사라지지 않고, 놓을 자리는 항상 정해진 곳뿐이다.
//   GRD-12 나가는 길    — 밀어서 통로를 막을 수 있는 조작은 넣지 않는다(의자는 2단 토글).
//   GRD-11 한 모달      — 창이 열려 있으면 E 를 아예 처리하지 않는다(App.jsx 에서 차단).

