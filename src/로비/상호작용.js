// [왜 광선(Raycaster)을 안 쓰는가]
//   이 씬은 드로우콜을 줄이려고 메시를 병합해 뒀고, 물건마다 외곽선 메시가 한 겹 더 있다.
//   거기에 광선을 쏘면 맞은 것에서 부모를 거슬러 올라가 주인을 찾아야 하고 비용도 크다.
//   물건이 전부 '한 점'으로 대표되는 소품이라, **시선에서 옆으로 얼마나 벗어났나**만
//   재면 충분하다. 계산이 싸고 결과가 예측 가능하다(벽 뒤가 안 잡히는 대신,
//   손 닿는 거리가 1.8m 라 벽 너머가 걸리는 경우가 사실상 없다).
const 손닿는거리 = 6; // 1 유닛 ≈ 0.30m → 6 ≈ 1.8m (조사시스템의 판정.거리와 같은 값)
const 기본반경 = 0.9; // 물건 크기를 따로 안 준 대상의 크기(≈27cm) — 아래 「점수」의 잣대
// ★ 겨냥 **허용 범위**는 반경보다 이만큼(≈24cm) 넓다(2026-10-01).
//   가운데 점을 물건에 정확히 얹어야만 잡혀서 조작이 빡빡하다는 지적을 두 번 받았다.
//   반경 자체를 키우면 안 된다 — 아래 「점수」가 반경으로 나누기 때문에, 작은 물건
//   (스탠드 등)까지 같이 부풀어 옆의 큰 물건(노트북)을 가로챘다(로비검사 실측).
// ★ 0.8 → 1.15(≈35cm) (2026-10-01 세 번째 「주울 때 반경을 더 넓혀 달라」).
const 겨냥여유 = 1.15;
// ★ 빈손으로 집을 때는 **손 닿는 거리도** 이만큼(≈36cm) 더 준다(같은 날 같은 지시).
//   물건마다 거리={6} 처럼 따로 적어 둔 것이 많아서, 하나씩 고치지 않고 여기서 한꺼번에 더한다.
//   들고 있을 때는 안 더한다 — 내려놓기·넣기는 원래 거리 그대로가 헷갈리지 않는다.
const 거리여유 = 1.2;

const _앞 = new THREE.Vector3();
const _차 = new THREE.Vector3();

/** 매 프레임(정확히는 겨냥판정 컴포넌트가 정한 주기마다) 부른다 */
// 이미 한 번 일러 준 대상은 다시 안 찍는다(매 프레임 콘솔이 넘친다)
const 터진대상 = new Set();

/**
 * @param 원점 거리를 재는 기준점 [x,y,z]. 안 주면 카메라 자리(= 1인칭).
 *   ★ 3인칭에서는 카메라가 캐릭터 뒤 9유닛에 있어서, 카메라에서 재면
 *     손 닿는 물건이 전부 '너무 멀다'로 걸러진다. 그때 캐릭터 자리를 넘긴다.
 *     보는 **방향**은 어느 쪽이든 카메라 것이 맞다(사람이 보는 쪽이니까).
 */
export function 겨냥갱신(카메라, 켬 = true, 원점 = null) {
  if (!켬) {
    if (겨냥id !== null) {
      겨냥id = null;
      겨냥알리기();
    }
    return;
  }
  카메라.getWorldDirection(_앞);
  // ★ 두 가지를 **다른 자리에서** 잰다.
  //   · 닿나?   = 사람(캐릭터) 자리에서 잰 **진짜 거리**
  //   · 보나?   = 카메라 광선(화면 한가운데) 기준 앞/옆
  //   전에는 둘 다 한 점에서 쟀다. 3인칭에서 원점을 캐릭터로 옮겼더니
  //   **발밑 물건이 시선 평면 뒤로 넘어가** `앞거리 <= 0` 에 걸려 사라졌다
  //   (동전이 안 잡히고 강조도 안 뜨던 것이 이것이다).
  //   광선은 늘 카메라에서 쏘는 게 맞다 — 화면 한가운데가 곧 그 선이니까.
  const 눈 = 카메라.position;
  const 손 = 원점 ?? 카메라.position;

  let 찾은id = null;
  let 최소옆거리 = Infinity;
  const 들었나 = !!상태.든것;

  for (const [id, t] of 대상) {
    // ★ 여기서 예외가 나면 **겨냥 루프 전체가 죽는다.** 그러면 이 물건 하나가
    //   아니라 문·물건 집기·호버까지 한꺼번에 먹통이 된다. 실제로 겪었다
    //   (끔 을 함수가 아니라 값으로 넘긴 대상 하나 때문에 전부 멈췄다).
    //   그래서 ① 끔 은 함수든 값이든 받고 ② 한 대상이 터져도 건너뛰기만 한다.
    let p;
    try {
      const 끔 = typeof t.끔 === "function" ? t.끔() : t.끔;
      if (끔) continue;
      p = t.위치();
    } catch (e) {
      if (!터진대상.has(id)) {
        터진대상.add(id);
        console.error(`[겨냥] "${id}" 가 말썽이라 건너뜁니다.`, e);
      }
      continue;
    }
    if (!p) continue;

    // ① 닿나 — 사람 자리에서 잰 진짜 거리. '거리' 라는 이름 그대로다.
    //    (전에는 시선 방향 성분으로 쟀다. 발밑을 내려다보면 그 값이 실제보다
    //     작게 나와서, 손이 안 닿는 것도 닿는 것처럼 잡히곤 했다)
    const 한계 = (t.거리 ?? 손닿는거리) + (들었나 ? 0 : 거리여유);
    _차.set(p[0] - 손.x, p[1] - 손.y, p[2] - 손.z);
    if (_차.lengthSq() > 한계 * 한계) continue; // 너무 멂

    // ② 보나 — 카메라 광선 기준. 앞/옆으로 나눈다.
    _차.set(p[0] - 눈.x, p[1] - 눈.y, p[2] - 눈.z);
    const 앞거리 = _차.dot(_앞);
    if (앞거리 <= 0) continue; // 등 뒤에 있는 것
    const 옆거리제곱 = _차.lengthSq() - 앞거리 * 앞거리;
    const 반경 = t.반경 ?? 기본반경;
    // ★ **들고 있을 때는 여유를 안 준다.** [E] 는 「겨냥한 것 → 없으면 내려놓기」
    //   순서라(App onKey), 넓은 허용에 옆 스탠드가 걸리면 컵을 내려놓으려던 [E] 가
    //   스탠드를 켰다(로비검사 실측). 여유는 **빈손으로 집을 때** 쓰라고 넓힌 것이다.
    const 허용 = 반경 + (들었나 ? 0 : 겨냥여유);
    if (옆거리제곱 > 허용 * 허용) continue; // 시선에서 너무 벗어남

    // 가장 정면에 가까운 것 하나만. (거리보다 '얼마나 정조준했나'를 우선한다 —
    // 책상 위에 물건이 붙어 있어서 거리로 고르면 옆 물건이 자꾸 잡힌다)
    // ★ 점수는 **제 크기에 견준** 벗어남(옆거리 ÷ 반경)이다. 허용을 넓힌 뒤로는
    //   큰 물건 한가운데를 겨눠도 그 중심점보다 옆 소품의 점이 선에 더 가까울 수
    //   있다. 크기로 나누면 「그 물건 안을 겨눴다」가 이긴다.
    const 점수 = 옆거리제곱 / (반경 * 반경);
    if (점수 < 최소옆거리) {
      최소옆거리 = 점수;
      찾은id = id;
    }
  }

  if (찾은id !== 겨냥id) {
    겨냥id = 찾은id;
    겨냥알리기();
  }
}

/**
 * 지금 겨냥한 것이 **어디 있나** [x,y,z]. 없으면 null.
 *
 * [왜 필요한가]
 *   [E] 로 만질 때 팔이 한 번 뻗는데, 그 손이 **몸 앞 한 방향**으로만 나갔다.
 *   그래서 자판기 버튼을 누르면 팔이 버튼이 아니라 **자판기 속으로** 들어갔고,
 *   서랍·스탠드도 손이 엉뚱한 데를 짚었다. 만지는 물건이 어디 있는지 알아야
 *   그 쪽으로 손을 보낼 수 있다(App 의 손붙이기 가 읽는다).
 *   상용 게임이 상호작용 지점마다 '손 자리'를 박아 두는 것과 같은 것인데,
 *   우리는 이미 겨냥 대상이 제 위치를 알고 있으니 그걸 그대로 쓴다.
 */
export function 겨냥위치() {
  if (!겨냥id) return null;
  const t = 대상.get(겨냥id);
  if (!t) return null;
  try {
    return t.위치() ?? null;
  } catch {
    return null; // 위치 함수가 터져도 팔 때문에 게임이 멈추면 안 된다
  }
}

/**
 * 겨냥 대상으로 등록한다. 컴포넌트가 살아 있는 동안만 등록된다.
 * @param id    물건마다 다른 이름
 * @param 정보  { 라벨, 위치:()=>[x,y,z], 실행:()=>void, 반경?, 거리?, 끔?:()=>bool|bool }
 *
 * ★ 위치·실행은 매 렌더 새로 만들어지는 함수라 의존성에 넣으면 등록이 계속 풀린다.
 *   그래서 최신 값을 상자에 담아 두고, 등록된 쪽은 상자를 통해 읽게 한다.
 */
export function use대상(id, 정보) {
  const 상자 = useRef(정보);
  상자.current = 정보;
  useEffect(() => {
    대상.set(id, {
      get 라벨() {
        return 상자.current.라벨;
      },
      get 반경() {
        return 상자.current.반경;
      },
      get 거리() {
        return 상자.current.거리;
      },
      get 끔() {
        return 상자.current.끔;
      },
      위치: () => 상자.current.위치(),
      실행: () => 상자.current.실행(),
    });
    return () => {
      대상.delete(id);
      if (겨냥id === id) {
        겨냥id = null;
        겨냥알리기();
      }
    };
  }, [id]);
}

