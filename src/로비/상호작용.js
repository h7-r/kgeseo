const 듣는이 = new Set();
function 세팅(부분) {
  상태 = { ...상태, ...부분 };
  for (const f of 듣는이) f();
}

export const 로비상태 = {
  값: () => 상태,
  구독: (f) => {
    듣는이.add(f);
    return () => 듣는이.delete(f);
  },
};

export const use로비상태 = () =>
  useSyncExternalStore(로비상태.구독, 로비상태.값);

// ── 서랍 ───────────────────────────────────────────────────
// [왜 부드럽게 안 밀고 몇 단계로 끊어 여는가]
//   서랍 몸통은 뺀 깊이(양)에 따라 **측벽·바닥 길이가 실제로 달라진다**
//   (CabinetDrawer 의 부품 useMemo 가 양에 물려 있다).
//   그래서 양을 매 프레임 바꾸면 프레임마다 BoxGeometry 4개를 새로 만들고 버린다.
//   사람 눈에는 몇 단계만 있어도 '스르륵'으로 읽히므로 단계로 끊었다.
const 열기단계 = [0.25, 0.55, 0.8, 1]; // 목표 대비 비율
const 닫기단계 = [0.8, 0.55, 0.25, 0]; // 마지막 0 = 완전히 닫힘(서랍을 떼어낸다)
const 서랍간격 = 45; // ms

export function 서랍열림(캐비닛id) {
  return 상태.서랍[캐비닛id] ?? null;
}

/**
 * 서랍을 연다/닫는다.
 * @param 방향 "열기" | "닫기"
 *
 * ★ '지금 열려 있나'를 여기서 판단하지 않고 씬이 정해 준다.
 *   캐비닛은 손대기 전에도 Leva 연출값(CAB_OPEN_PLAN)으로 이미 몇 칸이 열려 있다.
 *   이 상자만 보면 그걸 모르기 때문에, 화면에 실제로 보이는 상태를 아는 쪽이 정해야 한다.
 */
export function 서랍움직이기(캐비닛id, 칸, 최대양, 방향) {
  // 여는지 닫는지에 따라 소리가 다르다(실제 서랍 여닫힘과 같은 순간에 낸다).
  소리재생(방향 === "열기" ? "서랍열기" : "서랍닫기", { 볼륨: 0.9 });
  단계재생(캐비닛id, 칸, 최대양, 방향);
}

const 진행중 = new Map(); // 캐비닛id -> timer
function 단계재생(캐비닛id, 칸, 최대양, 방향) {
  clearInterval(진행중.get(캐비닛id));
  let i = 0;
  const 순서 = 방향 === "열기" ? 열기단계 : 닫기단계;
  const 한칸 = () => {
    const 비율 = 순서[i];
    // 비율 0 = 완전히 닫힘. null 을 넣어 서랍 컴포넌트를 통째로 떼면
    // 원래 GLB 앞판이 그대로 보인다(손대기 전과 같은 모습).
    const 다음 = 비율 <= 0 ? null : { 칸, 양: 최대양 * 비율 };
    세팅({ 서랍: { ...상태.서랍, [캐비닛id]: 다음 } });
    if (++i >= 순서.length) {
      clearInterval(진행중.get(캐비닛id));
      진행중.delete(캐비닛id);
    }
  };
  한칸();
  if (순서.length > 1) 진행중.set(캐비닛id, setInterval(한칸, 서랍간격));
}

// ── 램프 ───────────────────────────────────────────────────
export const 램프켜짐 = (id, 기본) => 상태.램프[id] ?? 기본;
export function 램프토글(id, 기본) {
  세팅({ 램프: { ...상태.램프, [id]: !램프켜짐(id, 기본) } });
}

// ── 의자 끌기 ──────────────────────────────────────────────
// [GRD-12(모든 화면에 나가는 길)는 왜 안 깨지나]
//   의자를 문 앞에 두면 길이 막힌다. 그런데 **막힌 의자는 여전히 잡을 수 있다** —
//   E 로 다시 끌어 옮기면 되므로 영구히 갇히는 상황이 생기지 않는다.
//   그래서 '놓을 수 있는 자리'를 따로 제한하지 않았다. 제한을 걸면 오히려
//   "왜 여기 못 놓는지"를 글자 없이 설명할 방법이 없다.
export const 끄는의자 = () => 상태.끄는의자;
export const 의자자리 = (id) => 상태.의자자리[id] ?? null;

export function 의자잡기(id) {
  if (상태.끄는의자 || 상태.든것) return false; // 한 번에 하나만
  세팅({ 끄는의자: id });
  루프시작("의자", { 볼륨: 0.9 }); // 끄는 동안 계속 반복 — 다시 E로 놓을 때 멈춘다
  return true;
}

/** 지금 끌던 의자를 이 자리에 놓는다 */
export function 의자놓기(x, z) {
  const id = 상태.끄는의자;
  if (!id) return false;
  루프정지("의자"); // 의자를 내려놓으면 긁는 소리를 멈춘다
  // ★ 좌표가 안 왔거나 이상한 값이면 자리를 옮기지 않고 그냥 놓는다.
  //   잡은 첫 프레임에 E 를 누르면 아직 따라오는 계산이 한 번도 안 돌아
  //   좌표가 비어 있을 수 있다. 그걸 그대로 쓰면 의자가 방 원점으로 날아간다.
  const 성한값 = Number.isFinite(x) && Number.isFinite(z);
  세팅({
    끄는의자: null,
    의자자리: 성한값 ? { ...상태.의자자리, [id]: { x, z } } : 상태.의자자리,
  });
  return true;
}

// ── 들기 / 놓기 ────────────────────────────────────────────
// [자리 = 자유 좌표]
//   어디에 놓을지는 배치.js 가 「광선 → 면 → 발자국 → 겹침 검사」로 계산한다.
//   여기서는 그 결과 좌표만 물건별로 들고 있는다. 값이 없으면 Leva 원래 자리.
//     자리[물건id] = { x, y, z, rot }

// ※ '지금 어디에 놓여 있나'는 씬이 Leva 값과 함께 계산한다(자리 좌표가 Leva 에 있으므로).
//   여기서는 「물건 → 자리 id」 짝만 들고 있는다.

// 물건 종류별 소리. paper*=종이(서류), mug*=컵, 나머지=박스.
//   드나: true=드는 소리 / false=놓는 소리.
const 물건소리 = (id, 드나) =>
  typeof id === "string" && id.startsWith("paper") ? "서류"
  : typeof id === "string" && id.startsWith("mug") ? "컵버리기"
  : 드나 ? "박스들기" : "박스놓기";

export function 집기(물건id) {
  if (상태.든것 || 상태.끄는의자) return; // 두 손에 들 수는 없다
  세팅({ 든것: 물건id });
  소리재생(물건소리(물건id, true), { 볼륨: 0.9 });
}

/**
 * 든 것을 이 좌표에 놓는다.
 * @param 곳 { x, y, z, rot } — 겹침 검사를 통과한 자리(배치.js 가 계산해 준다)
 */
export function 놓기(곳) {
  const 든 = 상태.든것;
  if (!든 || !곳) return false;
  세팅({ 든것: null, 자리: { ...상태.자리, [든]: { ...곳 } } });
  소리재생(물건소리(든, false), { 볼륨: 0.9 });
  return true;
}

/** 든 것을 원래 자리로 돌려놓는다(씬을 떠날 때 등) */
export function 제자리로() {
  const 든 = 상태.든것;
  if (!든) return;
  const 자리 = { ...상태.자리 };
  delete 자리[든];
  소리재생(물건소리(든, false), { 볼륨: 0.9 }); // 제자리에 되돌려 놓는 소리
  세팅({ 든것: null, 자리 });
}

// 콘솔 확인용
// 콘솔 확인용
//   ★ 겨냥갱신도 내놓는다. 겨냥은 마우스 잠금(active)일 때만 매 프레임 도는데,
//     헤드리스 브라우저에는 마우스 잠금이 없어서 시험이 한 번도 겨냥을 못 한다.
//     여기로 한 판 직접 돌려 "지금 이 자리에서 무엇이 겨냥되나"를 확인한다.
// ★ 중괄호 — 예전에는 없었다. 그래서 `if` 가 **첫 줄만** 덮고 아래 `__대상목록`
//   대입은 조건 밖에서 무조건 돌았다. 브라우저 전용이라 지금은 무해하지만,
//   window 가 없는 데(테스트 러너·SSR)서 돌리면 그 줄에서 바로 터진다.
if (typeof window !== "undefined") {
  window.__로비 = { 로비상태, 겨냥, 실행, 겨냥갱신, 겨냥위치, 제자리로 };
  // 콘솔 확인용 — 지금 화면에 등록된 **상호작용 지점 전부**와 그 자리.
  //   물건 앞까지 걸어가 하나씩 확인하는 데 시간이 너무 걸려서 만들었다.
  //   `__대상목록()` → [{id, 위치, 라벨, 끔}] · 렌더에는 영향이 없다.
  window.__대상목록 = () =>
    [...대상].map(([id, t]) => {
      let 위치 = null;
      let 끔 = null;
      try {
        위치 = t.위치();
      } catch {
        위치 = "오류";
      }
      try {
        끔 = typeof t.끔 === "function" ? t.끔() : t.끔;
      } catch {
        끔 = "오류";
      }
      return { id, 위치, 라벨: t.라벨, 끔, 거리: t.거리, 반경: t.반경 };
    });
}
