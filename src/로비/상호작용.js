//   적용 씬이 **S4·S7 둘 다**로 적혀 있다. 로비에서 E를 쓰는 건 이미 허용된 것.
//   ※ 다만 S4-009 는 04_조작 시트에만 있고 01_기능목록에는 S4-008 까지밖에 없다.
