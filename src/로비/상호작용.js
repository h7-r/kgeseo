/** 지금 겨냥 중인 것을 실행한다. 처리했으면 true (E 키가 여기서 소비된다) */
export function 실행() {
  const t = 겨냥id && 대상.get(겨냥id);
  if (!t) return false;
  t.실행();
  return true;
}

