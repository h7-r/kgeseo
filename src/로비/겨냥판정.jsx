// ── 시점을 바꾼 직후에만 짧게 따라붙는다 ─────────────────────────
// [무엇이 문제였나]
//   3인칭은 물건을 **손뼈 자리에 그대로 박고**(copy), 1인칭은 **카메라 앞
//   자리로 천천히 따라간다**(lerp). 계산이 통째로 다른 두 경로다. V 로 시점을
//   바꾸면 물건이 그 두 자리 사이를 **한 프레임에 순간이동**했다.
//   (1인칭 → 3인칭 쪽이 특히 심하다 — 카메라 앞에 있던 컵이 손에 '툭' 나타난다)
// [왜 늘 lerp 로 안 두나]
//   3인칭에서 손은 이미 애니메이션으로 움직인다. 거기에 또 감쇠를 물리면 두 번
//   늦어져서 물건이 손에서 흐물거린다(그래서 원래 copy 다).
// [그래서] 시점이 바뀐 **0.2초 동안만** 따라붙게 하고, 그 뒤에는 원래대로 박는다.
// ★ 지수 감쇠(lerp)로 하면 **첫 프레임이 가장 크게 튄다.** 두 자리가 5유닛쯤
//   떨어져 있어서 첫 프레임에만 1.59유닛이 건너뛰었다(실측). 그건 '따라붙는다'가
//   아니라 그냥 작은 순간이동이다.
//   그래서 **시작 자리를 기억해 두고 0 → 1 로 부드럽게 건너간다**(smoothstep).
//   시작과 끝의 속도가 0 이라 출발도 도착도 안 튀고, 창이 끝나는 순간 정확히
//   목표에 닿아 있어 남는 오차도 없다.
const 전환시간 = 0.3;

// 물건이 제 좌/우 짚는 점의 **세계 자리**를 알려 준다 — 양팔 IK 가 그리로 간다.
//   물건 변환을 아는 건 여기뿐이다(App 은 물건 폭을 모른다). 다음 프레임
//   손붙이기(−30)가 읽어 간다. 두 손 물건이 아니면 꺼 둔다 — 안 끄면 빈손인데
//   왼팔이 허공을 붙잡고 있다.
function 두손알림(규, o) {
  const 두 = 플레이어시점.두손;
  if (!규.두손 || !규.손자리) {
    두.쓸수있나 = false;
    return;
  }
  const [hx, hy, hz] = 규.손자리;
  // ★ 이 모델은 **로컬 +x 가 캐릭터의 왼쪽**이다(아바타의 발바닥 좌우 가르기와
  //   같은 규약). 물건을 yaw(몸각) 로만 돌리므로 그 규약이 그대로 이어진다.
  //   그래서 `손자리`(+x)는 **왼손** 자리고, 뒤집은 것이 오른손 자리다.
  //   반대로 넣었더니 두 팔이 **몸을 가로질러** 반대쪽을 잡았다 —
  //   오른팔은 어깨-목표 1.417/1.43(99%)로 쭉 펴졌고, 왼팔은 1.681(117%)이라
  //   아예 닿지도 못했다(실측). 팔이 가슴 앞에서 X 자로 꼬여 있었던 셈이다.
  두.왼.set(hx, hy, hz).applyQuaternion(o.quaternion).add(o.position);
  두.오른.set(-hx, hy, hz).applyQuaternion(o.quaternion).add(o.position);
  두.쓸수있나 = true;
}
// ── 잡기 — 손이 물건에 **닿은 뒤** 손으로 건너간다 ─────────────────
// [무엇이 문제였나]
//   [E] 를 누르면 `든것` 이 그 프레임에 바뀌어 물건이 곧바로 손 자리에 박혔다.
//   손은 아직 몸 옆에 있으니 물건이 탁자에서 손으로 **순간이동**하고, 그 뒤에
//   팔이 뒤늦게 올라온다. 1인칭에서 몸을 그리게 되자(1인칭 손) 이게 그대로 보였다.
// [상용은 어떻게 하나]
//   집기 클립에 「Attach」 알림을 두고 손이 물건에 닿는 프레임에 붙인다(UE 의
//   AnimNotify · Unity Animation Rigging 은 IK 가중치가 1 이 된 뒤 재부모).
//   우리는 집기 클립이 없고 팔뻗은양(공용.jsx)이 0.16초에 손을 물건까지 보내니,
//   그 시간만큼 물건을 제자리에 두었다가 짧게 손으로 건너가게 한다.
// [값] 지연 = 팔뻗은양 의 「나감」 0.16초와 같다. 건너감 0.14초 — 손이 물건
//   겉면 0.12 앞에서 멈추므로(뻗손자리) 그 틈을 메우는 짧은 이동이다.
//   ★ 시작 자리를 모르는 물건(동전·관창처럼 `시작자리` 를 안 넘긴 것)은 예전
//     그대로 첫 프레임에 손에 박힌다 — 넘긴 것만 달라진다.
const 잡기지연 = 0.16;
const 잡기건너감 = 0.14;

export function 손에든것({
  children,
  물건id,
  앞 = 2.1,
  아래 = 0.95,
  옆 = 0.85,
  // 물건 종류(머그·상자·서류…). 쥠표 가 이걸로 '어떻게 쥐나'를 정한다.
  종류,
  // 집기 전에 **놓여 있던 자리**(세계 좌표 [x,y,z])와 yaw(라디안). 위 「잡기」.
  시작자리 = null,
  시작각 = 0,
}) {
  const g = useRef(null);
  const 첫프레임 = useRef(true);
  const { camera } = useThree();
  // 시점 전환 직후인가 — 위 「전환시간」 참고
  const 이전삼인칭 = useRef(플레이어시점.삼인칭);
  const 전환남음 = useRef(0);
  const 전환시작 = useRef(new THREE.Vector3());
  const 전환시작각 = useRef(new THREE.Quaternion());
  // 잡기(위) — 남은 시간. 지연 동안은 시작 자리에, 그 뒤 건너감 동안 손으로.
  const 잡기남음 = useRef(0);
  // 물건을 내려놓으면 이 컴포넌트가 사라진다 — 마지막 값이 남아 있으면
  //   빈손인데도 왼팔이 허공을 붙잡고 있다. 떠날 때 꺼 준다.
  useEffect(
    () => () => {
      플레이어시점.두손.쓸수있나 = false;
      플레이어시점.집은자리.쓸수있나 = false;
    },
    [],
  );
  // 시작 자리를 알면 「잡기」를 건다 + 손붙이기(−30)가 팔을 뻗을 자리를 알려 준다.
  //   ★ 마운트 때 한 번이다. 시작자리 배열은 렌더마다 새로 만들어지므로
  //     의존성에 넣으면 매 렌더 되풀이된다 — 처음 값만 쓴다.
  useEffect(() => {
    if (!시작자리) return;
    const 집 = 플레이어시점.집은자리;
    집.자리.set(시작자리[0], 시작자리[1], 시작자리[2]);
    집.각 = 시작각;
    집.쓸수있나 = true;
    전환시작.current.copy(집.자리);
    전환시작각.current.setFromAxisAngle(_위축, 시작각);
    잡기남음.current = 잡기지연 + 잡기건너감;
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useFrame((_, dt) => {
    const o = g.current;
    if (!o) return;
    그림자흔들기(0.2); // 손에 든 물건은 계속 움직인다 — 그림자도 따라와야 한다

    // 시점이 방금 바뀌었나 (위 「전환시간」) — 바뀌는 순간의 자리를 붙잡아 둔다
    if (플레이어시점.삼인칭 !== 이전삼인칭.current) {
      이전삼인칭.current = 플레이어시점.삼인칭;
      전환남음.current = 전환시간;
      전환시작.current.copy(o.position);
      전환시작각.current.copy(o.quaternion);
    }
    // ★ **자른 dt** 로 줄인다. V 를 누른 그 프레임은 아바타가 켜지며 셰이더가
    //   컴파일돼 유난히 길다(실측: 0.3초 창이 **한 프레임에** 다 닳았다).
    //   그러면 부드럽게 건너가라고 만든 창이 그대로 순간이동이 된다.
    //   걷기가 DT최대로 빗장을 거는 것과 같은 이유다(공용.jsx 「긴 프레임 다루기」).
    if (전환남음.current > 0)
      전환남음.current = Math.max(0, 전환남음.current - Math.min(dt, DT최대));
    // 잡기(위 「잡기」)도 같은 방식으로 자른 dt 로 줄인다 — 집는 프레임에
    //   아바타가 켜지며(1인칭 손) 프레임이 길어질 수 있다.
    if (잡기남음.current > 0)
      잡기남음.current = Math.max(0, 잡기남음.current - Math.min(dt, DT최대));

    /** 물건을 제자리에 놓는다.
     *  평소에는 목표에 그대로 박고, 시점을 막 바꾼 동안만 **시작 자리에서
     *  목표까지 부드럽게 건너간다**(위 「전환시간」).
     *  방금 집은 동안(잡기)은 손이 올 때까지 시작 자리에 있다가 손으로 건너간다.
     *  @param 각 목표 회전. 안 주면 `_손각`(3인칭 경로들이 쓰는 값).
     *  @param 평소붙임 전환 중이 아닐 때 목표에 그대로 박을지. 1인칭 경로는
     *    **제 방식(살짝 늦게 따라가기)** 이 따로 있어서 false 로 넘긴다.
     *    (true 로 두면 여기서 박아 버려 그 맛이 통째로 사라진다)
     *  @returns 전환·잡기 중이라 여기서 자리를 정했으면 true */
    const 붙이기 = (각 = _손각, 평소붙임 = true) => {
      if (잡기남음.current > 0) {
        if (잡기남음.current > 잡기건너감) {
          // 손이 오는 동안 — 놓여 있던 그 자리 그대로
          o.position.copy(전환시작.current);
          o.quaternion.copy(전환시작각.current);
          return true;
        }
        const 진행 = 1 - 잡기남음.current / 잡기건너감; // 0 → 1
        const t = 진행 * 진행 * (3 - 2 * 진행);
        o.position.lerpVectors(전환시작.current, _목표, t);
        o.quaternion.copy(전환시작각.current).slerp(각, t);
        return true;
      }
      if (전환남음.current > 0) {
        const 진행 = 1 - 전환남음.current / 전환시간; // 0 → 1
        const t = 진행 * 진행 * (3 - 2 * 진행); // smoothstep: 시작·끝 속도 0
        o.position.lerpVectors(전환시작.current, _목표, t);
        o.quaternion.copy(전환시작각.current).slerp(각, t);
        return true;
      }
      if (평소붙임) {
        o.position.copy(_목표);
        o.quaternion.copy(각);
      }
      return false;
    };

    // ── 3인칭: 캐릭터 **오른손 뼈**에 쥐어 준다 ────────────────
    // [왜 카메라 기준이면 안 되나]
    //   1인칭은 카메라가 곧 사람이라 '카메라 앞 오른쪽 아래'가 손 자리와 같았다.
    //   3인칭은 캐릭터가 화면에 보이는데 물건만 카메라 앞에 떠 있으면,
    //   **사람과 물건이 따로 논다** — 동전이 혼자 공중에 떠 다니던 것이 그것이다.
    //   손뼈를 따라가면 걸을 때 팔 스윙대로 같이 흔들려서 쥔 것으로 읽힌다.
    const 규 = 쥠규격(종류, 물건id);

    // ── 3인칭 · 품에 안는 물건: 주인이 **손뼈가 아니라 가슴 앞**이다 ──
    // [왜 손이 주인이면 안 되나]
    //   손뼈를 따라가면 걸을 때 **팔 스윙대로 상자가 휘둘린다.** 컵은 그게 맞지만
    //   (팔에 매달린 물건이니까) 상자는 몸통에 안겨 어깨와 함께 움직이고 팔은
    //   그걸 붙잡고 있을 뿐이다. 자리·각은 App 이 이번 프레임 어깨로 만들어 둔다
    //   (몸알림 −15 — 아바타 뒤라 지연이 없다).
    //   ★ 1인칭이어도 「1인칭 손」이 켜진 프레임엔 온다 — 삼인칭 검사를 여기서
    //     따로 안 한다. `품.쓸수있나`·`쥠소켓`·`손` 은 App 의 손붙이기가
    //     「이번 프레임 아바타가 실제로 그려지나」를 보고 넘기는 값이라 그것만 본다.
    const 품 = 플레이어시점.품;
    if (규.품 && 품.켬 && 품.쓸수있나) {
      _목표.copy(품.자리);
      _손각.copy(품.각);
      if (규.쥠각[0] || 규.쥠각[1] || 규.쥠각[2]) {
        _보정.setFromEuler(
          _오일러.set(...규.쥠각.map((d) => (d * Math.PI) / 180)),
        );
        _손각.multiply(_보정);
      }
      // 품점은 **물건 로컬 좌표**라, 물건이 놓일 방향으로 돌린 뒤 빼야 한다
      //   (그 점이 가슴 앵커에 오도록 물건을 반대로 미는 것 — 쥠점과 같은 규칙).
      const 품점 = 규.품점 ?? 규.쥠점;
      if (품점[0] || 품점[1] || 품점[2]) {
        _쥠.set(품점[0], 품점[1], 품점[2]).applyQuaternion(_손각);
        _목표.sub(_쥠);
      }
      첫프레임.current = false;
      // 가슴 앵커는 이미 몸 변환을 그대로 따라간다 — 여기서 또 늦추면 상자만 뒤처진다.
      붙이기();
      두손알림(규, o);
      return;
    }

    // ── 소켓(prop_r)이 있으면 그게 기준이다 ─────────────────
    // [왜 더 나은가]
    //   손뼈 원점은 손목이고 그 축은 리그 사정대로 누워 있다(이 리그는 로컬 +Y 가
    //   세계 **아래**를 본다). 그래서 지금까지 ① 손목→주먹 중심을 눈대중으로
    //   보정하고 ② 물건이 뒤집히는 걸 회전으로 따로 세워야 했다.
    //   `prop_r` 은 이 리그에 **물건을 매달라고 들어 있는 뼈**라 그 둘이 공짜다.
    //   스킨 웨이트 0 · 모션 리타깃도 안 받아서 절대 안 흔들린다.
    const 소켓 = 플레이어시점.쥠소켓;
    if (소켓) {
      // ── 자리는 **언제나** 소켓에서 ─────────────────────────
      //   리그가 "여기에 물건을 매달라"고 만들어 둔 점이다. 손목에서 0.214 유닛
      //   (실측) 떨어진 주먹 한가운데라, 눈대중 보정이 필요 없다.
      소켓.getWorldPosition(_목표);

      // ── 회전은 물건마다 다르다 ────────────────────────────
      // [왜 하나로 못 정하나]
      //   컵은 팔이 흔들려도 **수평을 지켜야** 하고, 소방 노즐은 **손이 겨눈 쪽**을
      //   향해야 한다. 지금까지는 둘 다 같은 규칙이라 컵이 기울거나 노즐이
      //   엉뚱한 데를 봤다. 사용자가 "물건에 따라 손목 꺾임이 달라야 한다"고 한 것.
      // [어떻게] 두 끝을 만들어 `손따름` 으로 섞는다.
      //   0 = 몸 기준으로 똑바로(yaw(몸각))  ·  1 = 소켓(손) 회전 그대로
      //   실측: 소켓 회전을 그대로 쓰면 이 팔 자세에서 컵이 97.5° 기운다 —
      //   소켓이 팔을 따라 돌기 때문이다. 그래서 물건이 골라야 한다.
      const 따름 = Math.max(0, Math.min(1, 규.손따름 ?? 0));
      _손각.setFromAxisAngle(_위축, 플레이어시점.몸각 ?? 0);
      if (따름 > 0.001) {
        소켓.getWorldQuaternion(_소켓q);
        _손각.slerp(_소켓q, 따름);
      }
      const 쥠 = 플레이어시점.쥠;
      if (쥠.rx || 쥠.ry || 쥠.rz) {
        _보정.setFromEuler(_오일러.set(쥠.rx, 쥠.ry, 쥠.rz));
        _손각.multiply(_보정);
      }
      if (규.쥠각[0] || 규.쥠각[1] || 규.쥠각[2]) {
        _보정.setFromEuler(
          _오일러.set(...규.쥠각.map((d) => (d * Math.PI) / 180)),
        );
        _손각.multiply(_보정);
      }
      if (쥠.x || 쥠.y || 쥠.z) {
        _쥠.set(쥠.x, 쥠.y, 쥠.z).applyQuaternion(_손각);
        _목표.add(_쥠);
      }
      if (규.쥠점[0] || 규.쥠점[1] || 규.쥠점[2]) {
        _쥠.set(...규.쥠점).applyQuaternion(_손각);
        _목표.sub(_쥠);
      }
      첫프레임.current = false;
      붙이기();
      두손알림(규, o);
      return;
    }

    const 손 = 플레이어시점.손;
    if (손) {
      // ★ 손뼈 원점은 **손목**이다. 거기에 물건을 두면 주먹이 아니라 팔목에
      //   붙은 것처럼 보인다 — 머그가 손가락 옆을 스쳐 지나가던 게 그것이다.
      //   아바타가 재서 알려 준 '주먹 한가운데'(손뼈 로컬)를 세계로 옮겨 쓴다.
      //   localToWorld 라서 체형 슬라이더로 배율이 바뀌어도 저절로 맞는다.
      const 손바닥 = 플레이어시점.손바닥;
      if (손바닥) {
        _목표.set(손바닥.x, 손바닥.y, 손바닥.z);
        손.localToWorld(_목표);
      } else {
        손.getWorldPosition(_목표);
      }
      // ── ① 물건이 **어느 쪽을 보고 있나** ──────────────────
      // [왜 손뼈 회전을 그대로 안 쓰나]
      //   손뼈 축이 어느 쪽을 보는지는 리그가 정한다. 이 리그에서는 손뼈 회전을
      //   그대로 물려받으면 머그가 **세계 위에서 131.6° 기운 채**(거의 뒤집힌 채)
      //   들려서 커피가 쏟아질 자세였다.
      //   물건 여덟 개를 재 보니 "똑바로 세우는 각"이 전부 같았다(≈128°) —
      //   물건 값이 아니라 **리그가 정한 상수**라는 뜻이다. 그래서 물건마다
      //   128 을 베껴 넣지 않고, 여기서 **몸 기준 똑바른 자세**를 한 번 만든다.
      // [무엇을 기준으로 세우나] 몸이 바라보는 쪽(플레이어시점.몸각):
      //   +x = 몸의 오른쪽 · +y = 세계 위 · +z = 몸 앞.
      //   대부분의 물건이 모델 +y 가 '위'라 이것만으로 컵은 서고 서류는 눕는다.
      //   물건마다 다른 나머지는 쥠표 의 쥠각 이 얹는다(대개 0).
      // [손 흔들림을 잃지 않나] 자리(위치)는 여전히 손뼈를 따라간다. 회전만
      //   고정이다 — 컵을 든 사람의 손목이 컵을 기울이지 않는 것과 같다.
      _손각.setFromAxisAngle(_위축, 플레이어시점.몸각 ?? 0);
      // ② 손목 기준 공통 보정 — Leva 「손에 쥐기」로 사람이 얹는 손보기.
      const 쥠 = 플레이어시점.쥠;
      _쥠.set(쥠.x, 쥠.y, 쥠.z).applyQuaternion(_손각);
      _목표.add(_쥠);
      _보정.setFromEuler(_오일러.set(쥠.rx, 쥠.ry, 쥠.rz));
      _손각.multiply(_보정);

      // ③ 물건마다 다른 '잡는 자리' — 쥠표 가 들고 있다.
      //    컵은 손잡이, 상자는 품, 서류는 모아 쥐기… 물건 쪽 값이라 하나를
      //    고쳐도 다른 물건이 안 틀어진다(쥠표.js 머리말 참고).
      if (규.쥠각[0] || 규.쥠각[1] || 규.쥠각[2]) {
        _보정.setFromEuler(
          _오일러.set(...규.쥠각.map((d) => (d * Math.PI) / 180)),
        );
        _손각.multiply(_보정);
      }
      // 쥠점은 **물건 로컬 좌표**라, 물건이 놓일 방향으로 돌린 뒤 빼야 한다.
      //   (그 점이 손에 오도록 물건을 반대로 미는 것이다)
      if (규.쥠점[0] || 규.쥠점[1] || 규.쥠점[2]) {
        _쥠.set(...규.쥠점).applyQuaternion(_손각);
        _목표.sub(_쥠);
      }
      if (첫프레임.current && !(잡기남음.current > 0)) {
        첫프레임.current = false;
        o.position.copy(_목표);
        o.quaternion.copy(_손각);
        두손알림(규, o);
        return;
      }
      첫프레임.current = false;
      // 손은 이미 애니메이션으로 움직인다 — 여기서 또 늦추면 두 번 늦어 흐물거린다.
      붙이기();
      두손알림(규, o);
      return;
    }

    // ── 손뼈가 없을 때(1인칭 · 아바타 GLB 가 아직 안 붙은 처음 몇 프레임) ──
    // ★ 기준점은 카메라가 아니라 **사람이 선 자리**다.
    //   1인칭은 둘이 같아서 티가 안 났지만, 3인칭에서 손뼈가 잠깐이라도 비면
    //   카메라 기준 앞 2.1 은 캐릭터보다 **7 유닛 넘게 뒤**라서 물건이 등 뒤
    //   허공에 떴다. 방향(어디를 보나)만 카메라에서 가져오고 원점은 사람으로 둔다.
    const 사람 = 플레이어시점.쓸수있나 ? 플레이어시점.눈 : camera.position;

    // ① 들고 싶은 자리 = 사람 기준 오른쪽·아래·앞(보는 방향은 카메라)
    _목표.set(옆, -아래, -앞).applyQuaternion(camera.quaternion).add(사람);

    // ② 막혔으면 사람 쪽으로 당긴다. 물건 크기만큼 여유를 둔다.
    const 반경 = (크기.get(물건id)?.halfX ?? 0.3) + 0.12;
    _시작.copy(사람);
    const [x, y, z] = 스프링암(
      [_시작.x, _시작.y, _시작.z],
      [_목표.x, _목표.y, _목표.z],
      반경,
      물건id, // 들고 있는 자기 자신의 옛 자리는 검사에서 뺀다
      8,
      // 근평면(0.25)보다 넉넉히 앞. 책상 앞에서 집어도 물건이 안 사라진다.
      0.8,
    );
    _목표.set(x, y, z);

    // ③ 살짝 늦게 따라간다. 처음 든 순간만 즉시 맞춘다(안 그러면 방 저편에서 날아온다).
    //   잡기 중이면 붙이기 가 시작 자리에서 건너가게 하므로 여기서 박지 않는다.
    if (첫프레임.current && !(잡기남음.current > 0)) {
      첫프레임.current = false;
      o.position.copy(_목표);
      o.quaternion.copy(camera.quaternion);
      return;
    }
    첫프레임.current = false;
    // 시점을 막 바꿨으면 위 「전환시간」 동안 부드럽게 건너간다.
    //   그 밖에는 원래대로 살짝 늦게 따라간다(손 흔들림 대신 물건이 따라오는 맛).
    if (!붙이기(camera.quaternion, false)) {
      o.position.lerp(_목표, 1 - Math.exp(-dt * 20));
      o.quaternion.slerp(camera.quaternion, 1 - Math.exp(-dt * 15));
    }
    // 1인칭·대체 경로에서는 양팔 IK 를 걸지 않는다(몸이 화면에 없다).
    플레이어시점.두손.쓸수있나 = false;
  }, 프레임순서.든물건);

  // name 은 **검사용**이다. 손에 든 물건이 손뼈를 제대로 따라오는지 재려면
  //   씬에서 이 그룹을 집어낼 수 있어야 한다(`__씬.getObjectByName("손에든것")`).
  //   렌더에는 영향이 없다.
  return (
    <group ref={g} name="손에든것">
      {children}
    </group>
  );
}
