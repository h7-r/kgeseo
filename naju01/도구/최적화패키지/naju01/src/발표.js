// ── 발표=최소: 비상용 — 화풍을 일부 포기하고 프레임을 지킨다 ─────
//   [무엇을 끄나]  바닥 삼면결(픽셀마다 노이즈 72 번)을 아예 안 건다.
//   땅이 「단색 판」이 되지만, 발표장 노트북이 30 fps 도 안 나올 때는
//   이게 맞다. 그림자는 남긴다 — 툰 화풍의 뼈대라 없으면 다른 게임이 된다.
