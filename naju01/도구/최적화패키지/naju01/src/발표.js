// ═══════════════════════════════════════════════════════════════
//  발표.js — 주소 스위치로 Leva 값을 **덮어쓰는** 프리셋
// ═══════════════════════════════════════════════════════════════
// [왜 Leva 기본값을 안 고치나]
//   `useSavedControls` 는 localStorage 저장값이 코드 기본값을 **이긴다.**
//   발표장 노트북에 무엇이 저장돼 있을지 알 수 없다. 주소에 붙이는 스위치는
//   저장값 위에 얹히므로 어느 브라우저에서든 같은 화면이 나온다.
//   그리고 스위치를 떼면 **한 픽셀도 안 바뀐 원래 화면**이다 — A/B 가 10 초다.
//
// [스위치]
//   ?발표          개발용 겹침(라벨·격자·조사점 표식·단면선)을 끈다
//   ?발표=가볍게   위 + 원경·수풀 밀도와 그림자 범위를 줄이고 물의 그림자 수신을 끈다
//   ?발표=최소     위 + 바닥 삼면결·물 잔결까지 끈다(비상용 — 땅이 단색이 된다)
//   ?분위기=저녁   로비처럼 「어두운 바탕 + 낮게 기운 주광 하나」 — 하늘돔을 끄고
//                  안개를 당긴다
//   ?분위기=밤     더 어둡게. 달빛 같은 푸른 주광
//   여럿을 같이 붙여도 된다:  ?발표=가볍게&분위기=저녁
//
// [왜 여기서 값을 정하나]
//   씬은 `const T = use발표덮기(T원)` 한 줄만 안다. 값을 여기서 바꾸면 씬은
//   한 줄도 안 건드린다. 눈으로 보고 숫자를 돌릴 곳이 이 파일 하나다.
//
// [★ 해색]  원래 해(directionalLight)는 색 손잡이가 없었다. 씬에
//   `color={T.해색 ?? "#ffffff"}` 를 더했으므로 여기서만 준다 — 없으면 흰색.

import { useMemo } from "react";

const 쿼리 =
  typeof location !== "undefined"
    ? new URLSearchParams(location.search)
    : new URLSearchParams();

export const 발표모드 = 쿼리.has("발표") ? 쿼리.get("발표") || "기본" : null;
export const 분위기 = 쿼리.get("분위기");

// ── 발표: 개발용 겹침 끄기 ──────────────────────────────────
