// 스위치를 읽어 덮개 하나로 합친다 — 모듈이 실릴 때 한 번.
export const 덮개 = {
  ...(발표모드 ? 발표기본 : null),
  ...(발표모드 === "가볍게" || 발표모드 === "최소" ? 가볍게 : null),
  ...(발표모드 === "최소" ? 최소 : null),
  ...(분위기 === "저녁" ? 저녁 : null),
  ...(분위기 === "밤" ? 밤 : null),
};
const 덮을것있나 = Object.keys(덮개).length > 0;

if (덮을것있나 && typeof console !== "undefined")
  console.log(
    `%c[발표] 프리셋 켬 — 발표: ${발표모드 ?? "없음"} · 분위기: ${분위기 ?? "없음"} · ${Object.keys(덮개).length} 개 값 덮음`,
    "color:#F2C879;font-weight:bold",
  );

/**
 * Leva 값 위에 프리셋을 얹는다. 스위치가 없으면 **같은 객체**를 그대로 돌려준다 —
 * 씬의 memo·effect 가 보는 참조가 원래와 한 치도 안 달라진다.
 */
export function use발표덮기(T) {
  return useMemo(() => (덮을것있나 ? { ...T, ...덮개 } : T), [T]);
}
