// ═══════════════════════════════════════════════════════════════
//  미리읽기.js — 씬을 세우기 **전에** 무거운 것을 전부 받아 둔다
// ═══════════════════════════════════════════════════════════════
// [무엇이 문제였나 — 「들어갈 때 끊긴다」의 정체]
//   씬(공간그레이박스)은 지형·절벽·길·수풀·무리를 전부 useMemo 로 세운다.
//   그런데 그 memo 들이 보는 값이 **뒤늦게 하나씩** 도착했다:
//     · 편집.json          → 무리 40 개를 다시 만든다
//     · 지형.glb + 높이표  → `새땅켬` 이 뒤집혀 땅·절벽·길·수풀·무리 **전부** 다시
//     · 구렁이·아비사·어부 ×3 GLB → 도착할 때마다 무리 전부 다시(다섯 번)
//   그러니 첫 10~20 초 동안 씬을 예닐곱 번 통째로 다시 세우고, 그때마다
//   수백 ms 가 멈춘다. 그게 곧 「화면 엄청 끊긴다」였다.
//
// [어떻게]
//   여기서 전부 **먼저** 받아 각 모듈의 동기 곳간에 넣어 둔다. 그 뒤에 씬을
//   붙이면 `새지형쓰기`·`구운모형쓰기`·`편집미리값가져오기` 가 첫 렌더에서
//   곧바로 「됨」이라 memo 가 **한 번만** 돈다. 받는 동안은 App 이 로딩 화면을 띄운다.
//
// [실패해도 게임은 뜬다]
//   각 모듈이 이미 「못 읽으면 옛것으로」 원칙을 갖고 있다. 여기서도 하나가
//   실패했다고 전체를 막지 않는다 — 다 끝나면(성공이든 실패든) 씬을 붙인다.

import { 새지형미리읽기 } from "./새지형.js";
import { 구운모형미리읽기, 구운모형이름들 } from "./구운모형.js";
import { 편집미리읽기 } from "./배치.js";

/**
 * 전부 받는다. `진행(끝난수, 전체수, 이름)` 을 하나 끝날 때마다 부른다.
 * 돌려주는 것: Promise<void> — 절대 거절하지 않는다.
 */
export function 미리읽기(진행 = () => {}) {
  const 일들 = [
    ["지형", 새지형미리읽기()],
    ["편집", 편집미리읽기()],
    ...구운모형이름들.map((이름) => [`모형 ${이름}`, 구운모형미리읽기(이름)]),
  ];
  let 끝 = 0;
  const 전체 = 일들.length;
  진행(0, 전체, "");
  return Promise.all(
    일들.map(([이름, 약속]) =>
      Promise.resolve(약속)
        .catch(() => null)
        .then(() => {
          끝 += 1;
          진행(끝, 전체, 이름);
        }),
    ),
  ).then(() => undefined);
}
