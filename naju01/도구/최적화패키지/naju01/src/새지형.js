// ═══════════════════════════════════════════════════════════════
//  새지형.js — 블렌더가 구운 땅 한 벌(GLB + 높이표)을 읽어 온다
// ═══════════════════════════════════════════════════════════════
// [무엇을 바꾸나]
//   `도구/지형짓기.py` 가 한 배열에서 둘을 낸다 —
//     `에셋/지형.glb`      그림용 메시 (128,000 삼각형, 길이 **땅에 파여** 있다)
//     `에셋/지형높이.bin`  판정용 격자 (0.25 m, `지형표.js` 가 읽는다)
//   이 훅은 둘을 같이 읽어, 씬이 한 번에 갈아끼울 수 있게 내준다.
//
// [★ 왜 서스펜스(useGLTF)가 아닌가]
//   drei 의 `useGLTF` 는 로딩 중 컴포넌트를 **던진다**(suspend). 그러면
//   지형이 도착할 때까지 씬 전체가 안 그려지고, 실패하면 에러 경계로 튄다.
//   여기서는 실패해도 **옛 지형으로 그냥 돌아야** 한다 — 8.9 MB 가 안 와도
//   게임은 돌아가는 게 맞다. 그래서 직접 읽고 상태로 들고 있는다.
//
// [★ 미리 읽기 — 씬이 두 번 세워지지 않게]
//   예전에는 씬이 붙은 **뒤에** 읽기 시작했다. 그러면 첫 렌더는 옛 지형으로
//   땅·절벽·길·수풀·무리를 전부 세우고, 몇 초 뒤 GLB 가 오면 `새땅켬` 이
//   뒤집혀 **그 전부를 다시 세운다.** 걷는 도중 수백 ms 가 멈추는 첫 번째
//   이유였다. 이제 `새지형미리읽기()` 로 씬 전에 받아 두면(미리읽기.js),
//   훅이 **첫 렌더에서 곧바로 「됨」** 을 돌려줘 씬이 한 번만 선다.
//   미리 안 읽어도 예전처럼 붙은 뒤 읽는다 — 동작은 같고 순서만 다르다.
//
// [되돌리기]
//   이 훅을 안 쓰거나 `켬=false` 면 아무것도 안 읽는다. 옛 지형 코드
//   (`지표.js`·`바닥.js`·`통로.js`·`절벽.js`)는 **그대로 살아 있다.**

import { useEffect, useState } from "react";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { 높이표불러오기 } from "./지형표.js";

const 글b주소 = new URL("../에셋/지형.glb", import.meta.url).href;

// 한 번만 읽는다. `약속` 은 진행 중인 읽기, `값` 은 끝난 결과다.
//   값: undefined = 아직 · null = 실패 · {지오, 표} = 성공
let 약속 = null;
let 값 = undefined;

function 읽기() {
  if (약속) return 약속;
  약속 = (async () => {
    const 잰때 = performance.now();
    // ★ 둘을 **같이** 받는다. 서로 아무 상관이 없는 파일인데 예전에는
    //   높이표(0.18 MB)를 다 받고 나서야 GLB(4.0 MB)를 부르기 시작했다.
    //   실측(로컬 서버에서 같은 두 파일을 9회씩, 중앙값):
    //     줄줄이 228 ms  →  같이 117 ms
    const 표약속 = 높이표불러오기();
    const 지오약속 = new Promise((풀기) => {
      let 로더;
      try {
        로더 = new GLTFLoader();
      } catch (e) {
        console.warn("[새지형] 로더를 못 만들었다:", e);
        return 풀기(null);
      }
      try {
        로더.load(
          글b주소,
          (g) => {
            let 찾음 = null;
            g.scene.traverse((o) => {
              if (!찾음 && o.isMesh) 찾음 = o.geometry;
            });
            풀기(찾음);
          },
          undefined,
          (e) => {
            console.warn("[새지형] GLB 를 못 읽었다 — 옛 지형으로 간다:", e);
            풀기(null);
          },
        );
      } catch (e) {
        console.warn("[새지형] GLB 읽기가 던졌다:", e);
        풀기(null);
      }
    });
    // 둘 다 실패해도 던지지 않는다(각자 null 을 돌려준다).
    const [표, 지오] = await Promise.all([표약속, 지오약속]);
    if (!지오 || !표) return null;
    // 한 줄만 남긴다 — 8.9 MB 라 느린 회선에서 「왜 안 켜지지」가 생기고,
    //   조용히 실패하면 옛 지형으로 돌아가 티가 안 난다.
    //   ※ 헤드리스(SwiftShader)에서는 이게 20 초 넘게 걸린다.
    console.log(
      `[새지형] 준비됨 — ${표.nx}×${표.nz} 격자 · ` +
        `${(지오.index ? 지오.index.count : 지오.attributes.position.count) / 3} 삼각형 · ` +
        `${((performance.now() - 잰때) / 1000).toFixed(1)}초`,
    );
    // ★ 법선을 다시 계산하지 않는다. GLB 가 이미 싣고 왔다.
    return { 지오, 표 };
  })();
  약속.then(
    (v) => {
      값 = v;
    },
    () => {
      값 = null;
    },
  );
  return 약속;
}

/** 씬 전에 미리 받아 둔다(미리읽기.js). 절대 거절하지 않는다. */
export function 새지형미리읽기() {
  return 읽기().catch(() => null);
}

const 쉼 = () => ({ 지오: null, 표: null, 상태: "쉼" });
const 읽는중 = () => ({ 지오: null, 표: null, 상태: "읽는중" });
const 값으로 = (v) =>
  v ? { 지오: v.지오, 표: v.표, 상태: "됨" } : { 지오: null, 표: null, 상태: "실패" };

/**
 * 새 지형을 읽는다.
 *   켬  false 면 아무것도 안 읽는다(옛 지형 그대로).
 *   돌려주는 것 { 지오, 표, 상태 }
 *     지오  THREE.BufferGeometry — 단위는 **도면 미터**다.
 *           씬에서 `scale={미터}` 로 올려야 월드 유닛이 된다.
 *     표    `지형표.js` 의 조회기 — `지형.높이표설정(표)` 에 끼운다.
 *     상태  "쉼" | "읽는중" | "됨" | "실패"
 */
export function 새지형쓰기(켬) {
  // ★ 이미 받아 둔 것이 있으면 **첫 렌더부터** 「됨」이다 — 위 [미리 읽기].
  const [것, 것설정] = useState(() =>
    !켬 ? 쉼() : 값 === undefined ? 읽는중() : 값으로(값),
  );

  useEffect(() => {
    if (!켬) {
      것설정((앞) => (앞.상태 === "쉼" ? 앞 : 쉼()));
      return;
    }
    if (값 !== undefined) {
      // 같은 결과면 **같은 객체**를 지킨다 — 새 객체를 주면 씬의 memo 가
      //   「바뀌었다」고 보고 땅을 도로 다시 세운다.
      const 다음 = 값으로(값);
      것설정((앞) => (앞.지오 === 다음.지오 && 앞.상태 === 다음.상태 ? 앞 : 다음));
      return;
    }
    let 살아있나 = true;
    것설정((앞) => (앞.상태 === "읽는중" ? 앞 : 읽는중()));
    읽기()
      .catch(() => null)
      .then((v) => {
        if (살아있나) 것설정(값으로(v));
      });
    return () => {
      살아있나 = false;
    };
  }, [켬]);

  return 것;
}
