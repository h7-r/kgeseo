def 색풀기(글):
    """#RRGGBB → 선형 RGB. three 가 정점 색을 **선형**으로 읽기 때문이다.
    sRGB 값을 그대로 넣으면 전체가 허옇게 뜬다."""
    v = np.array([int(글[i:i + 2], 16) / 255.0 for i in (1, 3, 5)], dtype=np.float32)
    return np.where(v <= 0.04045, v / 12.92, ((v + 0.055) / 1.055) ** 2.4)


def 색칠하기(ob, X, Z, h, 잠금, nx, nz):
    """정점 색을 굽는다.

    ★ 이게 없으면 **땅이 새까맣게** 나온다.
      `공간그레이박스.jsx` 의 `바닥재질` 은 램버트든 툰이든 항상
      `vertexColors` 를 켠다(옛 `땅` 메시가 색을 싣고 다녔기 때문이다).
      색 속성이 없는 지오메트리를 물리면 three 가 곱할 값을 못 찾아 검게 칠한다.
      실제로 게임에 처음 올렸을 때 하늘·바위·풀은 멀쩡한데 바닥만 새까맸다.

    무엇으로 색을 정하나 —
      ① 구역: 도면 사각형을 **뒤틀어** 물어 경계가 자로 그은 듯 안 되게 한다
         (`지표.js` 의 `결코드` 와 같은 생각).
      ② 색↔색2 를 결 노이즈로 섞는다.
      ③ 가파른 면은 `그늘` 쪽으로 — 절벽이 대지와 같은 색이면 높이가 안 읽힌다.
      ④ 노면은 흙길 색으로, 물가는 모래색으로 물린다.
    """
    wX, wZ = 뒤틀기(X, Z, 1.6, 3307)
    바탕 = np.zeros(X.shape + (3,), dtype=np.float32)
    그늘색 = np.zeros(X.shape + (3,), dtype=np.float32)
    섞 = 결(X, Z, [(2.6, 1.0), (0.9, 0.5)], 6151)[..., None]

    쓴 = np.zeros(X.shape, dtype=bool)
    for 코드, xr, zr, _ in 구역들:
        안 = ((wX >= xr[0]) & (wX <= xr[1]) & (wZ >= zr[0]) & (wZ <= zr[1]) & ~쓴)
        c1, c2, cg = (색풀기(v) for v in 팔레트[코드])
        바탕 = np.where(안[..., None], c1 * (1 - 섞) + c2 * 섞, 바탕)
        그늘색 = np.where(안[..., None], cg, 그늘색)
        쓴 |= 안
    c1, c2, cg = (색풀기(v) for v in 팔레트["미설계"])
    바탕 = np.where(쓴[..., None], 바탕, c1 * (1 - 섞) + c2 * 섞)
    그늘색 = np.where(쓴[..., None], 그늘색, cg)

    # ③ 가파를수록 그늘색으로
    기울기 = np.hypot(np.gradient(h, 칸, axis=1), np.gradient(h, 칸, axis=0))
    급 = 사이((기울기 - 0.45) / 1.4)[..., None]
    색 = 바탕 * (1 - 급) + 그늘색 * 급

    # ④ 노면 · 물가
    색 = 색 * (1 - 잠금[..., None]) + 색풀기(길색) * 잠금[..., None]
    물 = 사이((Z - (강["Z시작"] - 2.5)) / 3.0)[..., None]
    색 = 색 * (1 - 물) + 색풀기(물가색) * 물

    me = ob.data
    값 = np.ones((nz * nx, 4), dtype=np.float32)
    값[:, :3] = 색.reshape(-1, 3)
    층 = me.color_attributes.new(name="바닥색", type="FLOAT_COLOR", domain="POINT")
    층.data.foreach_set("color", 값.ravel())
    me.update()


def UV펴기(ob):
    """상자 투영 UV.

    [왜 Smart UV Project 가 아닌가]  12 만 면에 돌리면 몇 분이 걸리고,
      지형은 조각이 잘게 흩어져 텍스처를 이어 붙이기 나쁘다.
      위에서 내려다본 투영을 기본으로 하고, **선 면(절벽)만 옆에서** 투영하면
      이음매가 적고 결이 흐르지 않는다. 1 m = UV 0.05 (20 m 에 한 바퀴).
    """
    me = ob.data
    me.uv_layers.new(name="UVMap")
    uv = me.uv_layers[0].data
    비 = 0.05
    코 = np.empty(len(me.vertices) * 3, dtype=np.float32)
    me.vertices.foreach_get("co", 코)
    코 = 코.reshape(-1, 3)
    법 = np.empty(len(me.polygons) * 3, dtype=np.float32)
    me.polygons.foreach_get("normal", 법)
    법 = 법.reshape(-1, 3)
    값 = np.empty((len(me.loops), 2), dtype=np.float32)
    루프꼭 = np.empty(len(me.loops), dtype=np.int32)
    me.loops.foreach_get("vertex_index", 루프꼭)
    시작 = np.empty(len(me.polygons), dtype=np.int32)
    me.polygons.foreach_get("loop_start", 시작)

    선면 = np.abs(법[:, 2]) < 0.55        # 블렌더 Z = 높이. 눕지 않은 면.
    for pi in range(len(me.polygons)):
        s = 시작[pi]
        for k in range(4):
            v = 코[루프꼭[s + k]]
            if 선면[pi]:
                # 옆면 — 가로는 X 나 Y 중 긴 쪽, 세로는 높이
                가로 = v[0] if abs(법[pi][1]) > abs(법[pi][0]) else v[1]
                값[s + k] = (가로 * 비, v[2] * 비)
            else:
                값[s + k] = (v[0] * 비, v[1] * 비)
    uv.foreach_set("uv", 값.ravel())
    me.update()


