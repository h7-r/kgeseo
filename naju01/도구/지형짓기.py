def 길그늘(X, Z, 고도, 리치=9.0):
    """이 칸은 **길이 다스리는가** — 대지 고도를 못박으면 안 되는 자리.

    ★ 대지와 길이 부딪히는 유일한 자리를 다룬다.
      T4 꼬리는 Z1 대지(EL 0) **안**을 EL 0 ~ 2.2 로 지나고,
      T3 은 Z4 대지(EL 8) 안을 EL 8 ~ 9.3 으로 지난다. 도면이 그렇게 그었다.
      대지를 나중에 못박으면 램프가 눌려 길이 끊기고, 길만 못박으면
      노면이 수직 축대로 떠오른다. 답은 **둑까지 통째로 길에게 넘기는 것**이다.
    ★ 판정은 「램프 높이가 대지 고도와 다른가」가 **아니다.**
      처음에 그렇게 짰더니 Z2 북서 모서리(34, 33)에 **10 m 기둥**이 섰다.
      거기서 가장 가까운 T4 구간은 (36, 24.5) — Z3 마루 위 EL 14 지점이고,
      Z2 모서리에서 9.5 m 다. 「가깝고 램프가 다르다」가 참이 되어 Z2 의
      대지 잠금이 풀렸고, 그 자리에 Z3 어깨 높이 10 m 가 그대로 남았다.
      길이 **저 위 딴 데** 있는데 이 대지를 다스린 것이다.

      다음으로 「그 길목이 이 대지 사각형 **안**에 있는가」로 바꿔 봤는데,
      이번엔 T4 가 Z1 테두리를 **건너는** 자리에서 깨졌다 — 칸은 Z1 안인데
      가장 가까운 길목 (21.5, 29) 은 Z1 밖(z<30)이라 그늘이 안 잡히고,
      노면은 EL 5.6 인 채 바로 옆 대지가 0 으로 잠겨 6 m 축대가 섰다.

      옳은 판정은 **「길의 흙일이 여기까지 닿는가」** 다.
      길이 대지보다 높으면 둑을 `둑뻗음` 까지 쌓고, 낮으면 `높이차/깎기각`
      만큼 파고든다. 그 거리 안쪽이 길의 땅이고, 밖은 대지의 땅이다.
      거리가 **높이차에서 나오므로** 공짜로 얻어지는 성질이 둘 있다 —
      램프가 대지와 같은 높이면(T1 전체) 그늘이 아예 없고,
      T4 의 EL 14 쪽 끝은 Z2 에서 멀어 Z2 를 건드리지 못한다.
    """
    갓 = 갓길["폭"] * 갓길["뻗음"]
    그늘 = np.zeros(X.shape, dtype=bool)
    for 코드, 폭, 시작, 끝, 점 in 통로들:
      for d, 램프 in 통로토막들(X, Z, 시작, 끝, 점):
        밖 = np.maximum(d - 폭 / 2 - 갓, 0.0)
        높이차 = np.abs(램프 - 고도)
        # 길이 대지보다 높으면 둑을 쌓고(둑뻗음까지), 낮으면 깎는다
        #   (높이차 / 깎기각 까지). 그 거리 안쪽만 길의 그늘이다.
        뻗음 = np.where(램프 > 고도, 둑뻗음, np.minimum(높이차 / 깎기각, 리치))
        그늘 |= (밖 <= 뻗음) & (높이차 > 0.25)
      # (토막마다 본다 — `통로토막들` 머리말의 스위치백 문제 때문이다)
    return 그늘


def 절벽그늘(X, Z):
    """절벽 면이 지나는 칸 — 대지 고도를 못박으면 안 되는 자리.

    ★ `길그늘` 과 같은 이유로 필요하다.
      74° 로 14 m 를 떨구려면 수평 4.01 m 가 든다. 도면이 준 자리는
      Z위 26 → Z아래 30, 즉 **4.00 m** 다. 1 cm 가 모자란다.
      게다가 마루선을 남으로 0~0.8 m 흔들므로 발치는 최대 30.8 까지 간다 —
      **Z2 대지 사각형(z 30~44) 안**이다.
      대지 잠금을 그대로 두면 z 29.8 에서 12 m 이던 면이 z 30.0 에서 0 으로
      잘린다(실측 최대 단차 12.00 m). 절벽이 대지 테두리에 먹힌 것이다.
      발치가 Z2 로 0.8 m 넘어오는 건 도면이 허용한 범위다 — 벼랑 밑
      너덜이 앉는 자리고, Z2 의 걷는 바닥이 그만큼 뒤로 물러날 뿐이다.
    """
    마루, 발치, 끝맺음 = 절벽선(X, Z)
    return (끝맺음 > 0.02) & (Z > 마루 - 0.1) & (Z < 발치 + 0.1)


def 다시못박기(X, Z, h):
    """`매끄럽게` 가 경계 바깥을 문지른 뒤, 규격 자리만 확인 사살한다.

    평균 필터는 못박힌 칸 자체는 안 건드리지만(풀림=0), 한 칸 차이로
    풀림이 0.0 이 아닌 테두리 칸이 생긴다 — 대지 맨 가장자리 한 줄이
    2~3 cm 처진다. 그 한 줄이 바로 에셋이 서는 자리다.

    ★ 순서는 대지 → 통로다(`높이짓기` ③ 과 같다).
      T3 는 z 8~13 구간이 Z4 대지 **안**을 지나면서 8 m → 9.3 m 로 오른다.
      대지를 나중에 못박으면 그 5 m 가 8 m 로 눌려 램프가 1.3 m 틀어진다.
      도면이 그렇게 그은 길이니 길이 이긴다 — `재기` 도 통로 밴드를 뺀다.
    """
    절그늘 = 절벽그늘(X, Z)
    for 코드, xr, zr, 고도 in 구역들:
        h = np.where((사각거리(X, Z, xr, zr) <= 1e-3)
                     & ~길그늘(X, Z, 고도)
                     & ~절그늘, 고도, h)
    for 코드, 폭, 시작, 끝, 점 in 통로들:
        d, 몫, _ = 통로밭(X, Z, 점)
        노면 = 노면몫(d, 폭 / 2.0 + 갓길["폭"] * 갓길["뻗음"])
        램프 = 시작 + (끝 - 시작) * 몫
        h = h * (1 - 노면) + 램프 * 노면
    return h


def 메시만들기(X, Z, h, nx, nz):
    """격자를 메시로. 블렌더는 Z 가 위라 축을 바꿔 담는다.

    ★ glTF 로 내보낼 때 블렌더 (x, y, z) → glTF (x, z, −y) 로 바뀐다.
      게임 좌표가 X=x · Y=높이 · Z=z 이므로,
      블렌더에는 **(x, −z, 높이)** 로 담아야 한다. 여기 틀리면 맵이 뒤집힌다.
    """
    co = np.empty((nz * nx, 3), dtype=np.float32)
    co[:, 0] = X.ravel()
    co[:, 1] = -Z.ravel()
    co[:, 2] = h.ravel()

    면 = []
    for j in range(nz - 1):
        r0 = j * nx
        r1 = (j + 1) * nx
        for i in range(nx - 1):
            # ★ 감는 순서 — 뒤집으면 **땅이 안 보인다.**
            #   블렌더에 (x, −z, 높이) 로 담으므로 j 가 늘면 Y 는 **줄어든다.**
            #   (i,j)→(i+1,j)→(i+1,j+1) 로 감으면 (+X)×(−Y) = −Z, 즉 법선이
            #   **아래**를 본다. 블렌더 워크벤치는 양면을 다 그려서 렌더로는
            #   멀쩡해 보였고, 게임의 단면(FrontSide) 재질에 올리고 나서야
            #   드러났다 — 위에서 보면 컬링돼 땅이 사라지고, 수직 광선도
            #   안 맞아 에셋이 앉을 자리를 못 찾는다(실측으로 잡았다).
            면.append((r0 + i, r1 + i, r1 + i + 1, r0 + i + 1))

    me = bpy.data.meshes.new("지형")
    me.from_pydata(co.tolist(), [], 면)
    me.update()
    ob = bpy.data.objects.new("지형", me)
    bpy.context.collection.objects.link(ob)
    return ob


def 높이표내보내기(h, 잠금, nx, nz, 경로):
    """판정용 높이 격자를 Uint16 로 내보낸다.

    ★ 이것이 이번 교체의 **핵심**이다.
      지금까지 진실의 출처가 셋이었다 — 걷기 판정(`지형.지면`) ·
      그림용 높이 함수(`지표.높이`) · 실제 삼각형(`땅` 메시).
      셋이 어긋나는 자리마다 물건이 묻히고 길에 구멍이 났다.
      GLB 와 이 표는 **같은 배열 h 에서 같은 순간에** 나온다.
      어긋날 수가 없다 — 서로 다른 코드가 아니라 같은 숫자다.

    [왜 레이캐스트가 아닌가]  격자가 0.25 m 로 고른 정규 격자다.
      정규 격자는 이중선형 보간으로 **O(1)** 에 높이가 나온다.
      BVH 를 얹는 것보다 빠르고, 저장소 루트 `package.json` 에
      의존성을 더할 필요도 없다(그 파일은 건드리면 안 된다).

    [형식]  머리말 **36 바이트** 뒤에 little-endian Uint16 이 nz 줄 × nx 칸.
      머리말: "NJTH" · 판(u16) · 예비(u16) · nx(u16) · nz(u16)
              · x0 · z0 · 칸x · 칸z (f32 ×4) · 낮 · 높 (f32 ×2)
      값 v → 높이 = 낮 + v / 65535 × (높 − 낮). 눈금 0.27 mm.
    """
    import struct
    낮, 높 = float(h.min()), float(h.max())
    q = np.clip(np.round((h - 낮) / (높 - 낮) * 65535), 0, 65535).astype("<u2")
    머리 = struct.pack("<4sHHHHffff", b"NJTH", 1, 0, nx, nz,
                       0.0, 0.0, 칸, 칸) + struct.pack("<ff", 낮, 높)
    os.makedirs(os.path.dirname(경로), exist_ok=True)
    길 = np.clip(np.round(잠금 * 255), 0, 255).astype(np.uint8)
    with open(경로, "wb") as f:
        f.write(머리)
        f.write(q.tobytes())
        f.write(길.tobytes())
    return 낮, 높, len(머리) + q.nbytes + 길.nbytes


