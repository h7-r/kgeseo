def 높이짓기():
    x0, x1 = 코어["X"]
    z0, z1 = 코어["Z"]
    nx = int(round((x1 - x0) / 칸)) + 1
    nz = int(round((z1 - z0) / 칸)) + 1
    xs = np.linspace(x0, x1, nx, dtype=np.float32)
    zs = np.linspace(z0, z1, nz, dtype=np.float32)
    X, Z = np.meshgrid(xs, zs)

    # ── ① 땅의 흐름 ──────────────────────────────────────
    # [무엇을 그리나]  영산강 북쪽 기슭이다. 남(z 큼)은 강으로 내려가는
    #   너른 둔치, 북으로 갈수록 오르는 산자락, 그 사이에 바위 노두가 솟는다.
    #   대지(구역)는 ② 가 눌러 앉히므로, 여기서는 **사이를 메우는 흐름**만 짓는다.
    남북 = 사이((44.0 - Z) / 36.0)                     # 남 0 → 북 1
    h = 2.2 * 남북                                      # 북으로 완만히 오른다
    # 동쪽이 더 높다 — Z4 능선이 거기 앉는다
    h += 4.2 * 사이((X - 30.0) / 40.0) * 남북
    # 바위 노두(Z3) 가 솟은 자리 — 대지 밑을 받치는 덩어리
    노두 = np.exp(-(((X - 46.0) / 26.0) ** 2 + ((Z - 17.0) / 16.0) ** 2))
    h += 9.5 * 노두
    # 큰 결 — 통짜 경사가 아니게
    h += (결(X, Z, [(34.0, 1.0), (13.0, 0.45)], 1301) - 0.5) * 3.4 * 남북

    # 강바닥 — 물가에서 아래로 파인다
    물몫 = 사이((Z - 강["Z시작"]) / (강["Z끝"] - 강["Z시작"]))
    h = h * (1 - 물몫) - 2.6 * 물몫

    # ── ② 자연스럽게 흔들기 ──────────────────────────────
    #   규격을 못박기 **전에** 한다. 뒤에 하면 대지가 기울고 길이 출렁인다.
    h += (결(X, Z, [(7.5, 1.0), (3.1, 0.5), (1.35, 0.25)], 5501) - 0.5) * 2.1
    h = 열침식(h, 되풀이=48, 안식각=0.62)

    # ── ③ 규격 못박기 ────────────────────────────────────
    h, 대지안, _ = 대지앉히기(X, Z, h)
    h, 절벽띠 = 절벽세우기(X, Z, h)
    절그늘 = 절벽그늘(X, Z)
    h, 길잠금 = 길파기(X, Z, h, 절그늘)

    # ── ③b 비탈에만 결을 되돌린다 ────────────────────────
    # [무엇이 문제였나]  ② 에서 노이즈와 열침식으로 만든 결을 ③ 의 대지
    #   어깨가 **전부 덮어 버린다.** `h*(1-섞) + 대지*섞` 에서 어깨 한복판은
    #   섞 ≈ 1 이라 원래 지형이 남지 않는다. 그래서 T3 스위치백 주변이
    #   각진 **판때기 덩어리**로 보였다 — 지형이 아니라 저폴리 바위였다.
    # [왜 기울기로 재나]  평평해야 할 대지에 결을 얹으면 규격이 깨진다.
    #   기울어진 자리에만 얹으면 대지는 그대로고 비탈만 살아난다.
    #   노면 근처는 `길잠금` 으로 뺀다 — 애써 깎은 벤치를 다시 울퉁불퉁
    #   만들 이유가 없다.
    기울기 = np.hypot(np.gradient(h, 칸, axis=1), np.gradient(h, 칸, axis=0))
    결세기 = 사이(기울기 / 0.30) * (1.0 - 길잠금)
    h = h + (결(X, Z, [(9.0, 1.0), (3.7, 0.55), (1.6, 0.3)], 8821) - 0.5) * 1.3 * 결세기

    # ── ④ 이음매 풀기 ────────────────────────────────────
    #   ③ 이 남긴 한 칸짜리 각만 눌러 준다. 못박힌 자리(대지 안·노면)와
    #   절벽 면은 손대지 않는다 — 절벽을 문지르면 실각이 무너진다.
    풀림 = (1.0 - np.maximum(np.maximum(대지안.astype(np.float32), 길잠금), 절벽띠))
    h = 매끄럽게(h, 풀림, 되풀이=5, 세기=0.5)

    # ── ⑤ 규격 다시 못박기 + 미세결 ──────────────────────
    #   ④ 가 경계 **바로 바깥**을 건드렸으니 안쪽을 한 번 더 확인 사살한다.
    h = 다시못박기(X, Z, h)

    # ★ 대지에 ±6 cm 미세결을 준다.
    #   편차 0.000 m 는 규격상 완벽하지만 눈에는 **CAD 철판**이다.
    #   6 cm 는 걷기·배치 어디에도 영향이 없고(에셋은 이 메시에 레이캐스트로
    #   앉는다), 스치는 빛이 걸려서 비로소 「흙바닥」으로 읽힌다.
    h = h + (결(X, Z, [(3.4, 1.0), (1.1, 0.6)], 4243) - 0.5) * 0.12 * (1.0 - 길잠금)

    return X, Z, h, nx, nz, 길잠금


def 열침식(h, 되풀이=40, 안식각=0.6):
    """열 침식 — 가파른 데서 흙이 흘러내려 쌓인다.

    [왜 넣나]  노이즈만 얹은 땅은 **우둘투둘한 잡음**이지 지형이 아니다.
      비탈에 흙이 흘러 발치에 쌓여야 눈이 「깎이고 쌓인 땅」으로 읽는다.
      물 침식은 무겁지만 열 침식은 이웃 넷만 보면 되어 싸다.
    [안식각]  이웃 칸과의 높이차가 이 값을 넘으면 그만큼을 흘려보낸다.
      0.62 는 칸(0.25 m) 기준이라 실제 경사로는 약 68°다.
    """
    h = h.copy()
    for _ in range(되풀이):
        총 = np.zeros_like(h)
        for dj, di in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            차 = h - 밀기(h, dj, di)
            넘침 = np.maximum(차 - 안식각, 0.0) * 0.22
            총 -= 넘침                                   # 나에게서 빠지고
            총 += 밀기(넘침, -dj, -di)                   # 이웃에 쌓인다
        h += 총
    return h


def 대지앉히기(X, Z, h):
    """구역 넷을 제 고도의 **평평한 대지**로 앉힌다.

    ★ 한 구역씩 차례로 덮어쓰면 안 된다.
      Z3(X 34~58)와 Z4(X 62~76)는 **4 m 밖에 안 떨어져 있다.** 어깨가 5 m 라
      Z4 를 앉힐 때 그 어깨가 **Z3 안쪽까지 들어와** 대지를 들어올린다
      (실측: Z3 안이 14 m 여야 하는데 11.8 m, 편차 2.2 m).
      그래서 ① 네 구역의 무게를 **한꺼번에** 구해 섞고,
      ② 사각형 **안**은 마지막에 제 고도로 못박는다.
    """
    무게 = []
    고도들 = []
    안 = np.zeros(X.shape, dtype=bool)
    안고도 = np.zeros(X.shape, dtype=np.float32)
    # 경계선을 구불거리게 — 무게가 아니라 **좌표**를 민다(`뒤틀기` 머리말).
    wX, wZ = 뒤틀기(X, Z, 어깨뒤틀림, 7001)
    for 코드, xr, zr, 고도 in 구역들:
        # 어깨는 **뒤틀린 좌표**로, 대지 안 판정은 **참 좌표**로 잰다.
        t = 사각거리비(wX, wZ, xr, zr, 어깨들[코드])
        # ★ 프로필은 smoothstep 이 아니라 **거의 직선**이다.
        #   smoothstep 은 가운데가 가팔라 어깨 한복판에 없던 단차를 만든다.
        #   흙비탈은 마루에서 발치까지 거의 같은 경사로 내려간다.
        #   1.35 승은 마루를 살짝 둥글리고 발치를 길게 끄는 정도다.
        w = np.clip(1.0 - t, 0.0, 1.0) ** 1.35
        무게.append(w)
        고도들.append(고도)
        이안 = 사각거리(X, Z, xr, zr) <= 1e-3
        안 |= 이안
        안고도 = np.where(이안, 고도, 안고도)

    합 = np.zeros(X.shape, dtype=np.float32)
    합고 = np.zeros(X.shape, dtype=np.float32)
    for w, 고도 in zip(무게, 고도들):
        합 += w
        합고 += w * 고도
    섞 = np.clip(합, 0.0, 1.0)
    대지 = np.where(합 > 1e-6, 합고 / np.maximum(합, 1e-6), 0.0)
    h = h * (1 - 섞) + 대지 * 섞
    # ★ 사각형 안은 **무조건** 제 고도. 여기가 걷는 바닥이다.
    #   `섞` 도 내준다 — 「여기는 대지가 다스리는 땅」이라는 표다.
    #   길 클램프가 그 위를 덮지 못하게 막는 데 쓴다(`길파기` 참고).
    return np.where(안, 안고도, h), 안, 섞


def 절벽선(X, Z):
    """Z3 남쪽 마루에서 Z2 바닥으로 떨어지는 74° 벼랑.

    도면이 허락한 범위 안에서 마루·발치 선을 흔든다 —
      마루는 남(+Z)으로 0~2.6 m 물러나고, 발치는 북(−Z)으로 0~1.5 m 당긴다.
      직사각 띠 그대로면 **자로 그은 옹벽**이 된다.
    """
    xa, xb = 절벽["X"]
    t = np.clip((X - xa) / (xb - xa), 0.0, 1.0)
    물결 = lambda a, b, c: np.sin(t * math.pi * a + b) * c
    s1 = 물결(1.7, 0.6, 0.55) + 물결(3.9, 2.1, 0.30) + 물결(7.3, 4.4, 0.15)
    s2 = 물결(2.3, 1.9, 0.50) + 물결(5.1, 0.4, 0.32) + 물결(9.7, 3.2, 0.18)
    # ★ **띠 폭을 4 m 로 붙들고 마루선만 흔든다.**
    #   처음에는 마루를 남으로, 발치를 북으로 따로 흔들었다. 그러면 둘이
    #   가까워지는 자리에서 띠가 1.9 m 까지 좁아져 **실각이 85°** 가 됐다
    #   (도면 74°). 14 m 를 74° 로 떨어뜨리려면 수평 4.01 m 가 있어야 한다.
    #   폭을 고정하면 각도가 어디서나 74° 고, 마루선은 여전히 들쭉날쭉하다.
    #   ※ 그 대신 발치가 Z2 쪽으로 최대 0.8 m 나간다 — 벼랑 밑 너덜이
    #     앉는 자리라 어색하지 않고, Z2 의 걷는 바닥은 그만큼 뒤로 물러난다.
    띠 = 절벽["높이"] / math.tan(math.radians(74.0))     # = 4.01 m
    # 마루 흔들림 0.8 → **0.25**. 0.8 이면 발치가 30.8 까지 남으로 나가
    #   Z2 대지(z 30~44) 안을 1.5 m 들어올렸다(옛 지형은 0.33 m). 0.25 면
    #   발치가 30.26 이라 Z2 의 걷는 바닥이 옛 지형보다도 깨끗하다.
    마루 = 절벽["Z위"] + (0.5 + s1 * 0.5) * 0.25         # 26.0 ~ 26.25
    발치 = 마루 + 띠                                     # 30.0 ~ 30.26

    # X 양 끝에서 절벽 영향이 잦아든다 — Z3 는 X 58 까지라 56~58 은 벼랑이 아니다
    끝맺음 = 사이((X - (xa - 1.2)) / 2.4) * (1.0 - 사이((X - (xb - 1.2)) / 2.4))
    return 마루, 발치, 끝맺음


def 절벽세우기(X, Z, h):
    """(아래 본문은 `절벽선` 이 준 마루·발치·끝맺음을 쓴다)"""
    마루, 발치, 끝맺음 = 절벽선(X, Z)

    t = np.clip((Z - 마루) / np.maximum(발치 - 마루, 1e-3), 0.0, 1.0)
    # ★ 면은 **곧게** 내린다. smoothstep 으로 두면 가운데가 급해져
    #   실각이 82° 로 잰다(도면 74°). 위·아래 끝만 살짝 둥글린다.
    몫 = np.clip((t - 0.06) / 0.88, 0.0, 1.0)
    몫 = 몫 * 0.94 + 사이(t) * 0.06
    면 = 절벽["높이"] * (1.0 - 몫)                        # 마루 14 → 발치 0
    # 벼랑 면에도 결을 준다 — 민판이면 콘크리트로 보인다
    면 += (결(X, Z, [(4.5, 1.0), (1.7, 0.5)], 9109) - 0.5) * 1.5 * 몫 * (1 - 몫) * 4
    # ★ 밴드를 **불리언으로 자르면 안 된다** — `뒤틀기` 머리말과 같은 병이다.
    #   `(Z > 마루-0.4) & (Z < 발치+0.4)` 로 자르면, 마루가 26.8 로 물러난
    #   자리에서 밴드 위 첫 칸은 면=14 인데 바로 옆(밴드 밖)은 Z3 어깨가
    #   이미 10.6 까지 내려와 있다 — 한 칸에 **3.4 m 단차**다.
    #   실측으로 x·z 양방향 최대 단차가 6 m(=87°)까지 나왔고, 그 500 칸의
    #   절반이 이 밴드 테두리였다.
    #   `면` 은 마루 위에서 14, 발치 아래에서 0 으로 이미 평평하므로,
    #   창을 **부드럽게** 열어 두면 양쪽 끝에서 저절로 지형과 맞물린다.
    근처 = 사이((Z - (마루 - 6.0)) / 4.0) * (1.0 - 사이((Z - (발치 + 2.0)) / 4.0))
    w = 끝맺음 * 근처
    # 두 번째로 돌려주는 것은 「여기는 문지르지 마라」 표다.
    #   `매끄럽게` 가 절벽 면을 평균내면 14 m 가 뭉개져 실각이 무너진다.
    return h * (1 - w) + 면 * w, w


def 길파기(X, Z, h, 절그늘):
    """통로를 땅에 **파 넣는다.**

    걷는 폭(|d| ≤ 반폭)은 좌우로 **수평**이고 진행 방향으로만 경사진다 —
      걷기 판정이 이 높이를 쓰므로 여기가 기울면 발이 안 붙는다.

    ★ 그 바깥은 **거리로 섞지 않고 각도로 벌린다.**
      전에는 갓길 밖 3.2 m 안에서 지형으로 물렸다. 길이 6 m 파인 자리에서
      3.2 m 는 곧 **58° 벽**이고, 0.25 m 격자에 걸려 계단으로 보였다.
      대신 「노면에서 멀어질수록 안식각만큼만 벌어질 수 있다」로 가둔다 —
        위로는 깎기각(38°), 아래로는 쌓기각(30°).
      가까이서는 꽉 죄고 멀어지면 저절로 풀려, 길이 산허리를 **감싼다.**
      전이 거리라는 임의의 숫자가 아예 사라진다.
    """
    잠금 = np.zeros(X.shape, dtype=np.float32)
    갓 = 갓길["폭"] * 갓길["뻗음"]
    # ★ 클램프는 스스로 멈추지 않는다 — **거리로 끊어 준다.**
    #   T4 는 위쪽 끝이 EL 14 라 쌓기각으로 14 / 0.58 = **24 m** 까지 땅을
    #   들어올린다. 그 반경이 Z2 대지의 서쪽 어깨를 통째로 덮어 7 m 를
    #   밀어올렸다.
    #   처음엔 「대지몫이 높으면 클램프를 푼다」로 막았는데, 그러면 반대로
    #   **대지 안에서 둑이 안 생긴다** — T4 꼬리는 Z1 대지(EL 0) 안을
    #   EL 2.2 로 지나므로, 클램프가 풀린 채 노면만 못박히면 2.2 m 짜리
    #   수직 축대가 된다. 거리로 끊으면 둘 다 해결된다.
    리치 = 9.0   # m — 이 밖에서는 길이 지형을 다스리지 않는다
    # ★ 절벽 면 위에서는 클램프를 아예 끈다.
    #   T4 는 (36, 24.5) 즉 **Z3 마루 위 EL 14** 에서 시작한다. 쌓기 클램프는
    #   「노면에서 4 m 안의 땅은 11.6 m 보다 낮을 수 없다」고 말하는데,
    #   그 4 m 안에 절벽 머리가 들어 있다. 실측하니 x 36 단면에서 절벽이
    #   14 → 0 으로 안 떨어지고 **11.6 에서 멈춰** 있었고, Z2 테두리에서
    #   그대로 0 으로 잘려 11.6 m 단차가 났다.
    #   벼랑에 흙을 쌓아 비탈을 만들 수는 없다 — 절벽이 이긴다.
    끔 = 절그늘.astype(np.float32) * 60.0
    # ★ 흙일의 기준은 **길을 파기 전의 땅**이다.
    #   h 를 그때그때 읽으면 T1 이 깎아 놓은 자리를 T4 가 다시 기준으로
    #   삼아, 길 순서에 따라 결과가 달라진다(순서 의존은 재현을 망친다).
    바탕 = h.copy()
    for 코드, 폭, 시작, 끝, 점 in 통로들:
        반 = 폭 / 2.0
        # ── 포락선: 토막마다 상·하한을 구해 min / max 로 모은다
        상한 = np.full(X.shape, 1e9, dtype=np.float32)
        하한 = np.full(X.shape, -1e9, dtype=np.float32)
        for d, 램프 in 통로토막들(X, Z, 시작, 끝, 점):
            밖 = np.maximum(d - 반 - 갓, 0.0)
            느슨 = np.maximum(밖 - 리치, 0.0) * 8.0 + 끔
            벽 = np.maximum(깎기각 * 밖,
                            np.minimum(옹벽각 * 밖, 옹벽높이))
            팸 = 깎깊이 * np.maximum(1.0 - 밖 / 깎뻗음, 0.0)
            상한 = np.minimum(상한,
                              np.maximum(램프 + 벽 + 느슨, 바탕 - 팸))
            둑 = 둑높이 * np.maximum(1.0 - 밖 / 둑뻗음, 0.0)
            하한 = np.maximum(하한, np.minimum(램프 - 쌓기각 * 밖 - 느슨, 바탕 + 둑))
        # ★ 순서는 **쌓기 먼저, 깎기 나중**이다.
        #   둘이 부딪히면(헤어핀 안쪽처럼) 깎기가 이겨야 한다 —
        #   쌓기가 이기면 아래 다리 노면 위로 흙을 덮어 길을 묻는다.
        h = np.minimum(np.maximum(h, 하한), 상한)
        # 노면 + 갓길은 못박는다 — 걷기 판정이 쓰는 자리다.
        d, 몫, 전체 = 통로밭(X, Z, 점)
        램프 = 시작 + (끝 - 시작) * 몫
        # ★ 노면 테두리를 **불리언으로 자르지 않는다.**
        #   `d <= 반+갓` 로 자르면 노면의 매끄러운 곡선이 0.25 m 격자를
        #   비스듬히 지나면서 「바깥 첫 칸」이 줄마다 들쭉날쭉해진다.
        #   그 옆이 72° 축대면 한 칸씩 튀어나온 **세로 빗살**로 보인다 —
        #   전경 렌더에서 길마다 보이던 그 무늬다.
        #   0.5 m 에 걸쳐 부드럽게 물리면 격자가 안 드러난다.
        #   ※ 걷는 폭(d ≤ 반)은 여전히 100 % 램프다 — `반+갓−0.2` 까지
        #     꽉 차 있으므로 램프 오차는 그대로 0 이다.
        노면 = 노면몫(d, 반 + 갓)
        h = h * (1 - 노면) + 램프 * 노면
        잠금 = np.maximum(잠금, 노면)
    return h, 잠금


