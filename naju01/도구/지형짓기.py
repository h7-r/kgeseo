# ── 값 노이즈 (격자 전체를 한 번에) ─────────────────────────
#   블렌더의 `mathutils.noise` 는 점 하나씩이라 6 만 점에 느리다.
#   numpy 로 격자 전체를 한꺼번에 굴린다.
def 노이즈(X, Z, 주기, 씨):
    rng = np.random.default_rng(씨)
    gx = int(코어["X"][1] / 주기) + 3
    gz = int(코어["Z"][1] / 주기) + 3
    격 = rng.random((gz, gx)).astype(np.float32)
    u = X / 주기
    v = Z / 주기
    i = np.floor(u).astype(np.int32)
    j = np.floor(v).astype(np.int32)
    fu = u - i
    fv = v - j
    # 부드럽게 — 선형이면 격자 자국이 그대로 보인다
    su = fu * fu * (3 - 2 * fu)
    sv = fv * fv * (3 - 2 * fv)
    i = np.clip(i, 0, gx - 2)
    j = np.clip(j, 0, gz - 2)
    a = 격[j, i]
    b = 격[j, i + 1]
    c = 격[j + 1, i]
    d = 격[j + 1, i + 1]
    return (a * (1 - su) + b * su) * (1 - sv) + (c * (1 - su) + d * su) * sv


def 결(X, Z, 층, 씨0):
    """여러 크기를 겹친 노이즈. 0~1."""
    합 = np.zeros_like(X)
    무게 = 0.0
    for k, (주기, w) in enumerate(층):
        합 += 노이즈(X, Z, 주기, 씨0 + k * 977) * w
        무게 += w
    return 합 / 무게


def 사이(t):
    """smoothstep 0~1"""
    t = np.clip(t, 0.0, 1.0)
    return t * t * (3 - 2 * t)


def 사각거리(X, Z, xr, zr):
    """사각형 **밖으로** 얼마나 떨어졌나. 안이면 0."""
    dx = np.maximum(np.maximum(xr[0] - X, 0.0), X - xr[1])
    dz = np.maximum(np.maximum(zr[0] - Z, 0.0), Z - zr[1])
    return np.hypot(dx, dz)


def 사각거리비(X, Z, xr, zr, 뻗음):
    """사각형 밖으로 얼마나 왔나 — **방향마다 다른 자로** 잰다. 안이면 0.

    돌려주는 값은 미터가 아니라 **0~1 몫**이다. 1 이면 그 방향의 어깨 끝.
    이렇게 해야 「서쪽은 20 m, 동쪽은 3 m」 같은 비대칭 어깨를 한 식으로 쓴다.
    ※ 서/동, 북/남은 서로 배타적이라 그냥 더해도 된다(한쪽은 늘 0).
    """
    서, 동, 북, 남 = 뻗음
    dx = np.maximum(xr[0] - X, 0.0) / 서 + np.maximum(X - xr[1], 0.0) / 동
    dz = np.maximum(zr[0] - Z, 0.0) / 북 + np.maximum(Z - zr[1], 0.0) / 남
    return np.hypot(dx, dz)


def 뒤틀기(X, Z, 폭, 씨):
    """좌표 자체를 부드럽게 민다(도메인 워프).

    ★ 경계선을 구불거리게 만드는 **올바른 방법**이다.
      전에는 무게 w 에 노이즈를 더하되 `(w>0.02)&(w<0.98)` 불리언 마스크로
      띠 안에서만 더했다. 마스크는 **끊긴다** — 그 선에서 w 가 0.45 만큼
      뚝 뛰고, 14 m 대지에서는 그게 6 m 절벽이다. 렌더에 보이던 **톱니**가
      전부 그 선이었다. 좌표를 밀면 경계는 구불거리되 밭은 끊기지 않는다.
    """
    ux = (결(X, Z, [(13.0, 1.0), (5.5, 0.45)], 씨) - 0.5) * 2.0 * 폭
    uz = (결(X, Z, [(13.0, 1.0), (5.5, 0.45)], 씨 + 613) - 0.5) * 2.0 * 폭
    return X + ux, Z + uz


def 밀기(h, dj, di):
    """가장자리를 **물고 늘어지는** 시프트. `np.roll` 은 반대편으로 감긴다 —
    북쪽 끝 높이가 남쪽 끝으로 넘어와 지도 테두리에 없던 단차를 만든다."""
    g = np.roll(np.roll(h, dj, axis=0), di, axis=1)
    if dj > 0:
        g[:dj, :] = h[:dj, :]
    elif dj < 0:
        g[dj:, :] = h[dj:, :]
    if di > 0:
        g[:, :di] = h[:, :di]
    elif di < 0:
        g[:, di:] = h[:, di:]
    return g


def 매끄럽게(h, 풀림, 되풀이=4, 세기=0.5):
    """격자 톱니를 **묶인 자리는 빼고** 눌러 준다.

    [왜 마지막에 이게 필요한가]  대지·절벽·노면을 못박고 나면 그 경계에
      한 칸짜리 각이 남는다. 0.25 m 격자에서 그 각은 그림자로 도드라져
      「계단」으로 읽힌다. 못박힌 칸은 그대로 두고 **그 사이만** 푼다 —
      규격은 하나도 안 건드리면서 이음매만 사라진다.
    `풀림` : 1 이면 풀어도 되는 칸, 0 이면 못박힌 칸.
    """
    h = h.copy()
    for _ in range(되풀이):
        평 = (밀기(h, 1, 0) + 밀기(h, -1, 0) + 밀기(h, 0, 1) + 밀기(h, 0, -1)) * 0.25
        h += (평 - h) * 세기 * 풀림
    return h


# ── 통로 중심선 다듬기 ──────────────────────────────────────
def 중심선다듬기(점, 간격=0.25, 되풀이=14):
    """도면 꼭짓점을 **둥글린** 중심선으로 바꾼다.

    ★ 이걸 안 하면 **경사진 길이 코너에서 끊긴다.**
      `지형.js` 의 `중심선뽑기` 머리말이 같은 일을 이미 적어 뒀다 —
      「도면 꼭짓점(직각으로 꺾임)을 그대로 쓰면, 꺾이는 데서 두 선분의
      호 길이가 달라 높이가 튄다 — 코너 안쪽에서 한 걸음에 0.5 m 가 꺼졌다.」
      나는 그 경고를 못 보고 꼭짓점을 날것으로 썼다.

    [왜 튀나]  노면 높이는 「가장 가까운 중심선 점의 **호 길이**」로 정한다.
      직각 코너 **안쪽**에서는 넓은 쐐기 모양 영역이 전부 코너 한 점에
      가장 가까워서, 그 쐐기가 통째로 같은 높이가 된다. 쐐기 바깥은
      정상적으로 오르내리므로 그 경계에 단차가 생긴다.
      경사가 0 인 T1 만 멀쩡했던 것이 그 증거다(높이차가 없으니 안 드러난다).

    [어떻게]  촘촘히 다시 뽑고 위치를 이웃과 평균한다(양 끝은 고정).
      코너가 반지름 1 m 쯤으로 둥글려져 호 길이가 매끄럽게 변한다.
      실제 산길도 직각으로 꺾이지 않으니 형태로도 이쪽이 옳다.
    """
    누 = [0.0]
    for i in range(len(점) - 1):
        누.append(누[-1] + math.hypot(점[i + 1][0] -점[i][0], 점[i + 1][1] -점[i][1]))
    전체 = 누[-1]
    n = max(2, int(round(전체 / 간격)))
    새 = []
    for k in range(n + 1):
        d = 전체 * k / n
        i = min(len(점) - 2, max(0, np.searchsorted(누, d, side="right") - 1))
        t = (d - 누[i]) / max(누[i + 1] - 누[i], 1e-9)
        새.append([점[i][0] + (점[i + 1][0] - 점[i][0]) * t,
                   점[i][1] + (점[i + 1][1] - 점[i][1]) * t])
    새 = np.array(새, dtype=np.float64)
    for _ in range(되풀이):
        새[1:-1] = (새[:-2] + 새[1:-1] * 2 + 새[2:]) / 4
    return [(float(a), float(b)) for a, b in 새]


