통로들 = [(코드, 폭, 시작, 끝, 중심선다듬기(점)) for 코드, 폭, 시작, 끝, 점 in 통로들]


# ── 통로 — 거리·호길이 밭 ───────────────────────────────────
def 통로밭(X, Z, 점, 발도=False):
    """폴리라인까지의 거리와, 가장 가까운 자리의 호 길이(0~1).

    `발도=True` 면 **그 가장 가까운 점의 좌표**까지 준다.
      「이 칸을 다스리는 길이 대지 안을 지나는가」를 판정하는 데 쓴다
      (`길그늘` 머리말).
    """
    거리 = np.full(X.shape, 1e9, dtype=np.float32)
    몫 = np.zeros(X.shape, dtype=np.float32)
    발x = np.zeros(X.shape, dtype=np.float32)
    발z = np.zeros(X.shape, dtype=np.float32)
    누적 = [0.0]
    for i in range(len(점) - 1):
        (x1, z1), (x2, z2) = 점[i], 점[i + 1]
        누적.append(누적[-1] + math.hypot(x2 - x1, z2 - z1))
    전체 = 누적[-1]
    for i in range(len(점) - 1):
        x1, z1 = 점[i]
        x2, z2 = 점[i + 1]
        dx, dz = x2 - x1, z2 - z1
        L2 = dx * dx + dz * dz
        t = np.clip(((X - x1) * dx + (Z - z1) * dz) / L2, 0.0, 1.0)
        cx = x1 + t * dx
        cz = z1 + t * dz
        d = np.hypot(X - cx, Z - cz)
        더가깝다 = d < 거리
        거리 = np.where(더가깝다, d, 거리)
        몫 = np.where(더가깝다, (누적[i] + t * math.sqrt(L2)) / 전체, 몫)
        if 발도:
            발x = np.where(더가깝다, cx, 발x)
            발z = np.where(더가깝다, cz, 발z)
    if 발도:
        return 거리, 몫, 전체, 발x, 발z
    return 거리, 몫, 전체


def 노면몫(d, 끝폭, 물림=0.5):
    """노면이 차지하는 몫 — 안쪽 1, `끝폭` 를 지나 `물림` 만에 0.

    걷는 폭은 통째로 1 이어야 하므로 감쇠는 `끝폭` **직전**에 시작한다.
    """
    return 1.0 - 사이((d - (끝폭 - 0.2)) / 물림)


def 통로토막들(X, Z, 시작, 끝, 점):
    """폴리라인의 **토막마다** (거리, 그 토막 위 램프 높이) 를 준다.

    ★ `통로밭` 은 **가장 가까운 토막 하나**만 본다. 흙일에 그걸 쓰면
      되돌아 꺾이는 길에서 터진다. T4 는 스위치백이라 내려오는 다리와
      꼬리 다리가 3 m 옆에 나란히 있는데, 두 다리의 램프 높이는 8 m 차이다.
      두 다리의 **중간선**에서 「가장 가까운 토막」이 홱 바뀌므로 램프가
      8 m 를 뛰고, 클램프가 그 선을 따라 그대로 벽을 세운다.
      04 컷에서 스위치백 옆에 보이던 톱니 벽이 바로 이것이었다.

    옳은 계산은 **포락선**이다 — 땅은 모든 토막의 조건을 동시에 만족해야
    하므로, 깎기는 토막별 상한의 **최솟값**, 쌓기는 하한의 **최댓값**이다.
    토막이 다 합쳐 20 개뿐이라 격자 전체로 돌려도 값싸다.
    """
    누적 = [0.0]
    for i in range(len(점) - 1):
        (x1, z1), (x2, z2) = 점[i], 점[i + 1]
        누적.append(누적[-1] + math.hypot(x2 - x1, z2 - z1))
    전체 = 누적[-1]
    for i in range(len(점) - 1):
        x1, z1 = 점[i]
        x2, z2 = 점[i + 1]
        dx, dz = x2 - x1, z2 - z1
        L2 = dx * dx + dz * dz
        t = np.clip(((X - x1) * dx + (Z - z1) * dz) / L2, 0.0, 1.0)
        d = np.hypot(X - (x1 + t * dx), Z - (z1 + t * dz))
        몫 = (누적[i] + t * math.sqrt(L2)) / 전체
        yield d, 시작 + (끝 - 시작) * 몫


