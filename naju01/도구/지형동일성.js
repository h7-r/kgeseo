// 지형 높이 동일성·속도 측정 (개발 전용, naju01/지형검사.html)
//
// [무엇을 재나]
//   ① 동일성 — 촘촘한 격자에서 `지표.지면(x, z)` 을 전부 불러 **바이트 단위 지문**을 낸다.
//      지형 코드를 고쳐도 이 지문이 같으면 "결과가 한 치도 안 바뀌었다"는 뜻이다.
//   ② 속도 — 그 격자를 도는 데 걸린 시간. 나주 진입이 느린 진짜 원인이 이 조회다
//      (CPU 프로파일: 진입 25초 중 지형·바닥 15.8초, 그중 `선분에투영` 하나가 8.5초).
//
// [왜 이렇게 재나]
//   바닥.js 의 `땅만들기` 가 격자 꼭짓점마다 이 함수를 부른다. 즉 여기서 재는 값이
//   실제로 첫 화면을 붙잡는 비용이다. 렌더러·GPU 가 끼지 않아 기계 차이도 적다.
//
// [쓰는 법]
//   npx vite naju01  →  http://localhost:5174/지형검사.html
//   화면과 콘솔에 지문·시간이 찍힌다. `window.__지형검사` 로 헤드리스에서도 읽는다.
import { 기본지형, 지형만들기 } from "../src/지형.js";

// 코어(80 × 50 m)를 넉넉히 덮는 격자. 실제 땅 메시의 꼭짓점 수와 같은 자릿수로 잡는다.
const 범위 = { x0: -10, x1: 90, z0: -10, z1: 60 };
const 가로칸 = 600;
const 세로칸 = 420;

// FNV-1a — 부동소수 배열의 **바이트**를 그대로 훑는다. 값이 1비트만 달라도 지문이 바뀐다.
function 지문(버퍼) {
  const 바이트 = new Uint8Array(버퍼.buffer,버퍼.byteOffset, 버퍼.byteLength);
  let h = 0x811c9dc5;
  for (let i = 0; i < 바이트.length; i += 1) {
    h ^= 바이트[i];
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

export function 재기(지표 = 기본지형) {
  const 개수 = (가로칸 + 1) * (세로칸 + 1);
  const 높이 = new Float64Array(개수);
  // 구역·통로·물 같은 갈래도 지문에 넣는다 — 높이가 같아도 판정이 달라지면 안 된다.
  const 갈래 = new Uint8Array(개수);
  const dx = (범위.x1 - 범위.x0) / 가로칸;
  const dz = (범위.z1 - 범위.z0) / 세로칸;

  const 시작 = performance.now();
  let i = 0;
  for (let a = 0; a <= 가로칸; a += 1) {
    const x = 범위.x0 + a * dx;
    for (let b = 0; b <= 세로칸; b += 1) {
      const z = 범위.z0 + b * dz;
      const r = 지표.지면(x, z);
      높이[i] = r.y;
      갈래[i] = (r.통로 ? 1 : 0) | (r.갓길 ? 2 : 0) | (r.낙하 ? 4 : 0) | (r.물 ? 8 : 0) | (r.구역 ? 16 : 0);
      i += 1;
    }
  }
  const 걸린 = performance.now() - 시작;

  let 최소 = Infinity;
  let 최대 = -Infinity;
  for (let k = 0; k < 개수; k += 1) {
    if (높이[k] < 최소) 최소 = 높이[k];
    if (높이[k] > 최대) 최대 = 높이[k];
  }
  return {
    점수: 개수,
    높이지문: 지문(높이),
    갈래지문: 지문(갈래),
    걸린ms: Math.round(걸린),
    최소: +최소.toFixed(6),
    최대: +최대.toFixed(6),
  };
}

// 지형을 새로 만드는 데 드는 값도 따로 잰다(구역·통로 실측·중심선 다듬기).
export function 만들기재기(설정) {
  const 시작 = performance.now();
  const 지표 = 지형만들기(설정);
  return { 걸린ms: Math.round(performance.now() - 시작), 지표 };
}

// 색인을 끈 것과 켠 것을 **같은 격자로** 재서 지문과 시간을 견준다.
const 옛것 = 만들기재기({ 색인쓰기: false });
const 새것 = 만들기재기({ 색인쓰기: true });
const 옛 = 재기(옛것.지표);
const 새 = 재기(새것.지표);
const 새2 = 재기(새것.지표);
const 같은가 = 옛.높이지문 === 새.높이지문 && 옛.갈래지문 === 새.갈래지문;
const 결과 = {
  옛: { ...옛, 만들기ms: 옛것.걸린ms },
  새: { ...새, 만들기ms: 새것.걸린ms },
  결정적: 새.높이지문 === 새2.높이지문 && 새.갈래지문 === 새2.갈래지문,
  지문같음: 같은가,
  배속: +(옛.걸린ms / Math.max(1, 새.걸린ms)).toFixed(1),
};

window.__지형검사 = 결과;
const 줄 = [
  `격자 ${가로칸 + 1} × ${세로칸 + 1} = ${옛.점수.toLocaleString()} 점`,
  "",
  `[옛것 — 모든 선분 훑기]  조회 ${옛.걸린ms} ms · 지형 만들기 ${옛것.걸린ms} ms`,
  `   높이 지문 ${옛.높이지문} · 갈래 지문 ${옛.갈래지문} · 범위 ${옛.최소} ~ ${옛.최대}`,
  "",
  `[새것 — 공간 색인]      조회 ${새.걸린ms} ms · 지형 만들기 ${새것.걸린ms} ms`,
  `   높이 지문 ${새.높이지문} · 갈래 지문 ${새.갈래지문} · 범위 ${새.최소} ~ ${새.최대}`,
  "",
  `★ 결과 지문 같음: ${같은가 ? "예 — 한 비트도 안 바뀌었다" : "아니오 ← 고쳐야 한다"}`,
  `★ 조회 속도: ${결과.배속} 배 (${옛.걸린ms} ms → ${새.걸린ms} ms)`,
  `   두 번 재서 지문 같음(결정적): ${결과.결정적 ? "예" : "아니오"}`,
].join("\n");
console.log(줄);
document.getElementById("결과").textContent = 줄;
document.title = `지형 ${같은가 ? "지문같음" : "지문다름"} · ${결과.배속}배`;
