// ═══════════════════════════════════════════════════════════════
//  바위에셋.js — Meshy 가 **형태째** 만들어 준 바위를 들이는 곳
// ═══════════════════════════════════════════════════════════════
// [왜 이게 따로 필요한가 — 리텍스처로는 형태를 못 고친다]
//   Meshy 의 리텍스처(Texture)는 **재질만** 입힌다. 우리가 넘긴 삼각형을
//   한 개도 안 바꾸고 돌려준다(실측으로 확인: 92,910 → 92,910).
//   그러니 「프롬프트로 바위 모양을 둥글게」는 **원리상 불가능**하다.
//   프롬프트가 형태에 관여할 수 있는 길은 딱 둘이다.
//     ① 법선맵으로 **요철을 흉내** 낸다 — 실루엣은 그대로지만 면이 거칠어진다
//     ② Image-to-3D / Text-to-3D 로 **새 덩어리를 만든다** — 실루엣이 바뀐다
//   도면이 절벽에 준 깊이가 4 m 뿐이라 ①로는 「판」을 못 벗어난다.
//   그래서 ②로 만든 바위를 여기서 받아 **절벽 앞에 얹는다.**
//
// [판정은 건드리지 않는다]
//   이 바위는 **그림 전용**이다. 걷는 높이는 여전히 지형.js 의 배터다.
//   그래야 도면과의 대조(±0.5 m)와 실측 하네스가 계속 유효하다.
//   바위가 배터보다 앞으로 나오면 그만큼은 '못 가는 곳'이 되는데,
//   §6 ②가 말하는 「절벽에서 발을 헛디디면 떨어진다」는 그대로 성립한다.
//
// [스케일]
//   Meshy 산출물은 크기가 제멋대로다(우리 지형은 133.3333 배로 줄어서 왔다).
//   그래서 반드시 `실치수맞춤` 을 통과시킨다 — 「이 바위의 가로는 몇 m」를
//   못 박아야 §3 의 「사람으로 보이나」 판정이 유지된다.
//
// [파일 자리]
//   naju01/에셋/바위/ 에 넣으면 된다. 없으면 조용히 건너뛴다(오류 아님).

import { GLB풀기, 첫메시, 실치수맞춤 } from "./에셋.js";
import { 미터 } from "./공간도면.js";

// Vite 가 빌드에 포함하도록 폴더째 훑는다. 파일이 없으면 빈 목록이 된다.
const 후보 = import.meta.glob("../에셋/바위/*.glb", {
  query: "?url",
  import: "default",
  eager: true,
});

export function 바위파일목록() {
  return Object.keys(후보).map((k) => k.split("/").pop());
}

// 이름(또는 첫 번째 파일)으로 하나 읽어 실치수에 맞춘 지오메트리를 돌려준다.
//   폭m   가로 실치수(미터). 절벽 폭이 22 m 이므로 그 언저리가 기본.
export async function 바위읽기({ 이름 = null, 폭m = 22 } = {}) {
  const 키들 = Object.keys(후보);
  if (!키들.length) return null;
  const 키 = 이름 ? 키들.find((k) => k.endsWith(이름)) : 키들[0];
  if (!키) return null;

  const 응답 = await fetch(후보[키]);
  if (!응답.ok) return null;
  const gltf = await GLB풀기(await 응답.arrayBuffer());
  const 메시 = 첫메시(gltf);
  if (!메시) return null;

  const g = 메시.geometry.clone();
  // 부모 변환까지 굳힌 뒤 실치수로 맞춘다
  메시.updateWorldMatrix(true, false);
  g.applyMatrix4(메시.matrixWorld);
  실치수맞춤(g, { 기준: "폭", 목표m: 폭m, 바닥맞춤: true });
  return { 지오: g, 이름: 키.split("/").pop() };
}

// 절벽 앞에 놓을 기본 자리 — Leva 에서 밀고 돌려 가며 맞춘다.
//   ※ 도면 숫자가 아니라 **화풍 값**이라 공간도면.js 가 아니라 여기 둔다.
export function 바위기본자리(절벽) {
  return {
    x: (절벽.X[0] + 절벽.X[1]) / 2,
    z: (절벽.Z위 + 절벽.Z아래) / 2,
    y: 0,
    회전: 0,
  };
}

export const 유닛변환 = 미터;
