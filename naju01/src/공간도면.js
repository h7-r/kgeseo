// ── 절벽 윤곽 (§3 · 모티브 사진) ───────────────────────────
// [왜 여기 있나]
//   도면은 절벽을 **직사각형 띠**로 그린다(X 34~56 · Z 26~30 · H 14).
//   그대로 세우면 자로 그은 옹벽이 된다 — 실제 앙암바위 사진과 가장 크게
//   어긋나는 지점이 바로 이것이었다(표면 무늬가 아니라 **덩어리 모양**).
//   그래서 띠 **안에서** 마루선·발치선·높이를 x 를 따라 흔든다.
//
// [왜 도면 파일에 두나]
//   이 값을 **판정(지형.js)과 그림(절벽.js)이 같이** 봐야 한다.
//   한쪽만 흔들면 눈과 발이 어긋난다 — 이 프로젝트가 가장 오래 싸운 버그다.
//   소음 라이브러리를 쓰지 않고 사인 몇 개로 정한 이유도 같다: 어디서 부르든
//   **같은 값**이 나와야 하고, 순환 참조 없이 아무 데서나 import 할 수 있어야 한다.
//
// [띠 밖으로 안 나간다]
//   마루는 남(+Z)으로만 물러나고 발치는 북(−Z)으로만 당긴다. 그래서
//   Z3(걷는 대지)와 Z2(자갈밭)를 침범하지 않는다.
export function 절벽윤곽(x) {
  const t = (x - 절벽.X[0]) / (절벽.X[1] - 절벽.X[0]);
  const 물결 = (a, b, c) =>
    Math.sin(t * Math.PI * a + b) * c;
  // −1 ~ 1 남짓
  const s1 = 물결(1.7, 0.6, 0.55) + 물결(3.9, 2.1, 0.3) + 물결(7.3, 4.4, 0.15);
  const s2 = 물결(2.3, 1.9, 0.5) + 물결(5.1, 0.4, 0.32) + 물결(9.7, 3.2, 0.18);
  const s3 = 물결(1.3, 2.7, 0.6) + 물결(4.4, 5.0, 0.28);
  return {
    // 마루 — 남쪽으로 0 ~ 2.6 m 물러난다. 물러난 만큼 어깨(선반)가 생긴다.
    마루: 절벽.Z위 + (0.5 + s1 * 0.5) * 2.6,
    // 발치 — 북쪽으로 0 ~ 1.5 m 당긴다. 발치가 들쭉날쭉해야 덩어리로 읽힌다.
    발치: 절벽.Z아래 - (0.5 + s2 * 0.5) * 1.5,
    // 높이 — 0.8 ~ 1.0. 능선처럼 솟았다 내려앉는다.
    높이: 절벽.높이 * (0.9 + s3 * 0.1),
  };
}

