// ── 자리 ────────────────────────────────────────────────────
//   ※ `씬1자리들` 과 형식이 같다. 처음 값은 도면에서 계산한 것이고,
//     팀이 편집기(E)로 옮기면 `편집.json` 이 그 위를 덮는다.
export function 씬2자리들({ 지면높이 }) {
  const y = (x, z) => (지면높이 ? 지면높이(x, z) : 0);
  const 두기 = (목록) => 목록.map((v) => ({ ...v, y: y(v.x, v.z) + (v.띄움 ?? 0) }));

  // ══════════════════════════════════════════════════════════
  //  자리 둘 — 능선 한 무리 + 나루터 낱개
  // ══════════════════════════════════════════════════════════
  //  ㉮ 능선 무리  x 71.7~74.5 · z 15.4~22.7 · EL +8
  //       팀이 편집기로 잡은 자리다. 진부촌 문(장승·명패, x 72~75 · z 9~15)
  //       **바로 앞**이고, 서남에서 올라오는 길이 닿는 곳이다.
  //       V3(65,19)에서 6.7~9.9 m — 전부 정면으로 보인다.
  //  ㉯ 나루터 낱개  (10.2, 31.2)·(10.9, 32.4) · EL 0
  //       **Z1** 강가. 손대지 않았다. 능선 사람과 강가 사람의 말이
  //       다른 게 이 씬의 뼈대라, 이 둘은 멀리 있어야 한다.
  //
  //  ※ 아래 좌표는 **편집기에서 잰 값을 구운 것**이다. 소수점 두 자리(1 cm)
  //    까지만 적었다 — 편집본과의 차이는 실측 최대 **0.5 cm** 로,
  //    자갈 하나 굵기의 1/20 이라 눈에 안 든다. 열다섯 자리를 그대로
  //    옮겨 적으면 사람이 읽고 고칠 수가 없다.
  //  ※ `편집.json` 이 살아 있는 동안은 **편집본이 이긴다**(`고침` 이 번호로
  //    덮는다). 여기 구운 값은 편집을 지웠을 때 돌아갈 자리다 —
  //    그래서 둘이 어긋나면 안 된다.
  //  ※ `y` 는 안 적는다. `두기()` 가 지면에서 다시 잰다 —
  //    편집본의 y(7.95~8.02)와 실측 지면이 ±0.07 m 안에서 같다.

  return {
    // ── ① 평상 ───────────────────────────────────────────────
    //   [옮겨진 뒤]  (67.3, 13.4) → **(74.03, 16.65)**.
    //     무리의 **동쪽 끝**으로 갔고, 키가 0.62 → 0.53 으로 낮아졌다.
    //     회전도 0.42 → 4.61 로 돌아, 상판의 긴 변이 걸상 줄을 마주 본다.
    //     낮아진 것이 맞다 — 평상은 걸터앉는 물건이라 0.5 m 가 실치수다.
    평상: 두기([
      { x: 74.03, z: 16.65, 키: 0.53, 폭비: 3.3, 깊이비: 2.5, 회전: 4.61 },
    ]),

    // ── ② 통나무 걸상 ────────────────────────────────────────
    //   [옮겨진 뒤]  평상을 **둘러싸던 것이 한 줄로 섰다.**
    //     x ≈ 71.8 에 다섯이 z 15.4 → 19.9 로 1.1~1.9 m 간격으로 늘어선다.
    //     평상은 그 줄에서 동쪽으로 2.1~2.3 m 떨어져 있다.
    //   ★ 「둘러앉았다」에서 **「한 줄로 앉아 같은 쪽을 본다」**로 뜻이 바뀌었다.
    //     이게 이 씬에 더 맞는다 — 둘러앉으면 저희끼리 이야기하는 것이고,
    //     한 줄로 앉아 같은 데를 보면 **다들 무언가를 보고 있었다**가 된다.
    //     증언이 나오려면 뒤쪽이어야 한다.
    //   ※ `키`·`회전`·`모양` 은 안 건드렸다 — 편집본에 x·y·z 만 들어 있다.
    걸상: 두기([
      { x: 71.94, z: 16.37, 키: 0.44, 모양: 0, 회전: 0.3 },
      { x: 71.82, z: 18.07, 키: 0.41, 모양: 1, 회전: 1.7 },
      { x: 71.76, z: 17.15, 키: 0.46, 모양: 2, 회전: 2.9 },
      { x: 72.01, z: 15.43, 키: 0.4, 모양: 3, 회전: 4.4 },
      { x: 71.67, z: 19.93, 키: 0.45, 모양: 1, 회전: 5.6 },
    ]),

    // ── ③ 지게 ───────────────────────────────────────────────
    //   [옮겨진 뒤]  (73.4, 19.6)·(73.9, 20.9) → **(72.02, 22.12)·(73.36, 22.73)**.
    //     무리의 **남쪽 끝**, 길이 올라오는 쪽으로 내려갔다. 둘 사이는
    //     1.5 m 로 여전히 한 짝으로 잡힌다.
    //   ★ 자리가 더 맞다 — 나무하러 올라온 사람은 **들어오는 쪽에** 짐을
    //     내려놓지, 앉는 자리까지 지고 가지 않는다.
    //   **둘**인 게 중요한 건 그대로다. 하나면 「누가 놓고 갔다」지만
    //   둘이면 「둘이 함께 올라왔다」 — 증언자가 여럿이라는 뜻이다.
    지게: 두기([
      { x: 72.02, z: 22.12, 키: 1.35, 모양: 0, 회전: 2.1 },
      { x: 73.36, z: 22.73, 키: 1.28, 모양: 1, 회전: 3.3 },
    ]),

    // ── ④ 물동이 ─────────────────────────────────────────────
    //   [옮겨진 뒤]  능선 것만 (68.0, 14.2) → **(74.08, 19.86)**.
    //     평상(74.03, 16.65)에서 곧장 남쪽으로 3.2 m — 같은 x 선에 섰다.
    //     나루터 것 (10.9, 32.4) 는 **손대지 않았다.**
    //   아비사가 여기 있었다는 표시다(F-01). 젊은이들의 연장(지게)만
    //   놓으면 이 능선이 남자들만의 자리가 되어, 그 사실이 사라진다.
    물동이: 두기([
      { x: 74.08, z: 19.86, 키: 0.52, 모양: 0, 회전: 0.9 },
      { x: 10.9, z: 32.4, 키: 0.5, 모양: 1, 회전: 2.4 },
    ]),

    // ── ⑤ 솟대 ───────────────────────────────────────────────
    //   [옮겨진 뒤]  (68.8, 11.9)·(74.6, 21.8) → **(74.51, 20.89)·(74.38, 22.21)**.
    //     60 m 떨어져 있던 둘이 **1.3 m 간격으로 나란히** 섰다.
    //     (10.2, 31.2) 의 셋째는 손대지 않았다.
    //   ★ **회전은 그대로 둔다.** 이 장치의 전부가 회전이다 —
    //       첫째 −1.01 → 강(서남)쪽을 본다
    //       둘째 −1.75 → 절벽 위(Z3, 서북)를 본다
    //       셋째  1.90 → 능선(동)쪽을 본다   (나루터에 서 있는 것)
    //     나란히 섰으니 **한 화면에 같이 들어온다.** 바로 옆에 선 둘이
    //     서로 다른 데를 보는 것이 멀리 떨어진 둘보다 훨씬 잘 읽힌다.
    //   ※ 회전은 +Z 기준, `Math.atan2(Δx, Δz)` 로 잡은 값이다.
    솟대: 두기([
      { x: 74.51, z: 20.89, 키: 3.2, 모양: 0, 회전: -1.01 },
      { x: 74.38, z: 22.21, 키: 3.0, 모양: 1, 회전: -1.75 },
      { x: 10.2, z: 31.2, 키: 3.1, 모양: 2, 회전: 1.9 },
    ]),
  };
}
