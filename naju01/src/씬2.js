// [무엇을 만드는가]
//   ④ Scene 구성표가 Scene 02 에 **반드시 있어야 한다**고 적은 것들을
//   실제 자리에 놓는다. `씬1.js` 와 같은 원칙이다 — 여기 놓는 것은 전부
//   **유형(type) 수준**이고, `instance_id`·퍼즐 정답·상호작용은 ④ §5 대로
//   이 문서에서 확정하지 않는다.
//
// [근거 — 무엇을 보고 놓았나]
//   `공간도면.js` 안에 이미 적혀 있는 것만 썼다. 밖에서 지어내지 않았다.
//     · 구역 Z4  이름 "진부촌 방향 증언 능선" · 씬 "S2" · X 62~76 · Z 8~32 · EL +8
//     · 구역 Z4  서사 "아비사 = 진부촌 처녀 F-01 · 젊은이들 F-10"
//     · 시점 V3  (65, 19) · 볼것 "진부촌 방향 원경 · 증언 요소"
//                          · 숨길것 "Z3 · Z2 사건 현장"
//     · 조사점 씬2  (66, 11) · (73, 20) · (10.5, 32)
//     · 차단물 B2  치움 { 씬: 2, 볼곳: [63.5, 11] } — 이 씬이 끝나면 무너진다
//
// [★ 이 씬의 공간 논리 — 왜 증언이 엇갈리는가]
//   도면이 이미 답을 갖고 있다. V3 의 `숨길것` 이 **"Z3 · Z2 사건 현장"** 이다.
//   즉 증언하는 사람들이 선 자리에서는 **사건이 벌어진 곳이 안 보인다.**
//   그래서 증언이 엇갈리는 것이지, 누가 거짓말을 해서가 아니다.
//   → 이 모듈이 놓는 물건은 전부 「**여기서 사람들이 이야기를 나눴다**」는
//     흔적이고, 그 자리가 사건 현장을 **못 본다**는 사실이 퍼즐의 바탕이다.
//     (그 사실은 코드가 아니라 지형이 지킨다. `도구` 의 시야 측정으로 확인한다.)
//
// [★ 자리는 팀이 편집기로 다시 잡았다 — 코드가 뒤따라 왔다]
//   아래 기본값은 처음에 내가 도면만 보고 계산한 것이 **아니다.**
//   팀이 편집기(E)로 Z4 를 통째로 다시 짜고, 그 결과를 여기 구웠다
//   (씬 1 도 같은 길을 밟았다 — `씬1.js` 「자리는 편집기에서…」 참고).
//   무엇이 어떻게 달라졌는지는 아래 `씬2자리들` 안에 항목마다 적는다.
//
//   [팀이 짠 Z4 의 얼개 — 실측(2026-09-11)]
//     · 길    (63.5, 28) 에서 북으로 올라 (70.7, 12) 까지. 서남에서 능선으로
//              올라오는 길이 생겼다. 「올라온다」가 지형으로 읽힌다.
//     · 마을 어귀  x 72~75 · z 9~15 에 장승 둘 · 명패 둘 · 횃불 둘 · 비석 ·
//              울타리 넷. **진부촌으로 들어가는 문**이다.
//     · 증언 자리  x 71.7~74.5 · z 15.4~22.7. 그 문 **바로 앞**이다.
//   ★ 이 얼개가 도면을 더 잘 읽어 낸다. Z4 의 이름이 「**진부촌 방향** 증언
//     능선」인데, 예전 내 배치에는 진부촌이 어디인지 가리키는 것이 하나도
//     없었다. 장승과 명패가 서면서 방향이 물건으로 생겼고, 젊은이들이
//     **제 마을 문 앞에** 모여 있는 그림이 됐다.
//
// [★ 증언 자리를 나누는 방식이 바뀌었다]
//   예전에는 Z4 안에 두 자리(㉠ 66,11 · ㉡ 73,20)를 떨어뜨려 놨는데,
//   팀이 그 둘을 **한 자리로 합쳤다.** 대신 갈라지는 것은
//     · 능선의 한 무리 (x 71.7~74.5)
//     · **Z1 나루터 쪽** 낱개 (10.2, 31.2)·(10.9, 32.4)
//   둘이다. 강가에서 본 사람과 능선에서 본 사람의 말이 다르다는 뼈대는
//   그대로고, 능선 쪽이 「한 무리가 같이 있었다」로 더 또렷해졌다.
//   ※ V3(65,19)에서 능선 것 11 개가 **전부 3/3 으로 보인다**(실측).
//     예전 배치에서는 절반이 나무·바위에 가려 안 보였다.
//
// [★ 솟대 셋 — 둘은 나란히, 하나는 멀리]
//   증언이 엇갈린다는 걸 **눈에 보이게** 하는 장치다. 솟대 꼭대기의 새가
//   **제각각 다른 데를 본다.**
//   팀이 능선의 두 기를 1.3 m 간격으로 **나란히** 세웠다. 60 m 떨어져
//   있을 때보다 낫다 — **한 화면에 같이 들어와야** 「둘이 서로 다른 쪽을
//   본다」가 보이지, 멀리 떨어져 있으면 그냥 각각 서 있는 장대다.
//   ※ 새가 가리키는 방위는 배치의 `회전` 이 정한다 — 표본은 +Z 를 본다.
//
// [색을 진짜로 굽는 이유]
//   한 덩이 안에 색이 여럿이다(나무 · 옹기 · 짚). `instanceColor` 는 무리
//   전체에 하나뿐이라 그걸로는 못 준다. 그래서 천막·나룻배와 같은 쪽을
//   택했다 — **표본에 진짜 색을 굽고, 자리에는 `색` 을 안 준다.**
//   (자리에 색을 주면 그게 곱해져 물건이 통째로 물든다. 프로젝트 규칙이다.)
//
// [단위]  도면 좌표 m. 표본은 **높이 1** 짜리이고, m 변환은 `무리만들기` 가 한다.

import * as THREE from "three";
import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { makeRandom } from "../../src/공용.jsx";
import { 색입히기 } from "./바닥.js";
import { 밑동원점으로 } from "./배치.js";

// 색 — 도면 숫자가 아니라 화풍 값이라 여기 둔다.
export const 씬2결 = {
  나무: "#7A6647", // 다듬은 소나무 — 평상 · 지게
  나무어둠: "#4A3B27",
  헌나무: "#8B7A5C", // 볕에 바랜 평상 상판
  껍질: "#5B4A33", // 껍질 붙은 통나무 걸상 옆면
  속살: "#C0A87E", // 그 걸상을 자른 단면
  옹기: "#5A3B2A", // 물동이 — 검붉은 질그릇
  옹기빛: "#8A5E42",
  짚: "#B9A472", // 나뭇짐을 묶은 새끼줄 · 이엉
  삭정이: "#6B5A42", // 나뭇짐
  새: "#3B3B3E", // 솟대 위의 오리
};

// ── 조각 만들기 (소품.js 와 같은 규약) ──────────────────────
const 풀기 = (g) => {
  const n = g.toNonIndexed();
  n.deleteAttribute("uv");
  n.deleteAttribute("uv1");
  g.dispose();
  return n;
};
const 상자 = (w, h, d) => 풀기(new THREE.BoxGeometry(w, h, d));
const 기둥 = (r1, r2, h, 각 = 6) =>
  풀기(new THREE.CylinderGeometry(r1, r2, h, 각, 1));
const 공 = (r, 겹 = 0) => {
  const g = new THREE.IcosahedronGeometry(r, 겹);
  g.deleteAttribute("uv");
  return g.toNonIndexed();
};
const 묶기 = (조각) => {
  const g = mergeGeometries(조각, false);
  조각.forEach((v) => v.dispose());
  return 밑동원점으로(g);
};
const 칠 = (g, 색) => 색입히기(g, new THREE.Color(색));

// ── ① 평상 ──────────────────────────────────────────────────
//   마을 젊은이들이 모여 앉던 마루. **「여기서 말이 오갔다」의 본체**다.
//   Z4 서사의 `젊은이들 F-10` 이 이 물건 하나로 자리를 얻는다.
//   다리 넷 + 널 상판 + 테두리. 상판을 통판으로 두면 탁자가 되어 버려서
//   **널을 한 장씩** 깐다 — 틈이 보여야 평상으로 읽힌다.
export function 평상표본들(수 = 3, 시드 = 5201) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 반가로 = 0.95 + 난수() * 0.2; // 높이 1 기준의 비율
    const 반세로 = 0.72 + 난수() * 0.15;
    const 상판 = 0.62; // 마루 높이 — 걸터앉는 높이다
    // 다리 넷 — 굵고 짧다. 가늘면 평상이 아니라 상이 된다.
    for (const sx of [-1, 1])
      for (const sz of [-1, 1]) {
        const 다리 = 상자(0.13, 상판, 0.13);
        다리.translate(
          sx * (반가로 - 0.12),
          상판 / 2,
          sz * (반세로 - 0.12),
        );
        조각.push(칠(다리, 씬2결.나무어둠));
      }
    // 귀틀 — 다리 위를 두르는 테. 널은 여기 얹힌다.
    for (const sz of [-1, 1]) {
      const 테 = 상자(반가로 * 2, 0.09, 0.1);
      테.translate(0, 상판 + 0.045, sz * (반세로 - 0.05));
      조각.push(칠(테, 씬2결.나무));
    }
    // 널 — 한 장씩. 틈을 남긴다.
    const 널수 = 7;
    for (let k = 0; k < 널수; k++) {
      const t = (k + 0.5) / 널수;
      const 널 = 상자(반가로 * 2 - 0.04, 0.055, (반세로 * 2) / 널수 - 0.035);
      널.translate(
        0,
        상판 + 0.118 + (난수() - 0.5) * 0.008, // 널마다 아주 살짝 들쭉날쭉
        -반세로 + 반세로 * 2 * t,
      );
      조각.push(칠(널, 난수() < 0.35 ? 씬2결.나무 : 씬2결.헌나무));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ② 통나무 걸상 ───────────────────────────────────────────
//   평상에 다 못 앉은 사람이 끌어다 앉는 것. **사람 수를 말해 준다** —
//   평상 하나만 있으면 둘이 앉은 자리지만, 걸상이 둘러 있으면 여럿이
//   둘러앉아 이야기한 자리가 된다(F-10 「젊은이들」).
//   옆은 껍질, 자른 면은 속살 — 두 색이라야 통나무로 읽힌다.
export function 걸상표본들(수 = 4, 시드 = 5202) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 굵 = 0.42 + 난수() * 0.12;
    const 몸 = 기둥(굵, 굵 * 1.04, 1, 9);
    몸.translate(0, 0.5, 0);
    // 살짝 기울여 세운다 — 반듯하면 사람이 놓은 게 아니라 자란 것처럼 보인다
    몸.rotateX((난수() - 0.5) * 0.12);
    몸.rotateZ((난수() - 0.5) * 0.12);
    조각.push(칠(몸, 씬2결.껍질));
    // 자른 면 — 아주 얇은 원반을 위에 덮는다
    const 면 = 기둥(굵 * 0.99, 굵 * 0.99, 0.05, 9);
    면.translate(0, 0.99, 0);
    조각.push(칠(면, 씬2결.속살));
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ③ 지게와 나뭇짐 ─────────────────────────────────────────
//   진부촌 젊은이들이 능선에 올라오는 **이유**다. 놀러 온 게 아니라
//   나무하러 올라왔다가 무언가를 봤다 — 그게 있어야 증언이 성립한다.
//   세워 두지 않고 **기대 놓는다.** 지게는 혼자 못 선다(작대기가 있어야 한다).
export function 지게표본들(수 = 3, 시드 = 5203) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 벌 = 0.17 + 난수() * 0.03; // 두 다리의 벌어짐
    // 새로 둘 — 위로 갈수록 모인다. 아래는 땅에 박힌다.
    for (const s of [-1, 1]) {
      const 새 = 기둥(0.035, 0.045, 1, 5);
      새.translate(0, 0.5, 0);
      새.rotateZ(s * 0.075);
      새.translate(s * 벌, 0, 0);
      조각.push(칠(새, 씬2결.나무));
    }
    // 세장 셋 — 두 새를 가로로 묶는 나무
    for (const h of [0.28, 0.52, 0.76]) {
      const 세장 = 기둥(0.026, 0.026, 벌 * 2.1, 5);
      세장.rotateZ(Math.PI / 2);
      세장.translate(0, h, 0.012);
      조각.push(칠(세장, 씬2결.나무어둠));
    }
    // 작대기 — 지게를 받쳐 세우는 것. 이게 없으면 물건이 공중에 선다.
    const 작대기 = 기둥(0.024, 0.03, 1.02, 5);
    작대기.translate(0, 0.51, 0);
    작대기.rotateX(-0.33);
    작대기.translate(0, 0, 0.2);
    조각.push(칠(작대기, 씬2결.나무));
    // 나뭇짐 — 삭정이 한 다발. 짐이 없으면 「나무하러 왔다」가 안 읽힌다.
    const 짐수 = 9 + Math.floor(난수() * 4);
    for (let k = 0; k < 짐수; k++) {
      const 길 = 0.55 + 난수() * 0.35;
      const 가지 = 기둥(0.014 + 난수() * 0.008, 0.01, 길, 4);
      가지.rotateZ(Math.PI / 2 + (난수() - 0.5) * 0.3);
      가지.rotateY((난수() - 0.5) * 0.5);
      가지.translate(
        (난수() - 0.5) * 0.12,
        0.62 + (난수() - 0.5) * 0.3,
        -0.1 - 난수() * 0.12,
      );
      조각.push(칠(가지, 씬2결.삭정이));
    }
    // 새끼줄 — 짐을 묶은 띠 한 겹
    const 줄 = 기둥(0.017, 0.017, 벌 * 2.4, 5);
    줄.rotateZ(Math.PI / 2);
    줄.translate(0, 0.6, -0.12);
    조각.push(칠(줄, 씬2결.짚));
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ④ 물동이 ────────────────────────────────────────────────
//   Z4 서사의 앞 절반 — 「**아비사 = 진부촌 처녀** F-01」이 자리를 얻는
//   물건이다. 젊은이들의 연장(지게)만 놓으면 이 능선이 남자들만의 자리가
//   되어 버려, 아비사가 여기 있었다는 사실이 공간에서 사라진다.
//   배가 부르고 아가리가 좁은 옹기. 뚜껑은 따로 옆에 놓는다.
export function 물동이표본들(수 = 3, 시드 = 5204) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    // 배 — 정이십면체를 눌러 배부른 항아리로. 원통은 통이지 옹기가 아니다.
    const 배 = 공(0.5, 1);
    배.scale(1, 0.92, 1);
    배.translate(0, 0.5, 0);
    조각.push(칠(배, 씬2결.옹기));
    // 굽 — 바닥을 좁혀 앉힌다
    const 굽 = 기둥(0.3, 0.26, 0.09, 9);
    굽.translate(0, 0.045, 0);
    조각.push(칠(굽, 씬2결.옹기));
    // 목 — 아가리. 좁아야 물동이다.
    const 목 = 기둥(0.24, 0.3, 0.16, 9);
    목.translate(0, 0.96, 0);
    조각.push(칠(목, 씬2결.옹기빛));
    // 전 — 아가리를 두르는 테
    const 전 = 기둥(0.27, 0.27, 0.04, 9);
    전.translate(0, 1.03, 0);
    조각.push(칠(전, 씬2결.옹기빛));
    // 똬리 — 머리에 이려고 쓰는 짚 고리. 하나는 옆에 벗어 둔다.
    if (i % 2 === 0) {
      const 똬리 = 기둥(0.26, 0.26, 0.06, 9);
      똬리.rotateZ(0.5 + 난수() * 0.3);
      똬리.translate(0.66, 0.05, 0.1);
      조각.push(칠(똬리, 씬2결.짚));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ⑤ 솟대 ──────────────────────────────────────────────────
//   마을 어귀에 세우는 장대. 꼭대기의 새가 한쪽을 본다.
//   [왜 이 씬에 있나]  위 머리말의 「★ 솟대를 셋 세운다」 참고 —
//   셋이 **서로 다른 쪽**을 보게 세워, 증언이 갈린다는 걸 눈으로 보여 준다.
//   ※ 표본의 새는 **+Z** 를 본다. 어디를 보게 할지는 자리의 `회전` 이 정한다.
export function 솟대표본들(수 = 3, 시드 = 5205) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    // 장대 — 아주 가늘고 길다. 굵으면 장승이 된다.
    const 장대 = 기둥(0.022, 0.042, 0.9, 6);
    장대.translate(0, 0.45, 0);
    장대.rotateZ((난수() - 0.5) * 0.05); // 세월에 조금 기운다
    조각.push(칠(장대, 씬2결.나무));
    // 밑동 돌무지 — 장대만 꽂으면 땅에 꽂힌 막대기다
    for (let k = 0; k < 5; k++) {
      const 돌 = 공(0.035 + 난수() * 0.025, 0);
      const a = (k / 5) * Math.PI * 2 + 난수();
      돌.translate(Math.cos(a) * 0.07, 0.025, Math.sin(a) * 0.07);
      조각.push(칠(돌, 씬2결.나무어둠));
    }
    // 새 — 오리. 몸 + 목 + 머리 + 부리. 부리가 **+Z** 를 본다.
    const 몸 = 공(0.075, 0);
    몸.scale(0.75, 0.62, 1.5);
    몸.translate(0, 0.94, -0.02);
    조각.push(칠(몸, 씬2결.새));
    const 목 = 기둥(0.018, 0.022, 0.075, 5);
    목.translate(0, 0.975, 0.055);
    조각.push(칠(목, 씬2결.새));
    const 머리 = 공(0.038, 0);
    머리.translate(0, 1.01, 0.062);
    조각.push(칠(머리, 씬2결.새));
    const 부리 = 기둥(0.009, 0.017, 0.07, 4);
    부리.rotateX(Math.PI / 2);
    부리.translate(0, 1.005, 0.115);
    조각.push(칠(부리, 씬2결.짚));
    // 꽁지 — 뒤로 뻗는다. 없으면 앞뒤가 안 갈려 어디를 보는지 모른다.
    const 꽁지 = 상자(0.05, 0.016, 0.085);
    꽁지.rotateX(-0.3);
    꽁지.translate(0, 0.955, -0.105);
    조각.push(칠(꽁지, 씬2결.새));
    표본.push(묶기(조각));
  }
  return 표본;
}

