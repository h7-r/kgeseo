export const 갈래목록 = [...new Set(에셋목록.map((v) => v.갈래))];
export const 에셋찾기 = (키) => 에셋목록.find((v) => v.키 === 키) ?? null;

// 표본을 한 번만 만들어 돌려쓴다(같은 물건을 두 번 만들 이유가 없다)
const 곳간 = new Map();
export function 에셋표본(키, 시드 = 5501) {
  if (곳간.has(키)) return 곳간.get(키);
  const 정의 = 에셋찾기(키);
  if (!정의) return null;
  const 표본 = 정의.표본(시드);
  곳간.set(키, 표본);
  return 표본;
}
