  어둠: "#57503E", // 파인 곳·균열 속 (너무 어두우면 실루엣이 새까맣게 뭉친다)
  젖음: "#4E5751", // 아래쪽 물가에 닿아 축축한 띠
  이끼: "#6B7355", // 층 사이에 낀 이끼
