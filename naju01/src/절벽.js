// ═══════════════════════════════════════════════════════════════
//  절벽.js — 앙암바위 절벽면을 '코드로' 만드는 곳
// ═══════════════════════════════════════════════════════════════
// [왜 여기가 제일 중요한가]
//   문서 §3 이 걸어 놓은 숙제가 「Z3 가장자리에서 Z2 의 사람이 사람으로 보이는
//   높이」다. 그 판정을 하려면 절벽이 **높이로 읽혀야** 한다. 매끈한 판 한 장은
//   14 m 인지 4 m 인지 알 수가 없다 — 눈이 크기를 잴 단서가 없기 때문이다.
//   그래서 이 파일이 하는 일은 장식이 아니라 **자(尺)를 새기는 것**이다.
//     · 가로 지층(층) — 되풀이되는 띠가 곧 눈금이다. 높이를 세게 해 준다
//     · 세로 균열      — 위아래로 흐르는 선이 낙차를 강조한다
//     · 깊이 그늘      — 파인 데가 어두워야 요철이 요철로 보인다
//
// [바닥과 다른 점 — 여기는 진짜로 파도 된다]
//   바닥은 걷는 판정이 평지라 ±0.12 m 를 못 넘겼다. 절벽면은 **설 수 없는 자리**다
//   (지형.js 의 `지면` 이 이 띠를 `낙하` 로 돌려준다). 그래서 지오메트리를
//   실제로 1~2 m 씩 파도 판정과 어긋날 일이 없다. 마음껏 판다.
//
// [안쪽으로만 판다]
//   Z2(자갈밭)는 Z ≥ 30 이다. 절벽면이 Z2 쪽으로 튀어나오면 걸어가는 사람 몸에
//   바위가 박힌다. 그래서 변위는 **언제나 안쪽(-면법선)** 으로만 준다.
//   위·아래 가장자리에서는 0 으로 잦아들게 해 Z3 바닥·Z2 바닥과 이음매가 안 벌어진다.
//
// [단위] 좌표·크기는 미터. 지오메트리만 유닛(× 미터).

