const 부드럽게 = (t) => t * t * (3 - 2 * t);
export const 사이 = (v, a, b) => THREE.MathUtils.clamp((v - a) / (b - a), 0, 1);

// 흙벽 — 통로를 받치는 비탈에 쓰는 색.
