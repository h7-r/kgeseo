// ═══════════════════════════════════════════════════════════════
//  깎인 면 — 절벽도 비탈도 이 규칙 하나를 같이 쓴다
// ═══════════════════════════════════════════════════════════════
// [왜 함수로 빼나]
//   절벽면과 통로 비탈은 **둘 다 흙·바위를 잘라 낸 면**이다. 그런데 절벽만
//   지층·균열·계단을 갖고 비탈은 매끈한 판이면, 같은 공간인데 재질이 따로 논다.
//   규칙을 한 곳에 두고 **세기만 달리** 하면 통일감을 지키면서도
//   "저건 암반, 저건 흙비탈"이라는 구분은 남는다.
//
//   파임     안쪽으로 파는 최대 깊이(m)
//   층두께   가로 지층 한 겹의 높이(m) — 이게 '높이의 눈금'이다
//   각짐     0 = 점토 덩어리 · 1 = 평면으로 쪼개진 바위
//   계단수   깊이를 몇 칸으로 끊을지
//   결세기   1 = 절벽처럼 또렷하게 · 0.5 = 흙비탈처럼 눅게
//   무늬배율 소음의 주기를 통째로 죄고 푼다.
//     ※ 이 값이 왜 필요한가 — 주파수는 22 × 14 m 짜리 절벽에 맞춰 잡았다.
//       그걸 6 × 3.5 m 짜리 차단물에 그대로 쓰면 **면 전체가 소음의 한 점**을
//       찍어서 값이 거의 안 변한다. 그래서 바위가 아니라 판때기로 보였다.
//       작은 덩어리일수록 이 값을 키워 잔결을 촘촘하게 만든다.
// [모티브 — 실제 앙암바위 사진을 보고 고친 것]
//   참고 사진의 바위는 이 코드가 만들던 것과 **정반대**였다.
//     · 가로 지층으로 층층이 쌓인 계단  →  실제로는 그런 단이 없다
//     · 각진 절리 격자로 쪼개진 덩어리  →  실제로는 둥글게 부푼 암괴다
//     · 대신 **세로로 길게 파인 홈**이 면을 지배한다(빗물이 흘러내린 자국)
//   그래서 세기를 재분배할 수 있게 손잡이를 뺐다. 비탈(흙벽)은 예전 값을
//   그대로 쓰므로 기본값을 건드리지 않았다 — 절벽만 다른 값을 넘긴다.
//     층세기   가로 지층. 절벽은 0 에 가깝게.
//     세로결   세로 홈. 절벽의 주역.
//     절리세기 각진 절리 격자. 절벽은 크게 낮춘다.
export function 깎인면만들기({
  파임, 층두께, 각짐, 결소음, 층소음, 결세기 = 1, 무늬배율 = 1,
  층세기 = 1, 세로결 = 0, 절리세기 = 1,
}) {
  return (X, Y, Z) => {
    const x = X * 무늬배율;
    const y = Y * 무늬배율;
    const z = Z * 무늬배율;
    // ① 가로 지층. 자로 그은 듯 수평이면 베개를 쌓아 놓은 벽이 된다 —
    //    층을 세는 좌표 자체를 x·z 를 따라 흔들고 살짝 기울인다.
    // 지층 간격(층두께)은 실제 미터로 정한 값이라 **Y 그대로** 쓴다.
    // 흔드는 소음만 무늬배율을 탄다.
    const y층 =
      Y + 층소음(x * 0.085 + z * 0.05, 4.1) * 층두께 * 1.1 + X * 0.035;
    const 층번호 = Math.floor(y층 / 층두께);
    const t = y층 / 층두께 - 층번호;
    const 층깊이 = 0.3 + 0.7 * (층소음(층번호 * 3.7, x * 0.06 + 1.3) * 0.5 + 0.5);
    // 층 사이는 두툼한 베개가 아니라 가느다란 홈이다 — 아래 25% 만 판다
    const 층 = (1 - 부드럽게(Math.min(1, t * 4))) * 층깊이 * 층세기;

    // ①' 세로 홈 — **y 를 거의 안 쓴다.** 그래야 위아래로 길게 이어진 골이 된다.
    //     굵은 골 + 잔 홈 두 벌을 겹쳐 굵기를 흩는다.
    const 골1 = Math.abs(결소음(x * 0.19 + z * 0.11, y * 0.012 + 11));
    const 골2 = Math.abs(결소음(x * 0.52 + z * 0.28, y * 0.02 + 37));
    const 세로 =
      세로결 > 0
        ? (Math.pow(Math.max(0, 1 - 골1 * 2.2), 2) * 1.0 +
           Math.pow(Math.max(0, 1 - 골2 * 2.6), 2) * 0.45) * 세로결
        : 0;

    // ② 큰 덩어리 — 튀어나온 보루와 움푹한 고랑
    const 덩어리 =
      (결소음(x * 0.045 + z * 0.03, y * 0.032) * 0.5 + 0.5) * 1.15;
    // ③ 중간 굴곡
    const 굴곡 = (결소음(x * 0.16 + z * 0.1, y * 0.13) * 0.5 + 0.5) * 0.5;
    // ④ 세로 균열 — 드물고 깊게
    const cc = 결소음(x * 0.2 + y * 0.03 + z * 0.12, y * 0.018);
    // ※ 너무 깊게 파면 균열 속이 빛을 못 받아 **검은 쐐기**로 보인다.
    //   그림자가 아니라 '안 보이는 구멍'이 되어 형태를 오히려 망친다.
    const 균열 = Math.pow(Math.max(0, 1 - Math.abs(cc) * 2.5), 4) * 1.0;

    const 날것 =
      (층 * 0.55 + 덩어리 * 0.6 + 굴곡 * 0.45 + 균열 + 세로 * 0.9) * 결세기;
    const 매끈 = (날것 / 2.2) * 파임;

    // ⑤ 절리(節理) — 여러 **방향**의 면으로 쪼갠다.
    //    ※ 예전에는 깊이 한 축만 계단으로 끊었다. 그러면 끊긴 면이 전부
    //      기준면과 나란해서 **수평 선반이 층층이 쌓인 것**처럼 보였다.
    //      실제 바위는 서로 다른 각도의 절리 여러 벌이 만나 각진 덩어리로
    //      쪼개진다. 그래서 기울어진 평면 셋으로 공간을 잘라 칸을 만들고,
    //      칸마다 깊이를 통째로 달리 준다. 면이 여러 방향으로 눕는다.
    const 칸 = (a, b2, c2, 크기, 씨) => {
      const n = Math.floor((x * a + y * b2 + z * c2) / 크기);
      // 칸 번호 → 0~1 잡음 (같은 칸이면 언제나 같은 값)
      let h = Math.imul(n ^ 씨, 0x27d4eb2d);
      h ^= h >>> 15;
      return ((h >>> 0) % 1024) / 1024;
    };
    const 절리 =
      칸(0.92, 0.28, 0.27, 2.3, 0x9e37) * 0.45 +
      칸(-0.35, 0.78, 0.52, 1.7, 0x85eb) * 0.33 +
      칸(0.41, -0.24, 0.88, 3.1, 0xc2b2) * 0.22;
    const 각 = 절리 * 파임 * 절리세기;

    // 각짐 0 = 매끈한 덩어리 · 1 = 절리로 완전히 쪼개진 바위
    return { d: 매끈 * (1 - 각짐 * 0.55) + 각 * 각짐, 층번호, t };
  };
}

// 깎인 면을 칠하는 규칙 — 절벽·비탈이 같이 쓴다.
//   층색(퇴적암처럼 겹마다 다름) → 깊이 그늘 → 아래쪽 젖음 → 층 홈의 이끼
export function 깎인면칠하기(
  c,
  { 층번호, d, t, 아래 = 0, 잔색 },
  { 팔레트, 파임, 층소음, 이끼세기 = 0.35 },
) {
  const 층색 = 층소음(층번호 * 7.1, 2.9) * 0.5 + 0.5;
  c.copy(팔레트.어둠).lerp(팔레트.밝음, 0.34 + 층색 * 0.66);
  // 0.8 이면 가장 깊은 데가 거의 순수 어둠색이 된다 — 하늘을 등지면 새까맣게 뭉친다
  c.lerp(팔레트.어둠, 사이(d / Math.max(0.01, 파임), 0, 0.9) * 0.62);
  c.lerp(팔레트.젖음, 사이(아래, 0.76, 1) * 0.4);
  c.lerp(팔레트.이끼, (1 - 사이(t, 0, 0.14)) * 이끼세기 * (1 - 사이(아래, 0.72, 1)));
  // 잔색 — 가까이서 보면 층색만으로는 **한 톤**으로 보인다.
  //   면(삼각형)마다 조금씩 달라야 바위가 알갱이를 가진 것으로 읽힌다.
  if (잔색 !== undefined) c.offsetHSL(0, 0, 잔색);
  return c;
}

// ── 절벽면 ──────────────────────────────────────────────────
//   절벽 = 지형만들기가 준 것 { X, Z위, Z아래, 높이 }
//   칸당 = 1 m 를 몇 칸으로 나눌지
//   파임 = 가장 깊이 파이는 깊이(m)
//   층두께 = 가로 지층 한 겹의 높이(m). 이게 '눈금 간격'이다
export function 절벽면만들기({
  절벽, 칸당, 파임, 층두께, 각짐, 결소음, 층소음, 얼룩소음,
}) {
  const { X, Z위, Z아래, 높이: h } = 절벽;
  const w = X[1] - X[0];
  const 배터 = Z아래 - Z위; // 도면상 4 m
  const 면길이 = Math.hypot(배터, h);
  const nu = Math.max(2, Math.round(w * 칸당 * 1.6)); // 윤곽이 흔들리므로 가로를 촘촘히
  const nv = Math.max(2, Math.round(면길이 * 칸당));
  // ★ 밑동을 땅 아래로 더 내린다. v = 1 에서 딱 끊으면 바위가 지면 선에서
  //   잘려 **얹혀 있는 것**처럼 보인다. 조금 더 내려서 땅에 묻히게 한다.
  const v끝 = 1.18;

  // ★ 면의 바깥 방향은 이제 **x 마다 다르다.** 마루·발치·높이가 흔들리므로
  //   기울기도 따라 흔들린다. 한 값으로 고정하면 변위 방향이 면과 어긋난다.
  const 법선 = (x) => {
    const { 마루, 발치, 높이: 벽 } = 절벽윤곽(x);
    const 배 = Math.max(0.3, 발치 - 마루);
    const L = Math.hypot(벽, 배) || 1;
    return { nz: 벽 / L, ny: 배 / L, 마루, 발치, 벽 };
  };

  // ★ 위쪽만 0 으로 여민다. **아래는 여미지 않는다.**
  //   예전에는 sin(πv) 라 v = 1(밑동)에서도 변위가 0 이었다. 그래서 밑동 한 줄이
  //   이상적인 빗면 그대로 매끈해져 **바위가 선반 위에 얹힌 것처럼 들려 보였다**
  //   (사용자 지적: 「바닥이 좀 들려있다」). 실제 바위는 물까지 그대로 내려간다.
  const 가장자리 = (v) => Math.min(1, v * 5);

  // 이 자리를 안쪽으로 얼마나 팔 것인가 (0 ~ 파임)
  //   절벽은 **세로 홈이 주역**이다 — 모티브 사진 참고(깎인면만들기 주석).
  const 깎기 = 깎인면만들기({
    파임, 층두께, 각짐, 결소음, 층소음,
    층세기: 0.12,   // 가로 지층은 거의 지운다
    세로결: 1.25,   // 빗물이 흘러내린 세로 골이 면을 지배한다
    절리세기: 0.3,  // 각진 격자는 흔적만
  });
  const 파임값 = (x, y, v) => {
    const r = 깎기(x, y, 0);
    return { d: r.d * 가장자리(v), 층번호: r.층번호, t: r.t };
  };
  // ★ 양옆 끝을 더 깊이 깎는다 — 가운데가 **부푼 암괴**로 읽히게.
  //   바깥으로 부풀리면 Z2(걷는 땅)를 침범하므로, 반대로 **가장자리를 깎아**
  //   같은 인상을 만든다. 판정은 도면의 배터 그대로 둔다.
  const 옆여밈 = (u) => 1 + Math.pow(Math.abs(u * 2 - 1), 2.2) * 1.15;

  // ★ 홈의 굵기·깊이를 x 를 따라 흔든다. 세기가 일정하면 **골판지 벽**이 된다
  //   (실제로 그렇게 보였다 — 규칙적인 세로줄이 오히려 인공물로 읽혔다).
  //   어떤 데는 매끈한 덩어리, 어떤 데는 깊게 파인 골이 되도록 0.35~1.5 로 흔든다.
  const 무늬세기 = (x) =>
    0.35 + (결소음(x * 0.075 + 3.3, 7.7) * 0.5 + 0.5) * 1.15;

  const 자리 = (u, v) => {
    const x = X[0] + w * u;
    const { nz: NZ, ny: NY, 마루, 발치, 벽 } = 법선(x);
    const z0 = 마루 + (발치 - 마루) * v;
    const y0 = 벽 * (1 - v);
    const { d, 층번호, t } = 파임값(x, y0, v);
    const dd = d * 옆여밈(u) * 무늬세기(x);
    return { x, y: y0 - NY * dd, z: z0 - NZ * dd, d: dd, y0, v, 층번호, t };
  };

  // ── 꼭짓점을 찍는다 (인덱스 없이 = 면마다 각진 노멀 = 깎인 바위) ──
  const 위치 = [];
  const 색깔 = [];
  const 밝음 = new THREE.Color(절벽결.밝음);
  const 어둠 = new THREE.Color(절벽결.어둠);
  const 젖음 = new THREE.Color(절벽결.젖음);
  const 이끼 = new THREE.Color(절벽결.이끼);
  const c = new THREE.Color();

  const 색계산 = (p) => {
    깎인면칠하기(
      c,
      {
        층번호: p.층번호,
        d: p.d,
        t: p.t,
        아래: p.v,
        // 잔색 — 층색만으로는 가까이서 한 톤으로 보인다. 면마다 조금씩 흔든다.
        잔색: 얼룩소음(p.x * 1.9, p.y0 * 1.9) * 0.11,
      },
      { 팔레트: { 밝음, 어둠, 젖음, 이끼 }, 파임, 층소음 },
    );
    // 세로로 흘러내린 물 얼룩 — 세로선이 낙차를 강조한다(절벽에만 준다)
    const 흘림 = 얼룩소음(p.x * 0.5, p.y0 * 0.03);
    c.offsetHSL(0, 0, 흘림 * 0.075);
    return c;
  };

  const 찍기 = (p) => {
    위치.push(p.x * 미터, p.y * 미터, p.z * 미터);
    const cc = 색계산(p);
    색깔.push(cc.r, cc.g, cc.b);
  };
  const 면 = (p1, p2, p3) => {
    찍기(p1);
    찍기(p2);
    찍기(p3);
  };

  // 앞면 — j 는 v끝(= 1.18)까지 간다. 마지막 띠가 땅 아래로 묻히는 부분이다.
  for (let i = 0; i < nu; i++) {
    for (let j = 0; j < nv; j++) {
      const v0 = (j / nv) * v끝;
      const v1 = ((j + 1) / nv) * v끝;
      const a = 자리(i / nu, v0);
      const b = 자리((i + 1) / nu, v0);
      const d2 = 자리((i + 1) / nu, v1);
      const e = 자리(i / nu, v1);
      // 바깥(Z2 쪽)에서 보이도록 감는다
      면(a, e, b);
      면(b, e, d2);
    }
  }

  // 옆 마구리 — 앞면만 있으면 X = 34 · 56 쪽에서 종잇장 옆구리가 보이고
  //   그 너머로 안이 훤히 뚫린다. 안쪽 벽까지 이어 붙여 덩어리로 닫는다.
  //   안쪽 벽은 Z3 덩어리 속(위쪽)과 땅속(아래쪽)이라 눈에 띄지 않는다.
  //   ※ 깊이를 **끝에서 0 으로 좁힌다.** 예전에는 양 끝(X=34·56)에서 마구리가
  //     그대로 남아 "칼로 자른 단면"이 보였다. 끝에서 안쪽 벽이 앞면에 붙으면
  //     마구리가 없어져 절벽이 지형 속으로 스며든다.
  //   ※ 0 까지 좁히면 마구리 사각형이 납작해지다 뒤집혀 **검은 쐐기**가 난다.
  //     최소 두께를 남긴다.
  const 뒤깊이 = (u) =>
    (파임 + 0.8) * Math.max(0.14, Math.min(1, Math.sin(Math.PI * u) * 3.2));
  const 안쪽 = (u, v) => {
    const p = 자리(u, v);
    const { nz: NZ, ny: NY, 마루, 발치, 벽 } = 법선(p.x);
    const z0 = 마루 + (발치 - 마루) * v;
    const y0 = 벽 * (1 - v);
    const 깊 = 뒤깊이(u);
    return { x: p.x, y: y0 - NY * 깊, z: z0 - NZ * 깊, d: 파임, y0, v };
  };
  for (const [u, 뒤집기] of [[0, false], [1, true]]) {
    for (let j = 0; j < nv; j++) {
      const v0 = (j / nv) * v끝;
      const v1 = ((j + 1) / nv) * v끝;
      const a = 자리(u, v0);
      const b = 자리(u, v1);
      const A = 안쪽(u, v0);
      const B = 안쪽(u, v1);
      if (뒤집기) {
        면(a, b, A);
        면(A, b, B);
      } else {
        면(a, A, b);
        면(A, B, b);
      }
    }
  }

  // 아랫자락 — 이제 앞면 자체가 v끝(1.18)까지 내려가 땅에 묻히므로
  //   자락은 **더 깊게** 늘여 바닥 요철이 아무리 파여도 틈이 안 나게만 한다.
  for (let i = 0; i < nu; i++) {
    const a = 자리(i / nu, v끝);
    const b = 자리((i + 1) / nu, v끝);
    const A = { ...a, y: a.y - 1.6 };
    const B = { ...b, y: b.y - 1.6 };
    면(a, A, b);
    면(A, B, b);
  }

  const geo = new THREE.BufferGeometry();
  geo.setAttribute("position", new THREE.Float32BufferAttribute(위치, 3));
  geo.setAttribute("color", new THREE.Float32BufferAttribute(색깔, 3));
  geo.computeVertexNormals(); // 인덱스가 없어 면마다 평평한 노멀 = 각진 바위
  return geo;
}

// ── 절벽 밑에 쌓인 너덜(돌무더기) ───────────────────────────
//   14 m 벼랑 밑에 아무것도 없으면 "잘라 붙인 벽"으로 보인다.
//   떨어져 나온 돌이 쌓여 있어야 저 위에서 여기까지 떨어진다는 게 읽힌다.
//   **배터 띠 안(설 수 없는 자리)에만** 놓아 걷는 사람과 안 부딪히게 한다.
// ※ `지면높이` 를 넘기면 그 자리의 진짜 땅에서 잰다. 예전에는 배터의
//   **이상적인 빗면**(h·(1−v))에 크기의 0.15 배를 더해 얹었는데, 그러면
//   깎아 낸 암벽의 실제 면보다 위로 떠서 발치 돌이 공중에 걸린다
//   (실측: 5/48 이 뜸, 최대 +0.93 m).
// ── 바위 덩어리 (버트레스 · 마루 돔) ──────────────────────
// [왜 필요한가 — 「아직도 각진 사각형」의 진짜 원인]
//   도면은 절벽에 **깊이 4 m** 만 준다. 14 m 를 4 m 안에서 떨어뜨리니 74° 다.
//   그 띠 안에서 표면을 아무리 흔들어도 결과는 **판(벽)** 이다.
//   모티브 사진의 앙암바위는 판이 아니라 **앞으로 뻗어 나온 덩어리**이고,
//   꼭대기는 둥글게 솟아 나무를 이고 있다. 그래서 띠 밖에 덩어리를 더 붙인다.
//
// [한 번 틀렸다]
//   처음에는 `바위덩이만들기`(차단물용 네모 덩어리)를 썼다. 결과가
//   **판때기 상자 몇 개**가 벽 앞에 세워진 꼴이라 오히려 더 나빴다 —
//   그 함수는 '상자에 결을 낸 것'이지 둥근 암괴가 아니다.
//   `돌모양만들기`(정이십면체를 흔든 것) 기반의 큰 돌이 맞다.
//
// [걷는 판정] 이 덩어리들은 그림 전용이다. 큰 것은 Z2 가장자리에 두어
//   걷는 길을 막지 않게 하고, 마루 것은 Z3 남쪽 가장자리 위에만 얹는다.
export function 바위덩어리자리들({ 절벽, 지면높이 }) {
  const 목록 = [];
  const { X } = 절벽;
  const 어디 = (u) => X[0] + (X[1] - X[0]) * u;
  // 발치 어깨 — 벽 앞으로 뻗어 나온 큰 암괴
  const 발치씨 = [
    [0.06, 4.2, 1.6], [0.15, 2.6, 0.9], [0.28, 5.0, 2.2],
    [0.40, 3.0, 1.2], [0.52, 5.6, 2.6], [0.64, 2.8, 1.0],
    [0.76, 4.4, 1.8], [0.88, 3.2, 1.3], [0.96, 2.4, 0.8],
  ];
  for (const [u, 크기, 앞] of 발치씨) {
    const x = 어디(u);
    const { 발치 } = 절벽윤곽(x);
    const z = 발치 + 앞;
    목록.push({
      x, z,
      // 밑동을 깊이 묻는다 — 얹혀 있으면 그게 곧 '떠 보인다'
      y: (지면높이 ? 지면높이(x, z) : 0) - 크기 * 0.42,
      크기,
    });
  }
  // ※ 마루(꼭대기)에도 큰 돌을 얹어 봤다가 **뺐다.** 지름 4~8 m 짜리 돌은
  //   벼랑 위에 얹히면 둥근 바위 머리가 아니라 **공중에 뜬 검은 덩어리**로 보인다.
  //   실루엣을 둥글게 만들려면 돌을 얹는 게 아니라 **대지 자체가 둥글게 솟아야** 한다
  //   — 그건 Z3 의 고도를 건드리는 일이라 도면 변경(§7 0단계) 안건이다.
  return 목록;
}

// ── 절벽에 붙는 수풀 자리 ──────────────────────────────────
// [왜]
//   모티브 사진(실제 앙암바위)에서 바위는 **맨살로 서 있지 않다.**
//   꼭대기와 어깨는 나무가 덮고, 갈라진 틈마다 덤불이 박혀 있고, 발치는
//   수풀이 메운다. 맨 암벽만 세워 두면 아무리 잘 깎아도 「모형」으로 보인다.
//
// [어디에 붙이나]
//   ① 틈    — 깎기 값이 깊은 자리(= 골). 실제로도 흙이 고이는 데가 거기다.
//   ② 발치  — 너덜 사이. 물가 쪽으로 갈수록 성글게.
//   경사가 급한 자리는 건너뛴다 — 수직 벽에 덤불이 붙으면 오히려 가짜가 된다.
export function 절벽수풀자리({ 절벽, 개수 = 90, 시드, 결소음, 층소음, 파임, 층두께, 각짐 }) {
  const { X, Z위, Z아래, 높이: h } = 절벽;
  const 난수 = makeRandom(시드);
  const 배터 = Z아래 - Z위;
  const L = Math.hypot(h, 배터) || 1;
  const nz = h / L;
  const ny = 배터 / L;
  const 깎기 = 깎인면만들기({
    파임, 층두께, 각짐, 결소음, 층소음,
    층세기: 0.12, 세로결: 1.25, 절리세기: 0.3,
  });
  const 자리들 = [];
  for (let i = 0; i < 개수; i++) {
    const u = 난수();
    // 아래쪽에 더 몰린다 — 흙이 아래로 쌓이므로
    const v = Math.pow(난수(), 0.6) * 0.98 + 0.02;
    const x = X[0] + (X[1] - X[0]) * u;
    const z0 = Z위 + 배터 * v;
    const y0 = h * (1 - v);
    const { d } = 깎기(x, y0, 0);
    // 골이 얕은 자리(= 튀어나온 데)에는 안 붙는다
    if (d < 파임 * 0.45) continue;
    // ★ 고르게 흩으면 **점을 찍어 놓은 것**처럼 보인다. 사진의 수풀은
    //   뭉쳐서 덩어리로 덮는다. 소음으로 밀도를 흔들어 모으고 비운다.
    const 뭉침 = 결소음(x * 0.13, y0 * 0.11 + 21) * 0.5 + 0.5;
    // ★ 좌우 끝을 더 빽빽하게. 사진에서도 바위 **옆구리**가 초록에 잠겨 있고
    //   가운데 암벽만 드러난다(사용자 지시: 「좌우측으로 좀 빼곡하게」).
    const 옆 = Math.pow(Math.abs(u * 2 - 1), 1.6); // 가운데 0 ~ 양끝 1
    if (난수() > (0.3 + 뭉침 * 뭉침 * 1.0) * (0.55 + 옆 * 1.5)) continue;
    const 깊 = d * (1 + Math.pow(Math.abs(u * 2 - 1), 2.2) * 1.15);
    자리들.push({
      x,
      y: y0 - ny * 깊,
      z: z0 - nz * 깊,
      // 위로 갈수록 작고 마르게
      키: (0.5 + 난수() * 1.5) * (0.55 + v * 0.7),
    });
  }
  return 자리들;
}

export function 너덜만들기({ 절벽, 개수, 시드, 결소음, 지면높이 }) {
  const { X, Z위, Z아래, 높이: h } = 절벽;
  const 난수 = makeRandom(시드);
  const 모양 = [];
  for (let i = 0; i < 5; i++) 모양.push(돌모양만들기(난수));
  const 조각 = [];
  const 밝음 = new THREE.Color(절벽결.밝음);
  const 어둠 = new THREE.Color(절벽결.어둠);
  const 색 = new THREE.Color();
  const 사원수 = new THREE.Quaternion();
  const 행렬 = new THREE.Matrix4();
  const 자리 = new THREE.Vector3();
  const 배율 = new THREE.Vector3();

  for (let i = 0; i < 개수; i++) {
    const x = X[0] + 난수() * (X[1] - X[0]);
    // 아래쪽 4분의 1 안에서만 — 벼랑 발치에 쌓인다
    const v = 0.82 + 난수() * 0.17;
    const z = Z위 + (Z아래 - Z위) * v;
    const y = h * (1 - v);
    // 굴곡이 깊은 자리(움푹한 데)에 더 잘 모인다
    if (결소음(x * 0.2, y * 0.2) < -0.35) continue;
    const 크기 = 0.25 + Math.pow(난수(), 2.4) * 1.5;
    const 납작 = 0.5 + 난수() * 0.4;
    const 폭비 = 0.7 + 난수() * 0.6;
    const 회전 = [
      (난수() - 0.5) * 1.2,
      난수() * Math.PI * 2,
      (난수() - 0.5) * 1.2,
    ];
    const 색흔들 = 난수();

    const g = 모양[Math.floor(난수() * 모양.length)].clone();
    사원수.setFromEuler(new THREE.Euler(회전[0], 회전[1], 회전[2]));
    배율.set(크기 * 미터, 크기 * 납작 * 미터, 크기 * 폭비 * 미터);
    // 얹지 말고 **묻는다** — 돌은 비탈에 박혀 있어야 굴러떨어지지 않아 보인다
    const 밑 = 지면높이 ? 지면높이(x, z) : y;
    자리.set(x * 미터, (밑 - 크기 * 0.22) * 미터, z * 미터);
    행렬.compose(자리, 사원수, 배율);
    g.applyMatrix4(행렬);
    색.copy(어둠).lerp(밝음, 0.35 + 색흔들 * 0.6);
    조각.push(색입히기(g, 색));
  }

  모양.forEach((g) => g.dispose());
  if (!조각.length) return null;
  const 합본 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합본;
}

// ── 바위 덩이 (차단물 B1·B1b·B2·B3 · 수목대 받침) ───────────
//   도면의 회색 상자를 각진 바위 덩어리로 바꾼다.
//   §4 가 시야 차단 장치라고 못박은 것들이라 **막는 부피가 그대로여야** 한다.
//   그래서 절벽면과 같은 규칙 — **안쪽으로만 판다.** 밖으로 부풀리면
//   `막힘` 이 쓰는 사각형(AABB)보다 커져서 걸어가는 사람 몸에 바위가 박힌다.
//
//   면마다 가장자리에서 파임을 0 으로 잦아들게 해 상자 모서리에서 서로 만난다.
//   블록 같은 각진 바위 능선이 되는데, 「바위 능선」이라는 이름에도 맞는다.
//   `머리` 는 숫자여도 되고 (x, z) → 높이 함수여도 된다.
//   Z3(+14)와 Z4(+8) 사이의 골처럼 **비스듬히 올라가는 능선**을 만들 때 함수를 쓴다.
//   기울임  위로 갈수록 단면을 좁힌다(0 = 상자 · 0.3 = 확실한 사다리꼴).
//     ※ 이게 없으면 아무리 표면을 파도 **실루엣이 직육면체**라 상자로 보인다.
//       사람 눈은 표면 무늬보다 윤곽을 먼저 읽는다.
export function 바위덩이만들기({
  X, Z, 발, 머리, 칸당, 파임, 각짐, 층두께, 결소음, 층소음,
  무늬배율 = 1, 기울임 = 0.22,
}) {
  const 마루 = typeof 머리 === "function" ? 머리 : () => 머리;
  const 위치 = [];
  const 색깔 = [];
  const 밝음 = new THREE.Color(절벽결.밝음);
  const 어둠 = new THREE.Color(절벽결.어둠);
  const 이끼 = new THREE.Color(절벽결.이끼);
  const c = new THREE.Color();
  const 잦아듦 = (t) => Math.min(1, Math.sin(Math.PI * t) * 2.2);

  // 절벽면과 **같은 규칙**을 그대로 쓴다 — 그래야 한 공간의 바위로 보인다
  const 깎기 = 깎인면만들기({
    파임, 층두께, 각짐, 결소음, 층소음, 무늬배율,
  });
  const 깊이 = (x, y, z) => 깎기(x, y, z);

  const 찍기 = (p) => {
    위치.push(p.x * 미터, p.y * 미터, p.z * 미터);
    깎인면칠하기(
      c,
      { 층번호: p.층번호, d: p.d, t: p.t ?? 0.5, 아래: 0 },
      { 팔레트: { 밝음, 어둠, 젖음: 어둠, 이끼 }, 파임, 층소음, 이끼세기: 0 },
    );
    // 꼭대기에는 이끼가 앉는다 — 위와 옆이 갈려야 덩어리로 보인다
    if (p.위) c.lerp(이끼, 0.35);
    색깔.push(c.r, c.g, c.b);
  };
  const 면 = (a, b, d) => {
    찍기(a);
    찍기(b);
    찍기(d);
  };
  const 격자 = (점, nu, nv, 뒤집기) => {
    for (let i = 0; i < nu; i++)
      for (let j = 0; j < nv; j++) {
        const a = 점(i / nu, j / nv);
        const b = 점((i + 1) / nu, j / nv);
        const d = 점((i + 1) / nu, (j + 1) / nv);
        const e = 점(i / nu, (j + 1) / nv);
        if (뒤집기) {
          면(a, e, b);
          면(b, e, d);
        } else {
          면(a, b, e);
          면(b, d, e);
        }
      }
  };

  const w = X[1] - X[0];
  const dz = Z[1] - Z[0];
  // 칸 수를 정할 때만 대표 높이를 쓴다
  const cxm = (X[0] + X[1]) / 2;
  const czm = (Z[0] + Z[1]) / 2;
  // 위로 갈수록 단면을 좁힌다 — 직육면체 윤곽을 깨는 가장 값싼 방법
  const 좁히기 = (x, z, v) => {
    const k = 1 - 기울임 * v;
    return [cxm + (x - cxm) * k, czm + (z - czm) * k];
  };
  const 대표머리 = (마루(X[0], Z[0]) + 마루(X[1], Z[1])) / 2;
  const hh = Math.max(0.5, 대표머리 - 발);
  const N = (v) => Math.max(1, Math.round(v * 칸당));

  // 옆면 넷 — 파임은 안쪽(상자 속)으로만
  const 옆 = (고정축, 값, 안쪽) => (u, v) => {
    const x0 = 고정축 === "x" ? 값 : X[0] + w * u;
    const z0 = 고정축 === "x" ? Z[0] + dz * u : 값;
    const y = 발 + (마루(x0, z0) - 발) * v;
    const [x, z] = 좁히기(x0, z0, v);
    const { d, 층번호, t } = 깊이(x, y, z);
    // 세로 모서리에서는 잦아듦을 약하게 — 세게 주면 상자 모서리가 되살아난다
    const dd = d * (0.45 + 0.55 * 잦아듦(u)) * 잦아듦(v);
    return 고정축 === "x"
      ? { x: x + 안쪽 * dd, y, z, d: dd, 층번호, t, 위: false }
      : { x, y, z: z + 안쪽 * dd, d: dd, 층번호, t, 위: false };
  };
  //                                        ↓ 감는 방향(바깥을 보게)
  격자(옆("x", X[0], +1), N(dz), N(hh), false);
  격자(옆("x", X[1], -1), N(dz), N(hh), true);
  격자(옆("z", Z[0], +1), N(w), N(hh), true);
  격자(옆("z", Z[1], -1), N(w), N(hh), false);

  // 윗면
  격자(
    (u, v) => {
      const x0 = X[0] + w * u;
      const z0 = Z[0] + dz * v;
      const 꼭 = 마루(x0, z0);
      const [x, z] = 좁히기(x0, z0, 1); // 옆면의 꼭대기와 맞물리게
      const { d, 층번호, t } = 깊이(x, 꼭, z);
      const dd = d * 잦아듦(u) * 잦아듦(v);
      return { x, y: 꼭 - dd, z, d: dd, 층번호, t, 위: true };
    },
    N(w),
    N(dz),
    true,
  );

  const geo = new THREE.BufferGeometry();
  geo.setAttribute("position", new THREE.Float32BufferAttribute(위치, 3));
  geo.setAttribute("color", new THREE.Float32BufferAttribute(색깔, 3));
  geo.computeVertexNormals();
  return geo;
}

// ── 아무 데나 돌 뿌리기 ─────────────────────────────────────
//   `자리들` = [{x, y, z, 크기}] . 절벽·비탈·물가가 같은 돌을 쓰게 하려고
//   여기에 둔다. 팔레트만 갈아 끼우면 흙비탈에도, 암반에도 어울린다.
export function 돌뿌리기({ 자리들, 밝음, 어둠, 시드, 납작 = [0.45, 0.85] }) {
  if (!자리들.length) return null;
  const 난수 = makeRandom(시드);
  const 모양 = [];
  for (let i = 0; i < 5; i++) 모양.push(돌모양만들기(난수));
  const 조각 = [];
  const 밝 = new THREE.Color(밝음);
  const 어 = new THREE.Color(어둠);
  const 색 = new THREE.Color();
  const 사원수 = new THREE.Quaternion();
  const 행렬 = new THREE.Matrix4();
  const 자리 = new THREE.Vector3();
  const 배율 = new THREE.Vector3();

  for (const a of 자리들) {
    const 납 = 납작[0] + 난수() * (납작[1] - 납작[0]);
    const g = 모양[Math.floor(난수() * 모양.length)].clone();
    사원수.setFromEuler(
      new THREE.Euler((난수() - 0.5) * 1.1, 난수() * Math.PI * 2, (난수() - 0.5) * 1.1),
    );
    배율.set(a.크기 * 미터, a.크기 * 납 * 미터, a.크기 * (0.7 + 난수() * 0.6) * 미터);
    // 절반쯤 묻는다 — 얹어 놓은 것처럼 뜨지 않게
    자리.set(a.x * 미터, (a.y - a.크기 * 납 * 0.22) * 미터, a.z * 미터);
    행렬.compose(자리, 사원수, 배율);
    g.applyMatrix4(행렬);
    색.copy(어).lerp(밝, 0.32 + 난수() * 0.62);
    조각.push(색입히기(g, 색));
  }
  모양.forEach((g) => g.dispose());
  const 합본 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return 합본;
}
