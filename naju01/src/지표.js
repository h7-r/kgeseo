// ═══════════════════════════════════════════════════════════════
//  지표.js — 이 맵의 '땅 표면'을 정하는 **단 하나의** 함수
// ═══════════════════════════════════════════════════════════════
// [왜 만들었나 — 이음매가 계속 새로 생기던 진짜 이유]
//   지금까지는 구역·통로·절벽·차단물이 **저마다 제 사각형 위에 제 표면**을
//   만들었다. Z1 은 Z1 의 소음으로, Z2 는 Z2 의 소음으로 판을 흔들었으니
//   둘이 맞닿는 선에서 높이가 어긋나 **단차가 남았다.** 하나를 메우면
//   다른 데가 터진 것도 그래서다. 조각마다 진실이 따로 있었기 때문이다.
//
//   그래서 땅의 진실을 여기 하나로 모은다.
//     · 높이(x, z)  이 자리의 **보이는** 땅 높이
//     · 결(x, z)    이 자리의 재질(바닥결의 어느 항목인가)
//     · 색(x, z)    이 자리의 땅 색
//   모든 조각이 이걸 조회해서 제 가장자리를 맞춘다. 같은 함수를 보므로
//   **맞닿는 자리의 값이 애초에 같다.** 이음매가 생길 수가 없다.
//
// [걷는 판정과의 관계]
//   걷는 높이는 여전히 `지형.지면(x, z).y` 다(도면 숫자 그대로).
//   여기서 더하는 요철은 ±0.12 m 안쪽이라 눈과 발이 어긋나지 않는다.
//   즉 **`높이` = 걷는 높이 + 결 요철**. 판정은 도면이, 그림은 여기가 맡는다.
//
// [구역 경계를 자로 그은 듯 두지 않는다]
//   구역은 도면상 직사각형이지만, 흙과 자갈이 직선으로 갈리는 땅은 없다.
//   어느 결을 쓸지 물을 때 **좌표를 소음으로 흔들어서** 묻는다.
//   판정(어디를 걷나)은 그대로 두고 **보이는 경계만** 들쭉날쭉해진다.
//
// [단위] 전부 미터.

import * as THREE from "three";
import { 바닥결, 소음만들기 } from "./바닥.js";
import { 강 } from "./공간도면.js";

export function 지표만들기({ 지형, 요철배율 = 1, 시드 = 20260908 }) {
  const 결소음 = 소음만들기(시드);
  const 얼룩소음 = 소음만들기(시드 + 7711);
  const 무늬소음 = 소음만들기(시드 + 4451);
  const 경계소음 = 소음만들기(시드 + 9137);

  // ── 이 자리는 무슨 땅인가 ────────────────────────────────
  //   좌표를 흔들어 물으므로 구역 경계가 들쭉날쭉해진다.
  const 결코드 = (x, z) => {
    const 흔 = 1.6;
    const hx = x + 경계소음(x * 0.16, z * 0.16) * 흔;
    const hz = z + 경계소음(x * 0.16 + 40, z * 0.16 + 40) * 흔;
    for (const zz of 지형.구역)
      if (hx >= zz.X[0] && hx <= zz.X[1] && hz >= zz.Z[0] && hz <= zz.Z[1])
        return zz.코드;
    return "미설계";
  };
  const 결 = (x, z) => 바닥결[결코드(x, z)];

  // ── 요철 ─────────────────────────────────────────────────
  //   결마다 세기·주기가 다르지만 **소음은 하나**를 쓴다.
  //   그래야 결이 바뀌는 자리에서도 높이가 이어진다.
  const 요철 = (x, z) => {
    const r = 결(x, z);
    if (!r || r.요철 <= 0) return 0;
    return 결소음(x * r.결크기, z * r.결크기) * r.요철 * 요철배율;
  };

  // 걷는 높이(도면) + 보이는 요철
  const 높이 = (x, z) => 지형.지면(x, z).y + 요철(x, z);

  // ── 이 자리가 얼마나 가파른가 ────────────────────────────
  //   지형.js 가 산허리를 채운 뒤로 맵 곳곳에 50° 넘는 사면이 생겼다.
  //   그런데 결은 여전히 구역 하나로만 정해져서, **비탈이 통째로 잔디색**이 됐다
  //   (스샷: 화면 가득 초록 벽). 현실에서 그 각도의 흙은 붙어 있지 못한다 —
  //   풀은 완만한 데만 남고 급한 데는 흙과 돌이 드러난다.
  //   → 각도로 재서 색과 알갱이를 바꾼다. **높이는 안 건드린다**(판정 불변).
  const 기울기 = (x, z) => {
    const e = 0.9;
    const dx = (지형.지면(x + e, z).y - 지형.지면(x - e, z).y) / (2 * e);
    const dz = (지형.지면(x, z + e).y - 지형.지면(x, z - e).y) / (2 * e);
    return Math.hypot(dx, dz);
  };
  // 0(평지) ~ 1(못 붙는 급사면). tan 27° ≈ 0.5 부터 드러나기 시작한다
  const 급함 = (x, z) => THREE.MathUtils.smoothstep(기울기(x, z), 0.5, 1.15);
  // 급사면에 드러나는 것 — 마른 흙과 부스러진 돌(절벽 팔레트와 같은 계열)
  const 흙바탕 = new THREE.Color("#8A7C63");
  const 흙그늘 = new THREE.Color("#4C4437");

  // 요철이 파일 수 있는 최대 깊이 — 아래 덩어리를 얼마나 낮출지 정할 때 쓴다
  const 최대요철 =
    Math.max(...Object.values(바닥결).map((r) => r.요철)) * 요철배율;

  // ── 색 ───────────────────────────────────────────────────
  //   굴곡 그늘 + 넓은 무늬 두 재질 + 잔얼룩. (바닥.js 에서 쓰던 규칙을
  //   자리 기준으로 옮긴 것이다 — 이제 판이 아니라 '자리'가 색을 안다)
  const 임시 = new THREE.Color();
  const 밑색 = new THREE.Color();
  // 물가 — 물에 잠겼다 드러나는 젖은 띠. 경계를 소음으로 흔들어야
  //   뭍과 물이 자로 그은 직선으로 갈리지 않는다.
  const 젖음색 = new THREE.Color("#4E5348");
  const 물가선 = (x) => 강.Z시작 - 2.2 + 경계소음(x * 0.11, 3.3) * 1.9;
  const 색 = (x, z, 접지그늘 = 0) => {
    const r = 결(x, z);
    const 밝음 = new THREE.Color(r.색);
    const 밝음2 = new THREE.Color(r.색2 ?? r.색);
    const 어둠 = new THREE.Color(r.그늘);
    const 무늬 = THREE.MathUtils.clamp(
      0.5 + 무늬소음(x * 0.06, z * 0.06) * 1.3,
      0,
      1,
    );
    밑색.copy(밝음2).lerp(밝음, 무늬);
    const 폭 = Math.max(1e-4, r.요철 * 요철배율);
    const 깊이 = THREE.MathUtils.clamp(요철(x, z) / 폭, -1, 1);
    임시.copy(어둠).lerp(밑색, 0.7 + 깊이 * 0.26);
    임시.lerp(어둠, 접지그늘 * 0.3);
    // 가파를수록 풀이 없어지고 흙·돌이 드러난다
    const 급 = 급함(x, z);
    if (급 > 0) 임시.lerp(흙바탕.clone().lerp(흙그늘, 접지그늘 * 0.4), 급 * 0.85);
    // 물가로 갈수록 젖는다
    const 선 = 물가선(x);
    if (z > 선) 임시.lerp(젖음색, THREE.MathUtils.clamp((z - 선) / 2.6, 0, 1) * 0.7);
    const e1 = 얼룩소음(x * 0.24, z * 0.24) * r.얼룩;
    const e2 = 얼룩소음(x * 0.37 + 53, z * 0.37 + 91) * r.얼룩;
    임시.setRGB(
      THREE.MathUtils.clamp(임시.r + e1, 0, 1),
      THREE.MathUtils.clamp(임시.g + e1 * 0.5 + e2 * 0.5, 0, 1),
      THREE.MathUtils.clamp(임시.b + e2, 0, 1),
    );
    return 임시;
  };

  // ── 법선 ─────────────────────────────────────────────────
  //   요철이 얕아 실제 기울기는 거의 0 이다. 빛이 굴곡을 읽게 **과장**한다.
  //   (기하는 얕게 두므로 걷는 데는 영향이 없다 — 텍스처 없는 범프)
  const 법선 = (x, z, 과장 = 5) => {
    const e = 0.3;
    const dx = (요철(x + e, z) - 요철(x - e, z)) * 과장;
    const dz = (요철(x, z + e) - 요철(x, z - e)) * 과장;
    const L = Math.hypot(dx, 2 * e, dz) || 1;
    return [-dx / L, (2 * e) / L, -dz / L];
  };

  return {
    결코드, 결, 요철, 높이, 색, 법선, 최대요철, 기울기, 급함,
    소음: { 결소음, 얼룩소음, 무늬소음, 경계소음 },
  };
}
