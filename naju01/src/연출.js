// ═══════════════════════════════════════════════════════════════
//  연출.js — 「씬이 끝나면 길목이 열린다」를 보여 주는 장치
// ═══════════════════════════════════════════════════════════════
// [무엇을 푸는가]
//   §4 의 차단물은 **그 씬 동안** 시야를 가리라는 규칙이지 영원히 막으라는
//   게 아니다. 그런데 지금은 한 번 세우면 끝까지 서 있어서, T3 들머리처럼
//   길 바로 옆에 18 m 벽이 붙은 자리가 「길이 막혔다」로 읽힌다.
//   씬이 끝날 때 그 벽을 **보여 주면서** 치우면 규칙도 지키고 길도 열린다.
//
// [왜 판정과 그림을 한 함수가 쥐고 있나]
//   둘이 따로 놀면 반드시 어긋난다 — 보이는데 못 지나가는 투명 벽이 되거나,
//   사라졌는데 여전히 막혀서 사용자가 벽에 부딪친다. 그래서 여기서
//   **끝나는 순간 한 번에** 연다. 진행률은 그림에만 쓰고, 판정은
//   `지형.치운것` 에 코드가 들어가는 그 시점에 딱 한 번 바뀐다.
//
// [단위]
//   시간은 초. 카메라 각도는 라디안. 자리는 도면 좌표(m).

import * as THREE from "three";

export const 기본길이 = { 돌아보기: 0.9, 무너지기: 1.4, 여운: 0.6 };

// 부드럽게 — 시작과 끝에서 속도가 0 이라야 「연출」로 보인다.
//   선형으로 움직이면 기계가 미는 것처럼 뚝 시작해서 뚝 멈춘다.
const 완만 = (t) => t * t * (3 - 2 * t);

// 각도 차를 -π~π 로 접는다. 안 접으면 카메라가 먼 쪽으로 한 바퀴 돌아간다.
const 각차 = (a, b) => {
  let d = (b - a) % (Math.PI * 2);
  if (d > Math.PI) d -= Math.PI * 2;
  if (d < -Math.PI) d += Math.PI * 2;
  return d;
};

// ── 한 편의 연출 ────────────────────────────────────────────
//   차단물   { 코드, 이름, 중심:[x,z], 머리 } — 어디를 무너뜨리나
//   볼곳     [x, z] — 카메라가 돌아볼 자리(열리는 길목). 없으면 차단물 중심.
//   말       다 무너진 뒤 알릴 한 줄. ※ 도면에서는 `치움.말` 안에 있으므로
//            부르는 쪽이 꺼내서 넘겨야 한다(예전에 여기서 `차단물.말` 을
//            찾다가 늘 기본 문구만 나왔다).
//   지면높이 (x,z) => y — 볼곳의 높이를 알아야 시선이 하늘로 뜨지 않는다
//   길이     { 돌아보기, 무너지기, 여운 } 초
//
//   `틱(dt, 카메라)` 을 매 프레임 불러 주면 되고, 끝나면 `끝났나 === true`.
//   `진행` 은 0~1 로 무너지는 정도다 — 그리는 쪽이 이걸 보고 가라앉힌다.
export function 연출만들기({
  차단물,
  볼곳,
  말, // 다 무너진 뒤 알릴 한 줄(도면 §4 차단물의 `치움.말`)
  지면높이,
  길이 = 기본길이,
  치우기, // () => void — 판정을 여는 콜백. 무너지기가 끝나는 순간 한 번만 부른다.
  알림, // (글) => void
}) {
  const [vx, vz] = 볼곳 ?? 차단물.중심;
  const 볼y = (지면높이?.(vx, vz) ?? 0) + 1.2;

  let 단계 = "돌아보기";
  let t = 0;
  let 시작각 = null; // 첫 틱에 카메라에서 읽는다
  let 목표각 = null;
  let 열었나 = false;

  const 상태 = {
    코드: 차단물.코드,
    진행: 0, // 0 = 멀쩡 · 1 = 다 무너짐
    끝났나: false,
    단계: () => 단계,
    틱(dt, 카메라) {
      if (상태.끝났나) return;
      t += dt;

      if (단계 === "돌아보기") {
        if (시작각 === null) {
          카메라.rotation.order = "YXZ";
          시작각 = { y: 카메라.rotation.y, x: 카메라.rotation.x };
          // 카메라 → 볼곳 방위. three 의 +Z 가 화면 뒤라 atan2 부호가 이렇게 된다.
          const dx = vx - 카메라.position.x * 0.3;
          const dz = vz - 카메라.position.z * 0.3;
          const 수평 = Math.hypot(dx, dz);
          목표각 = {
            y: Math.atan2(-dx, -dz),
            x: Math.atan2(볼y - 카메라.position.y * 0.3, Math.max(0.5, 수평)),
          };
        }
        const k = 완만(Math.min(1, t / 길이.돌아보기));
        카메라.rotation.order = "YXZ";
        카메라.rotation.y = 시작각.y + 각차(시작각.y, 목표각.y) * k;
        카메라.rotation.x = THREE.MathUtils.lerp(시작각.x, 목표각.x, k);
        카메라.rotation.z = 0;
        if (t >= 길이.돌아보기) {
          t = 0;
          단계 = "무너지기";
        }
        return;
      }

      if (단계 === "무너지기") {
        상태.진행 = 완만(Math.min(1, t / 길이.무너지기));
        if (t >= 길이.무너지기) {
          상태.진행 = 1;
          // ★ 판정은 **여기서 딱 한 번** 연다. 그림이 다 가라앉은 뒤라야
          //   「사라졌는데 아직 막힌다」가 안 생긴다.
          if (!열었나) {
            열었나 = true;
            치우기?.();
            알림?.(말 ?? `${차단물.이름 ?? 차단물.코드} 가 사라져 길이 열렸다`);
          }
          t = 0;
          단계 = "여운";
        }
        return;
      }

      // 여운 — 열린 길목을 잠깐 보여 준다. 바로 조작을 돌려주면 무엇이
      //   달라졌는지 읽을 새가 없다.
      if (t >= 길이.여운) {
        단계 = "끝";
        상태.끝났나 = true;
      }
    },
  };
  return 상태;
}

// ── 무너지는 모습 ───────────────────────────────────────────
//   진행 0~1 을 받아 그 덩어리에 줄 변환을 돌려준다.
//   **가라앉히고 · 낮추고 · 살짝 기울인다.** 그냥 투명하게 지우면
//   「없어졌다」가 아니라 「안 그려진다」로 보인다.
export function 무너짐변환(진행, 머리m = 4) {
  const p = THREE.MathUtils.clamp(진행, 0, 1);
  return {
    // 제 키만큼 땅 밑으로 내려간다(유닛 = m / 0.3)
    내림: -(머리m / 0.3) * p * 1.05,
    // 내려가면서 납작해진다 — 무너져 주저앉는 꼴
    눌림: 1 - 0.45 * p,
    // 마지막에만 빠르게 사라진다. 처음부터 흐려지면 유령처럼 보인다.
    불투명: p < 0.75 ? 1 : 1 - (p - 0.75) / 0.25,
    기울기: p * 0.10,
  };
}
