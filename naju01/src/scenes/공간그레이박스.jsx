        let z;
        if (p < w) { x = X[0] + p; z = Z[0]; }
        else if ((p -= w) < d) { x = X[1]; z = Z[0] + p; }
        else if ((p -= d) < w) { x = X[1] - p; z = Z[1]; }
        else { x = X[0]; z = Z[1] - (p - w); }
        // 모서리 바깥으로 조금 흩는다
