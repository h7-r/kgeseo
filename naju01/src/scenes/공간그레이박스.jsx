// 도면 좌표(미터) → three.js 좌표(유닛)
const V3 = (X, Z, EL) => new THREE.Vector3(X * 미터, EL * 미터, Z * 미터);

// ── 경사면 한 조각 ─────────────────────────────────────────
//   a, b = [X, Z, EL] (미터). 두 점을 잇는 판을 놓는다.
//   윗면이 정확히 EL 에 오도록 두께의 절반만큼 내려 앉힌다.
function 경사조각({ a, b, 폭, 두께 = 0.35, 색, 선긋기 }) {
  const A = V3(a[0], a[1], a[2]);
  const B = V3(b[0], b[1], b[2]);
  const 방향 = B.clone().sub(A);
  const 길이 = 방향.length();
  if (길이 < 1e-6) return null;
  const q = new THREE.Quaternion().setFromUnitVectors(
    new THREE.Vector3(0, 0, 1),
    방향.clone().normalize(),
  );
  const 중심 = A.clone().add(B).multiplyScalar(0.5);
  중심.y -= (두께 / 2) * 미터;
  return (
    <mesh position={중심} quaternion={q} receiveShadow castShadow>
      <boxGeometry args={[폭 * 미터, 두께 * 미터, 길이]} />
      <meshToonMaterial color={색} gradientMap={TOON_GRADIENT} />
      {선긋기}
    </mesh>
  );
}

// 바닥 재질 — 색은 지오메트리의 **꼭짓점 색**에 이미 구워 넣었으므로
//   재질 색은 흰색(=밝기만)으로 두고 곱하게 한다.
//   툰: 본편 화풍과 같은 계단 음영 · 부드럽게: 램버트(값싸고 그라데이션이 산다)
//   `양면` — 비탈 치마처럼 안팎이 다 보일 수 있는 면에 쓴다.
//     한쪽만 그리면 뒷면이 통째로 까맣게 뚫려 보인다. DoubleSide 로 두면
//     three 가 뒷면 프래그먼트의 노멀을 뒤집어 줘서 양쪽 다 제대로 받는다.
function 바닥재질({ 방식, 밝기, 양면 = false }) {
  const 색 = 색밝기("#FFFFFF", 밝기);
  const 면 = 양면 ? THREE.DoubleSide : THREE.FrontSide;
  return 방식 === "툰" ? (
    <meshToonMaterial
      vertexColors
      color={색}
      side={면}
      gradientMap={TOON_GRADIENT}
    />
  ) : (
    <meshLambertMaterial vertexColors color={색} side={면} />
  );
}

