        //   골에 선 것(B2·수목대)은 발이 0 인데 머리가 18 m 라, 도면의
        //   `높이: 4.0` 만큼만 내리면 14 m 가 그대로 남는다.
        실제키: (골 ? 능선마루((b.X[0] + b.X[1]) / 2) + b.높이 : 머리) - 발,
        중심: [(b.X[0] + b.X[1]) / 2, (b.Z[0] + b.Z[1]) / 2],
        // 수목대는 '능선 바위 + 그 위의 나무', 나머지는 통짜 바위 덩이
        바위: 바위(b.X, b.Z, 발, 머리),
