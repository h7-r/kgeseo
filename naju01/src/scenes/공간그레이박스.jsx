    //   평평한 +14 벽으로 두면 Z4 에 선 사람에게는 6 m 짜리 담이라,
    //   §4 가 「V3 의 주 차단 장치」라고 적은 수목대가 그 담 **위**로 올라가 버려
    //   정작 눈높이에서는 아무 구실을 못 한다.
    //   ※ 도면에 이 골의 고도가 없어서 내린 해석이다 — 팀 확인이 필요하다.
