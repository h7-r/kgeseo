//  씬4.js — Scene 04 「지워진 기억」이 요구하는 것들
// ═══════════════════════════════════════════════════════════════
// [무엇을 만드는가]
//   `씬1~3.js` 와 같은 원칙 — **유형(type) 수준**까지만 답한다.
//   `instance_id`·퍼즐 정답·상호작용은 ④ §5 대로 여기서 확정하지 않는다.
//
// [근거 — 무엇을 보고 놓았나]
//   `공간도면.js` 안에 이미 적혀 있는 것만 썼다.
//     · 씬이름 4  "지워진 기억"  (퍼즐 P03)
//     · 구역 Z1  씬 "S1 · S4" · 서사 "아랑사 = 택촌 어부 F-01 · 강 건너 관계 F-02"
//     · 구역 Z2  씬 "S1 · S3 · S4 · S5" · 서사 "아랑사 추락 F-07 · …"
//     · 조사점 씬4  **(18, 42.5)** · **(54, 42.5)**   ← 단 둘뿐이다
//   그리고 `왜곡.js` 가 문서에서 옮겨 온 것:
//     · ④ Scene 02 §3 「같은 장면이 조금씩 다르게 보이도록 한다.
//       **어느 재현이 진짜인지 판단할 수 없는 상태**를 유지한다」
//     · ④ Scene 02 §4 「흐려지거나 **겹쳐 보이는** 원경」
//
// [★ 조사점이 둘뿐이고, 둘의 Z 가 같다]
//   다른 씬은 조사점이 셋인데 이 씬만 **둘**이다. 게다가
//     (18, 42.5)  Z1 나루터 물가
//     (54, 42.5)  Z2 자갈밭 물가 — 36 m 떨어진 **같은 물가 선**
//   이건 「여기도 보고 저기도 보라」가 아니라 **「둘을 견주라」**다.
//   도면이 조사점 수와 좌표만으로 이미 대구(對句)를 만들어 놓았다.
//
// [★ 그래서 이 씬의 장치는 「같은 흔적이 두 군데 있다」이다]
//   두 자리에 **똑같은 것**을 놓는다 — 배를 끌어올린 자국, 그 배를 매던
//   말뚝, 물가로 걸어간 발자국. 같은 표본·같은 구성·같은 크기·같은 간격이다.
//   기억이 **한 벌 더 찍혀 있다** — 그게 「지워진 기억」이다.
//   똑같다는 것 자체가 단서다. 사람이 두 번 한 일은 절대 똑같지 않다.
//
//   ※ 처음에는 여기 「(54, 42.5) 는 절벽 발치라 배를 끌어올릴 일이 없으니
//     그쪽이 가짜다」라고 적었다. **그건 사실이 아니었다.** 실측해 보니
//     팀이 편집기로 놓은 `소품.나룻배` 가 ㉡ 에서 **4.4 m** 에 있고,
//     징검돌도 7~10 m 안에 있다. 그 물가는 이미 배가 드나드는 자리다.
//     → 「한쪽이 있을 수 없는 자리」라는 근거는 **버린다.** 장치는 자리의
//       그럴듯함이 아니라 **똑같음**에 기댄다.
//   ※ 어느 쪽이 진짜인지 이 모듈은 **정하지 않는다.** 그건 퍼즐이고,
//     ④ §5 가 여기서 정하지 말라고 한 바로 그것이다. 공간은 「둘이
//     똑같다」는 사실만 제시한다.
//
// [★ 흔적이 왜 「자국」이어야 하나 — 물건을 놓으면 안 된다]
//   여기에 배를 한 척 더 놓으면 그냥 배가 두 척인 맵이 된다.
//   지워진 기억은 **물건이 없고 자국만 남은** 자리다. 그래서 이 모듈이
//   놓는 것은 전부 「무엇이 있었던 흔적」이지 그 무엇이 아니다.
//     · 배자국 — 배는 없고 끌린 자국만
//     · 말뚝  — 매어 둔 것은 없고 **끊어진 밧줄**만
//     · 발자국 — 걸어간 사람은 없고 발자국만, 그나마 물가에서 **끊긴다**
//
// [★ 땅을 파지 않는다 — 두둑으로 만든다]
//   자국은 원래 **패인 것**인데, 인스턴스로는 지형을 깎을 수 없다.
//   실제로 배를 끌면 흙·자갈이 **양옆으로 밀려 두둑**이 지고 가운데가
//   반질해진다. 그 두둑을 세우면 파지 않고도 패인 것으로 읽힌다.
//   (같은 이유로 발자국도 테두리만 도드라진 얕은 테로 만든다.)
//
// [색을 진짜로 굽는 이유]  `씬2.js` 머리말과 같다.
// [단위]  도면 좌표 m. 표본은 **높이 1** 짜리다.

import * as THREE from "three";
import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { makeRandom } from "../../src/공용.jsx";
import { 색입히기 } from "./바닥.js";
import { 밑동원점으로 } from "./배치.js";

export const 씬4결 = {
  젖은흙: "#5E5445", // 물가의 젖은 바닥 — 마른 데보다 어둡다
  밀린흙: "#8D8168", // 끌리며 양옆으로 밀려난 두둑 — 속이 드러나 밝다
  반질: "#6E6553", // 배 밑이 쓸고 간 가운데 — 반반하다
  말뚝: "#6B5942",
  말뚝어둠: "#3E3327",
  밧줄: "#A89A74",
  끊긴줄: "#C7BC9A", // 끊어진 자리의 풀린 올 — 밝다
};

// ── 조각 만들기 (소품.js·씬2·3 과 같은 규약) ────────────────
const 풀기 = (g) => {
  const n = g.toNonIndexed();
  n.deleteAttribute("uv");
  n.deleteAttribute("uv1");
  g.dispose();
  return n;
};
const 상자 = (w, h, d) => 풀기(new THREE.BoxGeometry(w, h, d));
const 기둥 = (r1, r2, h, 각 = 6) =>
  풀기(new THREE.CylinderGeometry(r1, r2, h, 각, 1));
const 고리 = (r, 굵, 각 = 10) => {
  const g = new THREE.TorusGeometry(r, 굵, 4, 각);
  g.deleteAttribute("uv");
  return g.toNonIndexed();
};
const 묶기 = (조각) => {
  const g = mergeGeometries(조각, false);
  조각.forEach((v) => v.dispose());
  return 밑동원점으로(g);
};
const 칠 = (g, 색) => 색입히기(g, new THREE.Color(색));

// ── ① 배자국 ────────────────────────────────────────────────
//   배를 물에서 뭍으로 끌어올린 자국. **+Z 가 물 쪽**이다 —
//   자국은 물에서 시작해 뭍으로 들어오므로, 뭍 쪽(−Z)에서 끝난다.
//   [모양]  가운데 반질한 띠 하나 + 양옆에 밀려난 두둑 둘.
//           두둑은 **앞으로 갈수록 두꺼워진다** — 밀린 흙이 쌓이니까.
export function 배자국표본들(수 = 3, 시드 = 7401) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    // ★ **길이 대 높이 비가 전부다.** 처음엔 비가 12.8 : 1 이라 렌더에서
    //   높이 0.30 m 짜리 **연석**으로 보였다. 배를 끈 자국의 두둑은 실제로
    //   5~10 cm 다 — 비가 50 : 1 을 넘어야 「자국」으로 읽힌다.
    //   `밑동원점으로` 가 **높이**로 나누므로, 세로 조각들을 통째로 낮춘다.
    const 길 = 7.0 + 난수() * 1.6; // 높이 1 기준 비율 → 비 약 58 : 1
    const 폭 = 0.62 + 난수() * 0.12;
    const 마디 = 11;
    for (let k = 0; k < 마디; k++) {
      const t = (k + 0.5) / 마디; // 0 = 물 쪽, 1 = 뭍 쪽
      const z = (0.5 - t) * 길;
      // 가운데 — 배 밑이 쓸고 간 자리. 아주 얕게 도드라진다.
      const 가운데 = 상자(폭, 0.03, 길 / 마디 - 0.02);
      가운데.rotateY((난수() - 0.5) * 0.05);
      가운데.translate((난수() - 0.5) * 0.06, 0.015, z);
      조각.push(칠(가운데, 씬4결.반질));
      // 두둑 둘 — 앞(뭍 쪽)으로 갈수록 두껍다
      for (const s of [-1, 1]) {
        const 두께 = 0.05 + t * 0.06 + 난수() * 0.02;
        const 두둑 = 상자(0.22 + t * 0.12, 두께, 길 / 마디 - 0.02);
        두둑.rotateZ(s * 0.25);
        두둑.rotateY((난수() - 0.5) * 0.08);
        두둑.translate(s * (폭 / 2 + 0.12), 두께 * 0.45, z);
        조각.push(칠(두둑, 난수() < 0.35 ? 씬4결.젖은흙 : 씬4결.밀린흙));
      }
    }
    // 뭍 쪽 끝 — 배 고물이 멈춘 자리. 흙이 한 번 더 쌓인다.
    const 끝 = 상자(폭 + 0.5, 0.09, 0.32);
    끝.translate(0, 0.045, -0.5 * 길 - 0.1);
    조각.push(칠(끝, 씬4결.밀린흙));
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ② 말뚝 ──────────────────────────────────────────────────
//   배를 매어 두던 말뚝. **매인 것은 없고 끊어진 밧줄만** 남는다.
//   [왜 밧줄을 끊어 두나]  풀린 밧줄이면 「배가 떠났다」다. 끊어진 밧줄은
//     「뭔가 잘못됐다」다. 끊긴 자리의 **풀린 흰 올**이 그 차이를 낸다.
export function 말뚝표본들(수 = 3, 시드 = 7402) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 몸 = 기둥(0.085, 0.11, 1, 7);
    몸.translate(0, 0.5, 0);
    몸.rotateZ((난수() - 0.5) * 0.22); // 물에 밀려 기울었다
    조각.push(칠(몸, 씬4결.말뚝));
    // 머리 — 쳐서 박은 자리라 뭉개져 있다
    const 머리 = 기둥(0.13, 0.1, 0.11, 7);
    머리.translate(0, 0.99, 0);
    조각.push(칠(머리, 씬4결.말뚝어둠));
    // 감긴 밧줄 — 세 바퀴
    for (let k = 0; k < 3; k++) {
      const 감 = 고리(0.125, 0.028);
      감.rotateX(Math.PI / 2 + (난수() - 0.5) * 0.12);
      감.translate(0, 0.62 + k * 0.075, 0);
      조각.push(칠(감, 씬4결.밧줄));
    }
    // 늘어진 끝 — 땅으로 흘러내린다
    let x = 0.12;
    let z = 0.02;
    let y = 0.6;
    for (let k = 0; k < 5; k++) {
      const 길 = 0.24 + 난수() * 0.1;
      const 조 = 기둥(0.026, 0.024, 길, 4);
      const 기울 = 0.5 + k * 0.22;
      조.rotateX(Math.PI / 2);
      조.rotateZ(-기울);
      조.rotateY(0.6 + (난수() - 0.5) * 0.5);
      조.translate(x, y, z);
      조각.push(칠(조, 씬4결.밧줄));
      x += Math.cos(기울) * 길 * 0.8;
      z += 0.05;
      y -= Math.sin(기울) * 길 * 0.8;
      if (y < 0.05) y = 0.05;
    }
    // ★ 끊긴 자리 — 풀린 올. 이 한 조각이 「풀렸다」와 「끊겼다」를 가른다.
    for (let k = 0; k < 4; k++) {
      const 올 = 기둥(0.009, 0.005, 0.13 + 난수() * 0.07, 3);
      올.rotateZ(Math.PI / 2 - (난수() - 0.5) * 0.9);
      올.rotateY(난수() * 6.3);
      올.translate(x + 0.06, y + 0.02, z);
      조각.push(칠(올, 씬4결.끊긴줄));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ③ 발자국 한 줄 ──────────────────────────────────────────
//   물가로 걸어간 자국. **한 인스턴스가 한 줄 전체**다 —
//   발자국을 하나씩 인스턴스로 두면 편집기에서 열 몇 개를 따로 옮기게 되어,
//   「한 사람이 걸어간 줄」이라는 사실이 손에서 부서진다.
//   [모양]  땅을 못 파므로 **테두리만 도드라진 얕은 테**로 만든다.
//           젖은 바닥에 찍힌 발자국은 실제로 테가 솟는다.
//   [★ 물가에서 끊긴다]  줄이 +Z(물) 쪽으로 가다가 **끝까지 안 간다.**
//     돌아 나온 자국이 없는 것이 이 씬의 요점이다.
export function 발자국표본들(수 = 3, 시드 = 7403) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 걸음 = 7;
    const 보폭 = 0.62;
    const 벌 = 0.13; // 좌우 발 사이
    for (let k = 0; k < 걸음; k++) {
      const s = k % 2 ? 1 : -1;
      const z = (k - (걸음 - 1) / 2) * 보폭;
      const x = s * 벌 + (난수() - 0.5) * 0.06;
      const 각 = (난수() - 0.5) * 0.3;
      // 테 — 앞(발가락)이 좁고 뒤(뒤꿈치)가 둥근 타원을 여섯 도막으로
      for (let j = 0; j < 6; j++) {
        const u = (j / 6) * Math.PI * 2;
        // 발은 길이 0.25 · 폭 0.10 m 쯤이다. 처음엔 자국 하나가 0.36 m 로
        //   구워져 **어른 발보다 컸다** — 반지름을 줄인다.
        const rx = 0.075;
        const rz = 0.155;
        const 도 = 상자(0.07, 0.045 + 난수() * 0.02, 0.12);
        도.rotateY(u + 각);
        도.translate(
          x + Math.sin(u) * rx * Math.cos(각) + Math.cos(u) * rz * Math.sin(각),
          0.022,
          z + Math.cos(u) * rz * Math.cos(각) - Math.sin(u) * rx * Math.sin(각),
        );
        조각.push(칠(도, 씬4결.밀린흙));
      }
      // 바닥 — 테 안쪽. 둘레보다 어둡다(젖어 있다).
      const 안 = 상자(0.12, 0.02, 0.24);
      안.rotateY(각);
      안.translate(x, 0.01, z);
      조각.push(칠(안, 씬4결.젖은흙));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

