// ── 자리 ────────────────────────────────────────────────────
export function 씬4자리들({ 지면높이 }) {
  const y = (x, z) => (지면높이 ? 지면높이(x, z) : 0);
  const 두기 = (목록) => 목록.map((v) => ({ ...v, y: y(v.x, v.z) + (v.띄움 ?? 0) }));

  // ══════════════════════════════════════════════════════════
  //  ★ 두 자리는 **일부러 같은 값**이다
  // ══════════════════════════════════════════════════════════
  //  ㉠ (18, 42.5)  Z1 나루터 물가
  //  ㉡ (54, 42.5)  Z2 자갈밭 물가 — 36 m 떨어진 같은 물가 선
  //  아래 세 목록에서 ㉠ 과 ㉡ 의 `키`·`모양`·서로 간 거리가 **모두 같다.**
  //  숫자를 다르게 흔들고 싶은 손이 계속 가지만, 그러면 장치가 죽는다 —
  //  플레이어가 둘을 견줘 「똑같다」를 알아차리는 것이 이 씬의 전부다.
  //  ※ 회전만 다르다. 두 물가의 선 방향이 달라서, 회전까지 같게 두면
  //    한쪽 자국이 물가를 비스듬히 가로질러 도리어 안 닮아 보인다.

  const 한벌 = (cx, cz, 회전, 모양) => ({
    //   ★ `키` 는 **높이**만 정한다(표본이 높이 1 로 구워져 있다). 자국은
    //     납작하면서도 넓고 길어야 하므로 가로·세로를 `폭비`·`깊이비` 로
    //     따로 늘린다 — 키 하나로 맞추려 하면 두둑이 다시 솟는다.
    //     → 높이 0.085 m · 가로 1.3 m(나룻배 너비) · 길이 4.8 m.
    //   ※ 이건 **받아온 모형이 아니라 여기서 깎은 자국**이라 비를 늘려도 된다.
    //     Meshy 모형은 비를 건드리지 않는다(프로젝트 규칙).
    배자국: { x: cx, z: cz, 키: 0.085, 폭비: 2.4, 깊이비: 1.5, 모양, 회전 },
    // 말뚝 — 자국의 뭍 쪽 끝에서 1.2 m. 배를 매던 자리다.
    말뚝: {
      x: cx - Math.sin(회전) * 1.2,
      z: cz - Math.cos(회전) * 1.2,
      키: 0.95,
      모양,
      회전: 회전 + 0.4,
    },
    // 발자국 — 자국 옆 1.6 m 를 나란히 간다. 겹치면 둘 다 안 읽힌다.
    발자국: {
      x: cx + Math.cos(회전) * 1.6,
      z: cz - Math.sin(회전) * 1.6,
      키: 0.05,
      모양,
      회전,
    },
  });

  // 두 물가의 선 방향(실측이 아니라 도면의 물가 선 기울기에서 잡은 값).
  //   Z1 쪽 물가는 거의 X 축과 나란하고, Z2 쪽은 절벽을 따라 조금 돌아간다.
  //   ※ 이름에 ㉠㉡ 을 못 쓴다 — JS 식별자로 허용되지 않는 글자다(빌드가 막는다).
  const 나루벌 = 한벌(18, 42.5, 0.06, 0); // ㉠
  const 자갈벌 = 한벌(54, 42.5, -0.42, 0); // ㉡

  return {
    배자국: 두기([나루벌.배자국, 자갈벌.배자국]),
    말뚝: 두기([나루벌.말뚝, 자갈벌.말뚝]),
    발자국: 두기([나루벌.발자국, 자갈벌.발자국]),
  };
}
