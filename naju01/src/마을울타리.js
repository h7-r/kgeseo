// ═══════════════════════════════════════════════════════════════
//  마을울타리.js — 초가집 마당을 두르는 싸리울
// ═══════════════════════════════════════════════════════════════
// [왜 만드나]
//   초가집만 흩어 놓으면 **집이 들판에 떨어져 있는 것**으로 보인다.
//   마을은 집이 아니라 **마당과 울**이 만든다 — 어디까지가 누구네 집인지가
//   보여야 사람이 사는 데로 읽힌다(팀 지시).
//
// [왜 `울타리.js` 를 안 쓰나]
//   그건 **길을 따라가는** 울타리다(낭떠러지 쪽만 고르고, 가파르면 끊고,
//   중심선에서 바깥으로 민다). 마당 울은 **집을 두르는** 것이라 규칙이 다르다.
//   다만 **기둥·가로대 표본과 치수는 그대로 쓴다** — 같은 마을의 같은 목수가
//   세운 것처럼 보여야 한다.
//
// [★ 마당 크기는 이웃이 정한다]
//   실측: 진부촌은 집 사이가 최소 5.0 · 중앙 6.8 m 이고 집 폭이 4.8 m 쯤이다.
//   집 폭만 보고 마당을 잡으면 **옆집 마당과 겹친다.**
//   그래서 반쪽 크기를 `min(집 폭 × 0.85, 이웃까지 × 0.45)` 로 잡는다 —
//   이웃도 제 몫의 0.45 를 가져가므로 둘을 합쳐도 0.9 라 절대 안 닿는다.
//
// [★ 한 면은 비운다]
//   사방을 두르면 들어갈 데가 없어 **상자**로 보인다. 사립문 쪽 한 면을
//   통째로 비운다. 어느 쪽을 비울지는 **마을 한복판을 향한 쪽**이다 —
//   그래야 집들이 가운데 마당을 바라보는 꼴이 된다.

import * as THREE from "three";
import { 치수, 나무결 } from "./울타리.js";
import { makeRandom } from "../../src/공용.jsx";

// ── 마당 한 채 ──────────────────────────────────────────────
//   `가운데` 를 두르는 네모에서 한 면을 뺀 ㄷ 자 선을 돌려준다.
//   `열린쪽` 은 비울 방향(라디안, +Z 기준).
function 마당선(가운데, 반, 열린쪽, 회전) {
  // 네 모서리 — 집의 방위를 따라 돈다(집이 비스듬하면 마당도 비스듬하다)
  const 귀 = [
    [-반.x, -반.z],
    [반.x, -반.z],
    [반.x, 반.z],
    [-반.x, 반.z],
  ].map(([a, c]) => ({
    x: 가운데.x + a * Math.cos(회전) + c * Math.sin(회전),
    z: 가운데.z - a * Math.sin(회전) + c * Math.cos(회전),
  }));
  // 네 변 중 **열린쪽에 가장 가까운 변**을 뺀다
  const 변 = [0, 1, 2, 3].map((i) => {
    const a = 귀[i];
    const b = 귀[(i + 1) % 4];
    const mx = (a.x + 가운데.x * 0 + b.x) / 2 - 가운데.x;
    const mz = (a.z + b.z) / 2 - 가운데.z;
    return { a, b, 각: Math.atan2(mx, mz) };
  });
  const 차 = (u, v) => Math.abs(((u - v + Math.PI) % (Math.PI * 2)) - Math.PI);
  let 뺄 = 0;
  for (let i = 1; i < 4; i++)
    if (차(변[i].각, 열린쪽) < 차(변[뺄].각, 열린쪽)) 뺄 = i;
  // 남은 세 변을 이어 하나의 꺾인 선으로
  const 순 = [0, 1, 2, 3].filter((i) => i !== 뺄);
  // ㄷ 자가 이어지도록 뺀 변 다음부터 돌린다
  const 시작 = (뺄 + 1) % 4;
  const 줄 = [];
  for (let k = 0; k < 4; k++) {
    const i = (시작 + k) % 4;
    if (!순.includes(i)) continue;
    if (!줄.length) 줄.push(변[i].a);
    줄.push(변[i].b);
  }
  return 줄;
}

// ── 마을 전체 ───────────────────────────────────────────────
//   `집자리` 는 원경.js 가 내는 것과 같은 모양([{x, y, z, 키, 회전}, ...]).
export function 마을울타리자리들({
  집자리,
  지면높이 = null,
  집폭비 = 1.72, // 초가집 모형은 가로가 키의 1.72 배다(자연.js 에서 맞춰 굽는다)
  시드 = 7731,
} = {}) {
  const 기둥 = [];
  const 가로대 = [];
  if (!집자리?.length) return { 기둥, 가로대 };
  const 난수 = makeRandom(시드);
  // 색은 `울타리.js` 와 **같은 규칙**을 쓴다 — 같은 마을의 같은 나무다
  const 밝 = new THREE.Color(나무결.밝음);
  const 어 = new THREE.Color(나무결.어둠);
  const 색임시 = new THREE.Color();
  const 나무색 = () => 색임시.copy(어).lerp(밝, 0.35 + 난수() * 0.6).getHex();

  // 마을 한복판 — 비울 면을 정할 때 쓴다
  let cx = 0;
  let cz = 0;
  for (const h of 집자리) {
    cx += h.x;
    cz += h.z;
  }
  cx /= 집자리.length;
  cz /= 집자리.length;

  for (const 집 of 집자리) {
    // 이웃까지 거리 — 마당이 옆집을 밟지 않게 하는 값
    let 이웃 = Infinity;
    for (const 다른 of 집자리)
      if (다른 !== 집)
        이웃 = Math.min(이웃, Math.hypot(집.x - 다른.x, 집.z - 다른.z));
    // 집 가로·세로는 **자리가 들고 있는 `폭비`·`깊이비`** 로 잰다 —
    //   집마다 가로세로가 다르다(원경.js 가 `폭비 = w / 키` 로 적어 준다).
    const 키 = 집.키 ?? 3;
    const 집가로 = 키 * (집.폭비 || 집폭비);
    const 집세로 = 키 * (집.깊이비 || 집폭비 * 0.8);
    const 집폭 = Math.max(집가로, 집세로);
    const 반쪽 = Math.min(집폭 * 0.85, 이웃 * 0.45);
    // ★ **마당은 집보다 커야 한다.** 이게 안 지켜지면 울이 집 안을 지나간다
    //   (스크린샷에서 가로대가 지붕 밑을 뚫고 나왔다). 집 반 폭이 `집가로/2`
    //   이고 집이 비스듬히 앉으니 모서리는 그보다 더 나온다 — 0.68 배로
    //   **24 % 여유**를 두고, 그만큼도 못 두면 아예 안 두른다.
    //   (이웃이 5.0 m 까지 붙어 있는 진부촌에선 몇 채가 이 검사에 걸린다.
    //    빽빽한 데가 도리어 마을답게 보이므로 그대로 둔다.)
    if (반쪽 < 집가로 * 0.68 || 반쪽 < 집세로 * 0.68) continue;
    const 반 = {
      x: 반쪽,
      // 세로는 조금 눌러 마당을 정사각형이 아니게 한다 — 단, 집을 깔면 안 된다
      z: Math.max(반쪽 * (0.78 + 난수() * 0.3), 집세로 * 0.68),
    };
    // 마을 한복판을 향한 쪽을 비운다
    const 열린쪽 = Math.atan2(cx - 집.x, cz - 집.z);
    const 선 = 마당선(집, 반, 열린쪽, 집.회전 ?? 0);

    // 선을 따라 기둥을 세우고 사이에 가로대를 건다
    const 점 = [];
    for (let i = 0; i < 선.length - 1; i++) {
      const a = 선[i];
      const b = 선[i + 1];
      const 길 = Math.hypot(b.x - a.x, b.z - a.z);
      const 칸 = Math.max(1, Math.round(길 / 치수.기둥간격));
      for (let k = 0; k < 칸; k++) {
        const t = k / 칸;
        const x = a.x + (b.x - a.x) * t;
        const z = a.z + (b.z - a.z) * t;
        점.push({ x, z, y: 지면높이 ? 지면높이(x, z) : (집.y ?? 0) });
      }
      if (i === 선.length - 2)
        점.push({ x: b.x, z: b.z, y: 지면높이 ? 지면높이(b.x, b.z) : (집.y ?? 0) });
    }
    for (const q of 점)
      기둥.push({
        x: q.x,
        y: q.y - 치수.묻힘,
        z: q.z,
        키: 치수.기둥높이 * (0.9 + 난수() * 0.2),
        회전: (난수() - 0.5) * 0.6,
        기울기: (난수() - 0.5) * 0.09,
        기울기2: (난수() - 0.5) * 0.09,
        폭비: 치수.기둥굵기 / 치수.기둥높이,
        깊이비: 치수.기둥굵기 / 치수.기둥높이,
        색: 나무색(),
      });
    for (let i = 0; i < 점.length - 1; i++) {
      const a = 점[i];
      const b = 점[i + 1];
      const dx = b.x - a.x;
      const dz = b.z - a.z;
      const 평면 = Math.hypot(dx, dz);
      if (평면 < 0.05) continue;
      for (const 높이 of 치수.가로대) {
        const ay = a.y + 높이;
        const by = b.y + 높이;
        const 길이 = Math.hypot(평면, by - ay) * 1.04;
        가로대.push({
          x: (a.x + b.x) / 2,
          y: (ay + by) / 2,
          z: (a.z + b.z) / 2,
          키: 길이,
          // ※ 막대는 **국소 +Z** 로 누워 있다. 길이 축은 깊이비(Z) 이고,
          //   `높이비` 를 안 주면 기본 1 이라 키가 길이만큼 커진다
          //   (울타리.js 에서 실제로 그렇게 나서 널판이 섰다).
          회전: Math.atan2(dx, dz),
          기울기: -Math.atan2(by - ay, 평면),
          기울기2: 0,
          폭비: 치수.가로대폭 / 길이,
          높이비: 치수.가로대두께 / 길이,
          깊이비: 1,
          색: 나무색(),
        });
      }
    }
  }
  return { 기둥, 가로대 };
}
