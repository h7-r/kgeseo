// ── 비례 맞추기 ─────────────────────────────────────────────
// [왜 필요한가 — 실측으로 잡은 것]
//   규약을 맞춰 구워도 **비례까지 맞는 건 아니다.**
//     · 수풀 모형은 옆으로 퍼진 덩이(1.89 × 1.13 × 1.88)다. **키**로 1 을
//       맞추면 가로가 1.67 이 된다. 그런데 손으로 깎던 덤불은 가로 0.72 였다.
//       그대로 놓으니 `키 1.1` 짜리 덤불이 **폭 1.8 m** 가 되어, 언덕이
//       거대한 초록 조각들의 벽이 됐다(근접 스크린샷).
//     · 바위 모형은 납작하다(1.77 × 0.97 × 1.90). 가장 긴 쪽으로 맞추면
//       높이가 폭의 절반이라 **검은 판때기**로 보였다. 옛 돌표본은
//       0.64 × 0.79 × 0.68 로 오히려 세로가 길다.
//   그래서 구운 뒤에 **한 번 더 눌러/늘려** 옛 표본의 비례로 되돌린다.
//   숫자는 「옛 표본 폭 ÷ 모형 폭」이다 — 눈대중이 아니다.
const 비례 = (g, sx, sy, sz) => {
  g.scale(sx, sy, sz);
  g.computeBoundingBox();
  g.computeVertexNormals();
  return g;
};

// 한 벌 구워 두고 돌려쓴다.
//   씬과 팔레트 썸네일이 **각각** 부르므로, 안 그러면 두 번 굽는다.
const 곳간 = new Map();
const 한번 = (열쇠, 만들기) => {
  let v = 곳간.get(열쇠);
  if (!v) 곳간.set(열쇠, (v = 만들기()));
  return v;
};

// ── 나무 ────────────────────────────────────────────────────
//   줄기는 나무색, 잎은 초록. 색은 `수목결` 을 그대로 쓴다 — 손으로 깎던
//   나무와 **같은 팔레트**여야 원경(아직 옛 표본이다)과 안 겉돈다.
export function 나무모형들() {
  return 한번("나무", () => {
    const 줄기 = new THREE.Color(수목결.기둥);
    const 줄기어둠 = new THREE.Color(수목결.기둥어둠);
    const 잎 = new THREE.Color(수목결.잎);
    const 잎어둠 = new THREE.Color(수목결.잎어둠);
    const 잎밝음 = new THREE.Color(수목결.잎밝음);
    const 임시 = new THREE.Color();
    // 나무 — 키 1 로 맞추면 가로 0.64. 옛 나무는 0.52 였다 → 0.82 배
    return [나무1모형, 나무2모형, 나무3모형, 나무4모형, 나무5모형, 나무6모형, 나무7모형].map(
      (모형) =>
        비례(모형지오(모형, {
          칠하기: (면, 모, 색) => {
            const p = 면.attributes.position;
            const nor = 면.attributes.normal;
            const 나무부 = 가는것찾기(면);
            for (let i = 0; i < p.count; i++) {
              // 위를 보는 면은 해를 받고, 아래를 보는 면은 그늘이다.
              //   ※ `수목결.잎어둠` 주석 참고 — 너무 어두우면 잎덩이 **밑면**이
              //     새까매진다. 그래서 바닥을 잎어둠으로 잡고 위로 올린다.
              const 위봄 = THREE.MathUtils.clamp(nor.getY(i) * 0.5 + 0.5, 0, 1);
              if (나무부.has(i)) {
                const 결 = 0.5 + 0.5 * Math.sin(p.getY(i) * 260 + p.getX(i) * 41);
                임시.copy(줄기어둠).lerp(줄기, 0.25 + 0.68 * 위봄);
                임시.multiplyScalar(0.93 + 0.12 * 결);
              } else {
                임시.copy(잎어둠).lerp(잎, THREE.MathUtils.clamp(위봄 * 1.5, 0, 1));
                if (위봄 > 0.72) 임시.lerp(잎밝음, (위봄 - 0.72) / 0.28 * 0.55);
              }
              색[i * 3] = 임시.r;
              색[i * 3 + 1] = 임시.g;
              색[i * 3 + 2] = 임시.b;
            }
          },
        }), 0.82, 1, 0.82),
    );
  });
}

// ── 바위 ────────────────────────────────────────────────────
//   ★ **비율**만 굽는다. 진짜 색은 `돌담기` 가 자리마다 넘긴다(절벽돌·
//     통로돌·강가돌이 다 다른 빛이다). 여기서 색을 넣으면 두 번 곱해진다.
//   위를 보는 면이 밝고 아래가 어둡다 — 그게 돌의 부피를 만든다.
//   ※ 칠은 `돌칠` 하나로 묶었다 — 근경 바위와 자갈돌이 **같은 돌**이어야
//     한다. 면수만 다르지 색까지 달라지면 큰 것과 작은 것이 다른 돌로 보인다.
const 돌칠 = (면, 모, 색) => {
  const nor = 면.attributes.normal;
  const p = 면.attributes.position;
  for (let i = 0; i < nor.count; i++) {
    const 위봄 = THREE.MathUtils.clamp(nor.getY(i) * 0.5 + 0.5, 0, 1);
    // 잔 얼룩 — 없으면 돌이 매끈한 고무 덩이로 보인다
    const 얼 =
      Math.sin(p.getX(i) * 47 + p.getZ(i) * 31) * Math.sin(p.getY(i) * 53);
    const v = (0.66 + 0.52 * Math.pow(위봄, 0.8)) * (1 + 0.06 * 얼);
    색[i * 3] = v;
    색[i * 3 + 1] = v;
    색[i * 3 + 2] = v;
  }
};

export function 바위모형들() {
  return 한번("바위", () =>
    [바위1모형, 바위2모형, 바위3모형, 바위4모형, 바위5모형, 바위6모형, 바위7모형].map(
      (모형) =>
        // 바위 — 모형이 납작하다(높이가 폭의 절반). 옛 돌은 세로가 더 길었다.
        //   1.55 배 세워야 「판때기」가 아니라 「덩이」로 보인다.
        비례(모형지오(모형, { 칠하기: 돌칠 }), 1, 1.55, 1),
    ),
  );
}

