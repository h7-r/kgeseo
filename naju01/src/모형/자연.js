// ── 자갈 무리가 쓰는 표본 묶음 ──────────────────────────────
//   [왜 한 배열에 섞나]  「자갈」은 **한 무리**여야 한다. 무리를 쪼개면
//   `편집.json` 에 저장된 손 배치(25 개를 놓고 키를 7.8 m 까지 키워 뒀다)가
