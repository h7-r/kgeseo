//   ★ 앞 일곱이 근경 바위, 뒤 일곱이 자갈돌이다. 순서가 중요하다 —
//     손으로 놓은 것들은 `모양` 0~6 으로 저장돼 있어서, 앞쪽에 바위를 두면
