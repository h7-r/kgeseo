// ── 초가집 ──────────────────────────────────────────────────
// [★ 색이 넷이다 — 두 갈래로는 집이 안 된다]
//   처음엔 높이로 **지붕과 벽** 둘만 갈랐다. 그러면 기둥도 문틀도 창도
//   전부 흙벽 색이라, 멀리서 보면 **누런 덩어리**다. 집은 그렇게 안 생겼다.
//   지금은 넷으로 가른다 —
//     기단(돌)  아래 8 %          — 집이 땅에 얹힌 게 아니라 **놓인** 것으로
//     기둥·문틀 `가는것찾기` 가 잡는 것 — 나무. 이게 제일 크게 달라진다
//     지붕(초가) 위 45 % 위        — 누런 짚
//     흙벽      나머지
//   ※ `가는것찾기` 는 천막·나무에서 쓰던 그 수다. 기둥은 어느 높이에서
//     썰어도 가늘고, 벽은 넓게 퍼진다 — 집에서도 그대로 통한다.
//
// [면수를 왜 4,000 으로 잡았나 — 눈으로 재서 정했다]
//   1,596 : 지붕이 뭉개져 **덩어리**다. 기둥도 창도 없다
//   3,966 : 기둥·창·문·툇마루가 **다 읽힌다**  ← 여기가 경계
//   7,732 : 조금 더 깔끔할 뿐
//   23,892: 짚 한 올까지. 원경에 쓸 값은 아니다
//   ※ 집은 코어에서 중앙 25 m 다(실측). 가깝다.
//
// [폭을 맞춘다]  모형은 가로가 키의 2.4~3.2 배다. 손으로 깎던 원경집은
//   **1.72 배**였다. 그대로 놓으면 `키 4.2` 짜리 집이 폭 13.5 m 가 된다.
export function 초가집모형들() {
  return 한번("초가집", () => {
    const 짚 = new THREE.Color(원경결.초가);
    const 짚그늘 = new THREE.Color(원경결.초가).multiplyScalar(0.72);
    const 벽 = new THREE.Color(원경결.흙벽);
    const 벽그늘 = new THREE.Color(원경결.흙벽).multiplyScalar(0.68);
    const 나무 = new THREE.Color("#6A5540");
    const 나무그늘 = new THREE.Color("#3A2E22");
    const 기단 = new THREE.Color("#8B867C");
    const 기단그늘 = new THREE.Color("#4E4A44");
    const 임시 = new THREE.Color();
    const 지붕부터 = 0.45;
    const 기단까지 = 0.08;
    // ★ **초가집 2 는 여기 안 들어간다.** 띄워 보니 집 한 채가 아니라
    //   **집 여러 채 + 나무 + 바닥판**이 얹힌 「마을 한 덩이」였다.
    //   집 하나로 쓰면 마을 전체가 접시만 하게 줄어든다.
    //   그건 팔레트에 「초가 마을 덩이」로 따로 넣어 두었다 —
    //   손으로 한 덩이씩 놓을 때 쓴다.
    return [초가집1모형, 초가집3모형].map((모형) => {
      const g = 모형지오(모형, {
        칠하기: (면, 모, 색) => {
          const p = 면.attributes.position;
          const nor = 면.attributes.normal;
          const 높이 = 모.폭.y || 1;
          // 기둥·문틀·창틀 — 가로로 가는 것들
          const 목재 = 가는것찾기(면, { 반경: 0.1, 퍼짐문턱: 0.05, 작은축문턱: 0.03 });
          for (let i = 0; i < p.count; i++) {
            const 위로 = THREE.MathUtils.clamp(p.getY(i) / 높이, 0, 1);
            const 위봄 = THREE.MathUtils.clamp(nor.getY(i) * 0.5 + 0.5, 0, 1);
            if (위로 < 기단까지) {
              임시.copy(기단그늘).lerp(기단, 0.4 + 0.58 * 위봄);
            } else if (위로 > 지붕부터) {
              // 짚결 — 이엉을 얹은 결이 있어야 「초가」로 보인다
              const 결 = 0.5 + 0.5 * Math.sin(위로 * 190 + p.getX(i) * 23);
              임시.copy(짚그늘).lerp(짚, 0.45 + 0.55 * 위봄);
              임시.multiplyScalar(0.95 + 0.11 * 결);
            } else if (목재.has(i)) {
              const 결 = 0.5 + 0.5 * Math.sin(p.getY(i) * 240);
              임시.copy(나무그늘).lerp(나무, 0.3 + 0.66 * 위봄);
              임시.multiplyScalar(0.93 + 0.13 * 결);
            } else {
              임시.copy(벽그늘).lerp(벽, 0.4 + 0.58 * 위봄);
            }
            색[i * 3] = 임시.r;
            색[i * 3 + 1] = 임시.g;
            색[i * 3 + 2] = 임시.b;
          }
        },
      });
      g.computeBoundingBox();
      const bb = g.boundingBox;
      const 가로 = Math.max(bb.max.x - bb.min.x, bb.max.z - bb.min.z) || 1;
      return 비례(g, 1.72 / 가로, 1, 1.72 / 가로);
    });
  });
}

// ── 초가 마을 한 덩이 ──────────────────────────────────────
//   초가집 2 모형. 위 주석대로 **한 채가 아니라 마을**이라 원경 마을에
//   섞어 쓰면 안 되고, 손으로 놓는 에셋으로만 둔다.
export function 초가마을덩이들() {
  return 한번("초가마을", () => {
    const 짚 = new THREE.Color(원경결.초가);
    const 짚그늘 = new THREE.Color(원경결.초가).multiplyScalar(0.72);
    const 벽 = new THREE.Color(원경결.흙벽);
    const 벽그늘 = new THREE.Color(원경결.흙벽).multiplyScalar(0.68);
    const 임시 = new THREE.Color();
    return [
      모형지오(초가집2모형, {
        칠하기: (면, 모, 색) => {
          const p = 면.attributes.position;
          const nor = 면.attributes.normal;
          const 높이 = 모.폭.y || 1;
          for (let i = 0; i < p.count; i++) {
            const 위로 = THREE.MathUtils.clamp(p.getY(i) / 높이, 0, 1);
            const 위봄 = THREE.MathUtils.clamp(nor.getY(i) * 0.5 + 0.5, 0, 1);
            if (위로 > 0.5) 임시.copy(짚그늘).lerp(짚, 0.45 + 0.55 * 위봄);
            else 임시.copy(벽그늘).lerp(벽, 0.4 + 0.58 * 위봄);
            색[i * 3] = 임시.r;
            색[i * 3 + 1] = 임시.g;
            색[i * 3 + 2] = 임시.b;
          }
        },
      }),
    ];
  });
}

