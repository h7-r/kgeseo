// [무엇이 들어 있나]
//   나무 6 · 바위 7 · 수풀 2 · 잡초 2 · 꽃 1 · 자갈밭 1.
//   손으로 깎던 `수목.js`·`돌.js` 의 표본을 **자리는 그대로 두고 모양만**
//   갈아 끼운다. 규약(밑동 원점 · 키 1 / 중심 원점)을 맞춰 구웠으므로
//   놓는 쪽 코드도, 이미 저장된 편집 기록도 건드릴 필요가 없다.
//
// [★ 색을 어디에 두느냐가 물건마다 다르다 — 잘못 고르면 하얘지거나 물든다]
//   이 프로젝트에는 두 갈래가 있다.
//     ① 자리에 `색` 이 붙는 것(바위·자갈) → 표본은 **비율**만 굽는다.
//        `돌담기` 가 절벽·통로마다 다른 돌빛을 넘긴다. 표본이 진짜 색을
//        가지면 그 색이 **두 번 곱해져** 시커메진다.
//     ② 자리에 색이 없는 것(나무·덤불·풀·꽃) → 표본이 **진짜 색**을 가진다.
//        `흰색깔기` 가 흰색을 채우므로, 표본이 색을 안 가지면 **새하얗게**
//        나온다(통발에서 실제로 그랬다).
//   아래 함수들이 그 둘을 나눠 쓴다.
//
// [나무 줄기와 잎을 어떻게 가르나]
//   천막에서 쓴 것과 같은 수를 쓴다 — `가는것찾기`. 줄기는 어느 높이에서
//   썰어도 지름 몇 cm 짜리 점이고, 잎덩이는 사방으로 퍼진다.
//   ※ 나무는 키 1 로 맞춰져 있어 줄기 반지름이 0.02~0.04 쯤이다. 천막
//     기본값(퍼짐 0.06)이 그대로 맞는다.

