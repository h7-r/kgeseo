// ═══════════════════════════════════════════════════════════════
//  배치.js — 흩뿌린 것들을 **하나씩 만질 수 있게** 만드는 곳
// ═══════════════════════════════════════════════════════════════
// [왜 필요했나]
//   지금까지는 나무 200 그루·덤불 900 개를 `mergeGeometries` 로 **버퍼 한 장**에
//   구웠다. 드로우콜은 1 개로 싸지만, 그러면 「세 번째 나무」라는 물건이 아예
//   존재하지 않는다 — 클릭해도 덩어리 전체가 잡히고, 하나만 지우려면 버퍼를
//   통째로 다시 만들어야 한다.
//
//   InstancedMesh 는 그 둘을 같이 준다. 드로우콜은 **모양 한 종류당 1 개**로
//   유지되면서, 인스턴스마다 자리·회전·크기·색을 따로 갖는다.
//   광선을 쏘면 `instanceId` 가 나오므로 **몇 번째인지 특정**된다.
//
// [모양 변형을 여러 벌 두는 이유]
//   InstancedMesh 는 지오메트리 하나만 쓴다. 나무가 전부 같은 모양이면 복제
//   티가 난다. 그래서 **변형을 4~6 벌** 만들어 무리를 나눠 담는다.
//   드로우콜은 변형 수만큼 늘지만(4~6), 편집 가능성을 얻는다.
//
// [편집을 파일로 남긴다]
//   배치는 시드 기반이라 **매번 같은 결과**가 나온다(팀원 화면에서도 같다).
//   편집을 메모리에만 두면 새로고침에 날아가고 팀에 전달도 안 된다.
//   그래서 「무엇을 지웠고 무엇을 옮겼는가」만 `에셋/편집.json` 에 적고,
//   여기서 덧씌운다. **생성은 그대로 결정적이고, 편집만 얹힌다.**
//   → 도면·생성기를 고치면 편집은 그대로 남고 나머지는 새로 생성된다.

import * as THREE from "three";
import { 미터 } from "./공간도면.js";

// 자리 하나의 형식
//   { x, y, z, 키, 회전?, 색? }   ← 생성기들이 이미 이 꼴로 뱉는다
//
// 무리 하나
//   이름   "언덕수풀.나무" 처럼 **편집 파일의 열쇠**가 된다. 바뀌면 편집이 어긋난다.
//   모양들 [BufferGeometry, ...] 지름 1 기준으로 만들어 둔 변형들
//   자리들 위 형식의 배열
export function 무리만들기({ 이름, 모양들, 자리들, 편집 = null, 기준 = "지름" }) {
  if (!모양들?.length || !자리들?.length) return null;

  // ── 편집 덧씌우기 ────────────────────────────────────────
  //   지운 것은 빼고, 옮긴 것은 값을 갈아 끼운다.
  //   ※ 열쇠는 **생성 순서 번호**다. 생성이 결정적이라 번호가 안정적이다.
  const 지움 = new Set(편집?.지움?.[이름] ?? []);
  const 고침 = 편집?.고침?.[이름] ?? {};

  const 살아남음 = [];
  for (let i = 0; i < 자리들.length; i++) {
    if (지움.has(i)) continue;
    const 원 = 자리들[i];
    const 덮 = 고침[i];
    살아남음.push({ 번호: i, ...원, ...(덮인값있나(덮) ? 덮 : null) });
  }
  // ── 붙여넣기로 **더한** 것 ───────────────────────────────
  //   생성기가 만든 것이 아니라 사람이 복사해 붙인 것이다.
  //   번호를 100만 위로 띄워 생성 번호와 안 겹치게 한다 — 생성기를 고쳐
  //   개수가 늘거나 줄어도 더한 것의 번호가 밀리지 않는다.
  const 더함 = 편집?.더함?.[이름] ?? [];
  for (let i = 0; i < 더함.length; i++) {
    const 번호 = 추가시작 + i;
    if (지움.has(번호)) continue;
    const 덮 = 고침[번호];
    살아남음.push({ 번호, ...더함[i], ...(덮인값있나(덮) ? 덮 : null) });
  }
  if (!살아남음.length) return null;

  // ── 모양별로 나눠 담는다 ─────────────────────────────────
  const 통 = 모양들.map(() => []);
  for (const a of 살아남음) {
    // 같은 번호는 언제나 같은 모양을 쓴다(편집해도 모양이 안 바뀌게)
    const k = (a.모양 ?? a.번호) % 모양들.length;
    통[k].push(a);
  }

  const 임시행렬 = new THREE.Matrix4();
  const 임시자리 = new THREE.Vector3();
  const 임시회전 = new THREE.Quaternion();
  const 임시크기 = new THREE.Vector3();
  const 임시색 = new THREE.Color();

  const 무리 = [];
  for (let k = 0; k < 모양들.length; k++) {
    const 목록 = 통[k];
    if (!목록.length) continue;
    const 행렬들 = new Float32Array(목록.length * 16);
    const 색들 = new Float32Array(목록.length * 3);
    const 번호들 = new Int32Array(목록.length);
    for (let i = 0; i < 목록.length; i++) {
      const a = 목록[i];
      const s = (기준 === "지름" ? a.키 : a.키) * 미터;
      임시자리.set(a.x * 미터, a.y * 미터, a.z * 미터);
      임시회전.setFromEuler(
        new THREE.Euler(a.기울기 ?? 0, a.회전 ?? 0, a.기울기2 ?? 0),
      );
      임시크기.set(s * (a.폭비 ?? 1), s * (a.높이비 ?? 1), s * (a.깊이비 ?? 1));
      임시행렬.compose(임시자리, 임시회전, 임시크기);
      임시행렬.toArray(행렬들, i * 16);
      임시색.set(a.색 ?? 0xffffff);
      색들[i * 3] = 임시색.r;
      색들[i * 3 + 1] = 임시색.g;
      색들[i * 3 + 2] = 임시색.b;
      번호들[i] = a.번호;
    }
    무리.push({ 지오: 모양들[k], 행렬들, 색들, 번호들, 모양번호: k });
  }
  return { 이름, 무리, 총: 자리들.length, 살아있는수: 살아남음.length };
}

// 편집 덮어쓰기 값이 실제로 있는가 (null·빈 객체 걸러내기)
function 덮인값있나(v) {
  return v && typeof v === "object" && Object.keys(v).length > 0;
}

// ── 빈 편집 ────────────────────────────────────────────────
// 붙여넣은 것의 번호는 여기서부터 — 생성 번호(0,1,2…)와 안 겹친다
export const 추가시작 = 1000000;

export const 빈편집 = () => ({ 지움: {}, 고침: {}, 더함: {} });

// ── 편집 적용/해제 도우미 ──────────────────────────────────
export function 지우기(편집, 이름, 번호) {
  const 다음 = 복사(편집);
  다음.지움[이름] = [...new Set([...(다음.지움[이름] ?? []), 번호])];
  return 다음;
}

export function 되살리기(편집, 이름, 번호) {
  const 다음 = 복사(편집);
  다음.지움[이름] = (다음.지움[이름] ?? []).filter((v) => v !== 번호);
  return 다음;
}

const 복사 = (편집) => ({
  지움: { ...(편집?.지움 ?? {}) },
  고침: { ...(편집?.고침 ?? {}) },
  더함: { ...(편집?.더함 ?? {}) },
});

export function 고치기(편집, 이름, 번호, 값) {
  const 다음 = 복사(편집);
  const 무리 = { ...(다음.고침[이름] ?? {}) };
  무리[번호] = { ...(무리[번호] ?? {}), ...값 };
  다음.고침[이름] = 무리;
  return 다음;
}

// ── 흩뿌린 자리에 흔들림을 채운다 ──────────────────────────
//   생성기가 뱉는 자리는 { x, y, z, 크기 } 뿐이다. 회전·납작·색은 예전에는
//   지오메트리를 만들 때 그 자리에서 굴렸다. 인스턴스로 옮기면서 **자리 값**
//   으로 끌어올린다 — 그래야 편집기가 하나씩 돌리고 늘일 수 있다.
export function 돌흔들기(자리들, 시드, { 납작 = [0.45, 0.85], 색 } = {}) {
  let t = (시드 >>> 0) || 1;
  const 난수 = () => {
    t = (t + 0x6d2b79f5) >>> 0;
    let x = Math.imul(t ^ (t >>> 15), 1 | t);
    x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x;
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
  return 자리들.map((a) => ({
    x: a.x,
    y: a.y,
    z: a.z,
    키: a.크기 ?? a.키 ?? 1,
    회전: 난수() * Math.PI * 2,
    기울기: (난수() - 0.5) * 0.7,
    기울기2: (난수() - 0.5) * 0.7,
    폭비: 0.7 + 난수() * 0.6,
    높이비: 납작[0] + 난수() * (납작[1] - 납작[0]),
    깊이비: 0.75 + 난수() * 0.5,
    색: 색 ? 색(난수()) : undefined,
  }));
}

// ── 붙여넣기 ───────────────────────────────────────────────
//   생성기를 건드리지 않고 **사람이 더한 것**을 편집 파일에 쌓는다.
//   돌려주는 번호로 곧바로 고르기·옮기기를 이어갈 수 있다.
export function 더하기(편집, 이름, 자리) {
  const 다음 = 복사(편집);
  const 목록 = [...(다음.더함[이름] ?? []), 자리];
  다음.더함[이름] = 목록;
  return { 편집: 다음, 번호: 추가시작 + 목록.length - 1 };
}

// ── 파일로 읽고 쓰기 ───────────────────────────────────────
//   개발 서버(vite.config.js 의 `편집저장` 플러그인)가 POST 를 받아
//   naju01/에셋/편집.json 에 쓴다. 빌드본에서는 읽기만 한다.
export async function 편집읽기() {
  try {
    const r = await fetch("/__naju-edit?t=" + Date.now());
    if (!r.ok) return 빈편집();
    const j = await r.json();
    return { 지움: j.지움 ?? {}, 고침: j.고침 ?? {}, 더함: j.더함 ?? {} };
  } catch {
    return 빈편집();
  }
}

export async function 편집쓰기(편집) {
  const r = await fetch("/__naju-edit", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(편집, null, 2),
  });
  const 글 = await r.text();
  if (!r.ok) throw new Error(`저장 실패 (${r.status})`);
  // ★ 여기서 본문을 반드시 확인한다.
  //   저장 플러그인이 안 붙어 있으면 Vite 가 **index.html 을 200 으로** 돌려준다.
  //   `r.ok` 만 보면 **저장된 줄 알고 넘어간다** — 실제로 그래서
  //   「먹힌 건지 안 먹힌 건지 모르겠다」가 나왔다.
  if (글.trim() !== "ok")
    throw new Error("개발 서버에 저장 기능이 없다 — `npx vite naju01` 을 다시 띄워라");
  return true;
}

// 저장 기능이 붙어 있는지 미리 확인한다(편집 모드에 들어갈 때 알려 주려고)
export async function 저장가능한가() {
  try {
    const r = await fetch("/__naju-edit?t=" + Date.now());
    const 글 = await r.text();
    JSON.parse(글);
    return true;
  } catch {
    return false;
  }
}

// 편집이 몇 건인가 — 저장 안 한 변경을 세어 보여 주려고
export function 편집수(편집) {
  let n = 0;
  for (const v of Object.values(편집?.지움 ?? {})) n += v.length;
  for (const v of Object.values(편집?.고침 ?? {})) n += Object.keys(v).length;
  for (const v of Object.values(편집?.더함 ?? {})) n += v.length;
  return n;
}
