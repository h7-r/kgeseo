// ═══════════════════════════════════════════════════════════════
//  배치.js — 흩뿌린 것들을 **하나씩 만질 수 있게** 만드는 곳
// ═══════════════════════════════════════════════════════════════
// [왜 필요했나]
//   지금까지는 나무 200 그루·덤불 900 개를 `mergeGeometries` 로 **버퍼 한 장**에
//   구웠다. 드로우콜은 1 개로 싸지만, 그러면 「세 번째 나무」라는 물건이 아예
//   존재하지 않는다 — 클릭해도 덩어리 전체가 잡히고, 하나만 지우려면 버퍼를
//   통째로 다시 만들어야 한다.
//
//   InstancedMesh 는 그 둘을 같이 준다. 드로우콜은 **모양 한 종류당 1 개**로
//   유지되면서, 인스턴스마다 자리·회전·크기·색을 따로 갖는다.
//   광선을 쏘면 `instanceId` 가 나오므로 **몇 번째인지 특정**된다.
//
// [모양 변형을 여러 벌 두는 이유]
//   InstancedMesh 는 지오메트리 하나만 쓴다. 나무가 전부 같은 모양이면 복제
//   티가 난다. 그래서 **변형을 4~6 벌** 만들어 무리를 나눠 담는다.
//   드로우콜은 변형 수만큼 늘지만(4~6), 편집 가능성을 얻는다.
//
// [편집을 파일로 남긴다]
//   배치는 시드 기반이라 **매번 같은 결과**가 나온다(팀원 화면에서도 같다).
//   편집을 메모리에만 두면 새로고침에 날아가고 팀에 전달도 안 된다.
//   그래서 「무엇을 지웠고 무엇을 옮겼는가」만 `에셋/편집.json` 에 적고,
//   여기서 덧씌운다. **생성은 그대로 결정적이고, 편집만 얹힌다.**
//   → 도면·생성기를 고치면 편집은 그대로 남고 나머지는 새로 생성된다.

import * as THREE from "three";
import { 미터 } from "./공간도면.js";

// 자리 하나의 형식
//   { x, y, z, 키, 회전?, 색? }   ← 생성기들이 이미 이 꼴로 뱉는다
//
// 무리 하나
//   이름   "언덕수풀.나무" 처럼 **편집 파일의 열쇠**가 된다. 바뀌면 편집이 어긋난다.
//   모양들 [BufferGeometry, ...] 지름 1 기준으로 만들어 둔 변형들
//   자리들 위 형식의 배열
// `양면` — 안쪽이 보이는 물건(나룻배·꽃잎·풀잎)은 뒷면도 그려야 한다.
//   단면으로 두면 배 안쪽이 **뚫려서 물과 땅이 훤히 보이고**, 광선도 그대로
//   통과해 클릭이 안 된다(실제로 그랬다).
// ── 편집 덧씌우기 ──────────────────────────────────────────
// [왜 따로 빼냈나]
//   **화면에 실제로 선 자리**가 필요한 곳이 무리 만들기 말고 또 생겼다.
//   마을 울타리는 「집을 두르는」 물건이라 **사람이 편집기에서 지우거나 옮긴
//   뒤의 집 자리**를 봐야 한다. 생성기가 뱉은 원본 자리를 그대로 쓰면
//   울이 **없는 집을 두르고**, 옮겨 간 집은 맨몸으로 남는다(실제로 그랬다 —
//   울 112 개가 집 한 채도 못 두르고 X 99~200 에 따로 떨어져 있었다).
//   그래서 「지움·고침·더함을 얹어 최종 자리 목록을 낸다」를 한 군데로 모은다.
//   ※ 돌려주는 자리마다 `번호` 가 붙는다 — 편집 열쇠와 같은 번호다.
export function 편집덧씌우기(이름, 자리들 = [], 편집 = null) {
  //   지운 것은 빼고, 옮긴 것은 값을 갈아 끼운다.
  //   ※ 열쇠는 **생성 순서 번호**다. 생성이 결정적이라 번호가 안정적이다.
  const 지움 = new Set(편집?.지움?.[이름] ?? []);
  const 고침 = 편집?.고침?.[이름] ?? {};
  const 살아남음 = [];
  for (let i = 0; i < 자리들.length; i++) {
    if (지움.has(i)) continue;
    const 원 = 자리들[i];
    const 덮 = 고침[i];
    살아남음.push({ 번호: i, ...원, ...(덮인값있나(덮) ? 덮 : null) });
  }
  // ── 붙여넣기로 **더한** 것 ───────────────────────────────
  //   생성기가 만든 것이 아니라 사람이 복사해 붙인 것이다.
  //   번호를 100만 위로 띄워 생성 번호와 안 겹치게 한다 — 생성기를 고쳐
  //   개수가 늘거나 줄어도 더한 것의 번호가 밀리지 않는다.
  const 더함 = 편집?.더함?.[이름] ?? [];
  for (let i = 0; i < 더함.length; i++) {
    const 번호 = 추가시작 + i;
    if (지움.has(번호)) continue;
    const 덮 = 고침[번호];
    살아남음.push({ 번호, ...더함[i], ...(덮인값있나(덮) ? 덮 : null) });
  }
  return 살아남음;
}

export function 무리만들기({
  이름,
  모양들,
  자리들 = [],
  편집 = null,
  기준 = "지름",
  양면 = false,
}) {
  // ※ `자리들` 이 비어 있어도 **더함(사람이 놓은 것)** 만으로 무리가 설 수 있다.
  //   예전에는 여기서 곧바로 null 을 돌려줘서, 팔레트로 놓은 물건이 화면에
  //   안 나타났다(생성기가 만든 자리가 하나도 없는 종류라서).
  const 더함미리 = 편집?.더함?.[이름] ?? [];
  if (!모양들?.length || (!자리들.length && !더함미리.length)) return null;

  // ── 편집 덧씌우기 ────────────────────────────────────────
  const 살아남음 = 편집덧씌우기(이름, 자리들, 편집);
  if (!살아남음.length) return null;

  // ── 모양별로 나눠 담는다 ─────────────────────────────────
  // ── 못 쓸 값 걸러내기 ────────────────────────────────────
  // [왜]
  //   좌표나 크기에 NaN·Infinity 가 하나만 섞여도 인스턴스 행렬이 통째로
  //   망가지고, 그게 GPU 로 넘어가면 드라이버가 화면을 놓아 버린다
  //   (탭이 통째로 꺼진다). 편집 파일은 사람이 손으로 고칠 수도 있고,
  //   생성기가 무대 밖 좌표를 다룰 일도 생겼으니 **넘기기 전에 막는다.**
  const 성한값 = (v) => v === undefined || Number.isFinite(v);
  const 성한가 = (a) =>
    Number.isFinite(a.x) &&
    Number.isFinite(a.y) &&
    Number.isFinite(a.z) &&
    Number.isFinite(a.키) &&
    a.키 > 0 &&
    ["회전", "기울기", "기울기2", "폭비", "높이비", "깊이비"].every((k) =>
      성한값(a[k]),
    );
  const 성한것 = 살아남음.filter(성한가);
  if (성한것.length !== 살아남음.length && typeof console !== "undefined")
    console.warn(
      `[배치] ${이름}: 못 쓸 값이 든 ${살아남음.length - 성한것.length}개를 건너뛴다`,
    );
  if (!성한것.length) return null;

  // ── 모양별로 나눠 담는다 ─────────────────────────────────
  // ※ 한때 **공간 칸으로도 쪼갰다.** 시야 밖 칸을 버리려는 것이었는데,
  //   실측해 보니 이 맵에서는 벌 게 없었다 —
  //     ① 무대가 80 × 50 m 라 어디에 서든 대부분이 시야에 들어온다.
  //        열 곳에서 잰 부하 편차가 24 % 뿐이었다.
  //     ② 언덕수풀은 코어 밖 산자락까지 **142 m** 에 퍼져 있어, 칸을 나눠도
  //        조각 하나의 경계 구가 반지름 78 m — 무대보다 크다. 안 잘린다.
  //     ③ 모양이 5~7 가지라 칸 × 모양으로 조각이 곱해져 드로우콜만 늘었다
  //        (453 → 1,205 까지 갔다).
  //   그래서 되돌렸다. 이 맵에서 프러스텀 컬링은 지렛대가 아니다 —
  //   **그림자와 면 수**가 지렛대다.
  const 통 = 모양들.map(() => []);
  for (const a of 성한것) {
    // 같은 번호는 언제나 같은 모양을 쓴다(편집해도 모양이 안 바뀌게)
    const k = (a.모양 ?? a.번호) % 모양들.length;
    통[k].push(a);
  }

  const 임시행렬 = new THREE.Matrix4();
  const 임시자리 = new THREE.Vector3();
  const 임시회전 = new THREE.Quaternion();
  const 임시크기 = new THREE.Vector3();
  const 임시색 = new THREE.Color();

  const 무리 = [];
  for (let k = 0; k < 모양들.length; k++) {
    const 목록 = 통[k];
    if (!목록.length) continue;
    const 행렬들 = new Float32Array(목록.length * 16);
    const 색들 = new Float32Array(목록.length * 3);
    const 번호들 = new Int32Array(목록.length);
    for (let i = 0; i < 목록.length; i++) {
      const a = 목록[i];
      const s = (기준 === "지름" ? a.키 : a.키) * 미터;
      임시자리.set(a.x * 미터, a.y * 미터, a.z * 미터);
      // ★ 순서는 **YXZ** 다. 기본값(XYZ)을 쓰면 편집기가 되읽는 순서와 달라서,
      //   기울어진 것을 복사·붙여넣기 하면 자세가 미묘하게 틀어진다
      //   (편집기 `집기` 는 `setFromQuaternion(회, "YXZ")` 로 푼다).
      //   울타리 가로대처럼 **기울기가 눈에 보이는 것**은 이게 맞아야 한다 —
      //   YXZ 라야 「먼저 방위를 돌리고, 그 방위에서 위아래로 기울인다」가 된다.
      임시회전.setFromEuler(
        new THREE.Euler(a.기울기 ?? 0, a.회전 ?? 0, a.기울기2 ?? 0, "YXZ"),
      );
      임시크기.set(s * (a.폭비 ?? 1), s * (a.높이비 ?? 1), s * (a.깊이비 ?? 1));
      임시행렬.compose(임시자리, 임시회전, 임시크기);
      임시행렬.toArray(행렬들, i * 16);
      임시색.set(a.색 ?? 0xffffff);
      색들[i * 3] = 임시색.r;
      색들[i * 3 + 1] = 임시색.g;
      색들[i * 3 + 2] = 임시색.b;
      번호들[i] = a.번호;
    }
    // 표본에 꼭짓점 색이 없으면 흰색을 채워 둔다.
    //   재질이 `vertexColors` 라 three 는 `USE_COLOR` 를 켜는데, 지오메트리에
    //   `color` 속성이 없으면 그 값이 **(0,0,0)** 으로 읽혀 통째로 검게 나온다.
    //   흰색을 깔아 두면 `instanceColor` 가 그대로 곱해져 제 색이 나온다.
    //   (돌 표본이 색 없이 들어와 2,159 개가 새까맸다 — 실측으로 잡았다)
    흰색깔기(모양들[k]);
    무리.push({ 지오: 모양들[k], 행렬들, 색들, 번호들, 모양번호: k });
  }
  return { 이름, 무리, 양면, 총: 자리들.length, 살아있는수: 성한것.length };
}

// 꼭짓점 색이 없는 표본에 흰색을 한 번 깔아 둔다(이미 있으면 그대로 둔다)
function 흰색깔기(geo) {
  if (!geo || geo.attributes.color) return geo;
  const n = geo.attributes.position.count;
  const arr = new Float32Array(n * 3).fill(1);
  geo.setAttribute("color", new THREE.BufferAttribute(arr, 3));
  return geo;
}

// 편집 덮어쓰기 값이 실제로 있는가 (null·빈 객체 걸러내기)
function 덮인값있나(v) {
  return v && typeof v === "object" && Object.keys(v).length > 0;
}

// ── 표본 규약 ──────────────────────────────────────────────
//   인스턴스 표본은 **높이 1 · 밑동이 원점**이어야 한다.
//   그래야 자리의 `키`(m)가 그대로 배율이 되고, 자리의 y 가 곧 땅에 닿는 점이 된다.
//   (돌처럼 반쯤 파묻히는 것만 예외 — 그건 중심을 원점에 둔다)
export function 밑동원점으로(g) {
  g.computeBoundingBox();
  const b = g.boundingBox;
  const 높 = b.max.y - b.min.y || 1;
  g.translate(-(b.max.x + b.min.x) / 2, -b.min.y, -(b.max.z + b.min.z) / 2);
  g.scale(1 / 높, 1 / 높, 1 / 높);
  return g;
}

// ── 빈 편집 ────────────────────────────────────────────────
// 붙여넣은 것의 번호는 여기서부터 — 생성 번호(0,1,2…)와 안 겹친다
export const 추가시작 = 1000000;

export const 빈편집 = () => ({ 지움: {}, 고침: {}, 더함: {} });

// ── 편집 적용/해제 도우미 ──────────────────────────────────
export function 지우기(편집, 이름, 번호) {
  const 다음 = 복사(편집);
  다음.지움[이름] = [...new Set([...(다음.지움[이름] ?? []), 번호])];
  return 다음;
}

export function 되살리기(편집, 이름, 번호) {
  const 다음 = 복사(편집);
  다음.지움[이름] = (다음.지움[이름] ?? []).filter((v) => v !== 번호);
  return 다음;
}

const 복사 = (편집) => ({
  지움: { ...(편집?.지움 ?? {}) },
  고침: { ...(편집?.고침 ?? {}) },
  더함: { ...(편집?.더함 ?? {}) },
});

export function 고치기(편집, 이름, 번호, 값) {
  const 다음 = 복사(편집);
  const 무리 = { ...(다음.고침[이름] ?? {}) };
  무리[번호] = { ...(무리[번호] ?? {}), ...값 };
  다음.고침[이름] = 무리;
  return 다음;
}

// ── 흩뿌린 자리에 흔들림을 채운다 ──────────────────────────
//   생성기가 뱉는 자리는 { x, y, z, 크기 } 뿐이다. 회전·납작·색은 예전에는
//   지오메트리를 만들 때 그 자리에서 굴렸다. 인스턴스로 옮기면서 **자리 값**
//   으로 끌어올린다 — 그래야 편집기가 하나씩 돌리고 늘일 수 있다.
export function 돌흔들기(자리들, 시드, { 납작 = [0.45, 0.85], 색 } = {}) {
  let t = (시드 >>> 0) || 1;
  const 난수 = () => {
    t = (t + 0x6d2b79f5) >>> 0;
    let x = Math.imul(t ^ (t >>> 15), 1 | t);
    x = (x + Math.imul(x ^ (x >>> 7), 61 | x)) ^ x;
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
  return 자리들.map((a) => ({
    x: a.x,
    y: a.y,
    z: a.z,
    키: a.크기 ?? a.키 ?? 1,
    회전: 난수() * Math.PI * 2,
    기울기: (난수() - 0.5) * 0.7,
    기울기2: (난수() - 0.5) * 0.7,
    폭비: 0.7 + 난수() * 0.6,
    높이비: 납작[0] + 난수() * (납작[1] - 납작[0]),
    깊이비: 0.75 + 난수() * 0.5,
    색: 색 ? 색(난수()) : undefined,
  }));
}

// ── 붙여넣기 ───────────────────────────────────────────────
//   생성기를 건드리지 않고 **사람이 더한 것**을 편집 파일에 쌓는다.
//   돌려주는 번호로 곧바로 고르기·옮기기를 이어갈 수 있다.
export function 더하기(편집, 이름, 자리) {
  const 다음 = 복사(편집);
  const 목록 = [...(다음.더함[이름] ?? []), 자리];
  다음.더함[이름] = 목록;
  return { 편집: 다음, 번호: 추가시작 + 목록.length - 1 };
}

// ── 파일로 읽고 쓰기 ───────────────────────────────────────
//   개발 서버(vite.config.js 의 `편집저장` 플러그인)가 POST 를 받아
//   naju01/에셋/편집.json 에 쓴다. 빌드본에서는 읽기만 한다.
// ※ 한때 새 지형용 **이전본**(`에셋/편집-새지형.json`)을 따로 읽고 그동안
//   저장을 잠가 뒀다. 지금은 `도구/배치이전.mjs` 가 만든 그 이전본을
//   `편집.json` 자리에 **앉혔으므로** 갈래가 하나다 — 읽기도 저장도 예전 그대로.
//   옮긴 방식: 새 y = 새 지면(x,z) + (저장 y − 옛 지면(x,z)).
//   지면에 붙어 있던 것은 다시 앉고, 일부러 띄운 것은 띄운 채 올라갔다.

export async function 편집읽기() {
  try {
    const r = await fetch("/__naju-edit?t=" + Date.now());
    if (!r.ok) return 빈편집();
    const j = await r.json();
    return { 지움: j.지움 ?? {}, 고침: j.고침 ?? {}, 더함: j.더함 ?? {} };
  } catch {
    return 빈편집();
  }
}

export async function 편집쓰기(편집) {
  // ★ 미리보기 중에는 못 쓴다. 여기서 막지 않으면 **새 지형으로 옮긴 좌표가
  //   원본 `편집.json` 을 덮어쓴다.** 되돌릴 방법이 백업뿐인 사고다.
  const r = await fetch("/__naju-edit", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(편집, null, 2),
  });
  const 글 = await r.text();
  if (!r.ok) throw new Error(`저장 실패 (${r.status})`);
  // ★ 여기서 본문을 반드시 확인한다.
  //   저장 플러그인이 안 붙어 있으면 Vite 가 **index.html 을 200 으로** 돌려준다.
  //   `r.ok` 만 보면 **저장된 줄 알고 넘어간다** — 실제로 그래서
  //   「먹힌 건지 안 먹힌 건지 모르겠다」가 나왔다.
  if (글.trim() !== "ok")
    throw new Error("개발 서버에 저장 기능이 없다 — `npx vite naju01` 을 다시 띄워라");
  return true;
}

// 저장 기능이 붙어 있는지 미리 확인한다(편집 모드에 들어갈 때 알려 주려고)
export async function 저장가능한가() {
  try {
    const r = await fetch("/__naju-edit?t=" + Date.now());
    const 글 = await r.text();
    JSON.parse(글);
    return true;
  } catch {
    return false;
  }
}

// 편집이 몇 건인가 — 저장 안 한 변경을 세어 보여 주려고
export function 편집수(편집) {
  let n = 0;
  for (const v of Object.values(편집?.지움 ?? {})) n += v.length;
  for (const v of Object.values(편집?.고침 ?? {})) n += Object.keys(v).length;
  for (const v of Object.values(편집?.더함 ?? {})) n += v.length;
  return n;
}
