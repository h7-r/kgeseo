// [문서가 시킨 것]
//   ④ Scene 01 §3 「왜곡의 어긋남을 **크게 드러내지 않는다.** 강 건너 마을이
//     미묘하게 흐릿하거나, 물소리와 물결의 방향이 어긋나는 정도로 위화감만
//     심는다.」
//   ④ Scene 02 §3 「증언이 재현될 때마다 **같은 장면이 조금씩 다르게** 보이도록
//     한다. 어느 재현이 진짜인지 판단할 수 없는 상태를 유지한다.」
//   ④ Scene 02 §4 장식 「흐려지거나 **겹쳐 보이는** 원경 · 어긋난 그림자」
//   ④ Scene 03 §3 「진실 공개 직후 **왜곡이 걷히지 않는다**는 사실을 즉시 보여준다」
//   ④ §0.7    「**P04 이후** 왜곡 자동 해소 · 동적 연출 정상화」
//
// [그래서 이 파일이 잡은 모양]
//   ★ 왜곡은 **세기 슬라이더 하나가 아니다.** `(세기, 결)` 두 축이다.
//     ─ 세기: 얼마나 심한가 (0~1)
//     ─ 결  : 어떤 종류인가 ("흐림" | "겹침")
//     씬 1 → 씬 2 에서 달라지는 것은 **세기가 아니라 결**이다.
//       씬 1 흐림 = 「안 보인다」            (정보가 없다)
//       씬 2 겹침 = 「여럿 보이는데 뭐가 진짜인지 모른다」(정보가 모순이다)
//     이야기가 「실종(모름) → 엇갈리는 증언(모순)」으로 가는 것과 같은 모양이다.
//     세기 하나로 만들어 두면 씬 2 에서 못 쓴다. 그래서 처음부터 둘로 나눈다.
//
//   ★ 방아쇠는 **씬 번호가 아니라 퍼즐 완료**다. §0.7 표가 P01~P04 로 매겨져
//     있고, 씬 2 의 핵심 퍼즐 P01 은 **씬 2 가 끝날 때** 풀린다. 즉 씬 2 를
//     도는 동안 공간 상태는 아직 「초기」다. 씬 번호로 걸면 한 칸씩 어긋난다.
//
// [어떻게 그리나 — 잔상 겹치기 한 가지로 둘 다 만든다]
//   한 물체만 진짜로 흐리게 하려면 그 물체만 따로 떠서(RTT) 뭉갠 뒤 다시
//   합성해야 한다. 렌더 패스가 하나 더 늘고, 후처리 순서와도 싸워야 한다.
//   그레이박스에서 치를 값이 아니다.
//   대신 **같은 무리를 조금씩 어긋나게 여러 벌 겹쳐 그린다.**
//     · 오프셋을 작게(0.3 m) · 여러 벌 · 옅게  → 윤곽이 뭉개진다 = **흐림**
//     · 오프셋을 크게(2 m)  · 두 벌 · 진하게 → 둘로 보인다   = **겹침**
//   같은 장치의 숫자만 다르다. 그래서 씬 2 가 **공짜로 따라온다.**
//
// [왜 택촌에만 거나]
//   ★ 거리에 따라 뿌옇게 하면 그건 **안개**로 읽힌다. 왜곡이 아니다.
//   「저기가 이상하다」가 되려면 **그 마을만** 이상해야 한다. `원경.택촌` 을
//   숲·진부촌과 따로 담아 둔 것이 이것 때문이다(원경.js 참고).

import * as THREE from "three";

// ── 단계표 (④ §0.7) ────────────────────────────────────────
//   🟢 = 문서가 정한 것 · 🟡 = 이 그레이박스가 잡아 본 값(팀이 고친다)
//   `퍼즐` 은 **직전에 푼 퍼즐**이다. 초기 = 아무것도 안 푼 상태.
export const 왜곡단계 = {
  초기: { 세기: 0.42, 결: "흐림", 물어긋남: 0.55, 설명: "Scene 01~02 — 미묘한 위화감" },
  P01: { 세기: 0.5, 결: "겹침", 물어긋남: 0.65, 설명: "Scene 03 — 증언이 겹친다" },
  P02: { 세기: 0.62, 결: "겹침", 물어긋남: 0.8, 설명: "Scene 04 — 어긋남이 커진다" },
  P03: { 세기: 0.75, 결: "겹침", 물어긋남: 1.0, 설명: "Scene 05 직전 — 절정" },
  // ★ 걷히는 것은 여기 한 번뿐이다(§0.7). 씬이 넘어간다고 걷히지 않는다 —
  //   씬 3 이 「진실이 드러나도 왜곡이 걷히지 않는다」를 Q3 의 동력으로 쓴다.
  P04: { 세기: 0, 결: "없음", 물어긋남: 0, 설명: "왜곡 해소 · 동적 연출 정상화" },
};
export const 단계차례 = ["초기", "P01", "P02", "P03", "P04"];

// ── 잔상 배치 ───────────────────────────────────────────────
//   한 벌마다 { 밀기: [x, y, z] (m) · 짙기 · 흔듦 } 을 돌려준다.
//   `흔듦` 은 시간에 따라 얼마나 떠도는가 — 0 이면 붙박이다.
//
//   [왜 위아래로도 미나]  옆으로만 밀면 「그림자가 두 개」로 보인다.
//     아주 조금 띄워야 **아지랑이**처럼 읽힌다.
export function 잔상들(결, 세기) {
  if (!세기 || 결 === "없음") return [];
  // ★ 밀기 단위는 **미터**지만, 읽히는 것은 **화면 픽셀**이다.
  //   택촌은 63 m 밖이고 거기서 가로 1 m 는 화면 18.4 px 다(실측).
  //   처음엔 0.3 m(5.5 px)·1.9 m(35 px)로 잡았는데 화면에서는 거의 안
  //   보였다 — 크기가 아니라 **대비**가 모자랐다(아래 `잔상색` 참고).
  if (결 === "흐림")
    // 작게 · 여럿. 윤곽만 뭉갠다 — 「크게 드러내지 않는다」(§3) 를 지킨다.
    return [
      { 밀기: [0.85, 0.12, 0.5], 짙기: 0.5 * 세기, 흔듦: 0.55 },
      { 밀기: [-0.72, 0.28, -0.4], 짙기: 0.5 * 세기, 흔듦: 0.45 },
      { 밀기: [0.12, 0.55, 0.82], 짙기: 0.4 * 세기, 흔듦: 0.62 },
    ];
  // "겹침" — 크게 · 둘. 「어느 쪽이 진짜인지 모른다」가 되어야 하므로,
  //   한 채 폭(4.2 m ≈ 74 px)의 절반쯤 어긋나야 **둘로 세어진다.**
  return [
    { 밀기: [2.4, 0.15, 1.3], 짙기: 0.62 * 세기 + 0.3, 흔듦: 1.4 },
    { 밀기: [-2.1, 0.35, -1.1], 짙기: 0.55 * 세기 + 0.26, 흔듦: 1.2 },
  ];
}

// ── 잔상이 떠도는 자리 ──────────────────────────────────────
//   프레임마다 부른다. 주기를 서로 나누어떨어지지 않게 두어야 **되돌아오는
//   느낌**이 안 난다(같은 주기면 숨쉬듯 규칙적으로 보인다).
export function 잔상흔들기(잔상, 시각, 결과 = new THREE.Vector3()) {
  const [x, y, z] = 잔상.밀기;
  const s = 잔상.흔듦;
  return 결과.set(
    x + Math.sin(시각 * 0.23 + x * 3.1) * s,
    y + Math.sin(시각 * 0.17 + y * 5.7) * s * 0.35,
    z + Math.cos(시각 * 0.19 + z * 2.7) * s,
  );
}

// ── 잔상 색 ─────────────────────────────────────────────────
//   지평선 색 쪽으로 당긴다. 원래 색 그대로 겹치면 **진해져서** 오히려
//   또렷해 보인다 — 흐리게 하려는 일과 정반대가 된다.
//   [처음엔 반대로 갔다]  지평선 색으로 0.6 만큼 당겨 놨더니, 잔상이
//   **모래빛 들판과 같은 색**이 되어 통째로 사라졌다(A/B 스크린샷으로 잡았다).
//   흐리게 하려면 색을 지워야 한다고 생각했는데, 화면에서 안 보이면
//   흐린 게 아니라 **없는 것**이다. 조금만 당기고 원래 어둠을 남긴다.
export function 잔상색(바탕색, 지평색, 세기) {
  return new THREE.Color(바탕색).lerp(new THREE.Color(지평색), 0.12 + 0.16 * 세기);
}

// ── 물결이 어긋난다 (④ Scene 01 §3) ────────────────────────
//   [무엇이 어긋나나]  강물은 한 방향으로 흐른다. 그런데 여기서는
//   **너울(긴 물결)과 잔물결이 따로 논다** — 너울이 멎거나 거꾸로 간다.
//   한쪽만 보면 정상인데, 가만히 보면 말이 안 되는 상태다.
//   [왜 이게 읽히나]  사람은 물의 방향을 **너울**로 읽고, 속도를
//   **잔물결**로 읽는다. 둘이 다투면 어느 쪽으로 흐르는지 판단이 안 선다.
//   그게 이 씬이 심으려는 위화감이다.
//   [단계별로 실제로 어떻게 되나 — 수치를 적어 둔다]
//     `너울속 = -0.28 × (1 − 2×정도)` 이라, 정도가 0.5 면 너울이 **선다.**
//       0.55(초기) → +0.03  거의 멈춘 너울 · 잔물결만 움직인다
//                            = 「흐르지 않는데 잔물결은 인다」 — 씬 1 에 맞는
//                              「크게 드러내지 않는」 어긋남이다
//       0.65(P01)  → +0.08  느리게 거꾸로
//       0.80(P02)  → +0.17
//       1.00(P03)  → +0.28  정상과 **정확히 반대** 속도
//     즉 씬 1 은 「역류」가 아니라 「멎은 물」이다. 역류는 절정에서 온다.
//   ※ 이건 **움직임**이라 정지 화면으로는 판정이 안 된다. 실제로 보고 정해야 한다.
//   돌려주는 값은 `강면만들기` 의 `갱신` 에 그대로 넘긴다.
export function 물어긋남결(정도) {
  return {
    // 너울의 진행 방향을 뒤집는 정도. 0 = 정상 · 1 = 완전히 거꾸로
    너울뒤집기: THREE.MathUtils.clamp(정도, 0, 1),
    // 잔물결을 옆으로 미끄러뜨린다 — 물이 비스듬히 끌리는 느낌
    옆끌림: 0.6 * 정도,
  };
}
