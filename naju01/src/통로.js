// ═══════════════════════════════════════════════════════════════
//  통로.js — T1~T4 비탈길을 '코드로' 만드는 곳
// ═══════════════════════════════════════════════════════════════
// [지금까지 무엇이 문제였나]
//   통로가 **노란 리본**이었다. 도면의 중심선을 그대로 판때기로 세운 것이라,
//   ① 길로 안 읽히고 ② 「여기가 오를 수 있는 자리」라는 신호가 안 되고
//   ③ 무엇보다 **경사가 얼마나 센지 눈으로 가늠이 안 됐다.**
//   T2 가 27.9° 인데 그게 힘든 비탈인지 산책로인지 화면만 봐서는 몰랐다.
//
// [그래서 무엇을 만드나]
//   ① 길바닥  — 사람이 밟아 다져진 띠. 가운데가 밝고 가장자리로 갈수록 어둡다
//   ② 갓길    — 길 밖으로 흘러내리는 어깨. 길의 '폭'을 눈에 알려 준다
//   ③ 비탈    — 갓길에서 땅까지 내려가는 흙더미. 없으면 공중에 뜬 리본이 된다
//   ④ 길가 돌 — 다져진 길과 안 다져진 땅의 경계를 흐트러뜨린다
//
// [걷는 판정과 어긋나면 안 된다]
//   `지형.js` 는 중심선에서 **폭/2 안쪽**을 길로 친다. 그래서
//   길바닥의 폭은 도면 폭과 **정확히 같게** 두고, 갓길·비탈은 그 **바깥**으로만
//   낸다. 그러면 "보이는 길 위를 걷는데 갑자기 떨어지는" 일이 없다.
//   길바닥 자체의 요철은 바닥.js 와 같은 이유로 ±0.06 m 안쪽으로만 준다.
//
// [모서리 처리]
//   도면 중심선은 직각으로 꺾인다(특히 T1). 꺾인 데서 단면을 그냥 수직으로
//   내밀면 안쪽에서 면이 서로 파고든다. 그래서 잘게 나눠 뽑은 다음
//   **이웃한 방향을 평균 내어** 모서리를 둥글린다.
//
// [단위] 좌표·크기는 미터. 지오메트리만 유닛(× 미터).

