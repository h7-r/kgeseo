  //   절벽(암반)과 길 비탈(흙)이 맞닿는 데가 딱 잘려 보이는 게 이질감의 뿌리다.
  //   비탈 위에 **절벽과 같은 돌**을 흩어 놓으면 두 재질이 서로 물려 들어간다.
