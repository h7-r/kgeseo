        // 가파른 데는 바위가, 완만한 데는 덤불이 잘 붙는다
        // ★ 높이는 **그 돌이 실제로 놓인 자리**의 땅에서 다시 잰다.
        //   예전에는 갓길 점 q 의 높이에서 치마 매개변수 v 로 보간한 값을 썼다.
        //   그런데 치마는 낙차가 크면 건너뛰고, 지형.js 가 산허리를 채운 뒤로는
        //   그 자리의 진짜 땅이 따로 있다. 그래서 돌이 **최대 5 m 공중에 떴다**
        //   (실측: 길조형.돌 18/121 이 뜸, 최대 +5.03 m).
