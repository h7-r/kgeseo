import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { makeRandom } from "../../src/공용.jsx";
import { 색입히기 } from "./바닥.js";
import { 밑동원점으로 } from "./배치.js";

export const 씬5결 = {
  기둥: "#6B5942",
  기둥어둠: "#3E3327",
  새끼: "#B9A472", // 왼새끼 — 금줄은 왼쪽으로 꼰다
  // 매단 천 — ★ 이 씬에서 **처음으로 원색이 들어온다.**
  //   P04 에서 왜곡이 걷힌다(§0.7). 맵은 내내 누런 잿빛이었으므로,
  //   색이 돌아오는 것 자체가 「해소」의 신호가 된다.
  천흰: "#DCD6C6",
  천붉: "#A83A33",
  천푸: "#3B5F86",
  돌: "#8A8375",
  돌어둠: "#4A463E",
  소반: "#7A6647",
  놋: "#9C8A4E", // 놋그릇 — 자갈밭에서 눈에 드는 유일한 금속빛
};

// ── 조각 만들기 (소품.js·씬2~4 와 같은 규약) ────────────────
const 풀기 = (g) => {
  const n = g.toNonIndexed();
  n.deleteAttribute("uv");
  n.deleteAttribute("uv1");
  g.dispose();
  return n;
};
const 상자 = (w, h, d) => 풀기(new THREE.BoxGeometry(w, h, d));
const 기둥꼴 = (r1, r2, h, 각 = 6) =>
  풀기(new THREE.CylinderGeometry(r1, r2, h, 각, 1));
const 공 = (r, 겹 = 0) => {
  const g = new THREE.IcosahedronGeometry(r, 겹);
  g.deleteAttribute("uv");
  return g.toNonIndexed();
};
const 묶기 = (조각) => {
  const g = mergeGeometries(조각, false);
  조각.forEach((v) => v.dispose());
  return 밑동원점으로(g);
};
const 칠 = (g, 색) => 색입히기(g, new THREE.Color(색));

// ── ① 금줄 ──────────────────────────────────────────────────
//   기둥 둘 사이에 새끼줄을 치고 천을 맨다. 「여기는 그냥 자갈밭이
//   아니다」를 한 물건으로 말한다.
//   [왜 줄이 처져야 하나]  팽팽한 줄은 **빨랫줄**이다. 금줄은 제 무게로
//     가운데가 내려앉는다. 그 처짐이 없으면 아무도 금줄로 안 본다.
//   [왜 천이 세 색인가]  위 `씬5결.천*` 주석 참고 — P04 에서 색이 돌아온다.
//   ※ 줄은 **국소 X 축**을 따라 걸린다. 방향은 자리의 `회전` 이 정한다.
export function 금줄표본들(수 = 2, 시드 = 8501) {
  const 난수 = makeRandom(시드);
  const 천색 = [씬5결.천흰, 씬5결.천붉, 씬5결.천푸];
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 반너비 = 1.35 + 난수() * 0.25; // 높이 1 기준 비율
    const 기둥높 = 1.0;
    const 걸린높 = 0.88; // 줄이 기둥에 걸리는 높이
    const 처짐 = 0.2 + 난수() * 0.05;
    // 기둥 둘 — 바깥으로 조금 벌려 박는다. 곧게 세우면 줄에 끌려 보인다.
    for (const s of [-1, 1]) {
      const 기 = 기둥꼴(0.055, 0.075, 기둥높, 6);
      기.translate(0, 기둥높 / 2, 0);
      기.rotateZ(-s * (0.04 + 난수() * 0.03));
      기.translate(s * 반너비, 0, (난수() - 0.5) * 0.08);
      조각.push(칠(기, 씬5결.기둥));
      // 머리 — 쳐서 박은 자리
      const 머 = 기둥꼴(0.085, 0.06, 0.07, 6);
      머.translate(s * 반너비, 기둥높 - 0.01, 0);
      조각.push(칠(머, 씬5결.기둥어둠));
    }
    // 새끼줄 — 처지게 건다. 포물선을 도막으로 잇는다.
    const 도막 = 14;
    const 높이 = (t) => 걸린높 - Math.sin(Math.PI * t) * 처짐;
    for (let k = 0; k < 도막; k++) {
      const t0 = k / 도막;
      const t1 = (k + 1) / 도막;
      const x0 = -반너비 + 2 * 반너비 * t0;
      const x1 = -반너비 + 2 * 반너비 * t1;
      const y0 = 높이(t0);
      const y1 = 높이(t1);
      const 길 = Math.hypot(x1 - x0, y1 - y0);
      const 줄 = 기둥꼴(0.026, 0.026, 길 * 1.08, 4);
      줄.rotateZ(Math.PI / 2 - Math.atan2(y1 - y0, x1 - x0));
      줄.translate((x0 + x1) / 2, (y0 + y1) / 2, 0);
      조각.push(칠(줄, 씬5결.새끼));
    }
    // 매단 천 — 줄을 따라 다섯 자락. 길이를 들쭉날쭉하게.
    for (let k = 0; k < 5; k++) {
      const t = (k + 0.5) / 5;
      const x = -반너비 + 2 * 반너비 * t;
      const 위 = 높이(t);
      // ★ 자락 길이. 처음엔 0.3~0.56 이라 키 1.6 에서 **0.5~0.9 m** 가 되어
      //   천이 아니라 **색칠한 널빤지**가 걸린 꼴이었다(렌더로 잡았다).
      //   금줄에 매는 천은 한 뼘 남짓이다.
      const 길 = 0.14 + 난수() * 0.11;
      const 색 = 천색[k % 3];
      // 자락 하나를 두 도막으로 — 바람에 조금 꺾인다
      let y = 위;
      let 기울 = (난수() - 0.5) * 0.35;
      for (let j = 0; j < 2; j++) {
        const 조 = 상자(0.045, 길 / 2, 0.01);
        조.rotateZ(기울);
        조.translate(x + Math.sin(기울) * (길 / 4), y - 길 / 4, 0.02);
        조각.push(칠(조, 색));
        y -= 길 / 2;
        기울 += (난수() - 0.5) * 0.45;
      }
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ② 소반 ──────────────────────────────────────────────────
//   누가 와서 차린 상. **작아야 한다** — 큰 제단은 관(官)이 세운 것이고,
//   작은 소반은 사람이 손에 들고 온 것이다. 이 씬은 뒤쪽이다.
//   [모양]  납작한 돌 받침 + 소반 + 놋그릇 둘 + 얹은 돌 하나.
export function 소반표본들(수 = 3, 시드 = 8502) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    // 받침돌 — 자갈밭에 상을 그냥 놓으면 기운다. 납작한 돌을 깔았다.
    const 받침 = 공(0.62, 0);
    받침.scale(1.15, 0.3, 1.0);
    받침.translate(0, 0.1, 0);
    조각.push(칠(받침, 씬5결.돌));
    // 소반 — 상판 + 짧은 다리 넷
    const 상판 = 상자(0.95, 0.075, 0.72);
    상판.translate(0, 0.36, 0);
    조각.push(칠(상판, 씬5결.소반));
    for (const sx of [-1, 1])
      for (const sz of [-1, 1]) {
        const 다 = 상자(0.07, 0.16, 0.07);
        다.translate(sx * 0.38, 0.245, sz * 0.27);
        조각.push(칠(다, 씬5결.소반));
      }
    // 놋그릇 둘 — 하나는 물, 하나는 밥. 이 씬에서 유일한 금속빛이다.
    for (let k = 0; k < 2; k++) {
      const r = 0.16 - k * 0.025;
      const 몸 = 기둥꼴(r * 0.62, r, 0.16, 9);
      몸.translate(-0.2 + k * 0.42, 0.48, (난수() - 0.5) * 0.12);
      조각.push(칠(몸, 씬5결.놋));
      const 전 = 기둥꼴(r * 1.06, r * 1.06, 0.022, 9);
      전.translate(-0.2 + k * 0.42, 0.565, 0);
      조각.push(칠(전, 씬5결.놋));
    }
    // ★ 상 위에 얹은 돌 하나 — 돌무지에 얹는 그 돌이다.
    //   제물이 밥과 물만이면 여느 제사다. 돌이 하나 올라 있어야
    //   「이 자리의 이야기」와 이어진다.
    const 얹은 = 공(0.12, 0);
    얹은.scale(1.1, 0.72, 0.9);
    얹은.rotateY(난수() * 6.3);
    얹은.translate(0.06, 0.44, -0.2);
    조각.push(칠(얹은, 씬5결.돌어둠));
    표본.push(묶기(조각));
  }
  return 표본;
}

