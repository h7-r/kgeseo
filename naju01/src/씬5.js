//   씬 1~3 은 셋, 씬 4 는 둘, 씬 5 는 **하나**다. 조사점이 줄어드는 것이
//   이야기의 모양과 같다 — 흩어진 단서를 모으다가 **한 자리로 모인다.**
//   그래서 이 씬은 여기저기 놓는 씬이 아니라 **한 자리를 만드는** 씬이다.
//   (45, 37) 하나에만 놓는다. 다른 데 흩뿌리면 이 형태가 깨진다.
//
// [★ 왜곡은 여기서 안 건드린다]
//   P04 의 「왜곡 해소」는 `왜곡.js` 가 이미 단계표로 갖고 있고, 화면에서는
//   Leva 의 `왜곡단계` 를 P04 로 놓으면 그대로 걷힌다. 여기서 또 만들면
//   같은 것을 두 군데서 정하게 된다. **이 모듈은 물건만 놓는다.**
//
// [★ 무엇을 놓아야 「돌아온 이야기」인가]
//   이야기가 돌아왔다는 것은 **사람들이 다시 이야기한다**는 뜻이다.
//   그 흔적은 기념비가 아니다 — 비석은 「누가 한 번 새겼다」이지
//   「여럿이 계속 전한다」가 아니다. 여럿이 다녀간 자리는 이렇게 생겼다.
//     ① 돌무지가 **여럿** 쌓인다   — 지나는 사람이 하나씩 얹는다
//     ② 금줄이 쳐진다             — 「여기는 그냥 자갈밭이 아니다」
//     ③ 소반이 차려진다           — 누가 와서 기렸다
//
// [★ 돌탑 표본을 씬 1 것으로 그대로 쓴다]
//   ① 의 돌무지는 **`씬1.js` 의 `돌탑표본들` 을 그대로 부른다.** 새로 안 깎는다.
//   씬 1 에서 아비사가 물가에 쌓은 돌탑이 **하나**였다. 그것과 같은 돌탑이
//   마지막 자리에 **여럿** 서 있는 것이 이 씬의 전부다 — 한 사람이 남긴
//   것을 여럿이 잇는다. 모양이 달라지면 그 이음이 안 보인다.
//   ※ 무리 이름은 `씬5.돌무지` 로 따로 둔다. 표본은 같아도 **편집 열쇠는
//     달라야** 한다 — 씬 1 돌탑을 옮겼다고 이쪽이 따라 움직이면 안 된다.
//
// [색을 진짜로 굽는 이유]  `씬2.js` 머리말과 같다.
// [단위]  도면 좌표 m. 표본은 **높이 1** 짜리다.

