// ═══════════════════════════════════════════════════════════════
//  연결로.js — 무대(코어) 동쪽 끝에서 바깥 들판으로 내려가는 경사로
// ═══════════════════════════════════════════════════════════════
// [왜 필요한가]
//   코어 동쪽 가장자리는 바깥 들판보다 **6.7 m 높다**(실측). 그런데 원경에는
//   「코어 동쪽 끝 → 진부촌」으로 가는 마을길이 이미 그려져 있다(원경.js).
//   그 길이 **허공에서 시작**하고 있었다. 세상이 거기서 뚝 끊겨 보인다.
//   이 경사로가 그 6.7 m 를 이어 준다.
//
// [★ 도면 값이 아니다]
//   `설계` 의 숫자는 §2 통로 제원표에 없는 **새 설계**다. 사용자 요청으로
//   더한 것이므로 §7 0단계 안건이다. 도면의 T1~T4 와 고리 75.1 m 는 손대지
//   않았다 — 이건 고리 밖의 곁가지다.
//
// [경사]
//   도면 규칙은 `기준.최대경사` 이하다. 여기서는 **T3(14.9°)와 T4(26.6°)
//   사이**를 골랐다 — 짐을 지고 오르내리는 마을길이라 T4 만큼 가파르면 안 되고,
//   T3 만큼 눕히면 25 m 를 더 뻗어 원경 논밭을 가로지른다.
//
// [단위]  도면 좌표 m. 지오메트리는 유닛(1 유닛 = 0.3 m)이라 `미터` 를 곱한다.

import * as THREE from "three";
import { 미터, 코어 } from "./공간도면.js";
import { 통로결 } from "./통로.js";
import { 흙벽결 } from "./절벽.js";

// ── 설계값 ──────────────────────────────────────────────────
//   시작 : 코어 **안쪽**에서 시작한다. 가장자리에 딱 붙여 시작하면 코어 땅과
//          맞물리는 자리에 실밥 같은 틈이 남는다(격자가 서로 안 맞는다).
//   끝   : 바깥 들판. 마을길 들머리 (82, 12) 를 지나 그 너머까지 뻗는다.
export const 설계 = {
  // ★ 시작은 **코어 가장자리**다. 예전에는 5 m 안쪽(75)에서 시작했는데,
  //   코어 땅은 가장자리로 갈수록 이미 내려가고 있어서(78 에서 6.7 · 80 에서
  //   5.1) 경사로가 그 위에 **최대 2.0 m 떠 버렸다**(실측). 안쪽 구간은
  //   아예 두지 않고, 가장자리 높이에서 곧바로 시작한다.
  시작: [코어.X[1], 12], // (80, 12) — 코어 가장자리
  끝: [코어.X[1] + 23, 12], // (103, 12) — 바깥 들판
  폭: 3.2, // m — 마을길이라 사람 둘이 지나갈 만큼
  갓길: 1.4, // m — 길 밖으로 흘러내리는 어깨
  바닥깊이: 0.18, // m — 길바닥을 주변보다 이만큼 파 넣는다(다져진 길로 읽힌다)
};

// ── 경사로 한 벌 ────────────────────────────────────────────
//   코어높이(x,z)  무대 안쪽 지면(지표)
//   바깥높이(x,z)  무대 밖 들판 높이
//
//   돌려주는 것
//     지오       그릴 지오메트리(꼭짓점 색 포함)
//     높이(x,z)  그 자리 길바닥 높이 — 판정이 쓴다
//     위에있나(x,z)  길(갓길 포함) 안인가
//     실측       { 길이, 낙차, 경사 } — 계기판·문서에 그대로 쓴다
export function 연결로만들기({ 코어높이, 바깥높이, 칸당 = 0.5 }) {
  const [x0, z0] = 설계.시작;
  const [x1, z1] = 설계.끝;
  const dx = x1 - x0;
  const dz = z1 - z0;
  const 평면길이 = Math.hypot(dx, dz);
  const ux = dx / 평면길이;
  const uz = dz / 평면길이;
  const nx = -uz; // 왼쪽 법선
  const nz = ux;

  const 시작y = 코어높이(x0, z0);
  const 끝y = 바깥높이(x1, z1);
  const 낙차 = 시작y - 끝y;
  const 경사 = (Math.atan2(낙차, 평면길이) * 180) / Math.PI;

  // 길바닥 높이 — 양 끝에서 **기울기가 0** 이라야 땅과 부드럽게 만난다.
  //   곧은 직선으로 이으면 위·아래 이음매에 각이 서서 「판자를 걸쳐 놓은」
  //   꼴이 된다. 부드럽게(smoothstep) 내린다.
  const 부드럽 = (t) => t * t * (3 - 2 * t);
  const 길높이 = (u) => 시작y - 낙차 * 부드럽(THREE.MathUtils.clamp(u, 0, 1));

  // 그 자리가 길 위인가 · 길 위 어디쯤인가
  const 재기 = (x, z) => {
    const px = x - x0;
    const pz = z - z0;
    const u = (px * ux + pz * uz) / 평면길이; // 0(시작) ~ 1(끝)
    const 옆 = px * nx + pz * nz; // 중심선에서 옆으로 몇 m
    return { u, 옆 };
  };
  const 반폭 = 설계.폭 / 2;
  const 위에있나 = (x, z) => {
    const { u, 옆 } = 재기(x, z);
    return u >= -0.02 && u <= 1.02 && Math.abs(옆) <= 반폭 + 설계.갓길;
  };
  // 길바닥 높이 — 파 넣은 깊이는 **양 끝에서 0** 으로 뺀다. 끝까지 파 두면
  //   아랫자락이 들판 밑으로 들어가 덮여 버린다(실측: 마지막 3 m 가 안 보였다).
  const 길바닥 = (u) => {
    const 끝맺음 = Math.max(0, Math.min(1, Math.min(u, 1 - u) / 0.12));
    return 길높이(u) - 설계.바닥깊이 * 끝맺음;
  };
  const 높이 = (x, z) => {
    const { u, 옆 } = 재기(x, z);
    const y = 길바닥(u);
    const 밖 = Math.max(0, Math.abs(옆) - 반폭);
    if (밖 <= 0) return y;
    // 갓길 — 길 밖으로 갈수록 주변 땅으로 녹아든다
    const t = THREE.MathUtils.clamp(밖 / 설계.갓길, 0, 1);
    const 둘레 = u < 0.5 ? 코어높이(x, z) : 바깥높이(x, z);
    return THREE.MathUtils.lerp(y, 둘레, 부드럽(t));
  };

  // ── 지오메트리 ────────────────────────────────────────────
  // [왜 「둑」을 세우나]
  //   예전에는 길 양옆에 1.4 m 짜리 갓길만 달고 끝냈다. 그런데 이 길은
  //   가장자리에서 **5 m 넘게 떠 있다.** 폭 6 m 짜리 널판이 허공을 가로지르는
  //   꼴이라 「판판하다」는 말이 나왔다(사용자 지적).
  //   진짜 산길은 **흙을 쌓아 만든 둑** 위에 난다. 그래서 길 옆으로
  //   **안식각(흙이 저절로 무너지지 않는 각, 33°)** 으로 흘러내리는 비탈을
  //   붙인다. 길이 땅에서 5 m 떠 있으면 비탈은 5/tan33° ≈ 7.7 m 뻗는다.
  //   높이 차가 클수록 넓어지므로 **위쪽은 넓고 아래로 갈수록 좁아진다** —
  //   그게 언덕을 깎아 낸 길의 생김새다.
  const 안식각 = (33 * Math.PI) / 180;
  const 안식 = Math.tan(안식각);
  const 둘레높이 = (x, z) =>
    x <= 코어.X[1] && x >= 코어.X[0] && z >= 코어.Z[0] && z <= 코어.Z[1]
      ? 코어높이(x, z)
      : 바깥높이(x, z);

  // 흙 표면 흔들림 — 자로 잰 비탈은 콘크리트로 보인다
  const 결 = (x, z) =>
    Math.sin(x * 0.7 + z * 0.4) * 0.5 +
    Math.sin(x * 1.9 - z * 1.3 + 2.1) * 0.28 +
    Math.sin(x * 3.7 + z * 2.9 + 4.4) * 0.14;

  // 한 지점(u, 쪽)의 둑 폭 — 길 가장자리와 둘레 땅의 높이 차로 정한다
  const 둑폭 = (u, 쪽) => {
    const [ex, ez] = 중심자리(u, 반폭 * 쪽);
    const 길y = 길바닥(u);
    const 땅y = 둘레높이(ex, ez);
    const w = Math.abs(길y - 땅y) / 안식;
    return THREE.MathUtils.clamp(w, 0.9, 11);
  };

  const 중심자리 = (u, 옆) => {
    const x = x0 + ux * 평면길이 * u + nx * 옆;
    const z = z0 + uz * 평면길이 * u + nz * 옆;
    return [x, z];
  };

  const 칸수 = Math.max(14, Math.round(평면길이 * 칸당));
  const 결가지 = [1, 0.62, 0.28, 0]; // 둑 바깥 → 길 가장자리
  const 위치 = [];
  const 색깔 = [];
  const 다짐 = new THREE.Color(통로결.다짐);
  const 가장 = new THREE.Color(통로결.가장자리);
  const 흙밝 = new THREE.Color(흙벽결.밝음);
  const 흙어 = new THREE.Color(흙벽결.어둠);
  const 임시 = new THREE.Color();

  // 한 단면의 점들 — [옆거리(부호), 높이, 색]
  const 단면 = (i) => {
    const u = i / 칸수;
    const 줄 = [];
    const wL = 둑폭(u, -1);
    const wR = 둑폭(u, +1);
    const 길y = 길바닥(u);
    const 넣기 = (옆, t쪽) => {
      const [x, z] = 중심자리(u, 옆);
      let y;
      let 색;
      const 밖 = Math.abs(옆) - 반폭;
      if (밖 <= 0) {
        // 길바닥 — 한복판이 밟혀 다져지고 살짝 굼실거린다
        y = 길y + 결(x, z) * 0.035;
        const 가 = Math.abs(옆) / 반폭;
        색 = 임시.copy(다짐).lerp(가장, Math.pow(가, 1.7) * 0.8).clone();
      } else {
        // 둑 비탈 — 길 가장자리에서 둘레 땅까지 **오목하게** 흘러내린다.
        //   직선으로 이으면 각재를 덧댄 꼴이다. 아래로 갈수록 눕혀야
        //   흙이 쌓여 굳은 것처럼 보인다.
        const w = 옆 < 0 ? wL : wR;
        const t = THREE.MathUtils.clamp(밖 / w, 0, 1);
        const 땅y = 둘레높이(x, z);
        const 눕힘 = 1 - Math.pow(1 - t, 2.1);
        y = THREE.MathUtils.lerp(길y, 땅y, 눕힘) + 결(x, z) * 0.16 * (1 - t);
        // 파인 데는 어둡다 — 비탈 한복판이 가장 어둡고 아래로 갈수록 땅빛
        색 = 임시
          .copy(흙어)
          .lerp(흙밝, 0.35 + Math.pow(t, 0.8) * 0.55)
          .clone();
      }
      줄.push({ x, y, z, 색, t쪽 });
    };
    for (let k = 0; k < 결가지.length; k++)
      넣기(-(반폭 + wL * 결가지[k]), -1);
    넣기(0, 0);
    for (let k = 결가지.length - 1; k >= 0; k--)
      넣기(반폭 + wR * 결가지[k], 1);
    return 줄;
  };

  const 밀기 = (p) => {
    위치.push(p.x * 미터, p.y * 미터, p.z * 미터);
    색깔.push(p.색.r, p.색.g, p.색.b);
  };

  let 앞단면 = 단면(0);
  for (let i = 0; i < 칸수; i++) {
    const 뒤단면 = 단면(i + 1);
    for (let j = 0; j < 앞단면.length - 1; j++) {
      const a = 앞단면[j];
      const b = 뒤단면[j];
      const c2 = 앞단면[j + 1];
      const d2 = 뒤단면[j + 1];
      // ★ 감는 순서. 예전에는 a→b→c 로 감아 **법선이 전부 아래를 봤다**
      //   (실측: 288 개 모두). 해를 등지니 통째로 검게 나왔다.
      밀기(a); 밀기(c2); 밀기(b);
      밀기(b); 밀기(c2); 밀기(d2);
    }
    앞단면 = 뒤단면;
  }

  const 지오 = new THREE.BufferGeometry();
  지오.setAttribute("position", new THREE.Float32BufferAttribute(위치, 3));
  지오.setAttribute("color", new THREE.Float32BufferAttribute(색깔, 3));
  지오.computeVertexNormals();

  return {
    지오,
    높이,
    위에있나,
    실측: {
      길이: Math.hypot(평면길이, 낙차),
      평면길이,
      낙차,
      경사,
      시작y,
      끝y,
    },
  };
}
