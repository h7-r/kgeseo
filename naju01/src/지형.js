const 도 = 180 / Math.PI;

// ── 통로 실측 ───────────────────────────────────────────────
//   도면에 적힌 길이·경사가 맞는지 좌표에서 다시 계산한다.
//   여기서 나온 값이 도면 값과 다르면 계기판이 빨갛게 표시한다(§8 검증 항목).
export function 통로측정(t) {
  // ※ 이름을 '조각'으로 둔다. 도면의 `구간`("Z1 → Z2" 문자열)과 합쳐지므로
  //   여기서 `구간` 을 쓰면 그 문자열을 덮어써 버린다(라벨이 객체를 그리려다 죽는다).
  const 조각 = [];
  let 누적 = 0;
  for (let i = 0; i < t.점.length - 1; i++) {
    const [x1, z1] = t.점[i];
    const [x2, z2] = t.점[i + 1];
    const d = Math.hypot(x2 - x1, z2 - z1);
    조각.push({ x1, z1, x2, z2, d, 시작누적: 누적 });
    누적 += d;
  }
  const 평면길이 = 누적;
  const 낙차 = t.끝고도 - t.시작고도;
  return {
    조각,
    평면길이,
    실길이: Math.hypot(평면길이, 낙차), // 실제로 걷는 거리(경사면 포함)
    경사: Math.atan2(Math.abs(낙차), 평면길이) * 도,
    낙차,
  };
}

// ── 점 ↔ 선분 ───────────────────────────────────────────────
function 선분에투영(px, pz, s) {
  const dx = s.x2 - s.x1;
  const dz = s.z2 - s.z1;
  const len2 = dx * dx + dz * dz || 1;
  let t = ((px - s.x1) * dx + (pz - s.z1) * dz) / len2;
  t = Math.max(0, Math.min(1, t));
  const cx = s.x1 + dx * t;
  const cz = s.z1 + dz * t;
  return { 거리: Math.hypot(px - cx, pz - cz), 호길이: s.시작누적 + s.d * t };
}

// ── 중심선을 잘게 뽑는다 ────────────────────────────────────
//   도면 꼭짓점 사이를 `간격` 마다 채우고, 각 점의 진행 방향을 이웃과 평균 내어
//   모서리를 둥글린다. 고도는 호 길이에 비례해 올린다(지형.js 와 같은 규칙).
export function 중심선뽑기(t, 간격 = 0.4, 다듬기 = 2) {
  const 점들 = [];
  for (const s of t.조각) {
    const n = Math.max(1, Math.round(s.d / 간격));
    for (let i = 0; i < n; i++) {
      const f = i / n;
      점들.push({
        x: s.x1 + (s.x2 - s.x1) * f,
        z: s.z1 + (s.z2 - s.z1) * f,
        호: s.시작누적 + s.d * f,
      });
    }
  }
  const 끝 = t.조각[t.조각.length - 1];
  점들.push({ x: 끝.x2, z: 끝.z2, 호: t.평면길이 });

  // 방향 — 앞뒤 점을 이어 잡고, 이웃과 평균 내어 모서리를 둥글린다
  const 방향 = 점들.map((_, i) => {
    const a = 점들[Math.max(0, i - 1)];
    const b = 점들[Math.min(점들.length - 1, i + 1)];
    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const L = Math.hypot(dx, dz) || 1;
    return { x: dx / L, z: dz / L };
  });
  for (let 회 = 0; 회 < 다듬기; 회++) {
    for (let i = 1; i < 방향.length - 1; i++) {
      const dx = (방향[i - 1].x + 방향[i].x * 2 + 방향[i + 1].x) / 4;
      const dz = (방향[i - 1].z + 방향[i].z * 2 + 방향[i + 1].z) / 4;
      const L = Math.hypot(dx, dz) || 1;
      방향[i] = { x: dx / L, z: dz / L };
    }
  }

  return 점들.map((p, i) => ({
    ...p,
    y: t.시작고도 + t.낙차 * (p.호 / t.평면길이),
    // 왼쪽 법선(XZ 평면) — 진행 방향을 90° 돌린다
    nx: -방향[i].z,
    nz: 방향[i].x,
  }));
}

const 안에 = (v, [a, b]) => v >= a && v <= b;

// 점에서 축 정렬 상자까지의 수평 거리(안에 있으면 0)
const 상자거리 = (px, pz, X, Z) => {
  const dx = Math.max(X[0] - px, 0, px - X[1]);
  const dz = Math.max(Z[0] - pz, 0, pz - Z[1]);
  return Math.hypot(dx, dz);
};

// ═══════════════════════════════════════════════════════════════
//  지형 한 벌 만들기
// ═══════════════════════════════════════════════════════════════
//   절벽높이  = Z3 의 고도이자 절벽 낙차. 이것 하나가 아래를 전부 끌고 간다.
//   차단물배율 = 도면에 없는 차단물 높이를 통째로 키우고 줄인다(§4 눈으로 맞출 값).
export function 지형만들기({
  절벽높이 = 절벽원본.높이,
  차단물배율 = 1,
  갓길 = 갓길기본,
} = {}) {
  // ① 구역 — Z3 의 고도만 바뀐다. 나머지는 도면 그대로.
  const 구역 = 구역원본.map((z) =>
    z.코드 === "Z3"
      ? {
          ...z,
          고도: 절벽높이,
          표기: `24 × 18 m · EL +${절벽높이}`,
        }
      : z,
  );
  const 구역고도 = Object.fromEntries(구역.map((z) => [z.코드, z.고도]));

  // ② 통로 — Z3 에 닿는 두 통로의 끝 고도가 따라 움직인다.
  //    T3 는 Z3 로 올라가고(끝), T4 는 Z3 에서 내려온다(시작).
  const 통로 = 통로원본.map((t) => {
    if (t.코드 === "T3") return { ...t, 끝고도: 절벽높이 };
    if (t.코드 === "T4") return { ...t, 시작고도: 절벽높이 };
    return t;
  });
  //   ※ 판정도 그림도 **잘게 뽑아 다듬은 중심선**을 쓴다.
  //     도면 꼭짓점(직각으로 꺾임)을 그대로 쓰면, 꺾이는 데서 두 선분의
  //     호 길이가 달라 높이가 튄다 — 코너 안쪽에서 한 걸음에 0.5 m 가 꺼졌다.
  const 통로실측 = 통로.map((t) => {
    const 잰 = { ...t, ...통로측정(t) };
    const 선 = 중심선뽑기(잰);
    // 다듬은 선의 이웃 점끼리 이은 잔 조각 — 거의 일직선이라 이음매가 안 튄다
    const 세밀 = [];
    let 누적 = 0;
    for (let i = 0; i < 선.length - 1; i++) {
      const a = 선[i];
      const b = 선[i + 1];
      const d = Math.hypot(b.x - a.x, b.z - a.z);
      if (d < 1e-6) continue;
      세밀.push({ x1: a.x, z1: a.z, x2: b.x, z2: b.z, d, 시작누적: 누적 });
      누적 += d;
    }
    return { ...잰, 선, 세밀, 세밀길이: 누적 || 잰.평면길이 };
  });

  // ③ 차단물 — `바닥구역` 이 적힌 것은 그 구역 고도 위에 선다.
  const 차단물 = 차단물원본.map((b) => ({
    ...b,
    높이: b.높이 * 차단물배율,
    바닥: b.바닥구역 ? 구역고도[b.바닥구역] : (b.바닥 ?? 0),
  }));

  // ④ 절벽 — 배터 띠(Z 26~30)의 폭은 그대로라, 높이를 올리면 면이 더 서게 된다.
  const 배터폭 = 절벽원본.Z아래 - 절벽원본.Z위;
  const 절벽 = {
    ...절벽원본,
    높이: 절벽높이,
    실각: Math.atan2(절벽높이, 배터폭) * 도,
  };

  // 고리 1바퀴 — 도면의 75.1 m 와 맞는지 본다(수평 합)
  const 고리실측 = 통로실측.reduce((s, t) => s + t.평면길이, 0);
  // 경사면까지 따진 '실제로 다리가 가는' 거리
  const 실보행 = 통로실측.reduce((s, t) => s + t.실길이, 0);

  // ── 통로 위인가? 맞으면 그 자리의 고도를 돌려준다 ──────────
  //   ※ 길바닥(반폭)뿐 아니라 **갓길까지** 밟을 수 있어야 한다.
  //     길처럼 보이는 자리에서 꺼지면 그건 구멍이다(공간도면.js `갓길기본` 주석).
  //     갓길 위에서는 그림과 똑같은 만큼 내려앉은 높이를 돌려준다.
  function 통로높이(px, pz) {
    const 갓끝 = 갓길.뻗음 * 갓길.폭;
    let 최선거리 = Infinity;
    let 최선코드 = null;
    let 최선갓길 = false;
    let 무게합 = 0;
    let 높이합 = 0;
    let 최선y = 0;

    for (const t of 통로실측) {
      const 반폭 = t.폭 / 2;
      const 한계 = 반폭 + 갓끝;
      for (const s of t.세밀) {
        const { 거리, 호길이 } = 선분에투영(px, pz, s);
        if (거리 > 한계) continue;
        const 밖 = Math.max(0, (거리 - 반폭) / Math.max(1e-6, 갓길.폭));
        const 내림 = 갓길.낙차 * Math.pow(밖 / Math.max(1e-6, 갓길.뻗음), 1.5);
        const y = t.시작고도 + t.낙차 * (호길이 / t.세밀길이) - 내림;
        // ★ 가장 가까운 선분 하나만 고르면 **코너에서 높이가 튄다.**
        //   길이 꺾이는 데서는 두 선분이 거의 같은 거리에 있는데 호 길이는
        //   서로 달라서, 어느 쪽이 이기느냐에 따라 높이가 갑자기 바뀐다.
        //   실제로 코너 안쪽에서 **한 걸음에 0.7 m 가 꺼졌다**(걷기 시늉으로 확인).
        //   그래서 가까운 것에 더 무게를 주어 **섞는다.** 코너에서만 값이 섞이고
        //   곧은 구간에서는 어차피 한 선분만 걸리므로 결과가 같다.
        //   무게는 밴드 끝에서 **정확히 0** 이 돼야 한다. 안 그러면 선분이
        //   사정거리를 벗어나는 순간 기여가 뚝 끊겨 거기서 또 계단이 생긴다.
        //   ★ 나누는 값을 `한계` 가 아니라 `한계 + 여유` 로 둔다.
        //     그림(통로.js)의 치마 바깥 끝은 판정 밴드 끝과 **정확히 같은 거리**에
        //     찍힌다. `한계` 로 나누면 거기서 f 가 딱 0 이 되고, 그 자리에
        //     걸리는 선분이 그것 하나뿐이면 무게합이 0 이 되어 **0/0 = NaN** 이
        //     나왔다. NaN 좌표가 치마·장식 지오메트리로 그대로 흘러 들어가
        //     `computeBoundingSphere(): Computed radius is NaN` 이 떴다(실측 확인).
        const f = Math.max(0, 1 - 거리 / (한계 + 0.05));
        const w = (f * f * f) / (거리 * 거리 + 0.02);
        무게합 += w;
        높이합 += y * w;
        if (거리 < 최선거리) {
          최선거리 = 거리;
          최선코드 = t.코드;
          최선갓길 = 거리 > 반폭;
          최선y = y;
        }
      }
    }
    if (!최선코드) return null;
    // 무게가 그래도 0 이면(부동소수 끝자리) 가장 가까운 선분 값을 그대로 쓴다.
    // **어떤 경우에도 NaN 을 밖으로 내보내지 않는다.**
    const y합 = 무게합 > 1e-12 ? 높이합 / 무게합 : 최선y;
    return {
      거리: 최선거리,
      통로: 최선코드,
      갓길: 최선갓길,
      y: Number.isFinite(y합) ? y합 : 최선y,
    };
  }

  // ── 산허리 ────────────────────────────────────────────────
  // [왜 필요했나 — '온통 구멍'의 진짜 정체]
  //   도면은 구역 4 개와 통로 4 개의 높이만 말한다. 그 밖은 전부 EL 0 이었다.
  //   그런데 T3 는 +13 m, T4 는 +14 m 를 지난다. 즉 **두 비탈길은 평지 위
  //   13 m 상공에 뜬 리본**이었다. 갓길에서 한 걸음만 벗어나면 13 m 아래
  //   허공으로 떨어지고, 떨어진 자리는 리본 **밑**이라 위가 막힌 회색 공간이다.
  //   — 사용자가 말한 「구멍을 밟으면 비탈길 속 공간에 갇힌다」가 이것이다.
  //   (실측: T4 위험한 구멍 105/3278, 최대 낙차 13.7 m)
  //
  // [고침] 실제 산길은 산허리를 깎아 낸 것이지 공중에 건 다리가 아니다.
  //   도면이 말하지 않은 자리는 **가까운 설계면에서 일정 기울기로 흘러내리는
  //   흙더미**로 채운다.
  //     올림 = max( 높은 설계면 고도 − 거리 × 기울기 )   ← 산이 솟는다
  //     내림 = min( 낮은 설계면 고도 + 거리 × 기울기 )   ← 골로 내려간다
  //     지대 = clamp(min(올림, 내림), 0, …)
  //   원뿔들의 최대·최소라서 **어느 설계면과도 그 경계에서 정확히 만난다.**
  //   면끼리 어긋날 수가 없으므로 여기서 이음매가 새로 생기지 않는다.
  //
  // [절벽은 채우지 않는다] 도면의 배터 띠(Z 26~30)는 떨어지라고 만든 면이다.
  //   여기는 아래 `지면` 이 따로 처리한다.
  const 산기울기 = 0.62; // ≈ 32° — 굴러떨어지지 않고 내려올 수 있는 자연 사면
  // 골로 내려가는 쪽은 **더 급하게** 둔다. 여기도 32° 로 깎으면, EL 0 테라스에서
  // 8 m 떨어진 자리가 5 m 로 눌려 **비탈길을 받치던 산허리 자체가 사라진다**
  // (실측: T4 갓길 바로 옆이 11 m → 5.2 m 로 파여 6 m 짜리 구멍이 남았다).
  // 테라스 가장자리는 원래 깎아지른 둔덕이므로 급한 편이 도면에도 맞다.
  const 골기울기 = 1.6; // ≈ 58° — 테라스에 바짝 붙어서만 내려앉는 짧은 둔덕
  const 산사정 = 24; // 이보다 멀면 흙더미가 닿지 않는다

  // [왜 굴곡을 여기 두는가]
  //   원뿔의 최대·최소만으로 만든 산허리는 **매끈한 깔때기**다. 스샷으로 보면
  //   골프장 그린처럼 보인다. 실제 산허리는 능선과 골이 있다.
  //   그런데 굴곡을 지표.js(그림 전용)에 넣으면 **눈과 발이 어긋난다** —
  //   지표의 요철을 ±0.12 m 로 묶어 둔 이유가 그것이다.
  //   그래서 굴곡을 **판정인 여기**에 넣는다. 그림도 이 값을 보므로 둘이 같다.
  //   ※ 설계면(구역·통로) 가까이에서는 0 으로 사그라든다.
  //     도면이 말한 높이를 흔들면 그게 곧 이음매고 구멍이다.
  const 굴곡소음 = 소음만들기(31337);
  const 굴곡 = (px, pz, 최근) => {
    const 세기 = Math.min(1, Math.max(0, (최근 - 0.6) / 3.4));
    if (세기 <= 0) return 0;
    return (
      (굴곡소음(px * 0.055, pz * 0.055) * 1.0 +
        굴곡소음(px * 0.14 + 40, pz * 0.14 + 40) * 0.35) *
      1.9 *
      세기
    );
  };

  const 낮은면 = 구역.filter((z) => z.고도 <= 0);

  function 지대(px, pz) {
    let 올림 = 0;
    let 최근 = Infinity;
    for (const z of 구역) {
      const d = 상자거리(px, pz, z.X, z.Z);
      if (d < 최근) 최근 = d;
      if (z.고도 <= 0 || d > 산사정) continue;
      const h = z.고도 - d * 산기울기;
      if (h > 올림) 올림 = h;
    }
    // 통로는 성긴 도면 조각으로 충분하다 — 흙더미는 대세만 맞으면 된다
    for (const t of 통로실측) {
      const 한계 = t.폭 / 2 + 갓길.뻗음 * 갓길.폭;
      for (const s of t.조각) {
        const { 거리, 호길이 } = 선분에투영(px, pz, s);
        const d = Math.max(0, 거리 - 한계);
        if (d < 최근) 최근 = d;
        if (d > 산사정) continue;
        const y =
          t.시작고도 + t.낙차 * (호길이 / t.평면길이) - 갓길.낙차;
        const h = y - d * 산기울기;
        if (h > 올림) 올림 = h;
      }
    }
    const 결 = 굴곡(px, pz, 최근);
    if (올림 <= 0) return Math.max(0, 결);

    // 낮은 설계면(EL 0 테라스·강)이 옆에 있으면 그리로 흘러내려야 한다.
    let 내림 = Infinity;
    for (const z of 낮은면) {
      const d = 상자거리(px, pz, z.X, z.Z);
      const h = z.고도 + d * 골기울기;
      if (h < 내림) 내림 = h;
    }
    // 강도 낮은 면이다 — 물가로 갈수록 땅이 내려앉아야 둑이 안 선다
    내림 = Math.min(내림, Math.max(0, 강.Z시작 - pz) * 골기울기);
    return Math.max(0, Math.min(올림, 내림) + 결);
  }

  // ── 통로 둑 ───────────────────────────────────────────────
  //   T3 는 Z4(EL +8) **한가운데서 시작해** 올라가고, T4 는 아직 +4.7 m 인
  //   채로 Z1 안으로 들어온다. 길만 리본으로 띄우면 갓길 옆이 그대로 절벽이다
  //   (실측: Z1 경계에서 4.2 m 단차). 현실의 산길 초입은 흙을 쌓아 둑을 만든다.
  //
  //   [어떤 조각이 둑을 쌓는가] 아무 조각이나 쌓게 두면 **Z3 위(+14 m)를 지나는
  //   T4 가 Z2 자갈밭에 9 m 짜리 흙산을 부어 버린다.** 그래서 조건을 건다.
  //     · 지금 구역 안이면  → 그 구역 안을 지나는 조각만        (남의 땅에 못 붓는다)
  //     · 미설계 자리면      → 낮은 구역(EL ≤ 0) 안을 지나는 조각만
  //                            (높은 대지의 길은 허공으로 둑을 뻗지 않는다)
  //   같은 함수를 구역 안팎 **양쪽에서 똑같이** 부르므로 경계에서 값이 어긋날 수 없다.
  const 둑기울기 = 1.4; // ≈ 55° — 쌓아 올린 둑이라 자연 사면보다 급하다
  //   ※ 구역을 2 m 넉넉히 본다. T4 의 스위치백 꼭짓점(21.5, 29)은 Z1 경계에서
  //     겨우 1 m 북쪽인데 아직 +5.8 m 다. 딱 잘라 「Z1 밖」이라고 하면 둑이 안
  //     서고, 꼭짓점 바깥에 3.5 m 짜리 턱이 남는다(실측). 길이 테라스에 거의
  //     닿았으면 흙도 거기까지 쌓인 것으로 본다.
  const 둑여유 = 2;
  const 구역찾기 = (x, z) =>
    구역.find(
      (v) =>
        x >= v.X[0] - 둑여유 && x <= v.X[1] + 둑여유 &&
        z >= v.Z[0] - 둑여유 && z <= v.Z[1] + 둑여유,
    ) ?? null;

  function 통로둑(px, pz, 기준구역) {
    let h = 0;
    for (const t of 통로실측) {
      const 한계 = t.폭 / 2 + 갓길.뻗음 * 갓길.폭;
      for (const s of t.조각) {
        const { 거리, 호길이 } = 선분에투영(px, pz, s);
        const d = Math.max(0, 거리 - 한계);
        if (d > 12) continue;
        const f = Math.max(0, Math.min(1, (호길이 - s.시작누적) / s.d));
        const cx = s.x1 + (s.x2 - s.x1) * f;
        const cz = s.z1 + (s.z2 - s.z1) * f;
        const zc = 구역찾기(cx, cz);
        if (!zc) continue;
        if (기준구역 ? zc.코드 !== 기준구역.코드 : zc.고도 > 0) continue;
        const y = t.시작고도 + t.낙차 * (호길이 / t.평면길이) - 갓길.낙차;
        const v = y - d * 둑기울기;
        if (v > h) h = v;
      }
    }
    return h;
  }

  // ── 이 자리의 바닥 ────────────────────────────────────────
  //   ① 통로가 최우선이다. 통로는 층과 층을 잇는 '다리'라서,
  //      구역 경계 안쪽으로 조금 들어가 있어도 통로 높이를 따라야 이음매가 안 튄다.
  //   ② 다음이 구역(평지).
  //   ③ 어느 쪽도 아니면 EL 0 의 '미설계 평지'다.
  //      Z3 남쪽 절벽 띠(Z 26~30)와 영산강도 여기에 해당한다 —
  //      즉 절벽에서 발을 헛디디면 그 높이만큼 Z2 바닥으로 떨어진다(§6 ②).
  // ── 블렌더가 구운 높이표(있으면) ──────────────────────────
  //   ★ **y 만 덮어쓴다.** 구역·통로·갓길·낙하·물 깃발은 아래 해석식이
  //     그대로 낸다 — 그것들은 높이가 아니라 `공간도면.js` 의 사각형·
  //     폴리라인 판정이라 표와 무관하고, 씬 진행·퍼즐이 거기 걸려 있다.
  //   표를 안 끼우면(또는 못 읽으면) 예전과 **한 글자도 다르지 않게** 돈다.
  //   되돌리려면 `높이표설정(null)` 한 줄이면 된다.
  let 높이표 = null;
  function 높이표설정(v) {
    높이표 = v ?? null;
  }
  function 지면(px, pz) {
    const 값 = 지면해석(px, pz);
    if (높이표) {
      const y = 높이표.높이(px, pz);
      // null 이면 코어 밖이다 — 거기는 연결로·원경 들판이 받친다.
      if (y !== null) return { ...값, y };
    }
    return 값;
  }

  function 지면해석(px, pz) {
    const t = 통로높이(px, pz);
    if (t)
      return {
        y: t.y,
        구역: null,
        통로: t.통로,
        갓길: !!t.갓길,
        낙하: false,
        물: false,
      };

    for (const z of 구역) {
      if (안에(px, z.X) && 안에(pz, z.Z))
        return {
          y: Math.max(z.고도, 통로둑(px, pz, z)),
          구역: z.코드,
          통로: null,
          낙하: false,
          물: false,
        };
    }

    // ③ 절벽 배터 띠 — 도면이 해치로 그린 4 m 면. 여기는 채우지 않는다.
    //    예전에는 y = 0 을 돌려줬다. 그러면 Z3 가장자리에서 **한 걸음에 14 m**
    //    가 사라져 발밑이 사라지는 대신, 그림의 배터 면은 비스듬히 서 있어서
    //    눈과 발이 어긋났다. 이제 그림과 같은 면을 돌려주고 `낙하` 로만 표시한다
    //    — 서지는 못하지만 **면을 따라 미끄러져 내려간다**(§6 ②).
    if (안에(px, 절벽.X) && pz >= 절벽.Z위 && pz <= 절벽.Z아래) {
      // ★ 띠 안이라고 다 벼랑이 아니다. 도면의 직사각형을 그대로 세우면
      //   자로 그은 옹벽이 된다(모티브 사진과 가장 크게 어긋난 지점).
      //   `절벽윤곽` 이 x 마다 마루·발치·높이를 흔든다 — **그림과 같은 함수**다.
      const { 마루, 발치, 높이: 벽높이 } = 절벽윤곽(px);
      if (pz <= 마루) {
        // 마루보다 북쪽은 아직 **어깨(선반)** 다 — 여기는 설 수 있다.
        //   물러난 마루 덕에 벼랑 끝이 들쭉날쭉해진다.
        return { y: 벽높이, 구역: null, 통로: null, 낙하: false, 물: false };
      }
      if (pz >= 발치) {
        // 발치보다 남쪽은 이미 자갈밭 높이 — 바위 아래 평지다
        return { y: 0, 구역: null, 통로: null, 낙하: false, 물: false };
      }
      const f = (pz - 마루) / Math.max(0.05, 발치 - 마루);
      return {
        y: 벽높이 * (1 - f),
        구역: null,
        통로: null,
        낙하: true, // 여기가 진짜 벼랑면이다
        물: false,
      };
    }

    // ③-b 무대 밖 연결로 — 코어 동쪽에서 들판으로 내려가는 경사로.
    //   ※ **코어 밖에서만** 본다. 안쪽은 한 줄도 안 건드리므로 도면 대조와
    //     실측 하네스(구멍·어긋남·고리 75.1 m)에 아무 영향이 없다.
    //   ※ 기본은 `null` 이다. 씬이 `연결로설정()` 으로 끼워 줘야 살아난다.
    if (
      연결로 &&
      (px < 코어.X[0] || px > 코어.X[1] || pz < 코어.Z[0] || pz > 코어.Z[1]) &&
      연결로.위에있나(px, pz)
    ) {
      return {
        y: 연결로.높이(px, pz),
        구역: null,
        통로: "연결로",
        낙하: false,
        물: false,
      };
    }

    // ④ 그 밖 — 도면이 말하지 않은 자리는 산허리가 받친다.
    const 물 = pz >= 강.Z시작;
    // ★ 강바닥은 물가에서부터 **내려간다.**
    //   예전에는 물속도 y = 0 이라 강바닥이 수면과 같은 높이였다. 수면이
    //   ±0.09 로 물결치니 바닥이 곳곳에서 물 위로 비쳐, 강이 **젖은 자갈밭**
    //   처럼 보였다(나룻배가 물에 뜬 게 아니라 자갈 위에 얹힌 것처럼 보였다).
    //   물가에서 0 으로 시작해 완만히 깊어지면 물이 물로 읽힌다.
    const 바닥깊이 = 물
      ? -Math.min(2.6, (pz - 강.Z시작) * 0.55)
      : 0;
    // 코어 밖은 원경 들판이 받친다(끼워 줬을 때만)
    const 코어밖 =
      px < 코어.X[0] || px > 코어.X[1] || pz < 코어.Z[0] || pz > 코어.Z[1];
    if (바깥지면 && 코어밖 && !물)
      return { y: 바깥지면(px, pz), 구역: null, 통로: null, 낙하: false, 물: false };
    return {
      y: 물 ? 바닥깊이 : Math.max(지대(px, pz), 통로둑(px, pz, null)),
      구역: null,
      통로: null,
      낙하: false,
      물,
    };
  }

  // 무대 밖 연결로 — 씬이 만들어서 끼워 준다(지형은 도면만 안다).
  //   지형은 도면에서 나오는데 이 경사로는 도면 밖 설계라, 지형이 직접
  //   만들지 않고 **밖에서 받는다.** 안 끼우면 없는 것과 같다.
  let 연결로 = null;
  function 연결로설정(v) {
    연결로 = v ?? null;
  }
  // 무대 밖 지면 — 원경 들판 높이 함수. 안 끼우면 예전대로 `지대` 가 받친다.
  //   ※ 안 끼우면 코어 밖이 전부 y = 0 이라, 연결로로 내려가 봐야 들판보다
  //     0.3 m 뜬 **보이지 않는 평면** 위를 걷게 된다(실측으로 확인).
  let 바깥지면 = null;
  function 바깥지면설정(v) {
    바깥지면 = v ?? null;
  }

  // ── 막히는 곳 ─────────────────────────────────────────────
  //   시야 차단물은 실제로 못 지나간다. 덩어리가 차지하는 고도 구간
  //   (`발` ~ `바닥 + 높이`) 안에 발밑이 있을 때만 막는다.
  //   ※ `치운것` 에 든 코드는 건너뛴다 — 씬이 끝나 치워진 차단물이다.
  //     **그리기와 판정이 반드시 같이 열려야 한다.** 한쪽만 열면 보이는데
  //     못 지나가거나(투명 벽), 없는데 뚫려 보인다.
  const 치운것 = new Set();
  function 막힘(px, pz, y = 0, 반경 = 0.3) {
    for (const b of 차단물) {
      if (치운것.has(b.코드)) continue;
      const 발 = b.발 ?? 0;
      const 머리 = b.바닥 + b.높이;
      if (y < 발 - 1.5 || y > 머리) continue;
      if (
        px > b.X[0] - 반경 &&
        px < b.X[1] + 반경 &&
        pz > b.Z[0] - 반경 &&
        pz < b.Z[1] + 반경
      )
        return b.코드;
    }
    return null;
  }

  // ── 계기판이 쓸 이름표 ────────────────────────────────────
  const 구역이름 = Object.fromEntries(구역.map((z) => [z.코드, z.이름]));
  const 통로이름 = Object.fromEntries(통로.map((t) => [t.코드, t.이름]));

  function 자리이름(px, pz) {
    const g = 지면(px, pz);
    if (g.통로) return `${g.통로} ${통로이름[g.통로] ?? ""}`.trim();
    if (g.구역) return `${g.구역} ${구역이름[g.구역] ?? ""}`.trim();
    if (g.물) return 강.이름 ?? "영산강";
    if (g.낙하) return `${절벽.이름 ?? "절벽"} 면`;
    return "미설계";
  }

  return {
    구역,
    통로실측,
    차단물,
    치운것, // 씬이 끝나 치워진 차단물 코드 (그리는 쪽과 같은 객체를 본다)
    연결로설정,
    바깥지면설정,
    높이표설정,
    연결로있나: () => !!연결로,
    연결로위에있나: (x, z) => !!연결로 && 연결로.위에있나(x, z),
    절벽,
    고리실측,
    실보행,
    지면,
    막힘,
    자리이름,
  };
}

