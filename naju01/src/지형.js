//  지형.js — "이 자리의 바닥 높이는 몇 m 인가"
// ═══════════════════════════════════════════════════════════════
// [왜 필요한가]
//   기차·로비는 바닥이 하나였다(공용.jsx 의 use이동 은 눈높이 하나만 본다).
//   NAJU-01 은 EL 0 · +8 · +14 세 층이 하나의 지형으로 이어져 있어서,
//   "지금 서 있는 자리의 바닥"을 좌표로 물어볼 수 있어야 한다.
//
// [왜 상수가 아니라 '만드는 함수'인가]
//   문서 §9 가 「아직 확정되지 않은 값」이라고 적어 둔 것들 — 특히 절벽 높이 —
//   은 걸어 보면서 돌려 봐야 정해진다. 그런데 절벽 높이는 곧 **Z3 의 고도**라,
//   돌리면 T3(→Z3)·T4(Z3→)의 경사와 그 위에 선 차단물까지 전부 따라 움직인다.
//   한 번 계산해 둔 상수로는 이 연동을 못 만든다.
//   → `지형만들기(설정)` 이 그 설정에 맞는 지형 한 벌을 통째로 만들어 준다.
//     그림·이동·충돌·계기판이 **같은 한 벌**을 보므로 여전히 단일 진실원이다.
//
// [단위]
//   이 파일의 입출력은 전부 **미터**다. 유닛 변환은 부르는 쪽에서 한다.
//   (도면과 같은 숫자로 디버깅하기 위해서다)

