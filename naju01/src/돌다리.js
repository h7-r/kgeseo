// ═══════════════════════════════════════════════════════════════
//  돌다리.js — 절벽 아래 물가에서 강 건너 택촌으로 (징검다리)
// ═══════════════════════════════════════════════════════════════
// [왜 생겼나]
//   택촌은 강 건너에 있고(`F-02` 「영산강을 사이에 두고 진부촌과 택촌」),
//   지금까지 건너가는 길은 **배뿐**이었다. 그런데 ④ Scene 01 의 필수 장소
//   요소가 「진부촌 방향과 택촌 방향을 **구분할 수 있어야 한다**」이고,
//   씬 2 부터는 양쪽을 오가는 증언이 붙는다. 두 마을이 **이어져 있다**는 것이
//   화면에 서야 한다.
//
// [왜 이 생김새인가 — 한 번 고쳤다]
//   처음에는 **진천 농다리**로 만들었다. 납작한 돌을 쌓아 교각을 세우고 그
//   사이에 돌 상판을 걸치는 형식이다. 32.5 m 를 감당하는 우리 형식이라고
//   봤는데, 사용자가 사진으로 원하는 것을 보여 줬다 — **징검다리**다.
//   둘은 다른 물건이다.
//     농다리   교각을 쌓아 **다리 바닥을 물 위에 띄운다** → 구조물로 읽힌다
//     징검다리 큰 돌을 **물바닥에 그냥 놓는다**      → 강을 건너는 **자국**
//   징검다리는 다리라기보다 **건널 수 있게 해 둔 자리**다. 난간도 바닥도
//   없고, 발 디딜 돌만 물 위로 한 뼘 나온다. 물이 불면 잠긴다.
//   이 장면에는 이쪽이 맞다 — 두 마을은 이어져 있지만, 그 이음은 **약하다.**
//
// [사진에서 읽은 것]
//   · 돌은 **낱개**다. 서로 안 닿고 한 뼘씩 떨어져 있다
//   · 크기가 제각각이고 **납작**하다. 윗면이 평평해야 디딜 수 있다
//   · 줄이 **곧지 않다.** 물살과 바닥을 따라 좌우로 굽는다
//   · 가끔 **두 장이 나란히** 놓여 폭이 넓어진다(비켜 서는 자리)
//   · 물 위로 나온 높이가 낮다 — 한 뼘 남짓
//
// [★ 걷는 판정은 아직 없다 — 반드시 알고 써야 한다]
//   `땅소품.js` 와 같다. 이건 **그림일 뿐**이고, `지형.js` 의 `지면`·`막힘` 은
//   도면에서 나온다. 지금 이 돌을 밟으면 **뚫고 물에 빠진다.**
//   판정을 붙이려면 코어(Z 0~50) 안쪽 물 위에 디딜 면을 새로 만들어야 하고,
//   그건 도면과 하네스(구멍·맞춤)를 건드리는 일이라 팀이 정할 문제다.
//
// [단위]  표본은 1 짜리. m 변환은 `무리만들기` 가 `키 × 미터` 로 한다.
//   디딤돌 — 밑동이 원점, **Z 폭 1** (누운 물건 규약). `키` = 디디는 쪽 길이.

import * as THREE from "three";
import { makeRandom } from "../../src/공용.jsx";
import { 강굽이, 건너굽이 } from "./강.js";
import { 강 } from "./공간도면.js";

// 강돌 색 — 물에 씻겨 희끗한 화강암. 꼭짓점에는 **비율**만 굽는다.
export const 돌다리결 = {
  돌: "#8D8B85",
  돌어둠: "#4E4C48",
};

// ── 디딤돌 ──────────────────────────────────────────────────
//   납작하고 모난 돌. 윗면이 평평해야 **디딜 수 있게** 보인다.
//   [왜 상자를 안 쓰나]  상자를 흔들면 「부서진 상자」가 된다. 징검돌은
//   물에 오래 씻겨 **모서리가 닳고 윗면만 평평**하다. 그래서 위·아래를
//   따로 다룬다 — 윗면은 거의 안 건드리고, 옆구리만 크게 흔든다.
export function 디딤돌표본들(수 = 6, 시드 = 6101) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 모 = 7 + Math.floor(난수() * 4); // 모서리 수 — 제각각이어야 한다
    const 두께 = 0.42 + 난수() * 0.2;
    const 폭비 = 0.78 + 난수() * 0.34; // Z 대비 X 폭
    const 위 = [];
    const 아래 = [];
    for (let k = 0; k < 모; k++) {
      const a = (k / 모) * Math.PI * 2 + (난수() - 0.5) * 0.3;
      const r = 0.5 * (0.82 + 난수() * 0.28);
      // 윗면 — 평평하다. 높낮이를 아주 조금만 준다
      위.push(
        new THREE.Vector3(
          Math.sin(a) * r * 폭비,
          두께 * (0.94 + 난수() * 0.06),
          Math.cos(a) * r,
        ),
      );
      // 밑면 — 좁고 들쭉날쭉하다. 물바닥에 박힌 쪽이라 안 보인다
      아래.push(
        new THREE.Vector3(
          Math.sin(a) * r * 폭비 * (0.7 + 난수() * 0.2),
          난수() * 0.06,
          Math.cos(a) * r * (0.7 + 난수() * 0.2),
        ),
      );
    }
    const 꼭 = [];
    const 밝 = [];
    const 담기 = (a, b, c, v) => {
      for (const q of [a, b, c]) {
        꼭.push(q.x, q.y, q.z);
        밝.push(v, v, v);
      }
    };
    const 윗한복판 = new THREE.Vector3(0, 두께, 0);
    const 밑한복판 = new THREE.Vector3(0, 0.02, 0);
    for (let k = 0; k < 모; k++) {
      const n = (k + 1) % 모;
      // 윗면 — 볕을 정면으로 받아 가장 밝다
      담기(윗한복판, 위[k], 위[n], 1.0 + (난수() - 0.5) * 0.08);
      // 옆구리 — 물때가 앉아 어둡다
      담기(위[k], 아래[k], 아래[n], 0.6 + 난수() * 0.12);
      담기(위[k], 아래[n], 위[n], 0.66 + 난수() * 0.12);
      // 밑면 (거의 안 보이지만 뚫려 있으면 안 된다)
      담기(밑한복판, 아래[n], 아래[k], 0.42);
    }
    const g = new THREE.BufferGeometry();
    g.setAttribute("position", new THREE.Float32BufferAttribute(꼭, 3));
    g.setAttribute("color", new THREE.Float32BufferAttribute(밝, 3));
    g.computeVertexNormals();
    // Z 폭 1 · 밑동 원점
    g.computeBoundingBox();
    const bb = g.boundingBox;
    const L = Math.max(1e-6, bb.max.z - bb.min.z);
    g.translate(-(bb.min.x + bb.max.x) / 2, -bb.min.y, -(bb.min.z + bb.max.z) / 2);
    g.scale(1 / L, 1 / L, 1 / L);
    표본.push(g);
  }
  return 표본;
}

// ── 징검다리를 놓는다 ──────────────────────────────────────
//   `X` 자리에서 이쪽 물가 → 건너 물가를 잇는다. 물가 위치는 `강.js` 의
//   굽이 함수에서 그대로 가져온다 — **여기서 다시 계산하지 않는다.**
//   강 모양을 고치면 징검다리가 저절로 따라와야 한다(단일 출처 원칙).
export function 돌다리자리들({
  X = 46.2,
  걸음 = 1.18, // 돌 한 칸 — 사람 보폭이다. 넓히면 못 건넌다
  물위 = 0.24, // 수면 위로 나오는 높이. 한 뼘 남짓이어야 징검다리다
  흔들 = 0.9, // 줄이 좌우로 이만큼 굽는다 — 자로 그은 징검다리는 없다
  시드 = 6301,
  지면높이 = null,
  코어Z끝 = 50, // 이 너머로는 `지면높이` 를 믿으면 안 된다(아래 주석)
} = {}) {
  const 난수 = makeRandom(시드);
  const 이쪽 = 강.Z시작 + 강굽이(X);
  const 저쪽 = 강.Z시작 + 강.건너 + 3 + 건너굽이(X);
  // 양끝을 뭍으로 조금 물린다 — 물가에서 딱 끝나면 「끊어진 다리」로 보인다
  const 시작Z = 이쪽 - 1.6;
  const 끝Z = 저쪽 + 1.4;
  const 길이 = 끝Z - 시작Z;
  const 수 = Math.max(3, Math.round(길이 / 걸음));
  const 실걸음 = 길이 / 수;

  // 줄의 굽이 — 주기가 다른 사인 둘을 겹쳐야 되돌아오는 느낌이 안 난다
  const 굽음 = (t) =>
    X + Math.sin(t * Math.PI * 1.7 + 0.4) * 흔들 + Math.sin(t * Math.PI * 4.3) * 흔들 * 0.35;

  const 디딤돌 = [];
  for (let k = 0; k <= 수; k++) {
    const t = k / 수;
    const z = 시작Z + 길이 * t;
    const x = 굽음(t);
    // 양끝 돌은 뭍에 놓이므로 땅높이를 따른다. 가운데는 물바닥(0)이다.
    //   ★ `지면높이` 는 **코어 안에서만** 맞는다. 코어(Z ≤ 50) 밖에서 부르면
    //     엉뚱한 값이 나온다 — 예전 교각이 **−2.61 m 로 가라앉았다**(실측).
    //     이 다리가 닿는 건너편(z > 77)은 기슭 골이 끝난 데라 수면과 같다.
    const 뭍끝 = k <= 1 || k >= 수 - 1;
    const 바닥 = 지면높이 && 뭍끝 && z <= 코어Z끝 ? 지면높이(x, z) : 0;
    const 키 = 1.02 + 난수() * 0.42; // 디디는 쪽 길이 1.0~1.45 m
    // 돌 두께는 표본마다 다르므로(0.34~0.5 × 키), 윗면이 `물위` 에 오도록
    //   넉넉히 내려 박는다. 조금 파묻히는 편이 **놓은 돌**로 보인다.
    디딤돌.push({
      x,
      z,
      y: 바닥 + 물위 - 키 * 0.42,
      키,
      // ★ 아무 방향으로나 돌리면 안 된다. 처음엔 `난수 × 2π` 로 뒀는데,
      //   그러면 긴 축이 제멋대로 놓여 **줄 방향으로 짧아지는 돌**이 생기고
      //   그 자리에 구멍처럼 틈이 벌어진다(실측 스크린샷). 징검돌은 사람이
      //   **디디기 좋게** 놓은 것이라, 줄을 따라 가지런하고 조금씩만 틀어진다.
      회전: (난수() - 0.5) * 0.9,
      기울기: (난수() - 0.5) * 0.13, // 살짝 기운 돌이 섞여야 자연스럽다
      기울기2: (난수() - 0.5) * 0.13,
      폭비: 0.9 + 난수() * 0.4,
      깊이비: 0.9 + 난수() * 0.3,
      색: 돌다리결.돌,
    });
    // 가끔 옆에 한 장 더 — 비켜 서는 자리다(사진에 그런 데가 있다)
    if (k > 1 && k < 수 - 1 && 난수() < 0.22) {
      const 옆 = (난수() < 0.5 ? -1 : 1) * (0.72 + 난수() * 0.22);
      const 키2 = 0.9 + 난수() * 0.4;
      디딤돌.push({
        x: x + 옆,
        z: z + (난수() - 0.5) * 0.3,
        y: 물위 - 키2 * 0.42,
        키: 키2,
        회전: (난수() - 0.5) * 1.0,
        기울기: (난수() - 0.5) * 0.15,
        기울기2: (난수() - 0.5) * 0.15,
        폭비: 0.9 + 난수() * 0.35,
        깊이비: 0.9 + 난수() * 0.3,
        색: 돌다리결.돌,
      });
    }
  }
  return { 디딤돌, 실측: { 시작Z, 끝Z, 길이, 걸음: 실걸음, 돌수: 디딤돌.length } };
}
