// ═══════════════════════════════════════════════════════════════
//  돌다리.js — 절벽 아래 나루터에서 강 건너 택촌으로
// ═══════════════════════════════════════════════════════════════
// [왜 생겼나]
//   택촌은 강 건너에 있고(`F-02` 「영산강을 사이에 두고 진부촌과 택촌」),
//   지금까지 건너가는 길은 **배뿐**이었다. 그런데 ④ Scene 01 의 필수 장소
//   요소가 「진부촌 방향과 택촌 방향을 **구분할 수 있어야 한다**」이고,
//   씬 2 부터는 양쪽을 오가는 증언이 붙는다. 두 마을이 **이어져 있다**는 것이
//   화면에 서야 한다.
//
// [왜 하필 이 생김새인가 — 진천 농다리]
//   32.5 m 를 건너는 다리다(실측: x 46 에서 이쪽 물가 z 44.5 · 건너 z 77.0).
//   여기에 아치를 세우거나 난간을 두르면 **이 시대·이 동네 것이 아니게 된다.**
//   우리 것 중에 이 길이를 감당하는 형식이 **농다리**다 —
//     · 납작한 돌을 **모르타르 없이 쌓아** 교각을 만들고
//     · 그 사이에 **돌 상판**을 걸친다
//     · 난간이 없고, 수면에서 한 뼘 남짓만 뜬다
//   길고 낮게 깔려서 강폭을 오히려 **더 넓어 보이게** 한다. 그게 이 장면에
//   필요한 그림이다 — 건널 수는 있지만 멀다.
//
// [★ 걷는 판정은 아직 없다 — 반드시 알고 써야 한다]
//   `땅소품.js` 와 같다. 이건 **그림일 뿐**이고, `지형.js` 의 `지면`·`막힘` 은
//   도면에서 나온다. 지금 이 다리에 올라서면 **뚫고 물에 빠진다.**
//   판정을 붙이려면 코어(Z 0~50) 안쪽 물 위에 걸어 다닐 수 있는 면을 새로
//   만들어야 하고, 그건 도면과 하네스(구멍·맞춤)를 건드리는 일이라 팀이
//   정할 문제다. 여기서는 **보이는 것까지** 한다.
//
// [단위]  표본은 1 짜리. m 변환은 `무리만들기` 가 `키 × 미터` 로 한다.
//   교각 — 밑동이 원점, 키 1 (가로세로는 `폭비`·`깊이비`)
//   상판 — **국소 +Z 로 누운** 길이 1 짜리 (가로대·나루터와 같은 규약)

import * as THREE from "three";
import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { makeRandom } from "../../src/공용.jsx";
import { 강굽이, 건너굽이 } from "./강.js";
import { 강 } from "./공간도면.js";

// 강돌 색 — 물에 씻겨 희끗한 화강암. 꼭짓점에는 **비율**만 굽는다.
export const 돌다리결 = {
  돌: "#8D8B85",
  돌어둠: "#4E4C48",
};

// 꼭짓점 색을 비율로 굽는다(0.62 = 그만큼 어둡게 · 1 = 인스턴스 색 그대로)
const 비율칠 = (g, 밝기) => {
  const n = g.attributes.position.count;
  const c = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) {
    c[i * 3] = 밝기;
    c[i * 3 + 1] = 밝기;
    c[i * 3 + 2] = 밝기;
  }
  g.setAttribute("color", new THREE.BufferAttribute(c, 3));
  return g;
};

// 상자를 흔들어 「깎인 돌」로 만든다.
//   ※ `uv` 를 지운다 — `mergeGeometries` 는 속성 구성이 다르면 **조용히
//     null 을 돌려준다.** 이 프로젝트에서 세 번 겪었다.
const 돌덩이 = (난수, w, h, d, 거칢 = 0.18) => {
  const g = new THREE.BoxGeometry(w, h, d, 2, 1, 2);
  delete g.attributes.uv;
  delete g.attributes.uv1;
  const p = g.attributes.position;
  for (let i = 0; i < p.count; i++) {
    p.setXYZ(
      i,
      p.getX(i) * (1 + (난수() - 0.5) * 거칢) + (난수() - 0.5) * w * 0.06,
      p.getY(i) + (난수() - 0.5) * h * 0.22,
      p.getZ(i) * (1 + (난수() - 0.5) * 거칢) + (난수() - 0.5) * d * 0.06,
    );
  }
  g.computeVertexNormals();
  return g.toNonIndexed();
};

// ── 교각 ────────────────────────────────────────────────────
//   납작한 돌을 5~7 켜 쌓는다. 켜마다 조금씩 돌리고 어긋나게 놓아야
//   **쌓은 것**으로 보인다. 반듯하게 포개면 콘크리트 기둥이 된다.
//   물살을 가르도록 아래가 넓고 위가 좁다.
export function 교각표본들(수 = 4, 시드 = 6101) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 켜 = 5 + Math.floor(난수() * 3);
    const 조각 = [];
    let y = 0;
    for (let k = 0; k < 켜; k++) {
      const t = k / (켜 - 1); // 0 = 밑, 1 = 꼭대기
      const 두께 = (1 / 켜) * (0.85 + 난수() * 0.3);
      // 위로 갈수록 좁아진다 — 물살을 받는 밑이 넓어야 버틴다
      const 폭 = 1.0 - 0.32 * t;
      const 깊 = 1.0 - 0.18 * t;
      const g = 돌덩이(난수, 폭, 두께, 깊);
      g.rotateY((난수() - 0.5) * 0.5);
      g.translate((난수() - 0.5) * 0.06, y + 두께 / 2, (난수() - 0.5) * 0.06);
      // 켜마다 밝기를 달리해야 결이 보인다
      조각.push(비율칠(g, 0.78 + 난수() * 0.34));
      y += 두께 * 0.92; // 조금씩 파묻히게 — 틈이 벌어지면 무너져 보인다
    }
    const 합 = mergeGeometries(조각, false);
    if (!합) continue;
    // 키를 정확히 1 로, 밑동을 원점으로
    합.computeBoundingBox();
    const bb = 합.boundingBox;
    const H = Math.max(1e-6, bb.max.y - bb.min.y);
    합.translate(0, -bb.min.y, 0);
    합.scale(1, 1 / H, 1);
    표본.push(합);
  }
  return 표본;
}

// ── 상판 ────────────────────────────────────────────────────
//   교각 사이에 걸치는 널돌. **국소 +Z 로 누운** 길이 1 짜리다.
//   [왜 두 장인가]  한 장짜리 널은 두께가 균일해 「판때기」로 보인다.
//   나란한 두 장 사이에 실금이 있어야 **돌을 걸쳐 놓은 것**으로 읽힌다.
export function 상판표본들(수 = 4, 시드 = 6203) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    for (const 쪽 of [-1, 1]) {
      const g = 돌덩이(난수, 0.46, 0.1, 1.0, 0.1);
      g.translate(쪽 * 0.25, 0.05, 0);
      조각.push(비율칠(g, 0.86 + 난수() * 0.26));
    }
    const 합 = mergeGeometries(조각, false);
    if (!합) continue;
    합.computeBoundingBox();
    const bb = 합.boundingBox;
    const L = Math.max(1e-6, bb.max.z - bb.min.z);
    합.translate(-(bb.min.x + bb.max.x) / 2, -bb.min.y, -(bb.min.z + bb.max.z) / 2);
    합.scale(1 / L, 1 / L, 1 / L);
    표본.push(합);
  }
  return 표본;
}

// ── 다리를 놓는다 ───────────────────────────────────────────
//   `X` 자리에서 이쪽 물가 → 건너 물가를 잇는다. 물가 위치는 `강.js` 의
//   굽이 함수에서 그대로 가져온다 — **여기서 다시 계산하지 않는다.**
//   강 모양을 고치면 다리가 저절로 따라와야 한다(단일 출처 원칙).
export function 돌다리자리들({
  X = 46.2,
  칸 = 2.6, // 상판 한 장이 건너는 거리
  높이 = 0.78, // 수면에서 **교각 꼭대기**까지 (상판은 그 위에 얹힌다)
  흔들 = 0.55, // 좌우로 이만큼 굽는다 — 자로 그은 다리는 사람이 놓은 것 같지 않다
  시드 = 6301,
  지면높이 = null,
  코어Z끝 = 50, // 이 너머로는 `지면높이` 를 믿으면 안 된다(아래 주석)
} = {}) {
  const 난수 = makeRandom(시드);
  const 이쪽 = 강.Z시작 + 강굽이(X);
  const 저쪽 = 강.Z시작 + 강.건너 + 3 + 건너굽이(X);
  // 양끝을 뭍으로 조금 물린다 — 물가에서 딱 끝나면 「끊어진 다리」로 보인다
  const 시작Z = 이쪽 - 1.4;
  const 끝Z = 저쪽 + 1.2;
  const 길이 = 끝Z - 시작Z;
  const 수 = Math.max(2, Math.round(길이 / 칸)); // 상판 장수
  const 실칸 = 길이 / 수;

  const 굽음 = (t) => X + Math.sin(t * Math.PI * 1.35 + 0.4) * 흔들;
  const 교각 = [];
  const 상판 = [];

  for (let k = 0; k <= 수; k++) {
    const t = k / 수;
    const z = 시작Z + 길이 * t;
    const x = 굽음(t);
    // 양끝 교각은 뭍에 서므로 땅높이를 따른다. 가운데는 물바닥(0)이다.
    //   ★ `지면높이` 는 **코어 안에서만** 맞는다. 코어(Z ≤ 50) 밖에서 부르면
    //     엉뚱한 값이 나온다 — 건너편 교각이 **−2.61 m 로 가라앉았다**(실측).
    //     원경에서 이 다리가 닿는 자리(z > 77)는 기슭 골이 이미 끝난 데라
    //     수면과 같은 높이(0)다. 그래서 밖은 0 으로 둔다.
    //     ※ 이건 「원경 요소를 옮기면 튄다」와 같은 함정이다(편집기 `바닥높이`).
    const 뭍끝 = k === 0 || k === 수;
    const 바닥 = 지면높이 && 뭍끝 && z <= 코어Z끝 ? 지면높이(x, z) : 0;
    const 키 = Math.max(0.35, 높이 - 바닥);
    교각.push({
      x,
      z,
      y: 바닥,
      키,
      회전: (난수() - 0.5) * 0.4,
      폭비: (1.15 + 난수() * 0.2) / 키, // 실폭 ≈ 1.15~1.35 m
      깊이비: (1.6 + 난수() * 0.3) / 키, // 물살 방향으로 길다
      색: 돌다리결.돌,
    });
  }
  for (let k = 0; k < 수; k++) {
    const t0 = k / 수;
    const t1 = (k + 1) / 수;
    const z0 = 시작Z + 길이 * t0;
    const z1 = 시작Z + 길이 * t1;
    const x0 = 굽음(t0);
    const x1 = 굽음(t1);
    const 가운데Z = (z0 + z1) / 2;
    const 가운데X = (x0 + x1) / 2;
    // 상판은 교각 위에 얹히므로 **조금 겹치게** 길게 잡는다
    const 길 = Math.hypot(x1 - x0, z1 - z0) + 0.9;
    // ★ 표본은 **Z 폭 1** 로 맞춰져 있어서, 세 폭이 전부 `키` 에 비례해
    //   커진다. 널돌은 길어져도 **두꺼워지면 안 되므로** `높이비` 로 눌러
    //   실두께를 못박는다(표본 자체 두께가 0.1 이라 0.22/0.1 = 2.2 를 키로 나눈다).
    const 두께 = 0.22;
    상판.push({
      x: 가운데X,
      z: 가운데Z,
      y: 높이, // 교각 꼭대기에 얹는다
      키: 길,
      // 국소 +Z 가 다리 방향을 향하도록 돌린다
      회전: Math.atan2(x1 - x0, z1 - z0),
      폭비: (1.25 + 난수() * 0.15) / 길,
      높이비: 두께 / 0.1 / 길,
      깊이비: 1,
      색: 돌다리결.돌,
    });
  }
  return { 교각, 상판, 실측: { 시작Z, 끝Z, 길이, 칸: 실칸, 장수: 수 } };
}
