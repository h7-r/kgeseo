// ── 시드 고정 값소음 ────────────────────────────────────────
//   makeRandom(공용.jsx) 을 쓰므로 **매번 같은 결과**가 나온다.
//   그래야 도면과 대조할 수 있고, 팀원 화면에도 똑같이 뜬다.
export function 소음만들기(시드) {
  const 난수 = makeRandom(시드);
  const N = 128;
  // N 이 2의 거듭제곱이라 나머지 연산을 비트 마스크로 대신한다.
  //   `((a % N) + N) % N` 은 자리 하나를 물을 때마다 나눗셈을 두 번 한다. 표를 네 번 읽으므로
  //   한 겹에 여덟 번, 세 겹이니 **한 점에 스물네 번**이다. 땅 메시는 꼭짓점마다 이걸 부른다.
  //   ※ `& 마스크` 는 **결과가 같다.** 비트 연산은 값을 2^32 로 접는데 2^32 는 128 의 배수라
  //     낮은 7비트가 그대로 남는다. 음수도 마찬가지다(-1 & 127 === 127 === ((-1 % 128) + 128) % 128).
  const 마스크 = N - 1;
  const 표 = new Float32Array(N * N);
  for (let i = 0; i < N * N; i++) 표[i] = 난수() * 2 - 1;

  // 한 겹 — 값소음 한 장을 겹선형으로 읽는다. 셈하는 차례는 예전 그대로 둔다
  // (순서를 바꾸면 부동소수 끝자리가 달라져 지형 지문이 바뀐다).
  const 한겹 = (x, z) => {
    const xi = Math.floor(x);
    const zi = Math.floor(z);
    const tx = x - xi;
    const tz = z - zi;
    const u = tx * tx * (3 - 2 * tx);
    const v = tz * tz * (3 - 2 * tz);
    const x0 = (xi & 마스크) * N;
    const x1 = ((xi + 1) & 마스크) * N;
    const z0 = zi & 마스크;
    const z1 = (zi + 1) & 마스크;
    const a = 표[x0 + z0];
    const b = 표[x1 + z0];
    const c = 표[x0 + z1];
    const d = 표[x1 + z1];
    return (a + (b - a) * u) * (1 - v) + (c + (d - c) * u) * v;
  };

  // 세 겹을 겹친다 — 넓은 굴곡 · 중간결 · 잔결
  return (x, z) =>
    한겹(x, z) * 0.55 +
    한겹(x * 2.7 + 11, z * 2.7 + 7) * 0.3 +
    한겹(x * 7.3 + 31, z * 7.3 + 19) * 0.15;
}

// 이 자리의 표면이 기준면에서 몇 m 떠 있나 (± 요철)
export function 결높이만들기(결, 소음, 배율 = 1) {
  const 폭 = 결.요철 * 배율;
  if (폭 <= 0) return () => 0;
  return (x, z) => 소음(x * 결.결크기, z * 결.결크기) * 폭;
}

// ── 깎인 돌 여섯 종 ─────────────────────────────────────────
//   정이십면체(20면)의 꼭짓점을 흔든다. PolyhedronGeometry 는 인덱스가 없어
//   같은 자리 꼭짓점이 여러 번 들어 있으므로, **좌표를 키로 같은 크기만큼**
//   흔들어야 면이 찢어지지 않는다.
export function 돌모양만들기(난수) {
  const g = new THREE.IcosahedronGeometry(0.5, 0); // 지름 1 기준
  const p = g.attributes.position;
  const 흔들 = new Map();
  for (let i = 0; i < p.count; i++) {
    const x = p.getX(i);
    const y = p.getY(i);
    const z = p.getZ(i);
    const 키 = `${x.toFixed(3)},${y.toFixed(3)},${z.toFixed(3)}`;
    let f = 흔들.get(키);
    if (f === undefined) {
      f = 0.6 + 난수() * 0.62;
      흔들.set(키, f);
    }
    p.setXYZ(i, x * f, y * f, z * f);
  }
  g.computeVertexNormals(); // 인덱스가 없어 면마다 각진 노멀이 나온다 = 깎인 돌
  return g;
}

// 지오메트리에 꼭짓점 색을 입힌다(합치려면 모두 같은 속성을 가져야 한다)
export function 색입히기(geo, c) {
  const n = geo.attributes.position.count;
  const arr = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) {
    arr[i * 3] = c.r;
    arr[i * 3 + 1] = c.g;
    arr[i * 3 + 2] = c.b;
  }
  geo.setAttribute("color", new THREE.BufferAttribute(arr, 3));
  return geo;
}

// ── 땅 한 장 ────────────────────────────────────────────────
//   Playable Core 전체를 **하나의 그물**로 덮는다.
//   ※ 구역마다 판을 따로 만들던 게 Z1↔Z2 경계에 자로 그은 단차를 남기던
//     원인이었다. 이제 모든 자리가 `지표.높이` 하나를 보므로 이을 것이 없다.
//   가파른 자리(구역 옆구리·절벽)는 건너뛴다. 거기는 바위 메시가 덮고,
//   그 바위도 같은 `지표` 를 조회하므로 가장자리가 애초에 맞는다.
export function 땅만들기({ 지표, 코어, 절벽, 칸당, 법선과장, 그늘 }) {
  const w = 코어.X[1] - 코어.X[0];
  const d = 코어.Z[1] - 코어.Z[0];
  const nx = Math.max(2, Math.round(w * 칸당));
  const nz = Math.max(2, Math.round(d * 칸당));

  // 격자 꼭짓점을 미리 한 번씩만 잰다(같은 자리를 네 번 묻지 않게)
  const H = new Float32Array((nx + 1) * (nz + 1));
  const C = new Float32Array((nx + 1) * (nz + 1) * 3);
  const N = new Float32Array((nx + 1) * (nz + 1) * 3);
  const XS = new Float32Array(nx + 1);
  const ZS = new Float32Array(nz + 1);
  for (let i = 0; i <= nx; i++) XS[i] = 코어.X[0] + (w * i) / nx;
  for (let j = 0; j <= nz; j++) ZS[j] = 코어.Z[0] + (d * j) / nz;

  for (let j = 0; j <= nz; j++) {
    for (let i = 0; i <= nx; i++) {
      const k = j * (nx + 1) + i;
      const x = XS[i];
      const z = ZS[j];
      H[k] = 지표.높이(x, z);
      const c = 지표.색(x, z, 그늘 ? 그늘(x, z) : 0);
      C[k * 3] = c.r;
      C[k * 3 + 1] = c.g;
      C[k * 3 + 2] = c.b;
      const n = 지표.법선(x, z, 법선과장);
      N[k * 3] = n[0];
      N[k * 3 + 1] = n[1];
      N[k * 3 + 2] = n[2];
    }
  }

  const 위치 = [];
  const 색깔 = [];
  const 노멀 = [];
  // ※ 예전에는 「높이차가 크면 건너뛴다」였다. 그러니 Z3(+14)에서 Z1(0)로
  //   떨어지는 **비탈에 지형이 아예 없었고**, 그 자리를 T4 의 받침 치마가
  //   14 m 짜리 세로 지느러미로 혼자 메우고 있었다(광선으로 확인).
  //   이제는 **다른 메시가 확실히 덮는 자리만** 건너뛴다.
  // ※ 칸의 **한가운데**로 판정하면 안 된다. 그러면 띠에 걸친 칸이 통째로
  //   빠지면서 절벽 어깨(Z = 26)에 칸 하나 폭의 **틈**이 남는다 —
  //   광선으로 재 보니 Z3 가장자리에서 아래 암벽이 그대로 보였다(11 곳).
  //   칸이 **완전히** 띠 안에 들어갈 때만 건너뛴다. 땅이 절벽면을 조금 덮는 건
  //   괜찮지만, 사이가 벌어지는 건 구멍이다.
  //   ※ 마루선이 x 마다 다르므로(공간도면.js `절벽윤곽`) **그 x 의 마루** 아래만
  //     건너뛴다. 예전처럼 Z위(26)부터 통째로 건너뛰면, 마루가 남쪽으로
  //     물러난 자리에 생긴 **어깨(선반)** 에 땅이 안 그려져 구멍이 된다.
  const 절벽띠 = (x0, x1, z0, z1) => {
    if (!(x0 >= 절벽.X[0] - 0.05 && x1 <= 절벽.X[1] + 0.05)) return false;
    const 마루 = Math.max(절벽윤곽(x0).마루, 절벽윤곽(x1).마루);
    return z0 > 마루 + 0.02 && z1 < 절벽.Z아래 - 0.02;
  };
  // ※ 예전에는 높이 있는 구역의 **가장자리 2.4 m 띠**도 건너뛰었다
  //   (「구역바위가 옆구리를 세운다」). 그런데 지형.js 가 산허리를 채운 뒤로는
  //   그 자리에 진짜 비탈이 생겼는데도 땅이 안 그려져, 광선으로 재 보니
  //   Z3 서쪽 가장자리에서 **그림과 판정이 14.4 m 어긋났다**(구멍 110/680).
  //   구역바위는 이제 '덮개'가 아니라 '장식'이다 — 땅은 빠짐없이 그린다.

  const 찍기 = (i, j) => {
    const k = j * (nx + 1) + i;
    위치.push(XS[i] * 미터, H[k] * 미터, ZS[j] * 미터);
    색깔.push(C[k * 3], C[k * 3 + 1], C[k * 3 + 2]);
    노멀.push(N[k * 3], N[k * 3 + 1], N[k * 3 + 2]);
  };

  for (let j = 0; j < nz; j++) {
    for (let i = 0; i < nx; i++) {
      if (절벽띠(XS[i], XS[i + 1], ZS[j], ZS[j + 1])) continue; // 절벽면이 덮는다
      찍기(i, j); 찍기(i, j + 1); 찍기(i + 1, j);
      찍기(i + 1, j); 찍기(i, j + 1); 찍기(i + 1, j + 1);
    }
  }

  const geo = new THREE.BufferGeometry();
  geo.setAttribute("position", new THREE.Float32BufferAttribute(위치, 3));
  geo.setAttribute("color", new THREE.Float32BufferAttribute(색깔, 3));
  geo.setAttribute("normal", new THREE.Float32BufferAttribute(노멀, 3));
  return geo;
}

// ── 자갈·돌 흩뿌리기 (맵 전체) ──────────────────────────────
//   밀도·크기는 **그 자리의 결**이 정한다. 구역마다 따로 뿌리지 않으므로
//   경계에서 자갈이 뚝 끊기지 않고 자연스럽게 성글어진다.
//   `자리` 를 같이 돌려주어, 땅 색이 돌 발치를 어둡게 칠할 수 있게 한다.
export function 땅흩뿌림만들기({
  지표, 코어, 밀도배율, 시드, 뭉침소음, 놓을수있나,
}) {
  const 난수 = makeRandom(시드);
  const 모양 = [];
  for (let i = 0; i < 6; i++) 모양.push(돌모양만들기(난수));

  const w = 코어.X[1] - 코어.X[0];
  const d = 코어.Z[1] - 코어.Z[0];
  // 가장 촘촘한 결을 기준으로 뽑고, 자리마다 제 결의 확률로 걸러낸다
  const 최대밀도 = Math.max(...Object.values(바닥결).map((r) => r.밀도)) * 3.2;
  const 후보수 = Math.round(w * d * 최대밀도 * 밀도배율 * 1.6);
  const 조각 = [];
  const 자리 = [];
  const 자리들 = [];
  const 색 = new THREE.Color();
  const 사원수 = new THREE.Quaternion();
  const 행렬 = new THREE.Matrix4();
  const 놓을곳 = new THREE.Vector3();
  const 배율 = new THREE.Vector3();

  for (let i = 0; i < 후보수; i++) {
    const x = 코어.X[0] + 난수() * w;
    const z = 코어.Z[0] + 난수() * d;
    const 뽑기 = 난수();
    const 뽑기2 = 난수();
    const 크기뽑기 = 난수();
    const 폭비 = 0.7 + 난수() * 0.6;
    const 모양번호 = Math.floor(난수() * 모양.length);
    const 회전 = [(난수() - 0.5) * 0.7, 난수() * Math.PI * 2, (난수() - 0.5) * 0.7];
    const 색흔들 = 난수();

    const r = 지표.결(x, z);
    if (!r) continue;
    // 이 자리의 결이 요구하는 밀도만큼만 남긴다.
    // ※ 급사면은 흙이 씻겨 내려가 **돌이 더 드러난다** — 밀도를 올린다.
    //   (안 그러면 새로 생긴 산허리가 매끈한 초록 벽으로만 보인다)
    const 급 = 지표.급함 ? 지표.급함(x, z) : 0;
    if (뽑기 > (r.밀도 * (1 + 급 * 2.2)) / 최대밀도) continue;
    // 뭉침 — 고르게 뿌리면 기계처럼 보인다
    const 확률 = THREE.MathUtils.clamp(
      0.5 + 뭉침소음(x * 0.4, z * 0.4) * r.뭉침,
      0,
      1,
    );
    if (뽑기2 > 확률) continue;
    if (놓을수있나 && !놓을수있나(x, z)) continue;

    // 가끔 큰 바위를 섞는다 — 큰 것이 있어야 옆의 잔돌이 잔돌로 보인다
    const 큰 = r.큰돌 && 난수() < r.큰돌.확률;
    const 크기 = 큰
      ? r.큰돌.크기[0] + 난수() * (r.큰돌.크기[1] - r.큰돌.크기[0])
      : r.알[0] + (r.알[1] - r.알[0]) * Math.pow(크기뽑기, 2.2);
    const 세로 = 크기 * (큰 ? Math.min(1, r.납작 + 0.28) : r.납작);
    const y = 지표.높이(x, z);
    // 인스턴스로 심을 수 있게 자리도 같이 남긴다(편집기가 하나씩 고른다)
    //   ※ 색은 아래에서 정해진다. **난수 순서를 바꾸면 자갈 배치가 달라지므로**
    //     여기서 미리 뽑지 않고, 정해진 뒤에 이 객체에 얹는다.
    const 이자리 = { x, y: y - 세로 * 0.18, z, 크기, 높이비: 세로 / 크기, 폭비: 폭비 };
    자리들.push(이자리);
    const g = 모양[모양번호].clone();
    사원수.setFromEuler(new THREE.Euler(회전[0], 회전[1], 회전[2]));
    배율.set(크기 * 미터, 세로 * 미터, 크기 * 폭비 * 미터);
    놓을곳.set(x * 미터, (y - 세로 * 0.18) * 미터, z * 미터);
    행렬.compose(놓을곳, 사원수, 배율);
    g.applyMatrix4(행렬);
    색.copy(new THREE.Color(r.그늘)).lerp(
      new THREE.Color(r.색2 ?? r.알색).lerp(new THREE.Color(r.알색), 색흔들),
      0.34 + 난수() * 0.62,
    );
    이자리.색 = 색.getHex(); // 무리(인스턴스)도 같은 색을 쓴다
    조각.push(색입히기(g, 색));
    자리.push({ x, z, r: 크기 * 0.55 });
  }

  모양.forEach((g) => g.dispose());
  if (!조각.length) return { 지오: null, 자리, 자리들 };
  const 합본 = mergeGeometries(조각, false);
  조각.forEach((g) => g.dispose());
  return { 지오: 합본, 자리, 자리들 };
}

// 돌 발치를 어둡게 칠할 때 쓰는 조회기 — 격자로 나눠 빠르게 찾는다
export function 접지그늘만들기(자리들) {
  if (!자리들.length) return () => 0;
  // ※ 반경을 크게 잡으면, 자갈밭처럼 촘촘한 데서는 **모든 자리가 어느 돌의
  //   그늘 안**에 들어가 바닥 전체가 시커메진다(실제로 그렇게 났다).
  //   돌 바로 발치만 잡도록 좁게 둔다.
  const 반경 = (a) => a.r * 2.1;
  const 칸 = Math.max(0.8, 자리들.reduce((m, a) => Math.max(m, 반경(a)), 0));
  const 격자 = new Map();
  for (const a of 자리들) {
    const k = `${Math.floor(a.x / 칸)},${Math.floor(a.z / 칸)}`;
    let 통 = 격자.get(k);
    if (!통) 격자.set(k, (통 = []));
    통.push(a);
  }
  return (x, z) => {
    let 진하기 = 0;
    const cx = Math.floor(x / 칸);
    const cz = Math.floor(z / 칸);
    for (let i = -1; i <= 1; i++)
      for (let j = -1; j <= 1; j++) {
        const 통 = 격자.get(`${cx + i},${cz + j}`);
        if (!통) continue;
        for (const a of 통) {
          const R = 반경(a);
          const dd = Math.hypot(x - a.x, z - a.z);
          if (dd < R) 진하기 = Math.max(진하기, 1 - dd / R);
        }
      }
    return 진하기 * 진하기;
  };
}


// ── 인스턴스용 돌 표본 ──────────────────────────────────────
// [왜]
//   `돌뿌리기`·`땅흩뿌림만들기` 는 돌마다 지오메트리를 만들어 **통째로 병합**한다.
//   드로우콜은 싸지만 「저 바위 하나」를 고를 수가 없다 — 길 위에 얹힌 돌을
//   치우려면 그 하나를 집을 수 있어야 한다(배치.js 머리말 참고).
//   여기서 **지름 1 · 원점 중심** 짜리 표본을 몇 벌 만들어 두면, 자리·크기·회전은
//   인스턴스가 갖는다.
//
//   ※ 나무와 달리 **밑동을 원점에 두지 않는다.** 돌은 반쯤 파묻히므로
//     자리 좌표가 곧 돌의 **중심**이어야 기존 배치 규칙이 그대로 맞는다.
export function 돌표본들(수 = 6, 시드 = 7301) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const g = 돌모양만들기(난수);
    g.computeBoundingSphere();
    const r = g.boundingSphere?.radius || 0.5;
    g.scale(0.5 / r, 0.5 / r, 0.5 / r); // 지름 1 로 맞춘다
    표본.push(g);
  }
  return 표본;
}
