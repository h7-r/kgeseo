// ── 조각 만들기 (소품.js·씬2.js 와 같은 규약) ───────────────
const 풀기 = (g) => {
  const n = g.toNonIndexed();
  n.deleteAttribute("uv");
  n.deleteAttribute("uv1");
  g.dispose();
  return n;
};
const 상자 = (w, h, d) => 풀기(new THREE.BoxGeometry(w, h, d));
const 기둥 = (r1, r2, h, 각 = 6) =>
  풀기(new THREE.CylinderGeometry(r1, r2, h, 각, 1));
const 공 = (r, 겹 = 0) => {
  const g = new THREE.IcosahedronGeometry(r, 겹);
  g.deleteAttribute("uv");
  return g.toNonIndexed();
};
const 묶기 = (조각) => {
  const g = mergeGeometries(조각, false);
  조각.forEach((v) => v.dispose());
  return 밑동원점으로(g);
};
const 칠 = (g, 색) => 색입히기(g, new THREE.Color(색));

// ── ① 짚신 ──────────────────────────────────────────────────
//   [왜 이 모양인가]
//     바닥창(총)만 만들면 **깔창**이지 신이 아니다. 신으로 읽히려면
//     ㉠ 앞이 좁고 뒤가 넓은 바닥, ㉡ 그 위를 두르는 **울(전)**,
//     ㉢ 발등을 지나는 **들메끈** 셋이 다 있어야 한다.
//   [왜 `수` 만큼 만드나]
//     ★ 짚신은 **왼짝·오른짝**이 따로다. 같은 표본을 두 번 쓰면
//       한 켤레가 아니라 같은 짝이 둘이 된다. `모양 0` 을 왼짝,
//       `모양 1` 을 오른짝으로 굽는다(Z 를 뒤집는다).
export function 짚신표본들(수 = 2, 시드 = 6301) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 왼 = i % 2 === 0 ? 1 : -1; // 좌우 짝
    // ★ 길이 대 높이 비가 **실물과 같아야** 한다. 처음엔 `길 = 1.0` 이라
    //   비가 9.6 : 1 이었고, 신이 0.72 m 짜리 **널빤지**로 보였다(실측·렌더).
    //   짚신은 길이 0.25 m · 높이 0.06 m 쯤 — 약 4.2 : 1 이다.
    //   `밑동원점으로` 가 **높이**로 나누므로, 길이를 줄여야 비가 잡힌다.
    const 길 = 0.45; // → 비 약 4.9 : 1. 자리의 `키` 0.06 이 길이 0.29 m 가 된다.
    // 바닥창 — 앞이 좁고 뒤가 넓다. 마디를 나눠 **짚을 삼은 결**을 낸다.
    const 마디 = 7;
    for (let k = 0; k < 마디; k++) {
      const t = (k + 0.5) / 마디;
      // 발 모양: 뒤꿈치(t=0)가 넓고, 볼(t≈0.35)이 가장 넓고, 코(t=1)가 좁다
      const 폭 = 0.34 + Math.sin(Math.min(t, 0.45) / 0.45 * Math.PI * 0.5) * 0.16 - t * 0.22;
      const 창 = 상자(폭, 0.1, (길 * 2.4) / 마디 - 0.04);
      창.translate(0, 0.05, (-1.2 + 2.4 * t) * 길);
      조각.push(칠(창, k % 2 ? 씬3결.짚 : 씬3결.짚그늘));
    }
    // 울(전) — 바닥 둘레를 두르는 낮은 턱. 이게 없으면 깔창이다.
    for (const s of [-1, 1])
      for (let k = 0; k < 5; k++) {
        const t = (k + 0.5) / 5;
        const 폭 = 0.34 + Math.sin(Math.min(t, 0.45) / 0.45 * Math.PI * 0.5) * 0.16 - t * 0.22;
        const 울 = 상자(0.045, 0.11, (길 * 2.2) / 5 - 0.03);
        울.translate(s * (폭 / 2 - 0.02), 0.12, (-1.1 + 2.2 * t) * 길);
        조각.push(칠(울, 씬3결.짚그늘));
      }
    // 들메끈 — 발등을 가로지른다. 한쪽이 풀려 늘어져 있다(벗겨진 신이다).
    const 끈 = 기둥(0.022, 0.022, 0.42, 4);
    끈.rotateZ(Math.PI / 2);
    끈.translate(0, 0.2, 0.15 * 길);
    조각.push(칠(끈, 씬3결.들메끈));
    const 늘어진 = 기둥(0.02, 0.016, 0.5, 4);
    늘어진.rotateX(Math.PI / 2 - 0.25);
    늘어진.rotateY(왼 * (0.5 + 난수() * 0.3));
    늘어진.translate(왼 * 0.16, 0.05, -0.5 * 길);
    조각.push(칠(늘어진, 씬3결.들메끈));
    // 뒤축 — 뒤꿈치를 감싸는 코. 앞뒤를 갈라 준다.
    const 뒤축 = 상자(0.3, 0.16, 0.07);
    뒤축.translate(0, 0.13, -1.18 * 길);
    조각.push(칠(뒤축, 씬3결.짚));
    const 합 = 묶기(조각);
    if (왼 < 0) 합.scale(1, 1, -1); // 오른짝 — 앞뒤 대칭이 아니라 뒤집어야 한다
    표본.push(합);
  }
  return 표본;
}

// ── ② 댕기 ──────────────────────────────────────────────────
//   [왜 이 모양인가]
//     땅에 떨어진 천은 **판판하지 않다.** 곧은 띠 하나를 눕히면
//     붉은 테이프로 보인다. 마디마다 조금씩 꺾고 비틀어야 천이 된다.
//   [왜 붉은가]  자갈밭·마루 흙이 전부 누런 잿빛이다. 여기서 눈에 들려면
//     색이 달라야 한다 — 「저기 뭔가 있다」가 먼저고 정체는 그다음이다.
export function 댕기표본들(수 = 3, 시드 = 6302) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    let x = 0;
    let z = 0;
    let 각 = 난수() * Math.PI;
    // ★ 마디를 9 → 7 로 줄였다. 아홉 마디를 이으면 **붉은 밧줄**이 되어
    //   댕기가 아니라 뱀처럼 보였다(렌더로 잡았다).
    const 마디 = 7;
    for (let k = 0; k < 마디; k++) {
      const 길 = 0.34 + 난수() * 0.12;
      // 구불구불 — 꺾임이 없으면 천이 아니라 막대다
      각 += (난수() - 0.5) * 1.5;
      // 폭 0.3 → 0.13. 댕기는 손가락 두어 개 너비다. 0.3 이면 **머플러**다.
      const 조 = 상자(0.13, 0.055 + 난수() * 0.03, 길);
      조.rotateX((난수() - 0.5) * 0.5); // 접힌 데가 살짝 뜬다
      조.rotateY(각);
      조.translate(x, 0.035, z);
      조각.push(칠(조, k % 3 === 1 ? 씬3결.댕기그늘 : 씬3결.댕기));
      x += Math.sin(각) * 길 * 0.88;
      z += Math.cos(각) * 길 * 0.88;
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ③ 무너진 마루 (흙덩이) ──────────────────────────────────
//   [왜 필요한가]  위 머리말의 「★ 벼랑 끝은 무너져 있어야 한다」 참고.
//   [왜 돌이 아니라 흙인가]
//     맵에 이미 `발치너덜`·`틈바위` 가 잔뜩 있다. 같은 잿빛 돌을 더
//     뿌리면 **배경에 섞여 버려** 아무도 「무너진 자국」으로 안 읽는다.
//     갓 떨어져 나온 흙은 **속이 밝다** — 그 색 차이가 「최근」을 말한다.
export function 흙덩이표본들(수 = 4, 시드 = 6303) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 덩이수 = 4 + Math.floor(난수() * 4);
    for (let k = 0; k < 덩이수; k++) {
      const r = 0.2 + 난수() * 0.3;
      const d = 공(r, 0);
      // 찌그러뜨린다 — 정이십면체 그대로면 공깃돌이다
      d.scale(0.7 + 난수() * 0.7, 0.5 + 난수() * 0.4, 0.7 + 난수() * 0.7);
      d.rotateY(난수() * 6.3);
      d.rotateZ((난수() - 0.5) * 0.8);
      d.translate(
        (난수() - 0.5) * 1.4,
        r * 0.42 + 난수() * 0.12,
        (난수() - 0.5) * 1.4,
      );
      // 큰 덩이는 겉흙(어둡다), 부서진 작은 것은 속흙(밝다)
      조각.push(칠(d, r > 0.33 ? 씬3결.흙 : 난수() < 0.3 ? 씬3결.돌 : 씬3결.흙밝음));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

// ── ④ 부러진 가지 ───────────────────────────────────────────
//   [왜 필요한가]
//     14 m 를 떨어지면 **뭔가를 훑고 내려온다.** 발치에 잎 붙은 생가지가
//     부러져 있어야 그 경로가 읽힌다. 부러진 자리의 **흰 속살**이
//     「오래전 삭은 가지」와 「방금 꺾인 가지」를 가른다.
export function 부러진가지표본들(수 = 3, 시드 = 6304) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 길 = 2.6 + 난수() * 0.8;
    const 몸 = 기둥(0.075, 0.13, 길, 6);
    몸.rotateZ(Math.PI / 2);
    몸.rotateY((난수() - 0.5) * 0.3);
    몸.translate(0, 0.13, 0);
    조각.push(칠(몸, 씬3결.가지));
    // 부러진 자리 — 흰 속살. 이 한 조각이 「방금」을 말한다.
    const 속 = 기둥(0.075, 0.075, 0.09, 6);
    속.rotateZ(Math.PI / 2);
    속.translate(길 / 2, 0.13, 0);
    조각.push(칠(속, 씬3결.속살));
    // 잔가지 몇 — 없으면 몽둥이다
    for (let k = 0; k < 4; k++) {
      const t = (k + 0.6) / 5;
      const 잔 = 기둥(0.035, 0.015, 0.55 + 난수() * 0.4, 4);
      잔.rotateZ(Math.PI / 2 - (0.5 + 난수() * 0.6));
      잔.rotateY(난수() * 6.3);
      잔.translate(-길 / 2 + 길 * t, 0.16, 0);
      조각.push(칠(잔, 씬3결.가지));
    }
    // 잎 — 아직 푸르다. 시든 잎이면 오래된 가지가 된다.
    for (let k = 0; k < 9; k++) {
      const 잎 = 상자(0.26, 0.03, 0.38);
      잎.rotateY(난수() * 6.3);
      잎.rotateX((난수() - 0.5) * 0.7);
      잎.translate(
        (난수() - 0.5) * 길 * 0.9,
        0.16 + 난수() * 0.22,
        (난수() - 0.5) * 1.1,
      );
      조각.push(칠(잎, 씬3결.생가지));
    }
    표본.push(묶기(조각));
  }
  return 표본;
}

