// ═══════════════════════════════════════════════════════════════
//  울타리.js — 비탈길 낭떠러지 쪽에 세우는 나무 울타리
// ═══════════════════════════════════════════════════════════════
// [왜 필요한가]
//   T4 서측 하강로는 길 바깥으로 **7.9 m** 가 떨어진다(실측). 그런데 지금은
//   가장자리에 아무 표시가 없어서, 어디까지가 길인지 걷는 사람이 알 수 없다.
//   울타리는 장식이 아니라 **길의 가장자리를 읽게 해 주는 장치**다.
//
// [어느 쪽에 세우나 — 쪽을 박아 넣지 않는다]
//   「T4 는 왼쪽」처럼 적어 두면 도면이 바뀌는 순간 엉뚱한 데 선다.
//   대신 매 점에서 **양쪽 낙차를 재서 더 깊이 떨어지는 쪽**에 세운다.
//   실측으로 이 규칙이 맞는 걸 확인했다.
//     T1  양쪽 다 안 떨어짐        → 안 선다
//     T2  왼쪽 +2.46 / 오른쪽 -0.66 → 거의 안 선다(강변 우회로라 평지에 가깝다)
//     T3  왼쪽 +1.54 / 오른쪽 -0.81 → 오른쪽
//     T4  왼쪽 -1.98 / 오른쪽 -0.47 → 왼쪽 (가장 깊은 데가 -7.90)
//
// [판정은 안 건드린다]
//   **막지 않는다.** §6 ②는 「절벽에서 발을 헛디디면 떨어진다」를 규칙으로
//   두고 있고, 실제로 그게 이 공간의 사건이다. 울타리가 사람을 붙잡으면
//   그 규칙이 죽는다. 그래서 이건 **눈에만 있는 것**이다 —
//   「여기가 끝이다」를 알려 줄 뿐 붙잡지는 않는다.
//   ※ 막아야 한다는 판단이 서면 `지형.js` 의 `막힘` 에 넣어야 하고,
//     그건 도면 값이라 팀이 정할 일이다(§7 0단계).
//
// [단위]  도면 좌표 m. 표본은 **1 짜리**로 만들고, 유닛 변환(1 유닛 = 0.3 m)은
//         `무리만들기` 가 `키 × 미터` 로 해 준다 — 여기서 곱하면 두 번 곱해진다.

import * as THREE from "three";
import { mergeGeometries } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { makeRandom } from "../../src/공용.jsx";

// 나무 색 — 도면 숫자가 아니라 화풍 값이라 여기 둔다.
//   비바람 맞은 참나무. 너무 붉으면 새 목재로 보이고, 너무 회색이면 돌이 된다.
export const 나무결 = {
  밝음: "#8A7350",
  어둠: "#4A3B28",
};

// 울타리 치수 — 눈으로 맞출 값이라 여기 모아 둔다(§9 미결값 성격).
export const 치수 = {
  기둥간격: 1.6, // m — 좁으면 담이 되고 넓으면 줄이 된다
  기둥높이: 0.95,
  기둥굵기: 0.115,
  가로대: [0.42, 0.80], // 기둥 밑동에서 잰 높이(m)
  가로대두께: 0.075,
  가로대폭: 0.05,
  바깥으로: 0.35, // 길 가장자리에서 더 바깥으로 밀어내는 거리(m)
  최대기울기: 35, // ° — 기둥 사이가 이보다 가파르면 울타리를 끊는다
  묻힘: 0.12, // 기둥을 땅에 이만큼 박는다(안 그러면 떠 보인다)
};

// ── 세울 자리 고르기 ────────────────────────────────────────
//   통로실측  지형.통로실측 (선·폭이 들어 있다)
//   지면높이  (x, z) => y
//   낙차기준  이만큼(m) 넘게 떨어지는 쪽에만 세운다
//   내다보기  낙차를 재는 거리(m) — 길 가장자리에서 바깥으로
//
//   돌려주는 것 { 기둥: [...], 가로대: [...] }
//     기둥   { x, y, z, 키, 회전, 기울기, 기울기2, 폭비, 깊이비, 색 }
//     가로대 { … 키 = 길이 }
export function 울타리자리들({
  통로실측,
  지면높이,
  낙차기준 = 0.8,
  내다보기 = 1.5,
  시드 = 771103,
}) {
  const 난수 = makeRandom(시드);
  const 기둥 = [];
  const 가로대 = [];
  const 밝 = new THREE.Color(나무결.밝음);
  const 어 = new THREE.Color(나무결.어둠);
  const 색임시 = new THREE.Color();
  const 나무색 = () => 색임시.copy(어).lerp(밝, 0.35 + 난수() * 0.6).getHex();

  for (const 통 of 통로실측) {
    const 반폭 = 통.폭 / 2;
    // ① 중심선을 **촘촘히**(0.4 m) 훑어 점마다 「어느 쪽이 낭떠러지인가」를 본다.
    const 촘촘 = 고르게(통.선, 0.4);
    // ② 울타리가 설 구간마다 **바깥선**을 만든다.
    //    ※ 예전에는 중심선에서 간격을 잡고 그 점들을 바로 이었다. 스위치백
    //      모서리에서 법선이 뒤집히는 바람에 가로대가 **길을 가로질러** 3.2 m
    //      씩 날아갔다(실측으로 잡았다). 바깥선을 먼저 만들고 **그 선 위에서**
    //      간격을 잡으면 모서리를 자연스럽게 감아 돈다.
    const 구간들 = [];
    let 지금 = null;
    for (const p of 촘촘) {
      const 안 = 지면높이(p.x, p.z);
      const d = 반폭 + 내다보기;
      const 왼 = 지면높이(p.x - p.nx * d, p.z - p.nz * d) - 안;
      const 오 = 지면높이(p.x + p.nx * d, p.z + p.nz * d) - 안;
      const 쪽 = 오 < 왼 ? 1 : -1; // 더 깊이 떨어지는 쪽
      if (Math.min(왼, 오) > -낙차기준) {
        지금 = null; // 여기는 안 떨어진다 — 구간을 끊는다
        continue;
      }
      const 거리 = 반폭 + 치수.바깥으로;
      const 밖 = { x: p.x + p.nx * 거리 * 쪽, z: p.z + p.nz * 거리 * 쪽 };
      // 모서리에서 법선이 홱 돌면 **바깥선 자체가 건너뛴다.** 그 도약을 그냥
      //   이으면 가로대가 다시 길을 가로지른다(3 m 짜리 하나가 남아 있었다).
      //   촘촘 간격의 두 배를 넘게 뛰면 거기서 끊는다 — 모서리에서 울타리가
      //   한 칸 벌어지는 편이, 길 위로 널을 걸치는 것보다 낫다.
      const 이전 = 지금?.점?.[지금.점.length - 1];
      const 뛰었나 = 이전 && Math.hypot(밖.x - 이전.x, 밖.z - 이전.z) > 0.8;
      if (!지금 || 지금.쪽 !== 쪽 || 뛰었나) {
        지금 = { 쪽, 점: [] };
        구간들.push(지금);
      }
      지금.점.push(밖);
    }

    // ③ 바깥선 위에서 기둥 간격을 잡고, 이웃한 기둥끼리만 가로대를 건다
    for (const 구간 of 구간들) {
      const 자리 = 선위에고르게(구간.점, 치수.기둥간격);
      if (자리.length < 2) continue; // 기둥 하나짜리는 울타리로 안 보인다
      const 점들 = 자리.map((q) => ({ ...q, y: 지면높이(q.x, q.z) }));
      // 기둥 사이가 너무 가파르면 거기서 끊는다.
      //   T4 갓길에는 56° 로 꺼지는 자리가 있다(도면이 인접 지형을 안 준 그 턱).
      //   그대로 이으면 가로대가 땅으로 처박히는 꼴이 된다. 진짜 울타리는
      //   그런 데서 **멈춘다** — 벼랑 끝까지 널을 끌고 내려가지 않는다.
      for (const 점 of 가파른데서끊기(점들, 치수.최대기울기)) {
      if (점.length < 2) continue;
      for (const q of 점) {
        // 손으로 박은 것처럼 조금씩 흔든다 — 자로 잰 듯하면 공장 울타리가 된다
        기둥.push({
          x: q.x,
          y: q.y - 치수.묻힘,
          z: q.z,
          키: 치수.기둥높이 * (0.92 + 난수() * 0.16),
          회전: (난수() - 0.5) * 0.5,
          기울기: (난수() - 0.5) * 0.07,
          기울기2: (난수() - 0.5) * 0.07,
          폭비: 치수.기둥굵기 / 치수.기둥높이,
          깊이비: 치수.기둥굵기 / 치수.기둥높이,
          색: 나무색(),
        });
      }
      for (let i = 0; i < 점.length - 1; i++) {
        const a = 점[i];
        const b = 점[i + 1];
        const dx = b.x - a.x;
        const dz = b.z - a.z;
        const 평면 = Math.hypot(dx, dz);
        if (평면 < 0.05) continue;
        for (const h of 치수.가로대) {
          const ay = a.y + h;
          const by = b.y + h;
          const 길이 = Math.hypot(평면, by - ay);
          가로대.push({
            x: (a.x + b.x) / 2,
            y: (ay + by) / 2,
            z: (a.z + b.z) / 2,
            키: 길이 * 1.04, // 기둥 속으로 조금 물려 이음매가 안 벌어지게
            // 막대는 **국소 +Z** 로 눕혀 두었다. YXZ 순서라
            // 「방위(Y)를 먼저 돌리고 그 방위에서 기울인다(X)」가 된다.
            회전: Math.atan2(dx, dz),
            기울기: -Math.atan2(by - ay, 평면),
            기울기2: 0,
            // ※ 길이 축은 **깊이비(Z)** 다. 여기에 두께를 넣으면 길이가 얇아지고,
            //   안 준 `높이비` 가 기본값 1 로 남아 **키가 길이만큼** 커진다 —
            //   실제로 그렇게 나서 1.7 m 짜리 널판이 서 있었다.
            폭비: 치수.가로대폭 / (길이 * 1.04),
            높이비: 치수.가로대두께 / (길이 * 1.04),
            깊이비: 1,
            색: 나무색(),
          });
        }
      }
      } // 가파른 데서 끊긴 조각
    }
  }
  return { 기둥, 가로대 };
}

// 기둥 줄을 「너무 가파른 이음매」에서 잘라 여러 조각으로 돌려준다.
function 가파른데서끊기(점들, 최대각) {
  const 한계 = Math.tan((최대각 * Math.PI) / 180);
  const 조각 = [];
  let 지금 = [];
  for (let i = 0; i < 점들.length; i++) {
    if (i > 0) {
      const a = 점들[i - 1];
      const b = 점들[i];
      const 평면 = Math.hypot(b.x - a.x, b.z - a.z);
      if (평면 > 1e-6 && Math.abs(b.y - a.y) / 평면 > 한계) {
        조각.push(지금);
        지금 = [];
      }
    }
    지금.push(점들[i]);
  }
  조각.push(지금);
  return 조각;
}

// {x,z} 만 있는 선 위에서 일정 간격으로 점을 다시 뽑는다.
//   바깥선(offset)에 쓴다 — 모서리를 감아 돌기 때문에 중심선보다 길다.
//   끝점은 반드시 넣는다. 안 넣으면 울타리가 구간 끝에서 어정쩡하게 끊긴다.
function 선위에고르게(점들, 간격) {
  if (점들.length < 2) return 점들.slice();
  const 답 = [점들[0]];
  let 쌓임 = 0;
  for (let i = 0; i < 점들.length - 1; i++) {
    const a = 점들[i];
    const b = 점들[i + 1];
    const L = Math.hypot(b.x - a.x, b.z - a.z);
    if (L < 1e-9) continue;
    let 남 = 간격 - 쌓임;
    let t = 0;
    while (남 <= L - t) {
      t += 남;
      답.push({ x: a.x + ((b.x - a.x) * t) / L, z: a.z + ((b.z - a.z) * t) / L });
      남 = 간격;
      쌓임 = 0;
    }
    쌓임 += L - t;
  }
  const 끝 = 점들[점들.length - 1];
  const 마지막 = 답[답.length - 1];
  // 끝이 바로 옆이면 겹치니 넣지 않는다
  if (Math.hypot(끝.x - 마지막.x, 끝.z - 마지막.z) > 간격 * 0.35) 답.push(끝);
  return 답;
}

// 선을 따라 일정 간격으로 점을 다시 뽑는다. 법선(nx,nz)도 같이 옮겨 준다.
function 고르게(선, 간격) {
  const 답 = [];
  let 남은 = 0;
  for (let i = 0; i < 선.length - 1; i++) {
    const a = 선[i];
    const b = 선[i + 1];
    const L = Math.hypot(b.x - a.x, b.z - a.z);
    if (L < 1e-6) continue;
    let t = 남은;
    while (t <= L) {
      const k = t / L;
      답.push({
        x: a.x + (b.x - a.x) * k,
        z: a.z + (b.z - a.z) * k,
        nx: a.nx,
        nz: a.nz,
      });
      t += 간격;
    }
    남은 = t - L;
  }
  return 답;
}

// ── 표본 ────────────────────────────────────────────────────
// [왜 통짜로 안 만드나]
//   무리(InstancedMesh)로 세워야 **하나씩 고르고 옮길 수 있다.** 길 위에
//   어긋나게 선 기둥 하나를 치우려면 그 하나를 집을 수 있어야 한다
//   (배치.js 머리말 참고).

// 각진 기둥 — 밑동이 원점, 높이 1, 가로세로 1.
//   위로 갈수록 살짝 가늘어진다. 곧은 각기둥은 플라스틱처럼 보인다.
export function 기둥표본들(수 = 4, 시드 = 3301) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const g = new THREE.CylinderGeometry(0.38, 0.5, 1, 5, 1);
    // 위쪽을 도끼로 친 것처럼 비스듬히 자른 느낌 — 꼭짓점을 조금 흔든다
    const p = g.attributes.position;
    for (let k = 0; k < p.count; k++) {
      const 위 = p.getY(k) > 0;
      p.setX(k, p.getX(k) * (1 + (난수() - 0.5) * 0.12));
      p.setZ(k, p.getZ(k) * (1 + (난수() - 0.5) * 0.12));
      if (위) p.setY(k, p.getY(k) + (난수() - 0.5) * 0.06);
    }
    g.translate(0, 0.5, 0); // 밑동을 원점으로
    g.computeVertexNormals();
    표본.push(g.toNonIndexed());
    g.dispose();
  }
  return 표본;
}

// 가로대 — **국소 +Z 로 누운** 길이 1 짜리 각재. 원점이 한가운데.
export function 가로대표본들(수 = 3, 시드 = 5507) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  for (let i = 0; i < 수; i++) {
    const g = new THREE.BoxGeometry(1, 1, 1, 1, 1, 3);
    const p = g.attributes.position;
    for (let k = 0; k < p.count; k++) {
      // 길이 방향(Z)은 안 건드린다 — 건드리면 이음매가 벌어진다
      p.setX(k, p.getX(k) * (1 + (난수() - 0.5) * 0.18));
      p.setY(k, p.getY(k) * (1 + (난수() - 0.5) * 0.18));
    }
    g.computeVertexNormals();
    표본.push(g.toNonIndexed());
    g.dispose();
  }
  return 표본;
}

// 팔레트에 올릴 「울타리 한 칸」 — 기둥 둘 + 가로대 둘을 붙인 한 덩이.
//   밑동이 원점, 높이 1. 손으로 몇 칸 더 놓고 싶을 때 쓴다.
export function 울타리칸표본들(수 = 3, 시드 = 9109) {
  const 난수 = makeRandom(시드);
  const 표본 = [];
  const 기둥들 = 기둥표본들(수, 시드 + 1);
  for (let i = 0; i < 수; i++) {
    const 조각 = [];
    const 간 = 1.7; // 높이 1 기준 칸 너비
    for (const s of [-0.5, 0.5]) {
      const g = 기둥들[i].clone();
      g.scale(0.12, 1, 0.12);
      g.translate(0, 0, s * 간);
      조각.push(g);
    }
    for (const h of [0.44, 0.82]) {
      const g = new THREE.BoxGeometry(0.055, 0.08, 간 + 0.12);
      g.translate(0, h * (0.95 + 난수() * 0.1), 0);
      조각.push(g.toNonIndexed());
      g.dispose();
    }
    const 합 = mergeGeometries(조각, false);
    조각.forEach((g) => g.dispose());
    합.computeVertexNormals();
    표본.push(합);
  }
  기둥들.forEach((g) => g.dispose());
  return 표본;
}
